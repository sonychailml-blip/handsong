/* ═══ КУРСОРЫ ПЕРЕИГРОВКИ (слайс S3.2) — стоимость по ОКНУ, а не по всей песне ═══
   Оба цикла переигровки (scheduleLayers и fireNear) обходили ВЕСЬ массив событий, а tick зовёт их
   ОБА каждые SCHED_TICK_MS=25мс. На паре тактов это десятки событий и сорок обходов в секунду —
   бесплатно. На песне в несколько минут это десятки ТЫСЯЧ событий, то есть миллионы чтений полей в
   секунду на том же потоке, где крутятся MediaPipe и синтез. Курсор превращает «весь массив» в
   «события внутри окна».
   ⚠️ ОТСОРТИРОВАН ЛИ МАССИВ — ОТВЕТ: НЕ ЦЕЛИКОМ, И ЭТО ВАЖНО. Сортируют: остановка записи (recStop — её
   зовут и ●, и паника), пауза (onLoop), загрузка аранжировки, а ВО ВРЕМЯ ЗАПИСИ — ещё и каждый путь,
   который зовёт schedInvalidate при идущем взятом (⟳ setRegionOn, отмена, удаление дорожки, снятие
   подложки). Между ними push ДОПИСЫВАЕТ события взятого в конец. Время у них абсолютное, но при
   крутящейся скобе оно СВОРАЧИВАЕТСЯ в неё (songAt), то есть на каждом шве падает обратно к её началу.
   Значит дописанный хвост не отсортирован ни внутри себя, ни относительно тела.
   ⛳ НО ЭТОТ ХВОСТ — РОВНО ТЕКУЩЕЕ ВЗЯТОЕ: push ставит `tk: curTake`, а оба цикла и так пропускают его
   события (`recording && ev.tk===curTake` — их слышно живьём). Поэтому курсоры работают по
   ОТСОРТИРОВАННОМУ ПРЕФИКСУ длиной cursN, а хвост вне его — и не нужен им, и не мешает. Прежний материал
   ВООРУЖЁННОЙ дорожки лежит в префиксе и переигрывается как обычно.
   ⛔ Отсюда условие schedInvalidate: он объявляет префиксом ВЕСЬ массив, поэтому во время записи перед
   ним обязана стоять сортировка (правило #28).
   ⛳ ГЛАВНОЕ СВОЙСТВО БЕЗОПАСНОСТИ: курсор только СУЖАЕТ участок, который смотрим; ЧТО именно сыграть,
   по-прежнему решает явная проверка интервала внутри цикла. Поэтому курсор, вставший СЛИШКОМ РАНО,
   безвреден — лишние события отсеет проверка. Не убирайте эти проверки «раз есть курсор».
   ⚠️ ШОВ ПОВТОРА — НЕ ОСОБЫЙ СЛУЧАЙ, а просто «позиция поехала не туда, где стоит курсор»: при крутящейся
   скобе lo падает к её началу, курсор перепривязывается двоичным поиском. В коде курсора слова «шов» нет
   вовсе; без скобы шва не бывает, и курсор просто идёт вперёд. */
let cursN=0;                        // длина ОТСОРТИРОВАННОГО префикса events (хвост записи — за ним)
const curSched={i:0,at:null};       // курсор scheduleLayers: i — индекс, at — доля, которой он соответствует
const curNear ={i:0,at:null};       // курсор fireNear (своя временнáя база, см. довод у fireNear)
let chaseAt=null, chaseList=null;   // кэш догонялки (S3.5c): доля входа → владельцы, открытые к ней; сбрасывает schedInvalidate, см. chaseFor
/* Первый индекс в [0,cursN) с events[i].t >= t. Классический lower_bound. */
function cursLowerBound(t){
  let lo=0, hi=cursN;
  while(lo<hi){ const m=(lo+hi)>>1; if(events[m].t<t) lo=m+1; else hi=m; }
  return lo;
}
/* Поставить курсор на позицию x. Продолжаем с места, если он ровно там; иначе — двоичный поиск.
   Сравнение с допуском 1e-9: соседние сегменты дают ПОБИТОВО равные значения (hi предыдущего —
   то же выражение, что lo следующего), но допуск страхует от дрейфа после смены темпа. */
function cursSeek(c,x){
  /* СТРАХОВКА, О(1), на входе в оба цикла: если бы какой-то путь удалил события, забыв про
     schedInvalidate, cursN оказался бы БОЛЬШЕ массива — и цикл прочитал бы events[i].t у undefined,
     уронив насос звука целиком. Доказано, что таких путей нет (каждое удаление сбрасывает курсоры),
     но цена проверки — одно сравнение на вызов, а цена ошибки — тишина во всём приложении.
     ⛔ Это НЕ замена schedInvalidate: забытый сброс даст лишний обход, а не молчаливо верный результат. */
  if(cursN>events.length) cursN=events.length;
  if(c.at===null || Math.abs(c.at-x)>1e-9){ c.i=cursLowerBound(x); c.at=x; }
  return c.i;
}
/* ⛔ ЕДИНСТВЕННАЯ ТОЧКА СБРОСА КУРСОРОВ — сюда обязан приходить КАЖДЫЙ путь, который делает их
   неверными: правка состава событий (запись, аранжировка, отмена слоя, снятие подложки, очистка),
   пересортировка, и скачок временнóй базы (старт/возобновление транспорта, смена темпа, пауза,
   паника). Позже сюда же придут правка события и перемотка.
   ⛔ НИКАКИХ `curSched.i=0` ПО МЕСТАМ. Разбросанные сбросы — ровно тот способ, которым такая
   оптимизация тихо ломается: один забытый путь даёт пропущенные или удвоенные ноты, причём не сразу.
   Здесь же заново берётся и cursN — длина отсортированного префикса: эта функция вызывается ТОЛЬКО
   когда массив приведён в порядок (сразу после sort/уплотнения/очистки) либо когда запись ещё ничего
   не дописала, поэтому `events.length` в этот момент и есть граница сортированного. */
onInvalidate(()=>{ cursN=events.length; curSched.at=null; curNear.at=null; chaseAt=null; songLenRecalc(); rgnSync(); });   // REC2: the note view resets itself (song/notes.js listener); song length and brace follow the material

/* 1) СЛОИ ВПЕРЁД: на каждый опрос планируем события в окне [loop.sched, горизонт) по их ТОЧНОМУ времени
   loop.t0 + доля*spb. Интервал ПОЛУОТКРЫТ [lo,hi): включает начало → доля 0 (сильный удар) не теряется
   на старте. Событие пишущейся дорожки пропускаем. loop.sched — абсолютная доля, монотонно растёт.
   ⛳ S3.3 СНЯЛ ОТСЮДА ПРОЕКЦИЮ ЧЕРЕЗ ЗАВОРОТЫ. Было: внешний `while` резал окно по границам повторов,
   считал номер повтора `rep`, переводил абсолютную долю в долю ВНУТРИ петли и на каждой границе звал
   releaseLoopLayersAt. Со сквозным временем окно НИКОГДА не пересекает границу (её нет), поэтому весь
   цикл схлопнулся в один отрезок, а `guard` (страховка от бесконечного кручения по повторам) стал не
   нужен. Время события — просто `loop.t0 + ev.t*spb`.
   ⛳ S3.4 ВЕРНУЛ СЮДА ПРОЕКЦИЮ — ту же самую, только переанкеренную. Внешний `while` снова режет окно
   по границам проходов, `off` — это прежний `rep*lb`, а `guard` снова страхует от бесконечного
   кручения. Разница ровно одна: проходы отсчитываются не от нуля до длины петли, а от rgn.from до
   rgn.to. ⛔ При выключенной области цикл делает РОВНО ОДИН оборот с off=0 — то есть линейный путь
   S3.3 байт-в-байт, без единого лишнего действия.
   ⛳ И ЭТО ПОДТВЕРЖДАЕТ УСТРОЙСТВО КУРСОРА ИЗ S3.2 ВО ВТОРОЙ РАЗ: заворот в нём НИКОГДА не был особым
   случаем. Монотонный loop.sched вперёд не прыгает, а вот `lo` на границе прохода ПАДАЕТ к rgn.from —
   и cursSeek просто видит «позиция не там, где курсор» и перепривязывается двоичным поиском. Ни одного
   отдельного сброса под заворот не понадобилось. */
function scheduleLayers(){
  const spb=secPerBeat();
  const horizon=(AC.currentTime+SCHED_AHEAD-loop.t0)/spb;   // МОНОТОННАЯ доля на горизонте опережения
  const gated=laneGated();                                  // ОДИН раз на вызов: пока никто не заглушён, в цикле остаётся готовый булев
  const frz=frozenOn();                                     // F4: то же «посчитать один раз» — пока ничего не заморожено, цикл не платит ничего
  const R=loop.rgn, cyc=cycling(), L=rgnLen();
  let guard=0;
  while(loop.sched<horizon-1e-9 && guard++<64){
    /* Граница следующего прохода в МОНОТОННЫХ долях и сдвиг «монотонная → песенная» для этого отрезка.
       Без области границы нет (Infinity) и сдвиг нулевой — один оборот до горизонта. */
    const off=cyc ? rgnReps(loop.sched)*L : 0;
    const edge=cyc ? R.to+off : Infinity;
    const segEnd=Math.min(horizon,edge);
    const lo=loop.sched-off, hi=segEnd-off;                  // в ПЕСЕННЫХ долях
    const segT=timeAt(lo+off), rep=cyc?rgnReps(loop.sched):0;   // миг начала отрезка и номер прохода — место ОБОИХ швов заморозки (A2/A2b)
    /* ⛳ A2b: ШОВ ВЫХОДА — ДО СОБЫТИЙ ОТРЕЗКА. Дорожку, чей буфер звучит, но звучать больше не должен
       (устарела от правки или от тоники/A4/темпа, или разморожена на ходу), отдаём событиям с `lo`.
       Порядок несущий: догонялка открывает голоса аккорда/баса по времени шва, а события этого же
       отрезка (их ставит цикл ниже) их ведут — поставь мы их раньше, chordGlide/bassSet ушли бы в пустоту. */
    if(frz) for(const f of [...frozen.values()]){
      const fresh=freezeState(f.layer)==='fresh';
      if(f.swap && !f.swap.cut){ if(!fresh){ frzSwapCancel(f); continue; } }   // AF2: подмена ещё впереди, а дорожка устарела — отменить, события и так владеют
      else if(f.armedRep!=null && !fresh){ frzLeave(f, lo, segT, rep); continue; }
      if(fresh && f.evRun && !f.swap && f.armedRep!==rep) frzPlanSwap(f, lo, rep, off);   // AF2: свежую, которую играют события, — спланировать подмену (ДО событий отрезка: те, что раньше доли подмены, ещё играют)
    }
    /* КУРСОР: встаём на первое событие с t>=lo (продолжая с места, если оно там же) и идём, пока t<hi.
       Курсор двигаем по ВСЕМ событиям окна, а не только по сыгранным: он — позиция ВО ВРЕМЕНИ, а не
       «сколько нот прозвучало». Явная проверка ev.t>=lo оставлена НАРОЧНО (см. шапку курсоров). */
    let i=cursSeek(curSched,lo);
    for(; i<cursN && events[i].t<hi; i++){
      const ev=events[i];
      if(!isLayer(ev.fn)) continue;
      if(W.recording()&&ev.tk===W.curTake()) continue;               // S3.5c: пропускаем то, что звучит ЖИВЬЁМ (события этого взятого), а не весь слой — старый материал вооружённой дорожки должен звучать
      if(gated&&!laneAudible(ev.layer)) continue;           // дорожка заглушена (или молчит из-за чужого соло) — просто НЕ ПЛАНИРУЕМ её события; сами события НЕ трогаем
      if(frz&&frzSkipNear(ev,rep)) continue;                 // F4: ЗАМОРОЖЕНА — вместо её событий играет буфер (взводится ниже, на границе прохода). AF2: по отметке подмены — события ДО её доли ещё играют (та же пара «проход, доля», что у fireNear)
      if(ev.t>=lo){
        const when=timeAt(ev.t+off);                  // ТОЧНОЕ время: песенная доля события + сдвиг прохода
        W.ENG[ev.fn](ev.a,ev,{when});                         // ev несёт замороженный лад (§3.4). {when} ИМЕНОВАННО (S2): позиционный третий аргумент раньше значил у разных записей разное — см. шапку ENG
        if(ev.fn==='chOn'||ev.fn==='chSet') setLoopChordHl(ev.a,ev.sc);   // T4b4: место — из индекса в строе (hlOf). Подсветка ведёт на опережение (~до окна) — косметика; регистр лежит в том же событии
        else if(ev.fn==='chOff')W.chordHlOff();
      }
    }
    curSched.i=i; curSched.at=hi;                           // дошли до hi — следующий отрезок продолжит отсюда без поиска
    /* ⛳ F4: ИСТОЧНИКИ ЗАМОРОЖЕННЫХ — ИЗ ЭТОГО ЖЕ ЦИКЛА И ПО ЭТОЙ ЖЕ ФОРМУЛЕ ВРЕМЕНИ (правило #15).
       `rep` — номер прохода; сменился, значит начался новый круг и нужен НОВЫЙ узел (источник буфера
       одноразов). Взводим по НАЧАЛУ отрезка `lo`: при входе в песню это место входа, на шве — начало
       скобы. Второго пути таймирования не заводим. */
    /* ⛔ УСТАРЕВШУЮ/УХОДЯЩУЮ НЕ ВЗВОДИМ: её отдали событиям швом выхода выше (A2b; прежде здесь буфер
       глушили «сейчас», а события шли с горизонта — дыра до ~300 мс и молчащий аккорд до следующего «вкл»).
       СВЕЖУЮ, ещё не взведённую на этом проходе, — взводим; если до этого её играли СОБЫТИЯ (заморозили на
       ходу, либо снова стала свежей) — сперва шов ВХОДА (A2). */
    if(frz){ const segEndT=timeAt(hi+off);
      for(const f of frozen.values()){
        if(freezeState(f.layer)!=='fresh') continue;
        const sw=f.swap;
        if(sw){
          if(sw.seam){ if(segT>=sw.at-1e-6){ f.swap=null; f.evRun=false; frzArm(f, lo, segT, rep); } }   // AF2: проход после шва — буфер (отметку снимет tick)
          else if(!sw.cut){ if(sw.at<=segEndT+1e-6) frzSwapCut(f, rep); }                                // AF2: окно дошло до доли подмены — срез голосов (всё ДО неё уже поставлено)
          else if(rep!==sw.rep) f.swap=null;                                                              // подмена была в прошлом проходе (tick ещё не дошёл до отметки) — новый проход взводим как обычно
          if(f.swap) continue; }
        if(f.armedRep===rep || f.evRun) continue;          // evRun без подмены — её спланирует начало следующего отрезка
        frzArm(f, lo, segT, rep); } }
    /* ГРАНИЦА ПРОХОДА — гасим голоса дорожек по ЯВНОМУ времени. ⚠️ НЕСУЩЕЕ, а не косметика: события
       АРАНЖИРОВКИ несут открытия без закрытий, и в петле их гасил ровно этот вызов. */
    if(cyc && segEnd>=edge-1e-9){
      /* ⛳ AF2-fix: ПОДМЕНА НА ШВЕ — голоса прохода этой дорожки уходят В МИГ ШВА (равномощно, FRZ_XF), а не своим отпусканием. Найдено пробой
         («шов: скачок 4.4 дБ»): одними событиями новый проход тут же забирает те же голоса пула (cvAlloc берёт первый свободный — отпущенные
         на шве) и рубит их хвосты; у буфера на шве прежний узел тоже глушится (frzArm). А при подмене голоса никто не забирал — хвост
         долгого пада (1.8 с) звучал поверх нового прохода из буфера: двойное отпускание, ровно то, что AF2 чинил внутри прохода. */
      if(frz){ const eT=timeAt(edge); for(const f of frozen.values()){ const sw=f.swap;
        if(sw && sw.seam && !sw.seamCut && Math.abs(sw.at-eT)<1e-6){ sw.seamCut=true; AUD.voicesCut(k=>layerOfOwner(k)===f.layer, eT, sw.xf); } } }
      releaseLoopLayersAt(timeAt(edge));
      chasePlay(R.from, timeAt(edge), false);           // S3.5c: следующий проход начинается с R.from — поднять аккорды/бас, открытые к нему, ПО ТОМУ ЖЕ времени шва и ДО событий прохода (они пойдут следующим оборотом цикла). R.from=0 — пусто и бесплатно
    }
    loop.sched=segEnd;
  }
}
/* Гашение голосов ДОРОЖЕК (owner 'loop:'/'bassloop:'/'leadloop:'), по явному времени. Читает hold СЕЙЧАС.
   ⛳ S3.3 СМЕНИЛ ЕМУ ПОВОД, НЕ УСТРОЙСТВО. Звали его с границы повтора; границы больше нет, и теперь
   зовут ДВА места: заглушение дорожки (S1, с номером слоя) и КОНЕЦ ПЕСНИ (stopAtEnd, без номера).
   ⚠️ КОНЕЦ ПЕСНИ — НЕ КОСМЕТИКА, а необходимость: события АРАНЖИРОВКИ не несут выключений вовсе
   (buildArrangement кладёт chOn/bassOn без пары), и в петле их гасил именно заворот. Без этого вызова
   последний аккорд подложки звенел бы после конца песни бесконечно. Записанные игроком ноты свои
   выключения имеют — это гарантировал слайс S3.1.
   ⛳ layer — НЕОБЯЗАТЕЛЬНЫЙ фильтр (слайс S1): задан — гасим РОВНО этот слой (заглушение дорожки),
   не задан — ВСЕ дорожки разом (конец песни, перемотка). Обход ключей владельцев остаётся ОДИН:
   второй такой же цикл в другом месте рано или поздно разошёлся бы с этим.
   ⚠️ Сравниваем ХВОСТ ключа целиком ('loop:3' → '3') или хвост с двоеточием ('leadloop:3:0' → '3:'),
   а не просто начало: иначе слой 1 забрал бы и слой 12. */
/* ⛳ part (A2) — НЕОБЯЗАТЕЛЬНЫЙ: не задан — всё, как было; 'pool' — только аккорды и бас (их гасят по
   явному времени шва заморозки); 'lead' — только соло (оно «почти сейчас», его гасит tick, когда шов
   наступил). Обход ключей остаётся ОДИН — ради этого параметр, а не второй цикл в frzEnter. */
function releaseLoopLayersAt(when,layer,part){
  const own = layer==null ? null : String(layer);
  const hit = (k,pre)=>{ if(k.slice(0,pre.length)!==pre) return false;
    if(own==null) return true;
    const rest=k.slice(pre.length);
    return rest===own || rest.slice(0,own.length+1)===own+':'; };
  if(part!=='lead'){
    for(const k of Object.keys(chordHold)) if(hit(k,'loop:')) chordOff(k,when);
    for(const k of Object.keys(bassHold))  if(hit(k,'bassloop:')) bassOff(k,when);
  }
  if(part==='pool') return;
  /* СОЛО-СЛОИ гасим тем же обходом — страховка от ноты без пары (её мог оставить слой аранжировки или
     старая запись). Ноты, записанные игроком, свои выключения имеют с S3.1.
     ⛳ `when` СОЛО ПРИНИМАЕТ (S2 дал leadOff явное время), но ЗДЕСЬ МЫ ЕГО НАМЕРЕННО НЕ ПЕРЕДАЁМ: лид
     по-прежнему идёт «почти сейчас» (он не в isLayer), и гасить его по ЗАПЛАНИРОВАННОМУ времени,
     а ставить по стенным часам — значило бы рассинхрон. Перевод лида в планировщик — отдельная,
     СЛЫШИМАЯ работа, и этот слайс её сознательно не делает. */
  for(const k of Object.keys(leadHold))  if(hit(k,'leadloop:')) leadOff(k);
}
/* ═══ ДОГОНЯЛКА (CHASE): ВХОД В ПЕСНЮ НЕ С НАЧАЛА (слайс S3.5c) ═══
   ⚠️ ДЫРА, КОТОРУЮ ЭТО ЗАКРЫВАЕТ. У аккорда и баса ОДИН владелец голоса на слой ('loop:N', 'bassloop:N'),
   и смена аккорда/ступени — это ВЕДЕНИЕ уже звучащего голоса, а не новый: в записи это ОДНО chOn и цепочка
   chSet (защёлка той же плотности зовёт WchSet; бас-рука зовёт WbassOn каждый кадр, и запись всё после
   первого кадра пишет bassSet). А chordGlide / bassSet / leadSet при ОТСУТСТВИИ владельца молча выходят.
   Войди в песню ПОСЛЕ chOn — и все chSet ведут пустоту: роль молчит до следующего «вкл».
   ⛳ ЭТО НЕ ДЕФЕКТ СКОБЫ. Входов «не с начала» четыре, и первый — старше скобы:
     (1) ▶ с паузы посреди песни (S3.3: пауза гасит голоса, пуск продолжает с позиции) — startTransport;
     (2) шов повтора, когда скоба начинается не с такта 1 — scheduleLayers (и tick для соло);
     (3) запуск записи со скобы не с такта 1 — startTransport;
     (4) прыжок скобы на её начало (rgnApply) и seekTo — startTransport/rgnApply.
   Пока область всегда начиналась с 0, (2)–(4) были недостижимы, а (1) просто не замечали; скоба сделала
   дыру ЕЖЕПРОХОДНОЙ.
   СОЛО — ТОЙ ЖЕ ФОРМЫ, но уже: у него «вкл» на КАЖДУЮ ноту, поэтому молчат лишь ноты, ЗАЖАТЫЕ через вход
   (и глиссандо внутри щипка — это leadSet). Ударные — одиночные удары, им догонять нечего. Дрон — УРОВЕНЬ
   с жизненным циклом (droneOn на пуске по droneAudible), а не нота: не затронут.
   ⛳ ЛЕЧЕНИЕ — состояние, которое было бы при игре С НАЧАЛА: для каждого владельца последнее «вкл» до входа и
   последнее «ведение» после него (встреченное «выкл» владельца снимает). Голос поднимается В ЭТОМ состоянии
   ОБЫЧНЫМ ENG.chOn/bassOn/leadOn — по явному времени входа (правило #15), с ЗАМОРОЖЕННЫМ ладом своего
   события (правило #7: ctx — само событие) и с его картой эффектов. ⛔ Второго вывода частоты здесь НЕТ и
   не заводить: частоту выводит ENG, как при любой переигровке.
   ⚠️ Нагрузку склеиваем {...вкл.a, ...ведение.a}: у chSet нет inst (тембр живёт на атаке) — он приходит из
   chOn; всё, что ведение меняет (ступень, регистр, тип, громкость, яркость, эффекты), — из ведения.
   Контекст (лад) — от ведения: это то состояние, что звучало бы на входе.
   ⚠️ «ВЫКЛ» ВНУТРИ СКОБЫ ГАСИТ ДОГНАННЫЙ ГОЛОС КАК ОБЫЧНО: ключ владельца тот же (chaseKey зовёт те же
   chOwnerKey/bassOwnerKey/ldKey, что и ENG), а его chOff/bassOff/leadOff — обычное событие прохода.
   ⚠️ Владелец, у которого РОВНО на доле входа стоит своё «вкл» или «выкл», не догоняется: проход сыграет его
   сам в тот же миг (иначе — лишняя атака, тут же снятая, и украденные голоса пула). */
/* Владельцы, открытые к доле x (события с t<x). ⛳ СТОИМОСТЬ: построение — ОДИН линейный проход по
   отсортированному префиксу до x (O(n) на пятиминутной песне: десятки тысяч событий, доли миллисекунды), и
   ТОЛЬКО когда сменилась доля входа или состав событий. Результат КЭШИРУЕТСЯ по x и сбрасывается в
   schedInvalidate — единственной точке, через которую идёт каждое изменение событий. Поэтому на КАЖДОМ шве
   повтора (скоба не двигается, события те же) стоимость — O(открытых владельцев), то есть число дорожек.
   На тике — НОЛЬ: сюда ходят только шов и запуск, работу по окну из S3.2 это не трогает.
   ⚠️ Проход ВПЕРЁД, а не назад: итог тот же («последнее вкл, затем ведения, выкл снимает»), но одним
   проходом сразу для всех владельцев — обратному пришлось бы всё равно дойти до начала, ведь заранее
   неизвестно, у кого единственное «вкл» лежит на доле 0.
   Хвост записи (за cursN) не входит — это пишущаяся дорожка, её и так не переигрывают; фильтр
   слышимости и пишущегося слоя — при ПРИМЕНЕНИИ (chasePlay), не в кэше: mute/solo меняются без сброса. */
function chaseFor(x){
  if(chaseAt===x) return chaseList;
  const list=[]; chaseAt=x; chaseList=list;
  if(x<=1e-9) return list;                                   // вход с начала песни — догонять нечего, и обход не делаем вовсе
  if(cursN>events.length) cursN=events.length;               // та же страховка, что в cursSeek
  const lb=cursLowerBound(x), st=new Map();
  for(let i=0;i<lb;i++){ const ev=events[i], role=chaseRole(ev.fn); if(!role || (W.recording()&&ev.tk===W.curTake())) continue;   // S3.5c: события взятого звучат живьём — не догоняем (тот же пропуск, что в переигровке)
    const k=chaseKey(role,ev), kind=chaseKind(ev.fn);
    if(kind==='n') st.set(k,{role,on:ev,set:null});
    else if(kind==='t'){ const s=st.get(k); if(s) s.set=ev; }
    else if(kind==='f') st.delete(k);
  }
  for(let i=lb;i<cursN && events[i].t<=x+1e-9;i++){ const ev=events[i], role=chaseRole(ev.fn); if(!role || (W.recording()&&ev.tk===W.curTake())) continue;
    const kind=chaseKind(ev.fn); if(kind==='n'||kind==='f') st.delete(chaseKey(role,ev)); }   // своё вкл/выкл ровно на входе — проход сыграет сам
  for(const s of st.values()) list.push(s);
  return list;
}
/* Поднять догнанные голоса к доле x по времени when. lead=false — слои (аккорд/бас: они идут вперёд по
   планировщику), lead=true — соло (оно «почти сейчас», зовётся из tick на шве или со своим when из запуска). */
/* only (A2b) — НЕОБЯЗАТЕЛЬНЫЙ номер слоя: догнать ТОЛЬКО эту дорожку. Шов выхода из заморозки — это вход в
   середину песни для одной дорожки, и догонялка та же самая; сворачивание (chaseFor) при этом общее и
   кэшированное по доле, так что десять дорожек на одном шве стоят одну свёртку. */
/* ⛳ T4b2: НАГРУЗКА ДОГНАННОЙ НОТЫ — ОДНА ЧИСТАЯ ФУНКЦИЯ (её же сверяет проба P.checkLogic с прежней сборкой legacyChaseNote).
   Склейка {...вкл.a, ...ведение.a} и контекст — прежние. ⛳ ПОЧИНКА ДЕФЕКТА T4b1 (найден при T4b2): у НОТЫ ТЕРМЕНВОКСА ведения с hold
   несут ЖИВУЮ ближайшую ступень, и T4a поставил им её индекс; склейка возвращала ступень и регистр АТАКИ, но индекс оставляла от
   ведения — а звук с T4b1 считает высоту ПО ИНДЕКСУ: вход посреди удержанной ноты терменвокса звучал бы от чужой опоры (бенд — от
   неверной ступени). Теперь индекс берётся у атаки вместе со ступенью и регистром. */
function chaseNote(s,x){
  const hold=!!(s.set&&s.set.a.hold);                       // терменвокс: ведение с hold несёт ЖИВУЮ ступень, а высоту — бенд от ступени АТАКИ
  const a={...s.on.a, ...(s.set?(s.role==='ld'?s.set.a:noInst(s.set.a)):null)};   // T0-fix: у СОЛО тембр — от последнего ведения (нота переливается живьём, в точке входа звучал он); у баса — от атаки (он печётся на «вкл», ведение его не несёт); у аккорда в chSet тембра нет вовсе
  const ctx=(s.set&&!hold)?s.set:s.on;
  if(s.role==='ld'){
    if(hold){ a.oct=s.on.a.oct; a.ti=s.on.a.ti; }   // T4b2: ИНДЕКС и регистр атаки (см. шапку). ⛳ T4c-1: ступень не копируется (её не читает никто) — живую ступень ведения снимаем, чтобы не лежала чужая
    /* The bend curve counts from the attack; the chase plays its REST: config.bendPlan enters it at bendFrom beats (its value there,
       then what follows — mid-glide included). Without it the glissando would restart from the attack. */
    const B=s.on.a.bend;
    if(B&&B.length){ a.bend=B; a.bendFrom=x-s.on.t; }
  }
  return {a,ctx};
}
function chasePlay(x,when,lead,only){
  const list=chaseFor(x); if(!list.length) return;
  const gated=laneGated();
  for(const s of list){
    if((s.role==='ld')!==lead) continue;
    const ly=s.on.layer;
    if(only!=null && ly!==only) continue;
    /* S3.5c: пропуска «весь пишущийся слой» здесь БОЛЬШЕ НЕТ — он заглушил бы старые аккорды/бас вооружённой
       дорожки на входе. Живое (события взятого) отсеяно ещё при построении (chaseFor), тем же правилом, что
       в переигровке. */
    if(gated&&!laneAudible(ly)) continue;                     // заглушённая / молчащая из-за чужого соло — догнанной ноты у неё быть не должно
    if(frzChaseSkip(ly)) continue;                             // AF2: см. frzChaseSkip (прежде frzLayer||frzBufOwns — без подмены впереди). F4: ЗАМОРОЖЕННОЙ ДОГОНЯЛКА НЕ НУЖНА — у источника буфера есть СМЕЩЕНИЕ, вход посреди ноты играет с середины сэмпла сам. A2c: и УСТАРЕВШЕЙ, чей буфер ещё звучит (взведён), — её передаст событиям frzLeave на своём шве; догони мы её здесь, голос открылся бы дважды
    const {a,ctx}=chaseNote(s,x);
    if(s.role==='ch'){ W.ENG.chOn(a,ctx,{when}); setLoopChordHl(a,ctx.sc); }   // T4b4: подсветка — из индекса (hlOf)
    else if(s.role==='bs') W.ENG.bassOn(a,ctx,{when});
    else {
      W.ENG.leadOff(a,ctx,{when});                              // хвост прошлого прохода в том же владельце (событие у конца скобы) — снять, чтобы догнанная нота встала СВЕЖЕЙ атакой, а не глиссандо из чужой
      W.ENG.leadOn(a,ctx,{when});
    }
  }
}
/* 2) ЛИД/дрон — почти-сейчас (как раньше): события в (a,b] БЕЗ when → AC.currentTime. Слои тут пропускаем.
   ⚠️ УСЛОВИЯ РАЗВЁРНУТЫ В continue-ветки (было одно длинное &&) РАДИ ЧИТАЕМОСТИ ПОСЛЕ ДОБАВЛЕНИЯ
   ГЕЙТА ДОРОЖЕК — набор условий и их смысл не изменились. */
/* ⛳ У fireNear СВОЙ КУРСОР, а не общий со scheduleLayers — и это вынужденно, а не по вкусу. Три
   различия, каждого хватило бы: (1) ВРЕМЕННÁЯ БАЗА другая — здесь позиция ИГРЫ (loop.pos), там
   горизонт ОПЕРЕЖЕНИЯ, и они расходятся на SCHED_AHEAD; (2) интервал полуоткрыт С ДРУГОЙ СТОРОНЫ
   ((a,b] против [lo,hi)). ⛳ Третье различие — «на завороте fireNear зовут ДВАЖДЫ за тик, с прыжком
   назад к нулю» — S3.3 УБРАЛ вместе с заворотом; двух оставшихся по-прежнему достаточно.
   В СТРОЮ они держатся тем, что оба перепривязываются через ОДНУ функцию (schedInvalidate) и делят
   ОДНУ границу отсортированного префикса cursN.
   ⚠️ lower_bound даёт первое t>=a, а нам нужно строгое t>a — разницу снимает ОСТАВЛЕННАЯ явная
   проверка ev.t<=a: курсор может встать на одно событие раньше, и это безвредно по построению. */
function fireNear(a,b,rep=0){                                  // rep (A2b) — номер прохода скобы, к которому принадлежит интервал: шов заморозки сравнивается парой (проход, доля) — см. frzSkipNear
  const gated=laneGated();                                   // как в scheduleLayers: считаем один раз на вызов
  const frz=frozenOn();                                      // F4: так же дёшево, пока ничего не заморожено
  let i=cursSeek(curNear,a);
  for(; i<cursN && events[i].t<=b; i++){
    const ev=events[i];
    if(isLayer(ev.fn)||ev.t<=a) continue;
    if(W.recording()&&ev.tk===W.curTake()) continue;                    // S3.5c: как в scheduleLayers — только события этого взятого
    if(gated&&!laneAudible(ev.layer)) continue;              // заглушённая / молчащая из-за чужого соло дорожка
    if(frz&&frzSkipNear(ev,rep)) continue;                      // F4: заморожена — её соло/дрон играет буфер, а не события. A2/A2b: у швов входа и выхода — по доле шва (см. frzSkipNear)
    W.ENG[ev.fn](ev.a,ev);
    if(frz&&ev.fn[0]==='l') frzLeadRecut(ev);                  // AF2: соло-событие до подмены, сыгранное после постановки среза, — срезать и его голос в миг подмены
  }
  curNear.i=i; curNear.at=b;                                 // следующий вызов придёт с a===b и продолжит без поиска
}
/* ⛳ ВОССТАНОВЛЕНО В S3.4, И ИМЕННО КАК РЕШЕНИЕ, А НЕ КАК НАСЛЕДСТВО — тумбстоун S3.3 требовал
   решить заново, вот решение и довод.
   ЧТО ДЕЛАЕТ: на границе прохода гасит ЖИВЫЕ голоса руки ('lead:*') и живой бас, чтобы ещё зажатая
   рука ПЕРЕАТАКОВАЛА их с начала следующего прохода. Без этого удержанная нота тянулась бы сквозь шов
   одним непрерывным звуком, а записанный проход начинался бы с уже звучащей ноты — то есть на слух
   «повтор без начала». Для повторяемого участка переатака и есть верное поведение: каждый проход
   должен звучать одинаково, а значит и начинаться одинаково.
   ⛔ ЖИВОЙ АККОРД ('latch') НЕ ТРОГАЕМ — ПРАВИЛО #20. Защёлкнутый или удержанный аккорд принадлежит
   РУКЕ, а не повтору, и обязан пережить сколько угодно границ, пока игрок не отпустит пальцы или не
   сменит аккорд. Лид и бас так можно, а аккорд нельзя, и причина техническая: их зажатая рука
   переатакует со следующего кадра, а живой путь аккорда (WchSet→chordGlide) удалённые голоса НЕ
   ПЕРЕСОБИРАЕТ — погасив, мы бы его потеряли насовсем.
   ⚠️ ЛИД ГАСИМ ИЗБИРАТЕЛЬНО, только 'lead:*': в пуле голый обход снёс бы и переигранные соло-дорожки,
   у которых своя граница (её держит releaseLoopLayersAt).
   ⛳ СОЛО БОЛЬШЕ НЕ ПЛАТИТ (S3.5a-fix): во время записи вместо голого сброса — recFoldRoll, который
   закрывает удержанную ноту НАСТОЯЩИМ leadOff на конце прохода и поднимает базу номеров. Зажатая рука
   переатакует со следующего кадра и откроет НОВУЮ ноту с новым номером. Если кадр жестов успел
   раньше тика, шов уже обработан, и вызов здесь ничего не трогает — открытая нота нового прохода
   ОСТАЁТСЯ открытой (сброс здесь сделал бы её сиротой; поэтому recLeadReset — только вне записи).
   ⛳ БАС БОЛЬШЕ НЕ ПЛАТИТ (S3.5d-fix): здесь стояло «recBass=null без bassOff — удержанный через шов бас оставляет bassOn
   без пары». Починено тем же приёмом, что у соло: при записи бас закрывает recFoldRoll настоящим bassOff на конце прохода
   (см. последнюю строку функции ниже и сам recFoldRoll).
   ⛳ P2: живой бас гасим ПО ВСЕМ ЖИВЫМ ВЛАДЕЛЬЦАМ ('bass' и 'bass:…'), а не одним литералом 'bass': у полифонического баса
   (V2/V3) живых владельцев несколько, и нота второго иначе пережила бы шов. Ключи дорожек ('bassloop:…') не трогаем — у
   них своя граница (releaseLoopLayersAt). В ведущем режиме владелец один — прежнее поведение. */
const isLiveBassOwner=k=> k==='bass' || k.slice(0,5)==='bass:';
function liveWrapRelease(){ if(!AC)return;
  for(const k of Object.keys(leadHold)) if(k.slice(0,5)==='lead:') leadOff(k);
  for(const k of Object.keys(bassHold)) if(isLiveBassOwner(k)) bassOff(k);
  if(W.recording()) recFoldRoll(); else { recLeadReset(); W.recBass.clear(); }   // S3.5d-fix: при записи бас закрывает recFoldRoll (как соло); голое обнуление здесь осиротило бы бас-ноту, уже открытую в НОВОМ проходе, если кадр жестов успел раньше тика
}
function schedClicks(){                                // щелчки метронома с опережением по AC-часам
  const spb=secPerBeat(), ahead=AC.currentTime+SCHED_AHEAD;
  while(timeAt(loop.clickBeat)<ahead){
    const bt=timeAt(loop.clickBeat), inCount=loop.cnt&&loop.clickBeat<loop.lead;   // S3.5b: отсчёт — щелчки ДО доли запуска (при старте с 0 это прежнее clickBeat<0)
    /* Просроченный щелчок (bt в прошлом — зависание ДЛИННЕЕ окна) НАМЕРЕННО пропускаем, а не играем
       поздно: поздний щелчок слышен как «флам»/спотыкание (хуже, чем разовый пропуск, который ухо
       достраивает). С окном 0.30с пропуски редки; слои же наоборот — просроченные играем (звучат
       поздно, но не рвут состояние аккорда/баса; деградация к прежнему поведению на огромных столах). */
    if(bt>=AC.currentTime-0.001&&(inCount||W.recording()))
      metroClick(bt, beatLevel(loop.metre, (((loop.clickBeat%loop.metre)+loop.metre)%loop.metre)));   // акцент по ГРУППЕ, не только по началу такта
    loop.clickBeat++;
  }
}
/* ⛳ ТИК: ЛИНЕЙНЫЙ ПО УМОЛЧАНИЮ, С ЗАВОРОТОМ ОБЛАСТИ КАК ЧАСТНЫМ СЛУЧАЕМ (S3.4).
   S3.3 снял отсюда заворот и три его последствия; S3.4 вернул ровно их, переанкеренными на [from,to):
     (1) `fireNear(loop.pos, rgn.to)` — домести хвост прохода до его конца;
     (2) `liveWrapRelease()` — переатака удержанной руки с начала прохода (воскрешено, см. выше);
     (3) `fireNear(rgn.from-1e-9, p)` — и доиграй от начала прохода.
   Ветка `loop.first` НЕ вернулась и не вернётся: запись останавливают явно, это решение S3.3.
   ⛔ ПРИ ВЫКЛЮЧЕННОЙ ОБЛАСТИ songAt — тождество, `p<loop.pos` не наступает НИКОГДА, и остаётся ровно
   та единственная ветка `else`, что была в S3.3. Линейное поведение байт-в-байт. */
function tick(){
  if(!loop.on||!AC)return;
  schedClicks();
  scheduleLayers();                                   // СЛОИ — вперёд по явному времени (сэмпл-точно)
  const m=beatNow();       // МОНОТОННАЯ доля
  if(m<loop.lead)return;                              // отсчёт/разгон: только щелчки/планирование. ⚠️ lead, а не 0 (S3.5b): старт с доли 8 давал «отсчёт» по долям 4..8 ≥0 — с ним лид звучал в отсчёте, а бегунок стартовал с pos=8 при p=4 и тик принимал это за ЗАВОРОТ (гасил живые голоса и мёл хвост скобы). С доли 0 lead=0 — как было
  if(W.latchOpenAt()!=null && W.recording()) recLatchOpen();  // ⛳ первый тик ПОСЛЕ отсчёта: звучащая защёлка ложится в дубль с доли начала записи (см. recLatchOpen)
  const p=songAt(m);                                  // ПЕСЕННАЯ доля (при выключенной области — она же)
  const rep=cycling()?rgnReps(m):0;                   // A2b: номер прохода — для швов заморозки (fireNear/frzNearDone), та же формула, что у планировщика
  if(frozen.size) frzLeadAhead();                     // AF2: срез соло-голосов дорожки на миг подмены — заранее, по явному времени (соло идёт «почти сейчас»)
  if(cycling() && p<loop.pos){                        // заворот области: позиция ушла назад — тот же тест, что был у петли. cycling() — явно (S3.5b): без повтора заворота нет по определению, и ложный «назад» (разгон после старта) не должен гасить живые голоса
    fireNear(loop.pos,loop.rgn.to,rep-1);             // хвост ПРОШЛОГО прохода
    liveWrapRelease();
    chasePlay(loop.rgn.from,undefined,true);          // S3.5c: соло, зажатое через начало скобы, — поднять ДО событий прохода (fireNear ниже), «сейчас», как и весь лид. Скоба с такта 1 — пусто и бесплатно
    fireNear(loop.rgn.from-1e-9,p,rep);
  }else fireNear(loop.pos,p,rep);                     // лид/дрон — «почти сейчас», интервал (pos, p]
  loop.pos=p;
  if(frozen.size) frzNearDone(rep,p);                 // A2/A2b: пройденные швы заморозки — снять отметки (вход: соло-голоса слоя отдать буферу; выход: отпустить разморожённую запись)
  /* ⛳ O-2: ЗАХВАТ — ЗДЕСЬ, И МЕСТО ВЫБРАНО, А НЕ СЛУЧИЛОСЬ. Три свойства даёт именно эта точка:
       • ОТСЧЁТ УЖЕ ОТСЕЯН — выше стоит `if(m<loop.lead)return`, тот же порог, по которому отказывает push:
         автоматика взятого не может начаться раньше его первой ноты;
       • ДОЛЯ ПЕСЕННАЯ (p=songAt(m)), а не монотонная, — значит под крутящейся скобой захват сворачивается
         в неё ровно как события (ту же путаницу двух долей полоса лупера однажды уже пережила);
       • ПЛАНИРОВАНИЕ УЖЕ ОТРАБОТАЛО (schedClicks/scheduleLayers в начале тика) — обход идёт ПОСЛЕ него и
         окна опережения не задевает (правило #15). */
  takeCapSample(p);
  /* ⛳ O-3: и ВЕДЁМ ЗАПИСАННУЮ АВТОМАТИЗАЦИЮ — из того же сердца, по той же ПЕСЕННОЙ доле и после того же
     отсчёта, что и захват. ⛔ ТОЛЬКО НЕ ВО ВРЕМЯ ЗАПИСИ: иначе захват (строкой выше) снял бы наши же
     величины как «сыгранные рукой», и автоматизация писала бы сама себя. Хозяин величины ровно один:
     пока пишем — рука, пока играем — запись. */
  if(!W.recording()) fxPlayDrive(p);
  /* КОНЕЦ ПЕСНИ. Во время записи НЕ останавливаемся: игрок как раз дописывает материал за прежним
     концом. ⛔ И ПРИ ВКЛЮЧЁННОЙ ОБЛАСТИ не останавливаемся никогда — она затем и включена, чтобы
     играть по кругу; иначе транспорт вставал бы на первом же достижении конца песни. */
  if(!W.recording() && !cycling() && m>=songLen) stopAtEnd();
}
/* Останов по достижении конца материала. ⛔ НЕ softAllOff: тот погасил бы и ЖИВЫЕ руки, а человек
   в этот момент может держать ноту — инструмент не обязан замолкать оттого, что кончилась запись.
   Гасим ровно голоса ДОРОЖЕК (у событий аранжировки нет выключений — см. releaseLoopLayersAt) и дрон. */
function stopAtEnd(){
  loop.on=false; clearPump(); fxPlayStop();   // O-3: транспорт встал — состав цепи снова человеческий
  releaseLoopLayersAt();
  frzStopAll();                              // F4: и замороженные источники — конец песни для них тот же
  droneOff();
  schedInvalidate();
  hooks.loop && hooks.loop(false);
}
/* from — АБСОЛЮТНАЯ доля, с которой начинаем. t0 считаем так, чтобы в момент начала (после отсчёта,
   если он есть) позиция была ровно `from`: t0 = сейчас + отсчёт − from·spb. */
function startTransport(countIn, from=0){
  clearPump();
  /* ⛳ ГЛАВНАЯ точка сброса: временнáя база прыгает (pos/sched/t0 переставляются ниже). Покрывает старт
     записи, снятие паузы и старт от аранжировки.
     ⚠️ ПЕРЕНЕСЕНА ДО переустановки опоры (S3.5b): schedInvalidate теперь зовёт rgnSync, а тот при идущем
     транспорте перепривязывает опору по ТЕКУЩИМ t0/sched. Вызов посреди переустановки (sched уже новый,
     t0 ещё старый) испортил бы sched. До неё — опора ещё целиком старая и согласованная, а всё, что
     перепривязка сдвинет, ниже всё равно перезапишется. Сброс курсоров от порядка не зависит. */
  schedInvalidate();
  const spb=secPerBeat();
  loop.on=true; loop.lead=from; loop.cnt=!!countIn; loop.pos=from-1e-9; loop.sched=from;   // −1e-9: интервал fireNear полуоткрыт слева, иначе событие ровно в `from` не сыграло бы; lead — до этой доли тик молчит (отсчёт/разгон 60мс)
  loop.t0=AC.currentTime+(countIn?loop.metre*spb:0.06)-from*spb;   // отсчёт — ОДИН такт (loop.metre долей), при любом размере (предсказуемое правило)
  loop.clickBeat=Math.floor(from)-(countIn?loop.metre:0);   // щелчки идут от той же доли; при отсчёте — на такт раньше
  /* S3.5c: вход НЕ с начала песни (▶ с паузы, запись со скобы, seekTo) — догнать открытые к `from` аккорды,
     бас и соло ПО ТОЧНОМУ времени начала игры (после отсчёта/разгона). С доли 0 — не зовём вовсе. */
  if(from>1e-9){ const T=timeAt(from); chasePlay(from,T,false); chasePlay(from,T,true); }
  /* ⛳ F4: СБРАСЫВАЕМ ВЗВЕДЕНИЕ, А НЕ СТАРТУЕМ ЗДЕСЬ. Узлы поставит планировщик — из своего цикла и
     своей формулой времени (правило #15): armedRep=null заставит его взвести их на ближайшем тике.
     ⛔ Стартовать источники прямо тут значило бы завести ВТОРОЙ путь таймирования рядом с первым. */
  /* A2b: evRun — кто владеет дорожкой в этом прогоне с пуска. Свежую пуск отдаёт буферу (догонялка выше её
     пропустила — голосов нет); устаревшую — событиям (догонялка её подняла), и если она станет свежей на
     ходу, шов ВХОДА погасит эти голоса. Копия списка — frzStopOne отпускает разморожённые на ходу записи. */
  for(const f of [...frozen.values()]){ frzStopOne(f, AC.currentTime); f.evRun=freezeState(f.layer)!=='fresh'; }
  /* ⛳ AF6b-fix: ПЕРВОЕ ОКНО ПЛАНИРУЕМ СРАЗУ, в этом же вызове, а не первым тиком через 25 мс. Разгон до первой доли — 60 мс; заминка
     главного потока на старте (сборщик мусора, тяжёлый кадр) длиннее этого делала первый отрезок ОПОЗДАВШИМ: события звучали позже, а
     замороженный узел стартовал «с опозданием» со сдвинутым смещением (frzStart) — в разных пусках по-разному (проба AF6b получила
     «разные чтецы» в двух прогонах). Теперь окно опережения расписано до любой заминки; тик дальше идёт как шёл. */
  scheduleLayers();
  pumpTimer=setInterval(tick,SCHED_TICK_MS);
  hooks.loop && hooks.loop(true);
}
/* ⛳ ПЕРЕМОТКА (S3.3). Минимальная и единственная форма: начало отсчёта времени пересчитывается из
   целевой доли, всё остальное (курсоры, планировщик) подхватывается через schedInvalidate.
   ⚠️ UI СКРАББИНГА В ЭТОМ СЛАЙСЕ НЕТ — возможность выставлена, а ездит по ней пока ровно один путь:
   «доиграли до конца → следующий пуск с начала» (см. onLoop). Полноценная перемотка мышью/пальцем
   придёт вместе с таймлайном редактора.
   ⛔ Во время ЗАПИСИ перемотка запрещена: она разорвала бы уже открытые ноты, у которых выключение
   ещё впереди (их закрывает recAllOff на явной остановке). */
function seekTo(beat){
  if(!AC||W.recording())return;
  const b=Math.max(0,beat);
  releaseLoopLayersAt();                                   // прыжок во времени — звучащие голоса дорожек к нему не относятся
  frzStopAll();                                            // F4: источник буфера одноразов — прыжок means новый узел, старый глушим
  if(loop.on) startTransport(false,b);                     // играем — перезапускаем насос с новой базой
  else { loop.pos=b-1e-9; loop.sched=b; loop.t0=AC.currentTime-secOf(b); schedInvalidate(); }
}

