/* ═══════════ ВЫРАЗИТЕЛЬНОСТЬ («смычок») — ВСЕ настройки в ОДНОМ месте (крутят НА СЛУХ) ═══════════
   Метафора смычка: рука не ЗАДАёт звук, а КОРМИТ энергию, которую система тратит. МАЛО ВХОДОВ →
   БОГАТАЯ внутренняя динамика (резонатор энергии, дрейф тембра, инерц-пружина). Живость даёт именно
   средний слой, а не число параметров — не «упрощать» его в прямое отображение признак→узел.
   ЧЕТЫРЕ признака, и каждый ведёт СВОЮ ось звука (в этом весь смысл; см. tickExpr/applyExpr):
     ЭНЕРГИЯ    = скорость центра ладони      → ЖИВОСТЬ (шиммер высоты+амплитуды)
     НАТЯЖЕНИЕ  = сжатость кисти (центр→кончики) → ВАУ (резонансный пик бежит по частоте)
     РАЗМАХ     = попарный разлёт кончиков    → ТЕКСТУРА (характер искажения: тёплое ↔ грязное)
     НАКЛОН     = наклон плоскости ладони     → ПРОСТРАНСТВО (эхо)
   Раньше три канала из четырёх толкали ЯРКОСТЬ, и всё ощущалось как ОДНА ось, поделённая на четыре
   способа — поэтому яркость как ось убрана. НЕ направлять два канала в одно измерение восприятия.
   Всё в звук идёт через ВОЗБУЖДЕНИЕ (накачка-и-спад, пружина) и setTargetAtTime, НИКОГДА прямым
   присваиванием: прямое присваивание — ровно то, что делает управление «роботным», а вся фича
   существует, чтобы этого избежать.
   ОБЛАСТЬ: пока ТОЛЬКО соло (роль 'ld'), живьём — в событие не пишем НИЧЕГО (правило #11/#23). */
const EXPR_CFG={
  dtMin:0.005, dtMax:0.10,   // КЛАМП dt (с) — НЕ опционален: застрявший кадр дал бы огромный dt (и лишние суб-шаги). Устойчивость пружины он НЕ обеспечивает — это делает subDt (см. tickExpr)
  subDt:0.008,               // ФИКС. внутренний шаг интегрирования (~125 Гц): динамика суб-шагами, поэтому пружина/резонатор УСТОЙЧИВЫ при ЛЮБОЙ частоте кадров. Прежде f0=2.5Гц самовозбуждалась при dt>~0.075с (реальные ~10-20fps десктопа) → постоянное дрожание ~кадр/2, независимое от руки. ω·subDt=0.13 ≪ 2 — большой запас
  aPos:0.35,                 // сглаживание центра ладони (ema, доля за кадр) — ПЕРЕД дифференцированием (производная усиливает шум)
  tauV:0.12,                 // сглаживание СКОРОСТИ (с) — ПОСЛЕ дифференцирования: гасит скачки джиттера кадр-в-кадр, которые иначе накачивали бы энергию в покое
  v0:0.35, v1:2.5,           // МЁРТВАЯ ЗОНА скорости (размеров ладони/с): ниже v0 — РОВНО 0 (покоящаяся рука с джиттером ≈0.05..0.15 НЕ переходит порог), выше v1 — полный отклик. КНОБ: поднять v0, если в покое остаётся шевеление
  cOpen:1.15, cClosed:0.55,  // ВАУ (сжатость кисти): раскрытая ладонь ≈cOpen (пик вверх), кулак ≈cClosed (пик вниз) — среднее центр→5 кончиков / размер ладони
  orDead:0.20, orFull:0.75,  // ПРОСТРАНСТВО (наклон ладони → эхо): |верт. компонента нормали| ниже orDead — сухо (мёртвая зона у плашмя-к-камере), выше orFull — полное эхо
  sprMin:0.40, sprMax:1.20,  // ТЕКСТУРА (размах пальцев / размер ладони): щепоть ≈sprMin → тёплое, веер ≈sprMax → грязное
  tauT:0.25,                 // сглаживание ПОЗ (натяжение/наклон/размах, с) — поза, не рывок
  tauE:0.4,                  // РЕЗОНАТОР энергии: постоянная спада (с). «Смычок»: движение накачивает ЖИВОСТЬ, стоит — оседает (тон мертвеет)
  kPump:2.5,                 // сила накачки: kPump·tauE=1 → устойчивое E = e (линейный диапазон)
  springF0:2.5, springZeta:0.55,   // ИНЕРЦИЯ (масса-пружина) на ВСЕХ каналах (живость/вау/пространство/текстура): рывок → перелёт-и-оседание = «тело». f0 (Гц), затухание ζ. Устойчива благодаря subDt
  tcNode:0.03,               // сглаживание узлов выразительности, с   (числа стороны звука — глубины/диапазоны — в audio.EXPR_A: обратный импорт запрещён)
  tauEngage:0.3,             // ВВОД/ВЫВОД: плавный кроссфейд к нейтрали за ~эту постоянную (с) — без щелчка на появлении/уходе руки
};
/* smoothstep с мёртвой зоной: <a → 0 (РОВНО), >b → 1, между — гладко. Несущая часть: покоящаяся рука = 0 энергии. */
function smoothstep(a,b,x){ if(b<=a)return x>=b?1:0; const t=clamp((x-a)/(b-a),0,1); return t*t*(3-2*t); }
/* Динамика «смычка» — состояние ИНСТРУМЕНТА, не руки (владелец может смениться, энергия продолжается).
   E резонатор энергии; pres/wid/spat/sat — цели-через-пружину (X позиция, V скорость) = ЧЕТЫРЕ РАЗНЫЕ оси:
   ПРИСУТСТВИЕ (энергия), ШИРИНА (натяжение→фейзер), ПРОСТРАНСТВО (наклон→делей), ТЕКСТУРА (размах→драйв);
   engage кроссфейд к нейтрали. Яркость как ось убрана (была общей для трёх каналов — отсюда и жалоба). */
const EXPR={E:0,presX:0,presV:0,widX:0,widV:0,spatX:0,spatV:0,satX:0,satV:0,engage:0};
let exprPrevT=0;
/* Признаки руки-выразительности из СЫРЫХ lm, нормировано размером ладони (правило #12): sx/sy НЕ трогаем.
   Пишет S.exprE (энергия 0..1 через мёртвую зону), S.exprTsm (натяжение), S.exprMoveT (последнее движение). */
function exprFeatures(S,lm,dt,now){
  const hs=Math.max(dist(lm[0],lm[9]),0.02);
  const cx=(lm[0].x+lm[5].x+lm[9].x+lm[13].x+lm[17].x)/5, cy=(lm[0].y+lm[5].y+lm[9].y+lm[13].y+lm[17].y)/5;
  if(!S.exprPs){ S.exprPs={x:cx,y:cy}; S.exprTsm=null; S.exprVsm=0; S.exprOr=null; S.exprSpr=null; }
  const p=S.exprPs, nx=p.x+EXPR_CFG.aPos*(cx-p.x), ny=p.y+EXPR_CFG.aPos*(cy-p.y);
  const vRaw=Math.hypot(nx-p.x,ny-p.y)/hs/dt;            // скорость в размерах ладони/с (сглаженная позиция → диф.)
  S.exprPs={x:nx,y:ny};
  S.exprVsm+=(vRaw-S.exprVsm)*Math.min(1,dt/EXPR_CFG.tauV);   // сглаживаем СКОРОСТЬ: скачки джиттера кадр-в-кадр иначе пробивали бы мёртвую зону и качали энергию в покое
  S.exprE=smoothstep(EXPR_CFG.v0,EXPR_CFG.v1,S.exprVsm);      // мёртвая зона на СГЛАЖЕННОЙ скорости; покой → РОВНО 0
  /* НАТЯЖЕНИЕ (сжатость кисти) → ШИРИНА (фейзер): РАСКРЫТАЯ ладонь = широко/кружит (1), КУЛАК = узко/просто (0).
     Раскрыть руку интуитивно читается как «дать больше», сжать — как придержать: жест, который человек делает
     БЕЗ обучения. (Раньше вело яркость — убрали, чтобы каналы не сливались.) c — среднее центр→5 кончиков / размер ладони. */
  let cs=Math.hypot(lm[4].x-nx,lm[4].y-ny);               // большой (4) + четыре кончика (FINGER_TIPS) → 5
  for(const f of FINGER_TIPS)cs+=Math.hypot(lm[f].x-nx,lm[f].y-ny);
  const c=(cs/5)/hs, Traw=clamp((c-EXPR_CFG.cClosed)/(EXPR_CFG.cOpen-EXPR_CFG.cClosed),0,1);   // раскрыто (c большое)=1 широко, сжато=0 узко
  if(S.exprTsm==null)S.exprTsm=Traw;
  S.exprTsm+=(Traw-S.exprTsm)*Math.min(1,dt/EXPR_CFG.tauT);
  /* ПРОСТРАНСТВО (наклон ладони → ЭХО/делей). Нормаль плоскости через 0,5,17 (3D, с .z-глубиной MediaPipe).
     Плашмя к камере → нормаль вдоль оси z, |верт. компонента|≈0 (сухо); наклонил ладонь → верт. компонента
     растёт (эхо). Берём МОДУЛЬ (наклон в любую сторону = эхо): знак нормали зависит от хиральности руки (лево/
     право), модуль устойчив к этому. Мёртвая зона orDead у нейтрали. Знак/ось — кноб на слух (если «не та» сторона). */
  const ux=lm[5].x-lm[0].x, uy=lm[5].y-lm[0].y, uz=(lm[5].z||0)-(lm[0].z||0);
  const vx=lm[17].x-lm[0].x, vy=lm[17].y-lm[0].y, vz=(lm[17].z||0)-(lm[0].z||0);
  const nX=uy*vz-uz*vy, nY=uz*vx-ux*vz, nZ=ux*vy-uy*vx, nl=Math.hypot(nX,nY,nZ)||1e-6;
  const orRaw=smoothstep(EXPR_CFG.orDead,EXPR_CFG.orFull,Math.abs(nY/nl));   // мёртвая зона: почти-плашмя → РОВНО 0 сухо
  if(S.exprOr==null)S.exprOr=orRaw;
  S.exprOr+=(orRaw-S.exprOr)*Math.min(1,dt/EXPR_CFG.tauT);
  /* ТЕКСТУРА — РАЗМАХ пальцев: средняя ПОПАРНАЯ дистанция 5 кончиков / размер ладони (10 пар). ОТЛИЧНО от
     натяжения (там — от ЦЕНТРА): рука бывает раскрытой-но-щепотью или сжатой-но-веером. Веер=грязно, щепоть=чисто.
     Мёртвая зона — карта от щепоти (sprMin→0) к вееру (sprMax→1), покоящаяся щепоть = 0 (чисто). */
  const tp=[lm[4],lm[8],lm[12],lm[16],lm[20]]; let sp=0;
  for(let a=0;a<5;a++)for(let b=a+1;b<5;b++)sp+=Math.hypot(tp[a].x-tp[b].x,tp[a].y-tp[b].y);
  const spread=(sp/10)/hs, sprRaw=clamp((spread-EXPR_CFG.sprMin)/(EXPR_CFG.sprMax-EXPR_CFG.sprMin),0,1);
  if(S.exprSpr==null)S.exprSpr=sprRaw;
  S.exprSpr+=(sprRaw-S.exprSpr)*Math.min(1,dt/EXPR_CFG.tauT);
  if(S.exprE>0)S.exprMoveT=now;                           // «последнее движение» → выбор владельца при двух руках
}
/* Динамика + вывод в звук — ОДИН раз за кадр. Владелец = ПОСЛЕДНЯЯ ДВИГАВШАЯСЯ рука-выразительность
   (две руки не дерутся за один инструмент). Ничего не пишем в событие — живьём (как терменвокс-Гц). */
function tickExpr(now,dt){
  let owner=null;
  for(const k in HANDS){ const S=HANDS[k]; if(S.isExpr&&S.seen===now){ if(!owner||(S.exprMoveT||0)>(HANDS[owner].exprMoveT||0))owner=k; } }
  const active=!!owner;
  if(!active&&EXPR.engage<=1e-3)return;                   // ни одной руки-выразительности и уже нейтраль → узлы НЕ трогаем (байт-в-байт как сегодня)
  EXPR.engage+=((active?1:0)-EXPR.engage)*Math.min(1,dt/EXPR_CFG.tauEngage);   // engage — одно-полюсный, устойчив на полном dt
  const e=active?(HANDS[owner].exprE||0):0, T=active?(HANDS[owner].exprTsm||0):0,
        OR=active?(HANDS[owner].exprOr||0):0, SPR=active?(HANDS[owner].exprSpr||0):0;   // OR пространство (наклон), SPR текстура (размах)
  /* СУБ-ШАГ: вся динамика фиксированным малым шагом subDt, сколько бы ни длился кадр. Так пружина (и резонатор)
     устойчивы при ЛЮБОЙ частоте кадров — раньше f0=2.5Гц самовозбуждалась при dt>~0.075с (реальные ~10-20fps
     десктопа с синхронным MediaPipe), давая постоянное дрожание ~кадр/2 вне зависимости от руки. e/T/OR/SPR на
     кадр постоянны. Резонатор энергии («смычок») + инерц-пружина на КАЖДОМ из ЧЕТЫРЁХ каналов (полу-неявный
     Эйлер = «тело»). ЧЕТЫРЕ РАЗНЫЕ цели → четыре РАЗНЫЕ оси звука, а не одна ось четырьмя способами. */
  const w=2*Math.PI*EXPR_CFG.springF0, w2=w*w, zw=2*EXPR_CFG.springZeta*w;
  let rem=dt;
  while(rem>1e-6){
    const h=Math.min(EXPR_CFG.subDt,rem); rem-=h;
    EXPR.E+=(EXPR_CFG.kPump*e-EXPR.E/EXPR_CFG.tauE)*h; EXPR.E=clamp(EXPR.E,0,1);   // энергия → ЖИВОСТЬ (вибрато), НЕ громкость
    EXPR.presV+=(w2*(EXPR.E-EXPR.presX)-zw*EXPR.presV)*h; EXPR.presX+=EXPR.presV*h;   // ЖИВОСТЬ (энергия → глубина вибрато)
    EXPR.widV +=(w2*(T  -EXPR.widX )-zw*EXPR.widV )*h; EXPR.widX +=EXPR.widV *h;       // ВАУ (натяжение → частота пика)
    EXPR.spatV+=(w2*(OR -EXPR.spatX)-zw*EXPR.spatV)*h; EXPR.spatX+=EXPR.spatV*h;       // ПРОСТРАНСТВО (наклон → делей)
    EXPR.satV +=(w2*(SPR-EXPR.satX )-zw*EXPR.satV )*h; EXPR.satX +=EXPR.satV *h;       // ТЕКСТУРА (размах → характер искажения)
  }
  const presE=clamp(EXPR.presX,0,1), widE=clamp(EXPR.widX,0,1), spatE=clamp(EXPR.spatX,0,1), drvE=clamp(EXPR.satX,0,1);
  /* В звук ЧЕТЫРЕ канала 0..1 + engage; мэппинг канал→узел (глубины/диапазоны) — в audio (EXPR_A). Энергия
     (presE) → ЖИВОСТЬ (вибрато), НЕ громкость: громкость целиком у нотной руки. Натяжение (widE) → ВАУ,
     размах (drvE) → ТЕКСТУРА, наклон (spatE) → ПРОСТРАНСТВО. engage: нет руки → всё в нейтраль за ~0.3с. */
  applyExpr(presE, widE, drvE, spatE, EXPR.engage, EXPR_CFG.tcNode);
  setExprDisp(EXPR.engage*EXPR.E);                        // индикатор «ВЫР» — энергия/живость смычка (0 когда отпущено)
  setExprBrightDisp(EXPR.engage*widE);                   // тон точек руки — раскрытость (вау), не отдельная полоса
}

/* ================= ОБРАБОТКА РУК =================
   ПАРСИНГ MEDIAPIPE: result.landmarks — массив рук; в каждой 21 точка
   с нормированными координатами (x,y ∈ 0..1, origin слева-сверху КАДРА). Детектор читает ПОЛНЫЙ кадр.
   ДВЕ РОЛИ координат, строго врозь: (1) СЫРЫЕ lm.x/lm.y — вся гест-математика (щипок pinchRatios,
   размер ладони dist(0,9), какой палец, Z-реверб, пороги): работает и когда рука наполовину за
   кадром; (2) ЭКРАННЫЕ — позиция и попадание (половина/прямоугольник/зона, X-громкость) через
   state.sx/sy: экранный x = sx(lm.x,W) = ремап flipX(lm.x) по state.viewRect ·W, аналогично y.
   sx складывает ЗЕРКАЛО (flipX: фронт зеркалим, тыл нет) и COVER-КАДРИРОВАНИЕ (viewRect из
   config.coverView, пишет drawVideoBackground каждый кадр): холст заполняется суб-прямоугольником
   кадра с соотношением холста (без растяга) + поле CAM_MARGIN внутрь, чтобы рука на крайних
   прямоугольниках ещё была в кадре. ТА ЖЕ область кадрирует картинку — рука и видео не разъедутся.
   Ключевые точки: 4 — кончик большого, 8/12/16/20 — кончики пальцев,
   0 — запястье, 9 — основание среднего (по паре 0–9 меряем «глубину» Z:
   видимый размер кисти стабильнее, чем сырая z-координата модели).
   result.handednesses[i][0].categoryName ('Left'/'Right') — стабильный
   ключ руки между кадрами: у каждой руки свой независимый автомат щипка. */
const HANDS={}; let chOwner=null; let bassOwner=null;   // chOwner — рука защёлки, bassOwner — рука баса
/* ⚠️ leadOwner (ОДНА рука-владелец соло) УДАЛЁН: соло больше не моно. У КАЖДОЙ руки свой голос пула,
   ключ владельца строит ЭТА функция — единственное место, где он собирается.
   ПАЛЕЦ В КЛЮЧЕ ЗАЛОЖЕН СРАЗУ, хотя сегодня всегда null: когда ввод научится видеть несколько прижатых
   пальцев (одна рука — до четырёх нот прямоугольника), многоголосие включится ОДНИМ аргументом здесь,
   а не переделкой владения. Формат совпадает по духу с 'loop:N'/'latch' у аккордов. */
const soloKey=(key,finger=null)=> 'lead:'+handSide(key)+(finger==null?'':':'+finger);
let latchLen=0;   // сколько нот звучит у 'latch': по нему решаем «глиссандо или переатака»
/* handRole (левая='fx' палитра / правая='ноты') УДАЛЁН: привязки роли к handedness не осталось нигде.
   Соло/бас/аккорды берут функцию руки из handFn (handFnOf), палитра типов выбирается ПО ПОЛОЖЕНИЮ —
   одинаково в single-role и в сплите. Ударные палитры не имеют (обе руки бьют по рядам). */
/* Рука-ЛУПЕР (функция 'loop'): нот не играет, командует лупером щипками пальцев. Команды — СОБЫТИЯ, а не
   непрерывный звук: срабатывают РАЗ на формирование щипка (edge), не повторяются в удержании. Раскладка
   thumb+палец: указ.→запись, средн.→пуск/пауза, безым.→отмена слоя, мизинец→очистить ВСЁ (только после
   3с удержания с отсчётом — единственное разрушительное действие). Невозможные команды сообщаются, а не
   молчат. Здесь только логика; кнопки транспорта в UI работают как прежде (это ЕЩЁ один вход). */
function looperMsgSet(text,ok){ setLooperMsg({text, until:performance.now()+LOOPER_MSG_MS, ok}); }
function doLooper(cmd){
  if(cmd==='rec'){                                        // всегда возможно: пусто→запись, играет→наложение, пишет→стоп
    onRec(); looperMsgSet(recording ? t(loop.first?'msg.recording':'msg.overdub') : t('msg.recStop'), true);
  }else if(cmd==='play'){
    if(!loop.on && !events.length){ looperMsgSet(t('msg.noLoop'), false); return; }   // нечего играть
    onLoop(); looperMsgSet(t(loop.on?'msg.play':'msg.pause'), true);
  }else if(cmd==='undo'){
    if(!events.length){ looperMsgSet(t('msg.noLayers'), false); return; }                // нечего отменять
    onUndo(); looperMsgSet(t('msg.undo'), true);
  }else if(cmd==='clear'){
    if(!loop.on && !events.length){ looperMsgSet(t('msg.alreadyEmpty'), false); return; }    // нечего очищать — движок не дёргаем
    clearRec(); looperMsgSet(t('msg.cleared'), true);
  }
}
/* Вызов НА ЗАХВАТЕ щипка (edge) → единичное срабатывание по построению. index/middle/ring — сразу;
   мизинец только заводит 3с-таймер (S.clearT0) и показывает отсчёт, сама очистка — в блоке удержания. */
function fireLooperCmd(S,mf){
  const f=FINGER_TIPS.indexOf(mf);                        // 0 указ · 1 средн · 2 безым · 3 мизинец
  if(f===3){ S.clearT0=performance.now(); S.clearFired=false; setLooperClear(CLEAR_HOLD_MS); return; }
  if(f===0) doLooper('rec');
  else if(f===1) doLooper('play');
  else if(f===2) doLooper('undo');
}
/* ═══ ДИСКРЕТНЫЕ ДЕЙСТВИЯ ПАЛЬЦЕВ — ДЕСКРИПТОРЫ (слайс «д») ═══
   Всё, что движок обязан знать о действии, лежит ЗДЕСЬ, а не в ветках кода: движок не должен опознавать
   действие ПО ИМЕНИ, иначе каждое новое потянет за собой правку гейтов.
     avail()   — осмысленно ли действие ПРЯМО СЕЙЧАС. Это и есть механизм МЯГКОЙ ДЕГРАДАЦИИ: на ладу без
                 палитры (`typedChords` ложен) подписка НЕ СТИРАЕТСЯ, а просто не срабатывает, и палец
                 падает в обычное ведение параметров — не повисает мёртвым. Та же дисциплина, по которой
                 у параметра эффекта палец/ось переживают смену режима: снимать выбор человека молча нельзя.
     region    — где должен оказаться щипок ('palette' — внутри палитры; null — где угодно).
     exclusive — СЪЕДАЕТ ли действие палец. У палитры НЕТ (false): внутри палитры палец выбирает тип,
                 ВНЕ её — по-прежнему ведёт свои параметры эффекта, и разводит их ПОЛОЖЕНИЕ, безо всякого
                 дополнительного правила. У команд лупера было бы true — щипок срабатывает где угодно.
   ⚠️ ПОРЯДОК СТАРШИНСТВА, одной строкой: сперва решает ФУНКЦИЯ РУКИ, потом ПОДПИСКА ПАЛЬЦА. Рука не на
   эффектах ведёт себя ровно как раньше (положение + большой-указательный); рука НА эффектах делает
   только то, что её пальцам назначено. Прежде эти два гейта разводил ПОРЯДОК В ТЕРНАРЕ — палитра стояла
   выше эффектов и молча забирала указательный. */
const ACTIONS={
  chFam:{ id:'chFam', labelKey:'act.chFam', avail:()=>typedChords(), region:'palette', exclusive:false },
};
/* «Действие ВЗВЕДЕНО на этом пальце» — обобщённо, без упоминания конкретного действия. */
const actArmed=(role,hand,finger,actId)=>{
  const a=ACTIONS[actId];
  return !!a && a.avail() && handActOf(role,hand,finger)===actId;
};
/* ⛳ ЕДИНСТВЕННЫЙ ИСТОЧНИК «ЭТА РУКА ВЫБИРАЕТ ТИП АККОРДА ЭТИМ ПАЛЬЦЕМ». Зовётся ДВАЖДЫ — из тернара
   зоны (захват) и из пофреймовой перепроверки внутри зоны 'chFam'. ⛔ НЕ РАЗМНОЖАТЬ: разойдись эти два
   ответа, и ведение оборвалось бы ПОСРЕДИ жеста (палитру можно тянуть до соседней ячейки, не разжимая
   пальцев). Та же дисциплина, что у captureFx и пофреймового цикла в слайсе б.1.
   ⚠️ РУКА НЕ НА ЭФФЕКТАХ → палец 0, дословно как было: это документированная ОДНОРУЧНАЯ МОДЕЛЬ аккордов
   (одна и та же рука берёт тип слева и корень справа — по очереди, аккорд звучит и после размыкания).
   Подписки для неё не существует: назначаемы пальцы ТОЛЬКО у руки-эффектов — тем же законом, по
   которому handFn решает, чем рука ЯВЛЯЕТСЯ. */
const paletteFinger=(key,role,finger)=>
  handFnOf(key,role)==='fx' ? actArmed(role,'fx',finger,'chFam') : finger===0;
/* Роль-половина ЭТОЙ руки СЕЙЧАС: single — глобальный phoneInstr; сплит — замороженная S.role (щипок)
   или живая половина под указательным (lm[8]). Правило #18: в сплите функция руки берётся ПО РОЛИ
   ПОЛОВИНЫ.
   Потребителей два: рука-ВЫРАЗИТЕЛЬНОСТЬ и soloNoteHand (ниже).
   ⚠️ ПЕРЕИМЕНОВАНА ИЗ soloHalfRole (слайс б.1): «solo» в имени стало ложью. Функция и раньше
   отвечала про ЛЮБУЮ роль-половину — соло было лишь у её тогдашних потребителей; теперь роль руки
   спрашивают и для эффектов, где она может быть любой. Тело не тронуто. */
function handHalfRole(key,S,W){
  if(!splitOn) return phoneInstr;
  if(S.pinch) return S.role;
  const lm=S.lm; if(!lm) return null;
  // px через sx (поля кадра); для ВЫБОРА половины клампим в [0,W): рука в полях сатурируется к ближней кромке, а не проваливается в чужую половину
  const px=clamp(sx(lm[8].x,W),0,W-1), hs=phoneHalves(W), h=hs.find(q=>px>=q.rx0&&px<q.rx1)||hs[hs.length-1];
  return h.role;
}
/* «ИГРАЮЩАЯ (нотная) рука СОЛО» — та, чья ГЛУБИНА ведёт назначенный ей параметр (Пласт 3.2).
   ⚠️ Предикат ВОСКРЕШЁН: в Пласте 3.1 он был удалён вместе с прицелом реверба (его единственным
   потребителем был ПОКАЗ). Теперь у него снова один потребитель, но уже НАСТОЯЩИЙ — УПРАВЛЕНИЕ.
   Условия те же: (1) роль-половина этой руки — соло; (2) рука реально играет ноты (не эффекты, не
   лупер, не выразительность — единый закон state.playsNotes). Двух нотных рук — пишут обе, побеждает
   последняя за кадр: ровно тем же правилом жил реверб до 3.1. */
function soloNoteHand(key,S,W){
  return handHalfRole(key,S,W)==='ld' && playsNotes(handFnOf(key,'ld'));
}
/* Раньше у соло сетка обрезалась на высоту нижней полосы эффектов. Полосы больше нет
   (столбики рисуются ПОВЕРХ слева), поэтому ввод считается по ВСЕЙ высоте — как и
   рисуется. Эти две высоты обязаны совпадать: разойдутся — палец будет брать не ту
   ступень, которую видит, и тем сильнее, чем ниже по экрану. */
function degRaw(y,rows,H){ const seg=H/rows;
  let z=Math.floor(y/seg); if(z<0)z=0; if(z>rows-1)z=rows-1;
  return rows-1-z;
}
/* Гистерезис по границам ступеней: чтобы в 19/31-TET (узкие ряды)
   не было «трели» на стыке, соседняя ступень берётся лишь когда
   палец ушёл от границы дальше 16% высоты ряда. */
function degHyst(y,rows,H,prev){
  const seg=H/rows; let d=degRaw(y,rows,H);
  if(prev>=0&&prev<=rows-1&&Math.abs(d-prev)===1){
    const zTop=rows-1-Math.max(d,prev), b=(zTop+1)*seg;
    if(Math.abs(y-b)<seg*ROW_HYST)return prev;
  }
  return Math.min(d,rows-1);
}
/* Гистерезис ОДНОЙ оси — общий движок для колонок и рядов палитры: соседнюю ячейку
   берём, только если палец ушёл от границы дальше hyst её размера. Тот же приём, что
   degHyst по Y; без него на узких ячейках выбор дребезжал бы от дрожания руки. */
function axHyst(v,a0,a1,n,prev,hyst){
  const seg=(a1-a0)/n; let d=Math.floor((v-a0)/seg); if(d<0)d=0; if(d>n-1)d=n-1;
  if(prev>=0&&prev<=n-1&&Math.abs(d-prev)===1){
    const b=a0+Math.max(d,prev)*seg;
    if(Math.abs(v-b)<seg*hyst)return prev;
  }
  return d;
}
/* Попадание в ячейку палитры: ДВЕ независимые одномерные проверки. Сначала X даёт
   колонку (семейство), и только потом её types.length задаёт число рядов для Y —
   порядок важен, наборы могут быть рваными. prev-состояние живёт на РУКЕ (S.pc/S.pr),
   а не в глобальном стейте: новый щипок начинает с чистого листа, а залипшая ячейка
   при этом остаётся выбранной. */
function cellHyst(x,y,x0,x1,y0,y1,fams,prevC,prevR){
  const c=axHyst(x,x0,x1,fams.length,prevC,PAL_HYST_X);
  const nR=fams[c].types.length;
  const r=axHyst(y,y0,y1,nR,(prevR>=0&&prevR<nR)?prevR:-1,PAL_HYST_Y);
  return [c,r];
}
/* Другая рука, всё ещё держащая щипок в той же зоне — для моно-передачи голоса БАСА.
   ⚠️ БАС ВСЁ ЕЩЁ МОНО, соло — уже нет. Не сводить эти две ветки обратно в одну и не «унифицировать»
   их, пока бас не получит такой же пул: у соло передавать нечего (у каждой руки свой голос). */
function otherPinched(key,zone){ for(const k in HANDS){ if(k!==key){ const S=HANDS[k]; if(S.pinch&&S.zone===zone) return k; } } return null; }
function endPinch(key,S){
  if(S.pinch){
    /* СОЛО: просто гасим ноту ЭТОЙ руки — она играла в своём голосе пула.
       ⚠️ ЗДЕСЬ БЫЛА МОНО-ПЕРЕДАЧА («отпустил владелец, а другая рука ещё зажата — отдаём владение ей»).
       Она существовала ТОЛЬКО потому, что голос был один: без неё оставшаяся рука замолкала. С пулом она
       не просто не нужна — она ВРЕДНА: переназначала бы ключ владельца, который теперь означает
       конкретную руку, и вторая рука получила бы чужую ноту. Удалена намеренно, не забыта. */
    /* СОЛО: гасим КАЖДЫЙ звучавший голос по его КЛЮЧУ — рука могла держать до четырёх нот. S.snd хранит
       именно ключи (их собирает блок игры); при одном пальце это ровно один ключ 'lead:L/R', как было. */
    if(S.zone==='ld'){ for(const kk of (S.snd||[])) WleadOff(kk); }
    if(S.zone==='bs'&&bassOwner===key){ const nx=otherPinched(key,'bs'); if(nx)bassOwner=nx; else{ WbassOff(); bassOwner=null; } }   // БАС по-прежнему моно — передача владения ему нужна
    /* 'ch': в ЗАЩЁЛКЕ (S.fn!=='hold') WchOff НЕ зовём — аккорд звучит и после размыкания, лишь отпускаем
       руль. В УДЕРЖАНИИ (S.fn==='hold') размыкание пальцев ГАСИТ аккорд (как соло-hold) и чистит защёлку. */
    if(S.zone==='ch'&&chOwner===key){
      if(S.fn==='hold'){ WchOff('latch'); setLatchDeg(-1); setLatchTy(null); latchLen=0; }
      // ЗАЦЕПКА ОБУЧЕНИЯ: в ЗАЩЁЛКЕ пальцы разомкнуты, а аккорд ЗВУЧИТ дальше — урок «Аккорды» ловит этот момент (в удержании — нет, там аккорд погас выше).
      else if(latchDeg>=0) tutorTap('chordLatch',{deg:latchDeg});
      chOwner=null;
    }
    if(S.zone==='loop'&&S.clearT0!=null&&!S.clearFired){   // мизинец отпущен ДО 3с → очистка ОТМЕНЕНА (ничего не делаем, гасим отсчёт)
      setLooperClear(-1); setLooperMsg({text:t('msg.clearCancelled'), until:performance.now()+LOOPER_MSG_MS, ok:true});
    }
  }
  S.pinch=false; S.adj=null; S.deg=-1; S.slot=-1; S.rect=null; S.ty=null;   // S.rect — гистерезис прямоугольника, как S.pc/S.pr у палитры; S.ty — замороженный на атаке тип аккорда
  S.snd=[]; S.fing={}; S.order=[]; S.touch=new Set();   // многопальцевое состояние: звучавшие пальцы, их ноты, порядок прижатия, гистерезис касания
  S.inert=false; S.fresh=false; S.fn=null;      // размыкание снимает инертность и функцию руки
  S.clearT0=null; S.clearFired=false;           // отсчёт очистки лупера — сброс на размыкании
}
/* ================= КОНСТРУКТОР ЭФФЕКТОВ — Пласт 2, слайс 2.1 (механизм) =================
   Было: один палец = один эффект = одна ось (вертикаль), связка захардкожена в FX_META.
   Стало: СЛОТ ЦЕПИ РОЛИ СОЛО (state.fxChains.ld, Пласт 3.3; прежде fxLayout — индекс всё так же
   = палец) говорит, КАКОЙ эффект на пальце и чем ведётся КАЖДЫЙ его параметр — ось (x/y/z) и
   инверсия. Дефолтная раскладка выведена из FX_META,
   поэтому в ЭТОМ слайсе поведение обязано быть НЕОТЛИЧИМЫМ: те же четыре эффекта, по одному
   параметру, ось 'y', тот же размах 70%, тот же латч.
   ⚠️ ОСИ ОТСЧИТЫВАЮТСЯ ОТ ТОЧКИ ЗАХВАТА ЩИПКА и на СЫРЫХ координатах (правило #12): рука начинает
   «отсюда», куда бы ни пришла, и работает, даже когда наполовину за кадром. sx/sy здесь НЕЛЬЗЯ —
   они несут кадрирование COVER, это про ПОПАДАНИЕ, а не про жест.
   ⚠️ X идёт через flipX (правило #13, единственный источник зеркала): «вправо = больше» обязано
   значить одно и то же на фронтальной и тыловой камере. У Y такой беды нет и не было (вертикаль не
   зеркалится) — потому в старом коде флипа и не встречалось.
   ⚠️ Сплиту ничего не нужно: H в выражении по Y сокращается, а X считается в СЫРЫХ долях кадра, —
   размах не зависит ни от разрешения, ни от ширины половины. */
/* Параметры эффекта = чем читать и куда писать. ДВА РОДА, и они НЕ сведены в один — это и есть находка
   Пласта 1 (не делать вид, что все эффекты — однородный кубик):
   • СТАРЫЕ СКАЛЯРНЫЕ (dly/vib/drv/trm): ровно ОДИН параметр, пишется ровно туда, куда писался всегда —
     в state.fx[k]. ⚠️ Это ТОТ ЖЕ store, что уезжает в событие ноты (payload vib/drv/trm/dly): формат
     записи не меняется, старые петли играют как играли. Через модуль их НЕ гоняем.
   • МОДУЛИ (Пласт 1, пока один — реверб): столько параметров, сколько объявил модуль; читаем/пишем
     нормированное 0..1 (getNorm/setNorm), а перевод в секунды/герцы по лог-шкале живёт в дескрипторе.
   ⚠️ ЖИВЬЁМ, В ЗАПИСЬ НЕ ИДЁТ. Длина и окраска реверба — свойство КОМНАТЫ, а не ноты, и в событие не
   пишутся (тот же закон, что у Гц терменвокса, правило #11). Переигранный слой звучит в ТЕКУЩЕЙ
   комнате — это осознанно; расширение формата события — Пласт 3. */
/* ⚠️ РОЛЬ — ПЕРВЫМ АРГУМЕНТОМ (Пласт 3.5.1). Прежде параметры искались по одному fxId, и это молча
   означало «экземпляр один на всё приложение»: две роли с одним эффектом писали бы одни узлы. Теперь
   дескрипторы берутся у экземпляра ИМЕННО ЭТОЙ роли (fxInstance).
   ⚠️ СТАРЫЕ СКАЛЯРНЫЕ (dly/vib/drv/trm) — ТОЛЬКО У СОЛО, и пустой список для прочих ролей здесь не
   перестраховка, а ЗАЩЁЛКА: их величины живут в ОДНОМ глобальном state.fx и едут в соло-событие ноты
   (см. WleadOn), поэтому «делей у аккордов» без своего store и своей проводки писал бы соло-делей.
   Портирование старых эффектов на прочие шины — не 3.5, а вопрос формата события (3.7). */
const fxParamsOf=(role,fxId)=>{
  if(FX_META.some(m=>m.k===fxId)) return role==='ld' ? [{ get:()=>fx[fxId], set:v=>{ fx[fxId]=v; } }] : [];
  const inst=fxInstance(role,fxId);
  return inst ? inst.params.map(p=>({ get:()=>p.getNorm(), set:v=>p.setNorm(v) })) : [];   // нет эффекта (или ещё нет AudioContext) → [] → цикл записи не сделает ни одного шага
};
/* ЗАХВАТ ПО ПАЛЬЦУ (Пласт 3.4.2): морозим точку отсчёта по ТРЁМ осям и стартовые значения ВСЕХ
   параметров, ПОДПИСАННЫХ НА ЭТОТ ПАЛЕЦ, — по ВСЕЙ цепи, у скольких бы эффектов они ни лежали.
   ⛔ ПОЧЕМУ ЯВНЫЙ СПИСОК ЗАПИСЕЙ, А НЕ МАССИВ ПО ИНДЕКСУ ПАРАМЕТРА. Прежде эффект был один (слот =
   палец), и base[i] отвечал params[i] ПОЗИЦИОННО; тогдашний комментарий запрещал фильтровать base
   именно поэтому — фильтр сдвинул бы индексы, и палец поехал бы НЕ ТОТ параметр («оси перепутались»).
   Теперь позиционного соответствия НЕТ И БЫТЬ НЕ МОЖЕТ: адрес живёт у параметра, и один палец собирает
   параметры РАЗНЫХ эффектов вразбивку. Поэтому запись несёт СВОЙ адрес и СВОЙ сеттер целиком
   ({eff,pIdx,fxId,pa,set,base}), и в пофреймовом цикле НЕТ НИ ОДНОГО ИНДЕКСА, который мог бы
   разъехаться. Прежняя ловушка закрыта не запретом, а формой данных.
   ⚠️ pa — ЖИВАЯ ССЫЛКА на объект параметра, а не копия его полей: ось/инверсию можно менять в меню
   ПРЯМО ВО ВРЕМЯ щипка, и это должно действовать сразу (так было и раньше — цикл читал sl.params[i]
   каждый кадр). Сеттеры state правят объект НА МЕСТЕ ровно ради этого.
   ⚠️ ФИЛЬТР ПО РЕЖИМУ/РУКЕ ОСТАЛСЯ И В ПОФРЕЙМОВОМ ЦИКЛЕ, хотя захват уже отобрал записи: параметр
   могут переключить в «фиксировано» посреди щипка, и палец обязан тут же его отпустить. Прежнее
   правило «фильтр ровно в одном месте» держалось на позиционном base — его больше нет.
   z берётся НЕ здесь, а на первом кадре записи (p0.z=null): глубина сглаживается emaS, и позвать её
   дважды за кадр значило бы дважды продвинуть фильтр. x/y снимаются сразу — как y снимался всегда.
   ⚠️ ПУСТОЙ СПИСОК = НЕТ ЗАХВАТА (S.adj=null): на этом пальце не подписано ничего. Так же, как раньше
   вёл себя пустой слот, — и так же гаснет подсветка столбиков в draw. */
function captureFx(S,finger,lm,H){
  /* РОЛЬ ЗАХВАТА — ОДНО ИМЯ НА ДВА ЧТЕНИЯ (цепь и дескрипторы параметров).
     ⚠️ ЭТО И ЕСТЬ «ОДНА СТРОКА», КОТОРУЮ ОБЕЩАЛ ПРЕЖНИЙ КОММЕНТАРИЙ (слайс б.1): здесь стоял
     литерал 'ld' с доводом «сюда приходят только из зоны fx, а она бывает лишь у соло». Гейты зоны
     теперь пускают сюда ЛЮБУЮ роль, и роль берётся с S — ЗАМОРОЖЕННАЯ НА ЗАХВАТЕ, там же, где
     заморожены S.zone/S.rx0/S.rx1. Это не «ещё один способ узнать роль», а тот же самый: попадание,
     игра и отрисовка обязаны читать ОДНУ величину, иначе палец крутит не ту цепь, что нарисована.
     ⚠️ ПОФРЕЙМОВЫЙ ЦИКЛ РОЛИ НЕ ЗНАЕТ И ЗНАТЬ НЕ ДОЛЖЕН: он идёт по ЗАХВАЧЕННЫМ записям, у каждой
     свой сеттер (p.set) — роль уже «вшита» в замыкание. Потому б.1 его не трогает вовсе. */
  const role=S.role;
  const chain=fxChainOf(role);
  const ent=[];
  chain.forEach((eff,effIdx)=>{
    const ps=fxParamsOf(role,eff.fxId);
    eff.params.forEach((pa,pIdx)=>{
      if(pa.mode!=='drive' || pa.hand!=='fx' || pa.finger!==finger) return;
      const p=ps[pIdx]; if(!p) return;                       // параметр, которого у эффекта нет (реестр пуст до initAudio) — молча мимо
      ent.push({ effIdx, pIdx, fxId:eff.fxId, pa, set:p.set, base:p.get() });
    });
  });
  if(!ent.length){ S.adj=null; S.tutFx=null; return; }
  S.adj={ finger, p0:{ x:lm[4].x, y:lm[4].y*H, z:null }, ent };
  S.tutFx=null;   // S.tutFx — база для зацепки обучения 'fx' (сдвиг эффекта)
}
function processHands(res){
  const W=canvas.width, H=canvas.height, now=performance.now();
  const dtm=exprPrevT?clamp((now-exprPrevT)/1000,EXPR_CFG.dtMin,EXPR_CFG.dtMax):EXPR_CFG.dtMin;   // dt кадра для «смычка», КЛАМП обязателен (застрявший кадр иначе взорвал бы интеграторы)
  exprPrevT=now;
  const seen=new Set();
  const hands=(res&&res.landmarks)?res.landmarks:[];
  const heads=(res&&(res.handednesses||res.handedness))||[];

  for(let i=0;i<hands.length;i++){
    const lm=hands[i];
    let key=(heads[i]&&heads[i][0]&&heads[i][0].categoryName)||('H'+i);
    if(seen.has(key))key+=i;
    seen.add(key);
    /* regOct — РЕГИСТР сыгранной ноты (посчитан игрой: из слота у rect-раскладки, от пальца у узких
       рядов), slot — её слот сетки. Оба нужны потому, что на многопериодной сетке ступень уже НЕ
       задаёт ни высоту целиком, ни прямоугольник подсветки. Пишутся в тех же ветках, что и S.deg. */
    const S=HANDS[key]||(HANDS[key]={pinch:false,deg:-1,oct:0,regOct:0,slot:-1,zone:null,vol:.6,adj:null,sm:{},inert:false,fresh:false,role:null,rx0:0,rx1:0,fn:null,ty:null,clearT0:null,clearFired:false,
      touch:new Set(),order:[],fing:{},snd:[],pr:null});   // МНОГОПАЛЬЦЕВОЕ: прижатые пальцы (гистерезис), порядок прижатия, нота каждого пальца, звучащие сейчас. pr — память РЯДА палитры (пара к S.pc), см. cellHyst
    S.seen=now; S.lm=lm;
    /* X-диапазон роли по УМОЛЧАНИЮ (single-role, сплит выключен): вся ширина [0,W], раздел
       palSplitX(0,W)=CH_PAL_W*W (как было). При splitOn половину выводим из точки щипка и ЗАМОРАЖИВАЕМ
       на S (S.role/S.rx0/S.rx1) рядом с S.zone — чтобы чтение при игре совпало с захватом. */
    const [rx0,rx1]=[0,W], split=palSplitX(rx0,rx1);

    /* МНОГОПАЛЬЦЕВЫЙ ЩИПОК. r — отношения по ВСЕМ четырём пальцам (они и так считались), touch —
       множество прижатых. S.order хранит ПОРЯДОК прижатия: первый прижатый остаётся ГЛАВНЫМ пальцем,
       пока держится, — от него берутся позиция/зона/громкость (у руки одно положение на всех её нот),
       а остальные добавляют СВОИ ноты. Стабильный порядок важнее «ближайшего»: иначе главный палец
       перескакивал бы между кадрами и дёргал позицию.
       ⚠️ ПРИ pinchFingers===1 РАБОТАЕТ СТАРЫЙ ЗАКОН ЦЕЛИКОМ: главный = БЛИЖАЙШИЙ к большому, и его
       смена на лету по-прежнему переводит ноту (см. ветку удержания ниже). Так «одна нота» остаётся
       байт-в-байт прежней, а многоголосие — отдельный, осознанно включаемый режим. */
    const r=pinchRatios(lm), [mf0,mv]=minFinger(r);
    /* ⚠️ Здесь стояло S.pr=r (живые отношения для ВРЕМЕННОЙ диагностики щипка). Имя СТОЛКНУЛОСЬ с
       памятью гистерезиса палитры (S.pc колонка / S.pr РЯД, см. ниже): объект отношений писался
       каждый кадр ДО чтения в cellHyst, а axHyst с объектом вместо номера ряда молча проваливал
       гейт prev>=0 — гистерезис РЯДОВ палитры не работал (колонки уцелели, S.pc никто не трогал).
       Диагностика удалена вместе с этой строкой; ряды снова держатся. */
    const prevTouch=S.touch||new Set();
    const touch=touchedFingers(r,prevTouch);
    S.order=(S.order||[]).filter(f=>touch.has(f));                 // ушедшие пальцы вон
    for(let f=0;f<FINGER_TIPS.length;f++) if(touch.has(f)&&!S.order.includes(f)) S.order.push(f);   // новые — в конец
    S.touch=touch;
    const multi=pinchFingers>1;
    const pf = multi ? (S.order.length?S.order[0]:FINGER_TIPS.indexOf(mf0)) : FINGER_TIPS.indexOf(mf0);   // ГЛАВНЫЙ палец
    const mf = FINGER_TIPS[pf];

    if(!S.pinch&&touch.size){
      /* Захват щипка: палец задаёт октаву, а ЗОНА фиксируется по точке
         щипка и не меняется до отпускания — двигая руку по X ради
         громкости, нельзя случайно перескочить в соседнюю колонку. */
      S.pinch=true; S.oct=pf; S.deg=-1; S.sm={};
      S.fing={};                             // ноты ПО ПАЛЬЦАМ (палец → {deg,regOct,slot}) — новый щипок начинает с чистого листа
      S.pc=null; S.pr=null;                  // память гистерезиса палитры — на руке: новый щипок начинает с чистого листа
      S.rect=null;                           // память гистерезиса прямоугольника — тоже на руке, тем же приёмом
      S.ty=null;                             // ЗАМОРОЖЕННЫЙ тип аккорда — берётся на атаке (ниже), новый щипок начинает с чистого листа
      S.clearT0=null; S.clearFired=false;    // отсчёт очистки лупера — свежий на каждый щипок (мизинец заведёт ниже)
      {
        const py=sy((lm[4].y+lm[mf].y)/2,H);       // экранные пиксели игрового поля (поля кадра сняты); гест-математику щипка выше это не касается — там сырые lm
        const px=sx((lm[4].x+lm[mf].x)/2,W);
        if(splitOn){
          /* СПЛИТ-ЭКРАН: половину (роль + X-диапазон) выбираем ПО ТОЧКЕ ЩИПКА и ЗАМОРАЖИВАЕМ на S —
             как S.zone. Роль этой руки = роль её половины (зона=инструмент). Раздел палитра|ноты —
             palSplitX диапазона ИМЕННО этой половины. Палитра — ПО ПОЛОЖЕНИЮ (без handRole): любая
             рука с большим+указательным (S.oct===0) слева от раздела выбирает тип. Эффекты — по
             ФУНКЦИИ руки в соло (handFnOf==='fx'), только в соло-половине (h.role==='ld'): дефолт
             handFn.ld.L='fx' ДЕРИВИРУЕТ прежний хардкод «эффекты у левой», без отдельного правила. */
          const halves=phoneHalves(W), hx=clamp(px,0,W-1), h=halves.find(q=>hx>=q.rx0&&hx<q.rx1)||halves[halves.length-1];   // клампим px ТОЛЬКО для выбора половины: щипок в поле полей целится в ближнюю половину, а не в чужую
          S.role=h.role; S.rx0=h.rx0; S.rx1=h.rx1;
          const hLoop = handFnOf(key,h.role)==='loop';   // рука-ЛУПЕР: команды по пальцам, положение на экране НЕважно (октавную полосу/палитру игнорируем). ⚠️ Перечень ролей (ld/bs/ch) снят в б.4: он был ИЗБЫТОЧЕН всегда — у роли без записи handFnOf давал null, и сравнение и так было ложным; теперь 'loop' есть и у ударных, и перечень только отрезал бы их
          const hExpr = h.role==='ld' && handFnOf(key,'ld')==='expr';   // рука-ВЫРАЗИТЕЛЬНОСТЬ: щипком НИЧЕГО не играет (считается пофреймово ниже); перебивает положение, как лупер
          const hsplit=palSplitX(h.rx0,h.rx1);
          const rectRole = (h.role==='ld'||h.role==='bs'||h.role==='ch') && rectGrid();
          const octRight = !(h.role==='ch'&&typedChords()) || px>=hsplit;   // октаву прячем от палитры, а ПАЛИТРА бывает только у typedChords: без неё (диатоника и т.п.) полоса идёт во всю ширину роли, иначе левая пятая часть была бы мёртвой
          /* Октавная полоса существует ТОЛЬКО когда показан не весь диапазон (hasReg). Без этого гейта
             на многопериодной сетке нижний НОТНЫЙ прямоугольник перехватывался бы как регистровый и молчал. */
          const octBand  = rectRole && rectLayout().hasReg && octRight && degRaw(Math.min(py,H-1),rectRowsFull(),H)===0;
          const famHand  = h.role==='ch' && typedChords() && px<hsplit && paletteFinger(key,h.role,S.oct);   // ПОЛОЖЕНИЕ + ПОДПИСКА ПАЛЬЦА (слайс «д»; прежде жёсткое S.oct===0 без всякого учёта функции руки — оттого рука-эффекты и забирала указательный). Роль — h.role, ЗАМОРОЖЕННАЯ роль половины; ⛔ не phoneInstr
          S.zone = hLoop ? 'loop'
                 : hExpr ? 'expr'
                 : octBand ? 'oct'
                 : famHand ? 'chFam'
                 : handFnOf(key,h.role)==='fx' ? 'fx'   // эффекты — ФУНКЦИЯ руки В РОЛИ ЕЁ ПОЛОВИНЫ (правило #18), больше не «только соло»: слайс б.1. Дефолт handFn.ld.L='fx' по-прежнему ДЕРИВИРУЕТ «эффекты у левой в соло-половине». С б.4 запись есть у всех ролей (у ударных по умолчанию 'hit') — гейт честно ложен без отдельной проверки, пока руку не перевели на 'fx'
                 : h.role;
        }else{
          /* РОЛЬ И X-ДИАПАЗОН ЗАМОРАЖИВАЕМ И ЗДЕСЬ (слайс б.1). Прежде это делала ТОЛЬКО сплит-ветка,
             и S.role в single-role оставалась пустой — сходило с рук лишь потому, что все её читатели
             (handHalfRole, setRectOctReg, draw.drawHandsPhone) стоят под гейтом splitOn и в single-role
             берут phoneInstr. Величины ТЕ ЖЕ САМЫЕ, что эти читатели и подставляли: rx0/rx1 здесь —
             [0,W] по построению (см. объявление выше), так что заморозка НИЧЕГО не меняет для них.
             Нужна она captureFx: тому роль требуется на ОБОИХ путях, а не только в сплите. Заодно
             закрыто давнее расхождение кода с CLAUDE.md, где S.role уже описана как замороженная в обеих
             ветках. */
          S.role=phoneInstr; S.rx0=rx0; S.rx1=rx1;
          /* ── SINGLE-ROLE (сплит выключен) ──
             Особую роль рука получает там, где она есть: эффекты у соло — по ФУНКЦИИ руки (handFnOf),
             выбор семейства у типизированных аккордов — ПО ПОЛОЖЕНИЮ, ровно как в сплите (см. famHand
             ниже). Октавный прямоугольник — ПОЛОЖЕНИЕ важнее роли (полоса 0 → 'oct', даже если это
             fx-рука), стоит ПЕРВЫМ в тернаре. У аккордов октава живёт только в правой половине [SPLIT,W]. */
          const sLoop = handFnOf(key,phoneInstr)==='loop';   // рука-ЛУПЕР: команды по пальцам, положение НЕважно (октавную полосу/палитру игнорируем). Перечень ролей снят в б.4 — см. hLoop в сплит-ветке
          const sExpr = phoneInstr==='ld' && handFnOf(key,'ld')==='expr';   // рука-ВЫРАЗИТЕЛЬНОСТЬ: щипком НИЧЕГО не играет (считается пофреймово ниже)
          const rectRole = (phoneInstr==='ld'||phoneInstr==='bs'||phoneInstr==='ch') && rectGrid();   // rect-раскладка: соло, бас И аккорды
          const octRight = !(phoneInstr==='ch'&&typedChords()) || px>=split;   // см. сплит-ветку: гейт по НАЛИЧИЮ палитры (typedChords), а не по роли
          const octBand = rectRole && rectLayout().hasReg && octRight && degRaw(Math.min(py,H-1),rectRowsFull(),H)===0;   // полосы нет, когда показаны все регистры — иначе нижний НОТНЫЙ прямоугольник молчал бы
          /* Палитра типов — ПО ПОЛОЖЕНИЮ, БЕЗ привязки к руке (тот же гейт, что в сплите выше: большой+
             указательный слева от раздела). Прежде здесь стояло handRole(key)==='fx' — левая рука ВСЕГДА
             была палитрой и нот не играла, правая типов не выбирала; при вводе «Функций рук» привязку к
             руке сняли, но правку внесли только в сплит-ветку. Теперь один закон на оба пути: любая рука
             выбирает тип слева, любая играет справа, одна и та же — по очереди (аккорд звучит после
             размыкания). Цена та же, что в сплите: нотная рука, щипнувшая большим+указательным СЛЕВА,
             выберет тип, а не сыграет корень — но корни там и не рисуются (сетка живёт в [split,W]), а
             громкость слева мерилась минимумом, так что терять нечего. */
          const famHand = phoneInstr==='ch' && typedChords() && px<split && paletteFinger(key,phoneInstr,S.oct);   // ПОЛОЖЕНИЕ + ПОДПИСКА ПАЛЬЦА (слайс «д»). Роль здесь глобальная ЗАКОННО: сплита нет, роль на экране одна
          S.zone = sLoop ? 'loop'
                 : sExpr ? 'expr'
                 : octBand ? 'oct'
                 : famHand ? 'chFam'
                 : handFnOf(key,phoneInstr)==='fx' ? 'fx'   // эффекты — если ФУНКЦИЯ этой руки В ТЕКУЩЕЙ РОЛИ = fx (слайс б.1; прежде — только соло). Роль здесь глобальная ЗАКОННО: сплита нет, роль на экране одна
                 : phoneInstr;
        }
        S.fn = S.zone==='loop' ? 'loop'
             : (S.zone==='ld'||S.zone==='bs'||S.zone==='ch') ? handFnOf(key,S.zone) : null;   // функция руки: соло/бас — note/hold/therm; аккорды — latch/hold; лупер — loop; у fx/oct/chFam/ударных — null (у ударных НАМЕРЕННО и после б.4: 'hit' никому из читателей S.fn не нужен — см. шапку handFn)
        // ЗАЦЕПКА ОБУЧЕНИЯ: щипок сформирован (edge) — палец(=октава)+зона+рука. По построению раз на щипок.
        tutorTap('pinch',{finger:S.oct, zone:S.zone, hand:handSide(key)});
      }
      if(S.zone==='fx'){
        captureFx(S,FINGER_TIPS.indexOf(mf),lm,H);   // захват ПО ПАЛЬЦУ: цепь решает, какие параметры (и каких эффектов) на нём подписаны и по каким осям
      }else if(S.zone==='ld'){
        S.tutDeg=undefined;                  // владельца назначать больше не нужно (у руки свой голос пула); S.tutDeg сброшен — свежий щипок переизвестит обучение о ноте
      }else if(S.zone==='bs'){
        bassOwner=key; S.tutBass=undefined;  // бас моно — рулит последняя рука; S.tutBass сброшен — свежий щипок переизвестит обучение о басовой ноте
      }else if(S.zone==='ch'){
        S.fresh=true;                        // решение о защёлке примем этот кадр, когда посчитаем ступень
      }else if(S.zone==='dr'){
        S.fresh=true;                        // удар сработает этот кадр по ряду
      }else if(S.zone==='loop'){
        fireLooperCmd(S,mf);                 // команда лупера по пальцу — РАЗ на щипок (блок захвата = edge, единичное срабатывание по построению)
      }
    }else if(S.pinch){
      if(!touch.size){ endPinch(key,S); }
      /* СМЕНА ГЛАВНОГО ПАЛЬЦА НА ЛЕТУ — прежний закон дословно: ближайший к большому побеждает (порог
         PINCH_HOLD, свободнее щипкового), и выбор ПЕРЕЕЗЖАЕТ на него.
         ⚠️ ЗАКОН ОТМЕНЁН РОВНО В ОДНОМ МЕСТЕ: у СОЛО при потолке 2+. Там второй поднесённый палец — это
         вторая НОТА, а не перескок, и главным остаётся первый прижатый (меняется лишь когда сам
         отпущен, S.order выше). Всем прочим зонам (эффекты, октавная полоса, палитра, ударные) и соло
         при потолке 1 закон нужен как был: они одноголосые, и «перевести палец» там — обычный жест. */
      else if(!(multi&&S.zone==='ld')&&mv<PINCH_HOLD&&FINGER_TIPS.indexOf(mf0)!==S.oct&&S.fn!=='hold'&&S.fn!=='loop'){   // 'hold'/'loop' морозят палец: у hold — октаву, у лупера — выбранную команду (мизинец не «перескочит» на безымянный)
        S.oct=FINGER_TIPS.indexOf(mf0);      // смена пальца = смена октавы на лету (по БЛИЖАЙШЕМУ, как всегда)
        if(S.zone==='fx'&&S.adj){
          captureFx(S,FINGER_TIPS.indexOf(mf0),lm,H);   // перезахват на лету: НОВЫЙ палец → ДРУГОЙ набор записей (у него своя подписка) + свежая точка отсчёта по ВСЕМ трём осям, иначе первый кадр после смены дал бы скачок
        }
        // ЗАЦЕПКА ОБУЧЕНИЯ: палец сменён на лету (=другая октава) — то же событие pinch с новым пальцем.
        tutorTap('pinch',{finger:S.oct, zone:S.zone, hand:handSide(key)});
      }
      /* Многопальцевое СОЛО: ГЛАВНЫЙ отпущен, но рука ещё держит другие — повышаем следующий по порядку
         прижатия. Позиция/зона/громкость читаются с главного, поэтому без повышения они остались бы
         висеть на уже отпущенном пальце. Нота при этом НЕ переезжает: у каждого пальца своя (S.fing),
         и отпущенный гаснет отдельно. */
      else if(multi&&S.zone==='ld'&&touch.size&&S.oct!==pf) S.oct=pf;
    }
 
    if(S.pinch){
      /* Высота и громкость читаются с кончика ТОГО пальца, который
         зажат с большим (S.oct) — переключил палец, слежение мгновенно
         перешло на него. */
      const tip=lm[FINGER_TIPS[S.oct]];
      const x=emaS(S,'x',sx(tip.x,W),0.4);         // экранные пиксели игрового поля (поля кадра сняты) — позиция, громкость по X, попадание в прямоугольник/палитру
      const y=emaS(S,'y',sy(tip.y,H),0.4);
      S.x=x; S.y=y;
      /* X-диапазон роли ЭТОЙ руки при игре: при сплите — ЗАМОРОЖЕННЫЙ на захвате (S.rx0/S.rx1),
         иначе весь холст [0,W]. Раздел палитра|ноты — palSplitX того же диапазона. OFF → 0/W/split
         (байт-в-байт: диапазон от phoneInstr не зависел). */
      const prx0=splitOn?S.rx0:rx0, prx1=splitOn?S.rx1:rx1, psplit=palSplitX(prx0,prx1);

      if(S.zone==='fx'){
        /* Регулировка ОТНОСИТЕЛЬНАЯ («от точки захвата»), размах — 70% поля по каждой плоской оси;
           значение остаётся после отпускания (ЛАТЧ — оно живёт в state.fx, а S.adj гасит endPinch).
           ⚠️ ВЫРАЖЕНИЕ ПО Y ОСТАВЛЕНО ДОСЛОВНО (·H … /(H*0.7)): H в нём алгебраически сокращается,
           но сокращать его РУКАМИ нельзя — в плавающей точке это уже другой результат, а критерий
           слайса 2.1 — «неотличимо от продакшена». */
        const A=S.adj;
        if(A){
          const hs=emaS(S,'hs',dist(lm[0],lm[9]),0.15);   // РОВНО один вызов за кадр (потому z и не берётся в captureFx)
          if(A.p0.z==null) A.p0.z=hs;                     // точка отсчёта по глубине — первый кадр щипка, off.z там ровно 0 (как у x/y)
          const off={ x:(flipX(lm[4].x)-flipX(A.p0.x))/0.7,
                      y:(A.p0.y-lm[4].y*H)/(H*0.7),
                      z:(hs-A.p0.z)/REV_RANGE };
          /* ИДЁМ ПО ЗАХВАЧЕННЫМ ЗАПИСЯМ, а не по индексам параметров: у записи СВОЙ параметр (живая
             ссылка pa), СВОЙ сеттер и СВОЯ база — разъехаться нечему (см. captureFx). Один палец может
             вести параметры РАЗНЫХ эффектов, и все они поедут ВМЕСТЕ: это и есть «много параметров на
             одном адресе», ради чего затевался поворот. */
          for(const e of A.ent){
            const pa=e.pa;
            /* ФИЛЬТР ПО РЕЖИМУ И РУКЕ — тот же, что стоял здесь с 2.6.1, и по той же причине.
               'fixed' — палец не двигает: значение выставлено в меню и стоит на месте.
               hand!=='fx' — параметр ведёт ДРУГАЯ рука (играющая, Пласт 3.2), и лезть в него нельзя,
               иначе две руки подерутся за одну величину. Захват уже отобрал записи по этому же
               признаку, но параметр могли переключить ПОСРЕДИ щипка — тогда палец обязан его
               отпустить сразу. Всё ниже — прежняя арифметика, символ в символ. */
            if(pa.mode!=='drive' || pa.hand!=='fx') continue;
            const d=off[pa.axis]||0;
            const v=clamp01(e.base+(pa.inv?-d:d));
            e.set(v);
            // ЗАЦЕПКА ОБУЧЕНИЯ: значение реально сдвинулось от старта (>3%) — рука эффектов «крутит», не просто щипнула. Троттлинг 5%. Годится ЛЮБОЙ параметр: иначе переназначивший палец застрял бы в уроке «Основы».
            if(Math.abs(v-e.base)>0.03 && (S.tutFx==null||Math.abs(v-S.tutFx)>0.05)){ S.tutFx=v; tutorTap('fx',{k:e.fxId}); }   // fxId берём У ЗАПИСИ: на одном пальце теперь могут сидеть разные эффекты, общего A.fxId больше нет
          }
        }
      }else if(S.zone==='chFam'){
        /* Рука-ПАЛИТРА: ТОЛЬКО выбирает ячейку (семейство+вариант) ПОЛОЖЕНИЕМ и молчит.
           Ветка стоит рядом с 'fx', ДО общего блока — поэтому не считает ни ступень, ни
           громкость, не берёт chOwner и не доходит до защёлки: левая рука нот не играет.
           Два гейта, оба оставляют выбор ЛИПКИМ (ничего не трогаем):
             1. ПАЛЕЦ ИМЕЕТ ПРАВО ВЫБИРАТЬ — paletteFinger, ТОТ ЖЕ предикат, что решал на захвате
                (слайс «д»; прежде здесь стояло голое S.oct===0). ⛔ Второй копии правила быть не
                должно: разойдись захват с перепроверкой — и ведение оборвалось бы посреди жеста,
                хотя щипок не разжимали. Щипок «неуполномоченным» пальцем по-прежнему ничего не
                выбирает: случайное касание не должно сбивать заготовленную форму;
             2. только внутри палитры (S.x < psplit) — рука, ушедшая в зону нот, молчит.
           ⚠️ РОЛЬ БЕРЁТСЯ С S (S.role) — замороженная на захвате в ОБЕИХ ветках с б.1; ⛔ не phoneInstr:
           при сплите он не назовёт роль щипнувшей руки.
           Ведение непрерывное, пока щипок держат: можно дотянуть до соседней ячейки. */
        if(paletteFinger(key,S.role,S.oct) && S.x<psplit){
          const x0=prx0+CH_PAL_PAD, x1=psplit-CH_PAL_PAD, y0=CH_PAL_HEAD_H, y1=H-CH_PAL_HEAD_H;
          const [c,r]=cellHyst(clamp(S.x,x0,x1),clamp(S.y,y0,y1),x0,x1,y0,y1,chordFams(),
                               S.pc==null?-1:S.pc, S.pr==null?-1:S.pr);
          S.pc=c; S.pr=r;
          // ЗАЦЕПКА ОБУЧЕНИЯ: выбран ДРУГОЙ тип аккорда в палитре (положением) — урок «Аккорды» ловит выбор типа.
          if(c!==chordFam||r!==chordVar) tutorTap('chordType',{fam:c,var:r});
          if(c!==chordFam)setChordFam(c);
          if(r!==chordVar)setChordVar(r);
        }
      }else if(S.zone==='oct'){
        /* Октавная полоса: рука МОЛЧИТ (как палитра/эффекты) — ни ступени, ни громкости,
           ни владельца. Палец I–IV задаёт липкий регистр РОЛИ (соло→octReg, бас→bassOctReg
           через резолвер); смена пальца на лету (S.oct обновился выше) двигает регистр.
           S.oct здесь — «какой палец», как везде.
           РОЛЬ регистра: при сплите — инструмент ЭТОЙ половины (S.role, заморожен на захвате: из зоны
           'oct' роль не достать); иначе — активный phoneInstr (single-role, байт-в-байт, включая
           смену роли DOM-кнопкой на удержанном щипке — softAllOff щипок не снимает). */
        /* КЛАМП базы окна: полоса задаёт НАЧАЛО окна из rectLayout().octaves периодов, поэтому база
           не должна уводить верх окна за последний регистр (rectBase — тот же кламп, что при чтении;
           у однопериодной сетки это прежние четыре регистра 1-в-1). Палец сверх допустимого — холостой,
           как и лишние пальцы в прямоугольнике: ничего не меняет. */
        setRectOctReg(splitOn?S.role:phoneInstr, rectBase(S.oct));
      }else if(S.zone==='loop'){
        /* Рука-ЛУПЕР при удержании: команды index/middle/ring уже сработали НА ЗАХВАТЕ (edge, раз на
           щипок — здесь НЕ повторяются). Живёт лишь ОЧИСТКА (мизинец): 3с-обратный отсчёт, срабатывает
           РАЗ на отметке (гейт S.clearFired), отпускание раньше — отмена (endPinch гасит отсчёт). */
        if(S.clearT0!=null && !S.clearFired){
          const rem=CLEAR_HOLD_MS-(performance.now()-S.clearT0);
          if(rem<=0){ S.clearFired=true; setLooperClear(-1); doLooper('clear'); }
          else setLooperClear(rem);
        }
      }else if(S.zone==='expr'){
        /* Рука-ВЫРАЗИТЕЛЬНОСТЬ: щипком НИЧЕГО не играет. Её признаки считаются ПОФРЕЙМОВО (вне щипка,
           ниже по циклу, exprFeatures), поэтому здесь — ровно ничего. */
      }else{
        /* Сетка ПРЯМОУГОЛЬНИКОВ — соло, бас И аккорды. Y выбирает ПОЛОСУ; если у лада есть октавная
           полоса (RL.hasReg), она внизу и её перехватывает зона 'oct', поэтому нотный прямоугольник =
           полоса − RL.regBands (при показе ВСЕХ регистров regBands=0 и полоса === прямоугольник).
           Палец S.oct (0=указ. … 3=мизинец) выбирает ноту ВНУТРИ прямоугольника — их RL.k, а не всегда
           четыре. СЛОТ g = прямоуг*k + палец; ступень И регистр даёт ЕДИНАЯ формула rectNoteAt(g,база):
           при многопериодной сетке номер периода приходит из слота, поэтому регистр у каждой полосы
           свой. S.oct тут читается как «палец», а не «октава» — переосмысление ЛОКАЛЬНОЕ.
           У аккордов это КОРЕНЬ; тип берётся из палитры отдельно. */
        const rectPlay = (S.zone==='ld'||S.zone==='bs'||S.zone==='ch') && rectGrid();
        const noteZone = S.zone==='ld'||S.zone==='bs';
        const thereminOn = noteZone && S.fn==='therm';   // терменвокс — ФУНКЦИЯ руки, соло И бас
        const holdOn     = (noteZone||S.zone==='ch') && S.fn==='hold';   // удержание — соло/бас И аккорды: корень/октава мёрзнут одним и тем же гейтом (S.deg застыл ниже)
        const RL = rectPlay?rectLayout():null;
        /* БАЗА ОКНА: пока показан не весь диапазон, её задаёт липкий регистр роли и двигает ВСЁ окно
           (rectBase клампит, чтобы верх окна не уехал за последний регистр); когда показаны все
           регистры — база 0. У нерект-раскладки «база» = палец, как было (регистр выбирает палец). */
        const base = rectPlay ? rectBase(rectOctReg(S.zone)) : S.oct;
        /* ХОЛОСТОЙ ПАЛЕЦ: при k<4 лишние пальцы НЕ играют ничего. Молчание, а не чужая нота —
           иначе мизинец на 3-нотном прямоугольнике врал бы высотой. Владение НЕ отдаём: сдвинул
           палец на рабочий — звук вернётся тем же щипком (иначе пришлось бы перещипывать). */
        /* ПАЛЬЦЫ, КОТОРЫЕ ЗВУЧАТ (только соло). Порядок прижатия, обрезанный потолком pinchFingers, без
           холостых (при k<4 лишние пальцы молчат — тот же закон, что и у одного пальца).
           ТЕРМЕНВОКС — ОДНА НОТА НА РУКУ, намеренно: высоту там ведёт ВЕРТИКАЛЬ РУКИ, а палец ноту не
           выбирает вовсе, поэтому у всех пальцев вышел бы один и тот же Гц — унисон-дубли. Придумывать
           им сдвиг («второй палец = ступенью выше») было бы выдумкой без физического основания, а не
           инструментом. Поэтому у терменвокса играет только главный палец. */
        const solo=S.zone==='ld';
        const act = !solo ? []
          : thereminOn ? [S.oct]                                             // терменвокс — только главный палец (см. выше)
          : (multi ? S.order : [S.oct])                                      // потолок 1 → ровно прежний ЕДИНСТВЕННЫЙ (ближайший) палец, а не «первый прижатый»
              .filter(f=>!rectPlay||f<RL.k).slice(0,pinchFingers);
        const idle = solo ? act.length===0 : (rectPlay && !thereminOn && S.oct>=RL.k);
        if(idle){
          S.deg=-1; S.slot=-1;                    // ни ступени, ни подсветки: draw покажет тусклое кольцо и подпись «палец не занят»
        }else if(thereminOn){
          /* Непрерывная высота: y → Гц через thereminHz (по leadFreq), интерполяция в центах между
             реальными нотами лада. БАС на 2 октавы ниже соло (bassFreq=leadFreq/4) — та же кривая ÷4.
             S.deg/S.regOct — ближайшая НОТА (подсветка И запись: формат события не меняется), S.hz —
             живые Гц в звук. Палец ноту НЕ выбирает (потому холостой палец сюда и не заходит). */
          const th=thereminHz(y,H,base); S.deg=th.deg; S.regOct=th.oct; S.slot=rectPlay?th.slot:-1;
          S.hz = S.zone==='bs' ? th.hz/4 : th.hz;
        }else if(holdOn && S.deg>=0){
          /* УДЕРЖАНИЕ: высота (S.deg) и октава (S.oct) ЗАМОРОЖЕНЫ с ПЕРВОГО кадра щипка — рука уходит
             куда угодно, нота держится (смена пальца октаву не двигает — гейт выше). Громкость (X) ниже
             — ЖИВАЯ (свелл). Стоп — только размыканием пальцев (endPinch). deg берётся на первом кадре
             ветками ниже (тогда S.deg==-1), дальше сюда — и больше не пересчитывается. ОДИН механизм
             для соло/баса И аккордов: у аккорда S.deg — это КОРЕНЬ, значит замерзают корень+октава, тип
             тоже заморожен на атаке (S.ty, ниже), громкость свеллит — ровно как задумано «заморожен». */
        }else if(rectPlay){
          S.rect=degHyst(y,RL.bands,H,S.rect==null?-1:S.rect);          // полоса полной сетки — ОДНА на руку: все её ноты лежат в одном прямоугольнике, в этом весь смысл раскладки
          const r=clamp(S.rect-RL.regBands,0,RL.rects-1);               // нотный прямоугольник = полоса − октавная (если она есть); без мёртвой зоны
          const g=clamp(r*RL.k+S.oct, 0, RL.notes-1);                   // СЛОТ главного пальца (прямоуг*k + палец)
          const n=rectNoteAt(g,base); S.deg=n.deg; S.regOct=n.oct; S.slot=g;   // одна формула слот→(ступень,регистр) — её же читает подсветка в обратную сторону
        }else{
          const rows= S.zone==='dr' ? DRUM_ROWS : IVX().length;
          S.deg=degHyst(y,rows,H,S.deg);            // вся высота — ровно так же, как рисует draw
          S.regOct=S.oct; S.slot=-1;                // узкие ряды: регистр выбирает ПАЛЕЦ (как было)
        }
        /* НОТА КАЖДОГО ЗВУЧАЩЕГО ПАЛЬЦА. Общее у руки — ПОЛОЖЕНИЕ (прямоугольник/ряд по Y, громкость по
           X, Z-реверб); РАЗНОЕ — что палец берёт внутри него: в rect-сетке это слот прямоугольник*k+палец
           (четыре соседние ноты — аккорд пальцами), в узких рядах палец по-прежнему значит РЕГИСТР, то
           есть пальцы дают ту же ступень октавами (честное следствие того, что палец там и означает).
           УДЕРЖАНИЕ — ПО ПАЛЬЦУ: запись пальца, однажды посчитанная, не пересчитывается, поэтому каждая
           нота держит СВОЮ высоту и гаснет, когда разомкнётся ИМЕННО ЕЁ палец (см. гашение ниже). */
        if(solo&&!idle){
          for(const f of act){
            if(holdOn && S.fing[f]) continue;                            // удержание: нота этого пальца заморожена с его первого кадра
            if(rectPlay){ const g=clamp(Math.floor(S.slot/RL.k)*RL.k+f, 0, RL.notes-1), n=rectNoteAt(g,base);
              S.fing[f]={deg:n.deg,oct:n.oct,slot:g}; }
            else if(thereminOn) S.fing[f]={deg:S.deg,oct:S.regOct,slot:S.slot};
            else S.fing[f]={deg:S.deg,oct:f,slot:-1};                    // узкие ряды: ступень от Y (общая), регистр = САМ ПАЛЕЦ
          }
          for(const f of Object.keys(S.fing)) if(!act.includes(+f)) delete S.fing[f];   // палец отпущен — его записи больше нет (голос гасим ниже)
        }
        /* Типизированный аккорд: левые CH_PAL_W заняты палитрой, поэтому громкость мерится по
           ПРАВОЙ зоне [split,rx1] — иначе вся половина экрана читалась бы «тихо». Остальные роли
           (соло/бас/ударные/обычные аккорды) — по всей ширине роли [rx0,rx1]. */
        const typed = S.zone==='ch'&&typedChords();
        const[zx0,zx1]= typed ? [psplit,prx1] : [prx0,prx1];
        /* ⛳ X — ГРОМКОСТЬ ЛИБО ЭФФЕКТ, ТРЕТЬЕГО НЕ ДАНО (Пласт 3.7.3). Величина хода СЧИТАЕТСЯ ОДНА И
           ТА ЖЕ (xn), меняется только её АДРЕСАТ: по умолчанию это громкость (формула байт-в-байт
           прежняя, включая сужение зоны у типизированных аккордов), а если в цепи ЭТОЙ РОЛИ есть
           параметр с адресом play:x — ход уходит эффекту, а громкость встаёт на фиксированное значение
           из меню. Так «одно движение — одна величина» соблюдается буквально.
           ⚠️ РОЛЬ БЕРЁМ ИЗ S.zone — это роль ИМЕННО ЭТОЙ руки (в сплите она заморожена на захвате).
           Поэтому отданный X у соло НЕ замораживает громкость аккордов, баса и ударных.
           ⚠️ xn — ПОЗИЦИОННАЯ величина, как и громкость: считается из sx-координат (правила #12/#13 —
           кадрирование и зеркало учтены там же), поэтому «вправо = больше» одинаково на обеих камерах. */
        const xn=clamp01((x-zx0)/(zx1-zx0));
        if(roleXDriven(S.zone)){
          S.vol=fxVolFix[S.zone];
          for(const eff of fxChainOf(S.zone)){
            if(!eff) continue;
            let ps=null;                                   // дескрипторы берём ЛЕНИВО: у большинства записей play-параметров нет
            eff.params.forEach((pa,i)=>{
              if(pa.mode!=='drive' || pa.hand!=='play' || pa.axis!=='x') return;
              if(!ps) ps=fxParamsOf(S.zone,eff.fxId);
              const p=ps[i]; if(p) p.set(pa.inv ? 1-xn : xn);   // инверсия ЗЕРКАЛИТ (1−v), как у глубины: величина уже абсолютная 0..1, а не смещение
            });
          }
        }else S.vol=0.2+0.8*xn;
        /* Тип берётся из ЛИПКОГО выбора палитры (любой рукой, по положению), а не из положения играющей.
           Ссылка на элемент таблицы CHORD_FAM_SETS — от этого зависят и сравнение
           ty===latchTy, и заморозка a.ty в событии лупера. Кламп: у семейств может быть
           разное число вариантов, и chordVar мог остаться от более длинного.
           ЭТО — тип для СЛЕДУЮЩЕЙ атаки. Звучащий аккорд ведётся по ЗАМОРОЖЕННОМУ S.ty (см. ниже). */
        let ty=null;
        if(typed){
          const FS=chordFams(), fam=FS[chordFam]||FS[0];
          ty=fam.types[Math.min(chordVar,fam.types.length-1)].iv;
        }
        /* Октава для аккорда: rect — из СЛОТА (S.regOct, посчитан выше единой формулой rectNoteAt);
           узкие ряды — S.oct (палец), как было. Меняется ТОЛЬКО источник октавы, логика защёлки ниже
           — без изменений. */
        const chOct = S.regOct;   // роль = S.zone (в аккордовой ветке ='ch')
        /* СОЛО стоит ПЕРВЫМ в цепочке зон и само разбирается с холостыми пальцами: у него нот несколько,
           и «замолчать» — это не одно действие, а разность множеств (ниже). Прочие роли (бас/аккорды/
           ударные) остались одноголосыми, у них холостой палец — прежняя ветка `else if(idle)`. */
        if(S.zone==='ld'){
          /* КЛЮЧ ВЛАДЕЛЬЦА НОТЫ. При потолке 1 и у терменвокса — БЕЗ номера пальца: нота у руки одна, и
             ⚠️ ИМЕННО ПОЭТОМУ смена пальца на лету по-прежнему ВЕДЁТ ту же ноту глиссандо, а не
             переатакует её (ключ не меняется → тот же голос пула → прежний 20мс-глайд). С номером пальца
             тот же жест дал бы off+on — слышимый щелчок там, где раньше был плавный переезд.
             При многопальцевом — с номером: у каждого пальца свой голос. */
          const noteKey = f => (multi&&!thereminOn) ? soloKey(key,f) : soloKey(key);
          /* ГАШЕНИЕ — сначала и ПО КЛЮЧАМ, а не по пальцам: отпущенный (срезанный потолком, ставший
             холостым) палец должен замолчать в том же кадре, а «тот же ключ» — наоборот, продолжиться.
             S.snd — ключи, звучащие СЕЙЧАС. */
          const keys=act.map(noteKey), prevSnd=S.snd||[];
          for(const kk of prevSnd) if(!keys.includes(kk)) WleadOff(kk);
          S.snd=keys;
          if(!idle){   // без гейта владельца: у КАЖДОЙ соло-руки (и каждого её пальца) свой голос пула
            /* ⚠️ ГЛУБИНА ЗДЕСЬ БОЛЬШЕ НЕ СЧИТАЕТСЯ (Пласт 3.1): реверб ушёл с играющей руки. Прежде тут
               стояло `S.rev=clamp01((REV_NEAR-hs)/REV_RANGE); setRevDisp(S.rev)`, и emaS('hs') звался
               ради него одного — оба удалены вместе с прицелом и столбиком REV.
               ⚠️ КЛЮЧИ rev/vib/drv/trm/dly ИЗ НАГРУЗКИ УБРАНЫ (Пласт 3.7.2) и заменены КАРТОЙ a.fx.
               `rev` был МЁРТВЫМ ГРУЗОМ: писался нулём с 3.1 и не читался никем, его порог в дельта-сжатии
               (|0−0|>0.03) был ложью навсегда — снятие доказуемо ничего не меняет. Остальные четыре в
               нагрузке ЛЕЖАЛИ, но в СРАВНЕНИЕ не входили, поэтому в слой не попадали; теперь они едут
               картой и сравниваются по множеству. Карта СТРОИТСЯ ОДИН РАЗ НА КАДР (снимок цепи роли —
               величина общая для всех рук и пальцев), а не на каждый вызов: копию для записи делает push. */
            const fxSnap=fxSnapshot('ld');
            for(const f of act){
              const n=S.fing[f]; if(!n)continue;
              WleadOn(noteKey(f),{deg:n.deg,oct:n.oct,vol:S.vol,   // ступень+октава, не частота: запись = намерение; в rect-раскладке октава пришла из СЛОТА (rectNoteAt), в узких рядах — от пальца
                       fx:fxSnap,inst:leadIdx}, thereminOn?S.hz:null);   // 3-й арг — ЖИВОЙ override Гц (терменвокс), в запись не идёт
            }
            /* ЗАЦЕПКА ОБУЧЕНИЯ: соло-нота зазвучала/сменила ступень. Считаем по ГЛАВНОМУ пальцу — урокам
               нужен факт «нота сыграна», а не каждая нота аккорда (иначе одно движение слало бы четыре). */
            const nMain=S.fing[act[0]];
            if(nMain&&nMain.deg!==S.tutDeg){ S.tutDeg=nMain.deg; tutorTap('note',{deg:nMain.deg, half:splitOn?(S.rx0>0?1:0):null}); }
          }
        }else if(idle){
          if(S.zone==='bs'&&bassOwner===key)WbassOff();
        }else if(S.zone==='bs'){                            // бас: моно-голос, ведётся как соло
          if(bassOwner===key){ WbassOn({deg:S.deg,oct:S.regOct,vol:S.vol,inst:bassIdx}, thereminOn?S.hz:null);   // rect-бас — октава из СЛОТА (rectNoteAt); 2-й арг — живой override Гц (терменвокс-бас), в запись НЕ идёт (как соло)
            // ЗАЦЕПКА ОБУЧЕНИЯ: бас зазвучал/сменил ступень (тот же вызов, что дал звук) — урок «Лупер» (слой ДРУГОЙ ролью поверх соло: соло-моно на себя не слоится) И урок «Две роли» (half — половина сплита).
            if(S.deg!==S.tutBass){ S.tutBass=S.deg; tutorTap('bass',{deg:S.deg, half:splitOn?(S.rx0>0?1:0):null}); } }

        }else if(S.zone==='dr'){                            // ударные: один удар на щипок (по ряду)
          if(S.fresh){ S.fresh=false; WdrumHit(S.deg,S.vol); }
        }else if(!supportsChords()){
          /* Макам: лестницы аккордов нет — щипок в поле аккордов не строит ничего.
             Гейт стоит ЗДЕСЬ, после разбора зоны: рука жива (зона, ступень, громкость
             посчитаны — их читает draw для подсказки), молчит только аккордовая ветка.
             Соло/бас/ударные — соседние ветки выше, их это не касается; дрон живёт
             в лупере (ENG.drone), не в руке. Переигровка идёт мимо — по замороженному sc. */
        }else{ // 'ch' — колонка аккордов (владелец голосов — постоянный ключ 'latch'); функция руки latch/hold
          const hold = S.fn==='hold';             // «удержание» vs «защёлка»
          /* Z-ЯРКОСТЬ (глубина 0 близко/ярко .. 1 далеко/глухо): тот же размер кисти dist(0,9), что ведёт
             соло-реверб. Воздух гасит верхи быстрее низов → глубина читается как «аккорд отодвинулся» — та
             же природа, что реверб у соло, с другой стороны. Высоту НЕ трогает (только тембр). Считаем ДО
             WchOn/WchSet: bri едет в событие рядом с ty (как a.rev у соло) — слой запомнит свою яркость. */
          const bd = clamp01((REV_NEAR-emaS(S,'hs',dist(lm[0],lm[9]),0.15))/REV_RANGE);
          /* ═══ ГЛУБИНА АККОРДОВОЙ РУКИ → ПАРАМЕТРЫ ЦЕПИ АККОРДОВ (адрес play:z, цель «а») ═══
             Форма — та же, что у горизонтали в 3.7.3: обход цепи РОЛИ, отбор ПО АДРЕСУ, инверсия
             зеркалит (величина абсолютная 0..1, а не смещение от захвата).
             ⛔ ПОЧЕМУ ЗДЕСЬ, А НЕ В ОБЩЕМ БЛОКЕ ГЛУБИНЫ (тот, что под soloNoteHand): он гейтится на
             СОЛО и САМ зовёт emaS(S,'hs',…). Расширь его на аккорды — и для аккордовой руки фильтр
             сглаживания продвинулся бы ДВАЖДЫ ЗА КАДР (здесь и там), а это ровно та ловушка, о которой
             предупреждает captureFx. Величина уже посчитана строкой выше — переиспользуем её.
             ⛳ Побочная выгода, и она не случайна: теперь ЛЮБОЙ параметр цепи аккордов можно посадить на
             глубину руки — например подмес аккордового реверба, — а не только яркость. */
          for(const eff of fxChainOf('ch')){
            if(!eff) continue;
            let ps=null;                                   // дескрипторы берём ЛЕНИВО: у большинства записей play-параметров нет
            eff.params.forEach((pa,i)=>{
              if(pa.mode!=='drive' || pa.hand!=='play' || pa.axis!=='z') return;
              if(!ps) ps=fxParamsOf('ch',eff.fxId);
              const p=ps[i]; if(p) p.set(pa.inv ? 1-bd : bd);
            });
          }
          /* ЯРКОСТЬ, КОТОРУЮ УВЕЗЁТ СОБЫТИЕ, — теперь ИЗ ПАРАМЕТРА, а не из руки. Разница видна там, где
             её и ждут: зафиксировал величину в меню или увёл на другой адрес — рука перестаёт на неё
             влиять, а звук и запись слушаются параметра. Нет яркости в цепи → null → сегодняшнее
             поведение (chordOn открывает фильтр, chordGlide его не трогает). */
          const bri = fxChordBri();
          if(S.inert){
            // стоп-щипок отработал (только защёлка): рука молчит до размыкания пальцев
          }else if(S.fresh){
            S.fresh=false;                        // решение принимается один раз за щипок
            if(hold){
              /* УДЕРЖАНИЕ: каждый щипок — НОВАЯ атака; корень/октава уже заморожены гейтом holdOn выше
                 (S.deg застыл с первого кадра), тип берётся из палитры ЗДЕСЬ, на атаке, и тоже морозится
                 (S.ty ниже). Тумблера «тот же аккорд → выкл» тут НЕТ: выключение — это размыкание пальцев
                 (endPinch зовёт WchOff). */
              WchOn('latch',S.deg,chOct,S.vol,chIdx,ty,bri);
              S.ty=ty;                                // ЗАМОРОЗКА ТИПА на атаке (см. ведение ниже)
              latchLen=ty?ty.length:0;
              setLatchDeg(S.deg); setLatchOct(chOct); setLatchTy(ty); chOwner=key;   // регистр — рядом со ступенью: подсветке нужна ПАРА (одна ступень живёт в нескольких прямоугольниках)
              tutorTap('chord',{deg:S.deg, half:splitOn?(S.rx0>0?1:0):null});   // ЗАЦЕПКА ОБУЧЕНИЯ: аккорд зазвучал (свежая атака, удержание); half — половина сплита (урок «Две роли»)
            }else{
              /* Тождество защёлки: вне typedChords — ступень (как было, второй множитель
                 схлопывается в true); в typedChords — ПАРА (ступень+тип), иначе C→C7
                 читалось бы как «та же ступень» и глушило аккорд вместо переключения.
                 Цена: зона выключения сужается до конкретного сектора — это неизбежно. */
              /* ⚠️ РЕГИСТР ВХОДИТ В ТОЖДЕСТВО. Пока сетка показывала один период, ступень задавала
                 аккорд однозначно. Теперь одна и та же ступень есть в нескольких прямоугольниках, и
                 без регистра «до» из нижнего блока и «до» из верхнего читались бы как ОДИН аккорд:
                 второй щипок ГЛУШИЛ бы первый вместо перехода октавой выше. */
              const same = latchDeg>=0 && S.deg===latchDeg && S.regOct===latchOct && (!typedChords() || ty===latchTy);
              if(same){
                WchOff('latch'); setLatchDeg(-1); setLatchTy(null); chOwner=null; S.inert=true;   // тот же аккорд → выключаем, рука инертна
              }else{
                /* Переатака нужна, когда МЕНЯЕТСЯ ЧИСЛО НОТ: chordGlide ведёт только уже
                   звучащие голоса, и 4-я нота (maj7 из трезвучия) молча не зазвучала бы
                   до следующей атаки (BACKLOG §4 — секторы делают этот баг достижимым). */
                if(latchDeg<0||(ty&&ty.length!==latchLen))WchOn('latch',S.deg,chOct,S.vol,chIdx,ty,bri);
                else WchSet('latch',S.deg,chOct,S.vol,ty,bri);          // та же плотность → глиссандо без переатаки
                S.ty=ty;                              // ЗАМОРОЗКА ТИПА на атаке (см. ведение ниже)
                latchLen=ty?ty.length:0;
                setLatchDeg(S.deg); setLatchOct(chOct); setLatchTy(ty); chOwner=key;      // рулит последний щипнувший; регистр — компаньон ступени для подсветки
                tutorTap('chord',{deg:S.deg, half:splitOn?(S.rx0>0?1:0):null});   // ЗАЦЕПКА ОБУЧЕНИЯ: аккорд зазвучал (свежая атака, защёлка); half — половина сплита (урок «Две роли»)
              }
            }
          }else if(chOwner===key&&latchDeg>=0){
            /* Ведение КАЖДЫЙ кадр (~60/с) → живой звук яркости плавный через chordGlide; запись прорежена
               мёртвой зоной в recChSet. В защёлке корень следует за рукой (Y); в удержании S.deg заморожен
               гейтом выше → корень СТОИТ, меняется лишь громкость (свелл) и яркость (Z).
               ТИП — ЗАМОРОЖЕННЫЙ S.ty (взят на атаке), а НЕ живой ty из палитры: аккорд выбран в момент
               смыкания пальцев и держит свой тип до размыкания. Иначе смена ячейки палитры ДРУГОЙ рукой
               перестраивала бы уже звучащий аккорд (chordGlide уводит частоты живых голосов, а при другом
               числе нот была бы ещё и переатака). Новый тип вступает в силу со СЛЕДУЮЩЕЙ атаки — ровно как
               событие лупера морозит a.ty, а слой — свой лад (sc). Корень при этом по-прежнему следует за
               рукой: заморожен ТОЛЬКО тип. */
            const dty=S.ty;
            if(dty&&dty.length!==latchLen){ WchOn('latch',S.deg,chOct,S.vol,chIdx,dty,bri); latchLen=dty.length; }   // подстраховка: latchLen мог переписать щипок ДРУГОЙ руки
            else WchSet('latch',S.deg,chOct,S.vol,dty,bri);   // ведение: Y=корень (rect) или ступень, X=громкость, Z=яркость
            setLatchDeg(S.deg); setLatchOct(chOct); setLatchTy(dty);   // тип и регистр ведём вместе со ступенью — иначе сравнение (и подсветка) протухнут
          }else if(chOwner===key){
            chOwner=null;                         // латч сброшен извне (тоника/лад/паника) — отпускаем руль
          }
          /* ⚠️ ЗДЕСЬ ОБНОВЛЯЛСЯ ОТДЕЛЬНЫЙ ПОКАЗ ЯРКОСТИ (setChBrightDisp) — УДАЛЁН. Показывать величину
             отсюда больше не нужно и нельзя: яркость — обычный эффект цепи, и её столбик рисует общий
             обход, читая ЖИВОЕ значение у самого параметра (getNorm). Писать рядом второе, зеркальное
             (1−bri) представление значило бы держать два источника одной величины. Сам звук идёт как
             шёл — bri уезжает в WchOn/WchSet и в событие (a.bri). */
        }
      }
    }
    /* ВЫРАЗИТЕЛЬНОСТЬ считается ПОФРЕЙМОВО (БЕЗ щипка — дышат движением, не щипком), только если ЭТА рука
       назначена на 'expr' в соло (сплит — по роли её половины, правило #18). Играет НИЧЕГО, владельца не
       берёт; признаки — из СЫРЫХ lm (правило #12). */
    S.isExpr = handHalfRole(key,S,W)==='ld' && handFnOf(key,'ld')==='expr';
    if(S.isExpr){ exprFeatures(S,lm,dtm,now);
      // ЗАЦЕПКА ОБУЧЕНИЯ: рука-выразительность реально ДВИЖЕТСЯ (энергия «смычка» перешла порог) — урок «Функции рук». Гистерезис (0.35↑/0.12↓), чтобы не спамить.
      if(S.exprE>0.35 && !S.tutExpr){ S.tutExpr=true; tutorTap('exprMove'); }
      else if(S.exprE<0.12) S.tutExpr=false;
    }
    /* ═══ ГЛУБИНА ИГРАЮЩЕЙ РУКИ → ПАРАМЕТР ЭФФЕКТА (Пласт 3.2) ═══
       Здесь замыкается разделение ОДНОГО эффекта между ДВУМЯ руками: параметры со своим `hand:'fx'`
       крутит палец (цикл в ветке зоны 'fx'), а помеченные `hand:'play'` ведёт ГЛУБИНА этой руки. Эффект
       при этом ОДИН — руки адресованы ПАРАМЕТРАМ, а не копиям эффекта.
       ⚠️ ОТОБРАЖЕНИЕ АБСОЛЮТНОЕ, а не «от точки захвата», и это не мелочь: играющая рука щиплет НА
       КАЖДУЮ НОТУ, поэтому захват сбрасывал бы точку отсчёта десятки раз за фразу и положение руки
       перестало бы что-либо значить. Формула — ДОСЛОВНО прежняя ревербная (и та же, что у яркости
       аккордов): рука ближе → 0, дальше → 1. Мышечная память с до-3.1 переезжает целиком.
       ⚠️ ИНВЕРСИЯ здесь ЗЕРКАЛИТ (1-v), а не меняет знак: у fx-руки инвертируется СМЕЩЕНИЕ (−d), а тут
       величина уже абсолютная 0..1. Перепутать — получить всегда-отрицательное и вечный ноль.
       ⚠️ УДЕРЖАНИЕ ПРИ ОТСУТСТВИИ: нет нотной руки соло в кадре — НИЧЕГО НЕ ПИШЕМ, параметр стоит на
       последнем значении. Прежний revDisp в этом случае гасился в 0, но он был ПОКАЗОМ; здесь это ЗВУК,
       и щелчок в ноль на каждом моргании трекинга был бы слышен.
       ⚠️ emaS('hs') зовём РОВНО РАЗ НА РУКУ ЗА КАДР. Двойной вызов дважды продвинул бы фильтр (та же
       ловушка, о которой предупреждает captureFx). Здесь это безопасно ПО ПОСТРОЕНИЮ: два других места
       считают hs только для ЩИПНУВШЕЙ руки в зоне 'fx' и для АККОРДОВОЙ руки, а нотная рука соло не
       может быть ни той, ни другой (у неё handFnOf='note'/'hold'/'therm' и зона 'ld'). */
    if(soloNoteHand(key,S,W)){
      const hsD=emaS(S,'hs',dist(lm[0],lm[9]),0.15);
      const vD=clamp01((REV_NEAR-hsD)/REV_RANGE);
      /* ⚠️ ЭТОТ БЛОК ПОЧТИ НЕ ИЗМЕНИЛСЯ В 3.4.2, и это показательно: он С САМОГО НАЧАЛА ходил по ВСЕЙ
         цепи и отбирал параметры ПО АДРЕСУ (hand==='play'), а не по слоту-пальцу. Пальцевая ветка
         только теперь пришла к той же форме. Пальца здесь нет по существу: у играющей руки адрес один
         — ГЛУБИНА. */
      const role='ld';   // одно имя на оба чтения (цепь + дескрипторы), как в captureFx: блок под гейтом soloNoteHand, то есть роль-половина этой руки заведомо соло
      for(const eff of fxChainOf(role)){
        if(!eff) continue;
        let ps=null;                                   // дескрипторы эффекта берём ЛЕНИВО: у большинства записей play-параметров нет вовсе
        eff.params.forEach((pa,i)=>{
          /* ⚠️ ФИЛЬТР ПО ОСИ ОБЯЗАТЕЛЕН С 3.7.3, и раньше его тут НЕ БЫЛО — потому что у играющей руки
             адрес был РОВНО ОДИН (глубина), и проверять было нечего. Теперь их два (play:z и play:x):
             без `axis==='z'` глубина писала бы и в параметр, отданный ГОРИЗОНТАЛИ, — два источника на одну
             величину, то самое, чего мы избегаем правилом «один параметр — один адрес». */
          if(pa.mode!=='drive' || pa.hand!=='play' || pa.axis!=='z') return;
          if(!ps) ps=fxParamsOf(role,eff.fxId);
          const p=ps[i]; if(p) p.set(pa.inv ? 1-vD : vD);
        });
      }
    }
    /* ⚠️ ПРИЦЕЛ РЕВЕРБА ДО ЩИПКА УДАЛЁН (Пласт 3.1). Здесь по каждому кадру считалась глубина нотной
       руки соло и писалась в revDisp, чтобы можно было «прицелиться» ревербом ещё до игры. Реверб ушёл
       с играющей руки к fx-руке (параметр 'mix'), поэтому целиться стало нечем и незачем: подмес виден
       обычным столбиком своего слота. Вместе с блоком ушли soloNoteHand и revDisp. */
  }
  // ЗАЦЕПКА ОБУЧЕНИЯ (heartbeat): рука в кадре — троттлинг ~1/с. Обучение так отличит «камера не видит руку»
  // от «рука есть, но шаг не сделан» и подскажет про камеру/свет, а не про жест невидимой руке.
  if(hands.length && now-tutSeenT>1000){ tutSeenT=now; tutorTap('seen'); }
  /* Watchdog: рука пропала из кадра во время щипка → принудительный
     release через 120 мс (короткая пауза прощает мигание трекинга). */
  for(const k of Object.keys(HANDS)){
    const S=HANDS[k];
    if(!seen.has(k)&&now-S.seen>WATCHDOG_MS){ endPinch(k,S); delete HANDS[k]; }
  }
  /* Соло-владельца сбрасывать больше нечего: голос гасит endPinch по ключу СВОЕЙ руки (его зовёт и
     watchdog выше), а бас — моно, у него владелец один и его надо снять руками. */
  if(bassOwner&&!HANDS[bassOwner]){ WbassOff(); bassOwner=null; }
  /* ⚠️ СБРОС ИНДИКАТОРА РЕВЕРБА УДАЛЁН вместе с самим индикатором (Пласт 3.1): гасить в 0 стало нечего.
     Подмес реверба живёт в модуле (латч, как у длины и окраски) и НЕ должен обнуляться от того, что
     рука вышла из кадра, — комната остаётся, пока её не убавят пальцем. */
  /* НЕТ ЗВУЧАЩЕГО ЗАЩЁЛКНУТОГО АККОРДА → РУЛЬ ЗАЩЁЛКИ СВОБОДЕН. (Сброс показа яркости отсюда ушёл
     вместе с самим показом: столбик BRI берёт величину у параметра и в обнулении «по факту тишины»
     не нуждается — эффект настроен на столько, на сколько настроен.)
     ⚠️ chOwner=null ЗДЕСЬ — слайс б.3. Обычно руль отпускает ветка зоны 'ch' (её «латч сброшен извне»)
     или endPinch, но ОБЕ гейтятся S.zone==='ch'. Стоит переставить руку-защёлку на ЭФФЕКТЫ — и она в
     эту зону больше не попадает: softAllOff гасит звук и ставит latchDeg=-1, а chOwner остаётся
     показывать на руку, которая аккордов уже не берёт. Само по себе это не звенело (все читатели
     chOwner живут в той же ветке, и следующая защёлка любой руки перезаписывала владельца), но
     ИНВАРИАНТ «нет защёлки — нет владельца» держать дешевле, чем каждый раз доказывать безвредность.
     Место выбрано рядом с таким же сторожем баса выше и НЕ зависит от зоны — в этом вся суть. */
  if(latchDeg<0) chOwner=null;
  tickExpr(now,dtm);                   // «смычок»: динамика + вывод в звук раз за кадр (или плавный вывод к нейтрали, когда руки-выразительности нет)
}

