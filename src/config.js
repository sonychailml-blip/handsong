/* ═══ ОДНА КРИВАЯ ГРОМКОСТИ ДЛЯ ВСЕХ РОЛЕЙ (слайс VOL-2b, решение пользователя «громкость стандартизуется») ═══
   v — число громкости ноты (a.vol, 0…1; в меню 0…100). Амплитуда голоса = v², помноженная на ПОЛНЫЙ уровень роли (соло 1,
   бас и аккорды ins.lvl, удар 1). 0 — ТОЧНАЯ тишина у каждой роли, 1 — ровно прежняя полная громкость.
   ⛳ ПОЧЕМУ v²: громкость на слух растёт как амплитуда^0.6 (Стивенс), значит «ровные по слуху шаги» просят амплитуду ≈ v^1.67;
   v² — ближайшая целая степень: половина хода −12 дБ («вдвое тише»), 10 — −40 дБ, 0 — тишина без особого случая, одно
   умножение. Линейная амплитуда (прежнее соло) сваливала почти всё слышимое изменение в верх хода; куб и выше отдали бы
   нижнюю половину уровням, которых динамик телефона почти не воспроизводит.
   ⛳ ПРЕЖНЯЯ КАРТА (до VOL-2b), СЕЙЧАС — ТОЛЬКО ДЛЯ ПЕРЕСЧЁТА: доля амплитуды = пол + (1 − пол)·v, пол по роли —
   соло 0, аккорды 0.25, бас 0.3, удар 0.3. Отсюда две функции:
     • volFromOld(роль, v) — число НОВОЙ шкалы, звучащее РОВНО как прежнее v: √(пол + (1 − пол)·v). Им пересчитаны
       громкости подложек (arrange.js), громкость ноты, вставленной в редакторе, и умолчание «Фиксировано».
     • volVel(роль, a) — вход СКОРОСТИ УДАРА (тембр атаки: удар соло-банков, цель фильтра аккорда и баса) из получившейся
       амплитуды a = v²: прежнее число, выраженное через амплитуду, (a − пол)/(1 − пол), с полом 0. Так соотношение
       «уровень ↔ яркость атаки» остаётся прежним, подложки совпадают и по тембру, а ноты тише прежнего пола упираются в
       базу фильтра — самую тёмную атаку, какая бывала и раньше.
   ⚠️ На v = 1 всё точно: 1·1 = 1, √(пол + (1 − пол)) = √1 = 1 (0.3+0.7 и 0.25+0.75 в double дают ровно 1), (1 − пол)/(1 − пол) = 1. */
const VOL_OLD_FLOOR={ ld:0, ch:0.25, bs:0.3, dr:0.3 };
export const volAmp=v=>{ const x = v>0 ? (v<1 ? v : 1) : 0; return x*x; };
export const volFromOld=(role,v)=>{ const f=VOL_OLD_FLOOR[role]||0; return Math.sqrt(f+(1-f)*v); };
export const volVel=(role,a)=>{ const f=VOL_OLD_FLOOR[role]||0; return f ? Math.max(0,(a-f)/(1-f)) : a; };

