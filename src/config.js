/* ПОЛЯ КАДРА. Доля кадра с КАЖДОЙ стороны, что остаётся ВНЕ игрового/видимого поля, чтобы
   MediaPipe продолжал видеть руку на КРАЙНИХ прямоугольниках: рука уходит за кромку картинки,
   но детектор (он читает ПОЛНЫЙ кадр <video>, поля его не касаются) ещё держит трекинг. Игровое
   поле = внутренние CAM_MARGIN..1-CAM_MARGIN кадра по КАЖДОЙ оси. ГЕСТ-МАТЕМАТИКА (щипок, размер
   ладони, палец, Z-реверб, пороги) считает по СЫРЫМ 0..1 — поля её не трогают; двигают ТОЛЬКО
   экранную позицию и ПОПАДАНИЕ (половина/прямоугольник/зона, X-громкость) через remapAxis. */
export const CAM_MARGIN=0.12;
/* Пересчёт СЫРОЙ нормированной координаты (0..1 кадра) в нормированную ИГРОВОГО поля (0..1):
   поле CAM_MARGIN..1-CAM_MARGIN → 0..1. Линейный, БЕЗ клампа — рука в полосе полей уезжает за
   кромку (<0 или >1), и это смысл фичи (крайние прямоугольники всё ещё в кадре). Клампится только
   РЕЗУЛЬТАТ выбора (нет прямоугольников за крайним), не координата. Симметричен относительно 0.5,
   поэтому КОММУТИРУЕТ с flipX (зеркало) — порядок flip/remap не важен. ЕДИНЫЙ источник ремапа: и
   gestures (попадание), и draw (рендер точек, видеофон) зовут его через state.sx/sy. */
export const remapAxis=v=>(v-CAM_MARGIN)/(1-2*CAM_MARGIN);

/* COVER-кадрирование видео в холст — ЕДИНАЯ формула для картинки И координат. Кадр камеры имеет
   СВОЁ соотношение сторон (обычно 4:3), холст — соотношение окна. Прямая растяжка одного в другое
   ИСКАЖАЛА картинку (на широком десктопе — видимый горизонтальный растяг). coverView возвращает
   суб-прямоугольник кадра (нормир. 0..1 по каждой оси), который: (а) ЦЕНТРИРОВАН; (б) в ПИКСЕЛЯХ
   имеет соотношение холста → cover: заполняет без полос, лишнее по одной оси обрезается, БЕЗ
   искажений; (в) ужат внутрь на CAM_MARGIN (зум для трекинга за кромкой — рука уходит за видимый
   край, детектор ещё держит её). Эту ОДНУ прямоугольную область читают И drawImage (draw, источник),
   И ремап точек (state.sx/sy, границы): картинка и рука кадрируются одним прямоугольником и не
   разъедутся (правило #12). Прямоугольник симметричен относительно 0.5 по X → КОММУТИРУЕТ с flipX
   (зеркало), порядок flip/кадрирование не важен. Заменяет прежний квадрат полей [M,1-M]², который
   игнорировал соотношение сторон и потому растягивал. Особый случай va==ca даёт ровно remapAxis. */
export const coverView=(vw,vh,W,H,M=CAM_MARGIN)=>{
  const va=vw/vh, ca=W/H, k=1-2*M;
  let fw,fh;
  if(ca>=va){ fw=1;     fh=va/ca; }   // холст ШИРЕ кадра → cover режет ВЫСОТУ (по X — вся ширина)
  else      { fw=ca/va; fh=1;     }   // холст УЖЕ кадра  → cover режет ШИРИНУ (по Y — вся высота)
  fw*=k; fh*=k;                        // ужать внутрь на поле CAM_MARGIN, обе оси одинаково → соотношение (cover) сохраняется
  return { ax0:(1-fw)/2, ax1:(1+fw)/2, ay0:(1-fh)/2, ay1:(1+fh)/2 };
};

