/* ПОЛЯ КАДРА. Доля кадра с КАЖДОЙ стороны, что остаётся ВНЕ игрового/видимого поля, чтобы
   MediaPipe продолжал видеть руку на КРАЙНИХ прямоугольниках: рука уходит за кромку картинки,
   но детектор (он читает ПОЛНЫЙ кадр <video>, поля его не касаются) ещё держит трекинг. Игровое
   поле = внутренние CAM_MARGIN..1-CAM_MARGIN кадра по КАЖДОЙ оси. ГЕСТ-МАТЕМАТИКА (щипок, размер
   ладони, палец, Z-реверб, пороги) считает по СЫРЫМ 0..1 — поля её не трогают; двигают ТОЛЬКО
   экранную позицию и ПОПАДАНИЕ (половина/прямоугольник/зона, X-громкость) через remapAxis. */
export const CAM_MARGIN=0.12;
/* Пересчёт СЫРОЙ нормированной координаты (0..1 кадра) в нормированную ИГРОВОГО поля (0..1):
   поле CAM_MARGIN..1-CAM_MARGIN → 0..1. Линейный, БЕЗ клампа — рука в полосе полей уезжает за
   кромку (<0 или >1), и это смысл фичи (крайние прямоугольники всё ещё в кадре). Клампится только
   РЕЗУЛЬТАТ выбора (нет прямоугольников за крайним), не координата. Симметричен относительно 0.5,
   поэтому КОММУТИРУЕТ с flipX (зеркало) — порядок flip/remap не важен. ЕДИНЫЙ источник ремапа: и
   gestures (попадание), и draw (рендер точек, видеофон) зовут его через state.sx/sy. */
export const remapAxis=v=>(v-CAM_MARGIN)/(1-2*CAM_MARGIN);

