/* REC3 part 2 (stage 3) — THE CAPTURE RECORDS (what a take played on its chains: snapshot + lane, by take number), their version, the
   take counter, the ONE law of a lane segment's shape (autSmoothOf / fxLaneAt / fxLaneExpand) and a track's role and chain key — moved
   from recorder.js (which re-exports them — a facade). The SAMPLING (takeCapStart / takeCapSample, the live chain) stays in the recorder.
   Pure: no DOM, no Web Audio; imports only song/ and config.js; the engine's declarations and the chain key through song/env.js.
   Moved verbatim; the edited lines are marked REC3. */
import { events, evRole } from './store.js';
import { ENV } from './env.js';
import { curveU } from '../config.js';
const fxPerm=(...a)=>ENV.fxPerm(...a), chainKeyOf=(...a)=>ENV.chainKeyOf(...a);   // REC3: the engine's declaration and the chain key, wired

/* REC3: the take number — monotonic for the session (see the recorder's comment at curTake); takeNext() hands out the next one */
let takeSeq=0;
const takeNext=()=>++takeSeq;
/* ═══ ЗАХВАТ СЫГРАННОГО: СНИМОК ЦЕПЕЙ + ДОРОЖКА АВТОМАТИЗАЦИИ (слайс O-2) ═══
   ⛳ ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ. ЗАМОРОЗКА — это РЕЖИМ ВОСПРОИЗВЕДЕНИЯ, а не преобразование: дорожку можно
   разморозить, поправить и заморозить снова, сколько угодно раз. Это работает только если ПОВТОРНЫЙ
   рендер даёт ТОТ ЖЕ звук, а значит всё, что рендер читает, обязано лежать В ЗАПИСИ, а не на живой
   ручке. Крутанул ручку и не записал — восстановить уже нечем.
   ⚠️ СЕГОДНЯ НЕ ПОМНИТ НИКТО: аккорды, бас и ударные не помнили никогда, а у соло пер-нотные величины
   снял слайс O-1 (эффекты стали свойством звучащего тембра). Этот реестр — замена сразу для всех
   владельцев и для ВСЕХ параметров, включая те, что пер-нотными быть не могли в принципе: длина и
   окраска комнаты, время и повторы делея, глубина и скорость тремоло.
   ⛳ КЛЮЧ — НОМЕР ВЗЯТОГО, и это не вкус. ⛔ Не дорожка: в одной дорожке лежит несколько взятых,
   записанных в разное время и с разными настройками. ⛔ Не номер слоя: номера ПЕРЕИСПОЛЬЗУЮТСЯ и имеют
   дыры (см. закон у laneNew). tk уже стоит на КАЖДОМ событии — по нему всё и сходится.
   ФОРМА ЗАПИСИ:
     { kinds:{ключ:вид}, chains:{ключ:[{fxId,params:[v01,…]},…]}, lane:[{t,key,fx,p,v},…] }
     chains — СОСТАВ И ЗНАЧЕНИЯ на старте взятого, В ПОРЯДКЕ ЦЕПИ (цепь последовательна — порядок слышен);
     lane   — ТОЛЬКО ИЗМЕНЕНИЯ после старта, t в АБСОЛЮТНЫХ ПЕСЕННЫХ долях (как у событий);
     kinds  — вид владельца ключа (см. chainOwners): чтобы цепи ТЕМБРА потом слились, а не мигрировали.
   ⛔ ЭТО НЕ СОБЫТИЯ. Реестр живёт РЯДОМ с events и не входит в него: он не касается ни курсоров
   переигровки, ни отсортированного префикса, ни единственной точки сброса (правило #28). Тронет —
   станет источником событий и унаследует все их законы разом. */
const takeFx=new Map();
/* ⛳ ВЕРСИЯ ЗАХВАТА — ЕДИНСТВЕННАЯ ИМЕНОВАННАЯ ТОЧКА ЕГО ПРОТУХАНИЯ (слайс O-4).
   ⚠️ ЗАЧЕМ ОНА ПОНАДОБИЛАСЬ. Подпись ленты переигровки (fxPlaySignature) считала ДЛИНЫ: число событий,
   число взятых, число точек. Пока захват только РОС, этого хватало. Редактор же двигает точку — время и
   величина меняются, а длины все до одной остаются прежними: лента не пересобралась бы, и правка не
   зазвучала бы, причём МОЛЧА. Поэтому всякая правка захвата поднимает счётчик, а подпись его читает.
   ⛔ ЭТО НЕ schedInvalidate И РЯДОМ С НИМ НЕ СТОИТ: захват — не события (правило #28), у него своя
   лента, свой курсор и вот эта своя точка сброса. Смешаешь — захват станет источником событий. */
let takeFxVer=0;
const takeFxTouch=()=>{ takeFxVer++; };
const FX_CHAIN='#chain';   // ⚠️ ЗАРЕЗЕРВИРОВАННЫЙ id записи состава. Решётка не может встретиться в настоящем fxId (те — идентификаторы), поэтому столкнуться не с чем
/* ═══ ГЛАДКАЯ АВТОМАТИЗАЦИЯ ШИННЫХ ПАРАМЕТРОВ — ОДИН ЗАКОН ИНТЕРПОЛЯЦИИ ═══
   ⛳ ФОРМА ЖИВЁТ НА ТОЧКЕ И ОПИСЫВАЕТ ОТРЕЗОК, КОТОРЫЙ В НЕЁ ВХОДИТ (поле sh точки ленты). ТРИ значения:
     's' — ПЛАВНО (поставил человек), по прямой в НОРМИРОВАННОЙ шкале 0..1 — той самой, в которой полоса рисует (у лог-параметров
           это ровный ход на слух, как и у ручки);
     'h' — СТУПЕНЬКОЙ (поставил человек: точка после полки, кнопка ⌐, правленая точка, застывшая в ступеньке);
     нет поля — ЗАПИСАННАЯ точка: отрезок в неё ПЛАВНЫЙ (autSmoothOf ниже). Пауза записанного — не форма отрезка, а ДАННЫЕ: тонкая
           запись (fineStep) находит её по излому и кладёт ТОЧКУ УДЕРЖАНИЯ с прежней величиной в миг, где рука пошла, — поэтому ровная
           пауза и подъём ровно с места движения получаются сами, а медленное движение — сплошной прямой, хоть единица за пять секунд.
   ⛳ ПОЧЕМУ БОЛЬШЕ НЕ ВЫВОДИМ ПО ПРОМЕЖУТКУ И СКАЧКУ (как было в слайсе «плавная внутри движения»). Тот закон отличал движение от паузы
   по ДВУМ точкам: длинный промежуток с решительным скачком — ступенька. Медленное движение (единица в секунду и медленнее) даёт ровно
   такие промежутки — и закон рисовал бы его ступенями. Различить медленное движение и паузу по двум точкам нельзя; по ВСЕМ выборкам
   между ними — можно, и это делает запись, у которой они есть (fineKnee). Отрезку остаётся одно правило: записанное — плавно.
   Её зовут ВСЕ: переигровка (fxPlayDrive на тике), рендер заморозки и ухо-проба (fxLaneExpand) и рисунок полосы (autPointsCalc кладёт
   ответ в вид, draw его только читает). Разойтись рисунку и звуку нечем.
   ⛳ ОТ ТОЧКИ СНИМКА (snap) ПЛАВНЫЙ ОТРЕЗОК НЕ НАЧИНАЕТСЯ: снимок — состояние цепи на старте взятого, а не точка с ручкой; полоса
   рисует его полкой, и прямая от начала взятого к первой точке была бы подъёмом, которого там никто не ставил.
   ⛳ ПЕРЕКЛЮЧАТЕЛЬ ДЛЯ УХА (autRecSmoothOn): выключен — записанные точки снова ступеньки, как до слайса, везде сразу (▶, полоса,
   рендер, R.live). Ставит его только ухо-проба (render.recSteps / aud({recSteps})); в интерфейсе его нет.
   Живая переигровка зовёт это на каждом тике (fxPlayDrive), рендер и ухо-проба — через fxLaneExpand. Второй формулы нет. */
let autRecSmoothOn=true;
const setAutRecSmooth=on=>{ autRecSmoothOn=!!on; takeFxTouch(); };   // takeFxTouch — переигровка пересоберёт ленту, полоса — вид (мемо autPoints)
/* ФОРМА ОТРЕЗКА prev→pt: форма человека главнее; нет её — записанная точка, отрезок в неё плавный (если переключатель уха не снят).
   prev — точка, не снимок (от снимка не едут — см. fxLaneSmooth). Пустой промежуток — не отрезок. */
function autSmoothOf(prev,pt){
  if(!prev||!pt) return false;
  if(pt.sh==='s') return true;
  if(pt.sh) return false;                                         // 'h' — ступенька, поставленная человеком
  return autRecSmoothOn && pt.t>prev.t+1e-9;
}
const fxLaneSmooth=e=>{ const n=e&&e.nx; return !!(n && !e.snap && n.t>e.t+1e-9 && autSmoothOf(e,n)); };
function fxLaneAt(e,x){
  if(!fxLaneSmooth(e)) return e.v;
  const n=e.nx, u=(x-e.t)/(n.t-e.t);
  return u<=0 ? e.v : u>=1 ? n.v : e.v+(n.v-e.v)*curveU(u,n.k||0);   // BEND-CURVE: the one shape law (config.curveU), straight when k is absent
}
/* РАЗВЁРТКА ПЛАВНЫХ ОТРЕЗКОВ В ТОЧКИ — для тех, кто ставит величины ЗАРАНЕЕ по списку (офлайн-рендер, ухо-проба R.live).
   ⛳ ШАГ — ТОТ ЖЕ, ЧТО У ЖИВОГО ТИКА (SCHED_TICK_MS), переведённый в доли по темпу вызывающего: живой тик ставит величину раз в
   25 мс, сеттер сглаживает ступеньку своей τ; рендер обязан делать ровно то же, иначе заморозка звучала бы глаже или грубее ▶.
   Сэмпл несёт tk и слой своей точки, поэтому победитель при равной доле решается тем же законом (сортировка по (t, tk)).
   ⚠️ Нативную рампу AudioParam (linearRamp/exponentialRamp) здесь НЕ берём, и это не лень: величина обязана пройти СЕТТЕР
   эффекта (единственная дверь, правило #29), а сеттеры нелинейны — длина реверба пересчитывается в усиления четырёх линий
   (10^(−3d/RT60)), глубина тремоло пишет два узла. Рампа в одном AudioParam повела бы не ту величину, которую рисует полоса. */
function fxLaneExpand(list,stepBeats){
  if(!(stepBeats>0)) return list;
  const out=[];
  for(const e of list){ out.push(e);
    if(e.fx===FX_CHAIN || !fxLaneSmooth(e)) continue;
    for(let t=e.t+stepBeats; t<e.nx.t-1e-9; t+=stepBeats) out.push({ t, tk:e.tk, layer:e.layer, key:e.key, fx:e.fx, p:e.p, v:fxLaneAt(e,t) });
  }
  out.sort((a,b)=> a.t-b.t || a.tk-b.tk);   // устойчивая сортировка: при равной доле и взятом точка ленты остаётся перед сэмплом, как и была
  return out;
}
/* ⛳ РОЛЬ ДОРОЖКИ (T4). С T2 в дорожке РОВНО ОДНА роль (маршрут по источнику), поэтому роль первого же её
   события с ролью — это роль всей дорожки; вторую искать незачем, её там нет по построению.
   null — у дорожки нет ни одной ноты: опустела правками или это слой дрона (дрон — уровень, а не нота, и
   роли не даёт — см. evRole). ⛔ Роль НЕ выдумывается: вызывающий обязан показать «нот нет», а не ось
   чужой роли. O(событий) — зовут её на открытии редактора и в правках цепи, не на кадр. */
function laneRoleOf(layer){
  if(layer==null) return null;
  for(const e of events) if(e.layer===layer){ const r=evRole(e.fn); if(r) return r; }
  return null;
}
/* ОДНА ЦЕПЬ ДОРОЖКИ — ключ владельца её роли. Выбора «в чью цепь» больше нет (его держали вкладки
   редактора, пока дорожка могла нести несколько ролей): у дорожки ровно одна роль, значит одна цепь. */
const laneChainKey=layer=>{ const r=laneRoleOf(layer); return r ? chainKeyOf(r) : null; };
/* ЧТО ЗАХВАЧЕНО У ДОРОЖКИ — для показа в редакторе (единственный сегодняшний читатель). Отдаёт СВОДКУ,
   а не сам реестр: наружу не должно утекать то, что пока никто не исполняет.
   ⛳ ОТБОР ПО ЦЕПИ САМОЙ ДОРОЖКИ — ГЛАВНОЕ ЗДЕСЬ, и это правка ошибки, а не украшение. Реестр взятого
   хранит цепи ВСЕХ владельцев (сплит пишет две роли в одно взятое, и они ложатся в РАЗНЫЕ дорожки);
   без отбора басовая дорожка показывала бы делей СОЛО и яркость АККОРДОВ. С T4 отбор — по ОДНОЙ цепи:
   роль у дорожки одна (laneRoleOf).
   ⚠️ ИМЕНА ЭФФЕКТОВ СОБИРАЕМ И ИЗ СНИМКА, И ИЗ ДОРОЖКИ. Снимок — это состав НА СТАРТЕ взятого; эффект,
   добавленный ПОСРЕДИ него, живёт только в дорожке (записью состава и своими величинами). Без второго
   источника «добавил реверб во время записи» читалось бы как «ничего не захвачено» — при непустом счёте
   точек, то есть противоречиво.
   ⚠️ null, А НЕ ПУСТАЯ СВОДКА, когда дорожки нет или у неё нет роли (опустевшая дорожка, слой дрона):
   показывать «захвачено: ничего» там, где вопрос неприменим, — шум. */
function captureInfoOf(layer){
  const role=laneRoleOf(layer); if(!role) return null;
  const key=chainKeyOf(role), tks=new Set();
  for(const e of events) if(e.layer===layer) tks.add(e.tk||0);
  const ids=new Set(); let pts=0;
  for(const tk of tks){ const r=takeFx.get(tk); if(!r) continue;
    const ch=r.chains[key]; if(ch) for(const e of ch) if(!fxPerm(e.fxId)) ids.add(e.fxId);   // VOL-0: громкость в сводке не называем (она у дорожки есть всегда и в этом слайсе невидима)
    for(const ent of r.lane){ if(ent.key!==key||fxPerm(ent.fx)) continue; pts++; if(ent.fx!==FX_CHAIN) ids.add(ent.fx); }   // FX_CHAIN — служебная запись состава, у неё нет имени и показывать её нечем. VOL-0/VOL-2: точки громкости (они бывают, когда громкость на пальце руки-эффектов — тогда захват пишет её общий p.cur; на горизонтали её p.cur не движется) в счёт не идут — громкость «в ноте», переигровка их не читает, и сводка их не называет
  }
  return { takes:tks.size, role, fx:[...ids], pts };
}

