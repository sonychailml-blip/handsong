const songAt=m=>{ if(!cycling()) return m; return m-rgnReps(m)*rgnLen(); };
/* ═══ СКОБА ПОВТОРА (слайс S3.5b) — ОДИН орган на ДВЕ работы, как loop brace в DAW ═══
   ГРАНИЦЫ скобы — ЧТО повторяется (когда ⟳ включён); НАЧАЛО скобы — ОТКУДА начинается запись.
   ⛔ Отдельной «линейки точки записи» нет и не заводить: это решение, а не упрощение.
   Кнопка ⟳ теперь ТОЛЬКО включает/выключает повтор скобы и границ НЕ переопределяет (прежде она на
   каждом включении помечала всю песню заново).
   ⛳ ДВА СОСТОЯНИЯ (rgn.user):
     false — СКОБА СЛЕДУЕТ ЗА МАТЕРИАЛОМ: [0, конец материала вверх до такта]. Так её видит нетронутая
             песня, и так она растёт при записи.
     true  — человек её ПОСТАВИЛ: стоит, где поставили; запись за её конец её НЕ двигает. Трогает её лишь
             одно — песня стала КОРОЧЕ её конца (отмена, снятие подложки): поджимаем к концу материала,
             чтобы скоба не указывала в пустоту. ✕ (clearRec) возвращает в «следует».
   ⛳ КВАНТ — ТАКТ, И ЭТО НЕ НЕДОДЕЛКА. На полосе в ~300px такт пятиминутной песни — пара пикселей: любая
     точность мельче такта была бы ЛОЖЬЮ о том, куда попал палец. ⛔ Не «улучшать» до долей без зума
     таймлайна. Побочная выгода — несущая: длина скобы кратна размеру, поэтому монотонная доля и песенная
     различаются на ЦЕЛОЕ число тактов — акценты метронома при повторе не съезжают, а перепривязка
     опоры (rgnApply) точна без округлений.
   ⛳ МИНИМУМ — ОДИН ТАКТ. Нулевая скоба не повторяет ничего (cycling() и так не считал её повтором) и
     на экране неотличима от отсутствия; повтор ОДНОГО такта — законная музыка (такт барабанов, остинато).
     Поэтому ноль запрещён клампом, такт разрешён. */
const braceCapBars=()=>Math.max(1,Math.ceil(songLen/loop.metre-1e-9));   // тактов материала (не меньше одного); −1e-9 — чтобы 8.0000000001 долей не дали лишний пустой такт
function braceClamp(from,to){                // ЕДИНЫЙ кламп границ: [0, конец материала], длина ≥ такт
  const M=loop.metre, cap=braceCapBars()*M;
  to=Math.min(to,cap); from=Math.max(0,Math.min(from,to-M)); to=Math.max(to,from+M);
  return [from,to];
}
/* ⛳ ЕДИНСТВЕННЫЙ ПИСАТЕЛЬ ГРАНИЦ И ВКЛЮЧЕНИЯ rgn (как laneNew у дорожек). Одно исключение — рост
   «следующей» скобы в push (braceFollowGrow), и оно безопасно ровно потому, что там повтор выключен.
   ⚠️ ГЛАВНАЯ РАБОТА — ПЕРЕПРИВЯЗКА ОПОРЫ, если транспорт идёт. Песенная доля — это songAt(m) по
   ГРАНИЦАМ; смени границы при неподвижной t0 — и песенная доля ПРЫГНЕТ. Именно так было до этого
   слайса: выключи ⟳ после нескольких проходов — m уже далеко за концом песни, songAt стал тождеством,
   и транспорт тут же вставал «в конце». Теперь: берём песенную долю p по СТАРОЙ карте, пишем границы и
   сдвигаем опору (t0, sched, lead, clickBeat) на целое число тактов так, чтобы по НОВОЙ карте сейчас было
   ровно p. Звук не рвётся, уже запланированное не дублируется, щелчки не съезжают.
   ⚠️ ИСКЛЮЧЕНИЕ — БЕГУНОК ОКАЗАЛСЯ ЗА КОНЦОМ ВКЛЮЧЁННОЙ СКОБЫ (край подвинули левее него): прыгаем на её
   НАЧАЛО — ровно то, что сделал бы шов. Это перемотка, и цена у неё та же, что у seekTo: голоса дорожек
   гасим, а удары/щелчки, уже поставленные в окно SCHED_AHEAD (~300мс), доиграют.
   Бегунок ПЕРЕД началом скобы остаётся где был и въезжает в неё линейно — решение S3.4 (rgnReps=0 до
   первого достижения конца), здесь не пересматривается. */
function rgnApply(from,to,on){
  const R=loop.rgn;
  if(from===R.from && to===R.to && on===R.on) return;
  const live=!!AC && loop.on;
  const m=live ? (AC.currentTime-loop.t0)*loop.bpm/60 : 0;
  const p=live ? songAt(m) : 0;                              // песенная доля по СТАРОЙ карте
  R.from=from; R.to=to; R.on=on;
  if(!live || m<loop.lead) return;                           // стоим или идёт отсчёт — опору заново поставит запуск/сама не сдвинется
  const spb=60/loop.bpm, d=m-p, past=cycling() && p>=R.to-1e-9;
  if(past || Math.abs(d-Math.round(d))>1e-6){                // вторая ветка — страховка: при потактовых границах d всегда целое
    const tgt=past ? R.from : p;
    releaseLoopLayersAt();
    loop.t0=AC.currentTime+0.06-tgt*spb; loop.lead=tgt; loop.cnt=false;
    loop.pos=tgt-1e-9; loop.sched=tgt; loop.clickBeat=Math.floor(tgt);
    if(tgt>1e-9){ const T=loop.t0+tgt*spb; chasePlay(tgt,T,false); chasePlay(tgt,T,true); }   // S3.5c: прыжок — тоже вход не с начала (см. chaseFor). chaseAt здесь может быть от старых границ — ключ кэша ДОЛЯ, не границы, поэтому он верен
    return;
  }
  const k=Math.round(d);
  if(k){ loop.t0+=k*spb; loop.sched-=k; loop.lead-=k; loop.clickBeat-=k; }   // монотонные величины — на k долей назад; loop.pos (ПЕСЕННАЯ) не трогаем: она и есть то, что сохраняем
}
/* Привести границы к материалу: «следующая» — пересчитать, «поставленная» — только поджать. Зовётся из
   schedInvalidate — единственной точки, через которую проходит КАЖДОЕ изменение состава событий
   (отмена, подложка, очистка, остановка записи), поэтому второго списка мест не заводим. */
function rgnSync(){
  const R=loop.rgn;
  const [from,to]= R.user ? braceClamp(R.from,R.to) : braceClamp(0, braceCapBars()*loop.metre);
  rgnApply(from,to,R.on);
}
/* Рост «следующей» скобы по одному событию — O(1), из push. ⚠️ ПРЯМАЯ запись мимо rgnApply, и она
   безопасна ТОЛЬКО при выключенном повторе: тогда границы не входят во временнýю карту вовсе. При
   включённом повторе расти и нечему — push сворачивает время внутрь скобы. Полный пересчёт — rgnSync. */
function braceFollowGrow(){
  const R=loop.rgn; if(R.user || cycling()) return;
  const to=braceCapBars()*loop.metre; if(to>R.to) R.to=to;
}
const regionOn=()=>loop.rgn.on;
/* ⟳ — ТОЛЬКО включить/выключить повтор скобы. Границы не трогает.
   ⚠️ СОРТИРОВКА ВО ВРЕМЯ ЗАПИСИ — несущая: schedInvalidate объявляет ВЕСЬ массив отсортированным
   префиксом (cursN=length), а дописанный хвост записи не отсортирован. Прежний setRegion звал
   schedInvalidate при записи БЕЗ сортировки — курсоры бинарным поиском шли по несортированному, и
   события других дорожек могли пропускаться. Сортировка на тапе стоит O(n log n) один раз. */
function setRegionOn(on){
  if(recording) events.sort((x,y)=>x.t-y.t);
  rgnSync();
  rgnApply(loop.rgn.from, loop.rgn.to, !!on);
  schedInvalidate();
}
/* ⛳ ТАП ПО ПОЛОСЕ СКОБЫ: доля → БЛИЖАЙШАЯ ЛИНИЯ ТАКТА; туда едет БЛИЖНИЙ к ней край. Равное расстояние
   (скоба в два такта, тап по средней линии) решает сторона тапа от середины скобы — иначе скобу в два
   такта нельзя было бы сузить до одного ни одним тапом. Возвращает, какой край взят ('from'/'to'), —
   ui держит его при перетаскивании, чтобы край не «перескакивал» на соседний.
   ⛔ ВО ВРЕМЯ ЗАПИСИ ПРАВКА ЗАПРЕЩЕНА (как и перемотка): сдвиг времени под открытыми нотами. */
function braceTap(beat){
  if(!AC||recording) return null;
  rgnSync();
  const R=loop.rgn, M=loop.metre, line=Math.max(0,Math.round(beat/M))*M;
  const d1=Math.abs(line-R.from), d2=Math.abs(line-R.to);
  const edge= d1<d2 ? 'from' : d2<d1 ? 'to' : (beat<(R.from+R.to)/2 ? 'from' : 'to');
  braceMove(edge,beat);
  return edge;
}
/* Поставить край edge на ближайшую к beat линию такта. Первое касание переводит скобу в «поставлена». */
function braceMove(edge,beat){
  if(!AC||recording) return;
  const R=loop.rgn, M=loop.metre, line=Math.max(0,Math.round(beat/M))*M;
  let from=R.from, to=R.to;
  if(edge==='from') from=Math.min(line,to-M); else to=Math.max(line,from+M);
  [from,to]=braceClamp(from,to);
  if(R.user && from===R.from && to===R.to) return;         // перетаскивание внутри того же такта: ничего не трогаем (и не перепривязываем каждый кадр)
  R.user=true;
  rgnApply(from,to,R.on); schedInvalidate();
}
/* ГРУППИРОВКА (акценты) по размеру — СТАТИЧНАЯ, по умолчанию. Массив длин групп, сумма = размер.
   Нечётные размеры чувствуются НЕ ровно: балканская 7 = 3+2+2, 9 = 2+2+2+3, 5 = 2+3; индийский
   тинтал (16) — 4 вибхага по 4. Пользовательский выбор 3+2+2 vs 2+2+3 отложен (BACKLOG §3.23) —
   один разумный вариант на размер. Дефолт нечислового/неизвестного — одна группа (акцент только сам).
   khali — индексы ГРУПП, что ОСЛАБЛЕНЫ (не акцент, а «пустая» голова, структурная черта тала). */
const METRE_GROUPS={ 2:[2],3:[3],4:[4],5:[2,3],6:[3,3],7:[3,2,2],8:[4,4],9:[2,2,2,3],10:[2,3,2,3],12:[3,3,3,3],16:[4,4,4,4] };
const METRE_KHALI ={ 16:[2] };   // тинтал: 3-й вибхаг (индекс 2 = доля 8) — khali (открытый баян, без баса)
/* Уровень акцента доли b∈[0,metre): 2 сам (начало такта), 1 голова группы, -1 khali-голова, 0 обычная. */
function beatLevel(metre,b){
  const g=METRE_GROUPS[metre]||[metre], kh=METRE_KHALI[metre]||[];
  let acc=0;
  for(let i=0;i<g.length;i++){ if(acc===b) return b===0?2:(kh.includes(i)?-1:1); acc+=g[i]; }
  return 0;   // не голова группы
}
const loopChordDeg=()=>loop.on?curChordDeg:-1;       // draw: подсветить аккорд петли, когда рука его не держит
const loopChordOct=()=>loop.on?curChordOct:0;        // его регистр — тем же путём (подсветка ищет прямоугольник по ПАРЕ deg+oct)
const maxLayer=()=>events.reduce((m,e)=>Math.max(m,e.layer),0);

/* ═══ ДОРОЖКИ: ЗАГЛУШЕНИЕ И СОЛО (слайс S1 «Редактора дорожек») ═══
   ⚠️ НАСТРОЙКА КЛЮЧУЕТСЯ НА СГЕНЕРИРОВАННОМ id ДОРОЖКИ, А НЕ НА НОМЕРЕ СЛОЯ. Номер для этого НЕ
   ГОДИТСЯ, и это не предосторожность на будущее, а три уже существующих факта:
     (1) номера ПЕРЕИСПОЛЬЗУЮТСЯ — овердаб берёт maxLayer()+1, поэтому после ⤺ отмены следующая
         запись получает ТОТ ЖЕ номер; ключуйся мы на номере, новая дорожка молча родилась бы
         заглушённой (и человек искал бы пропавший звук);
     (2) в номерах бывают ДЫРЫ — clearJam вырезает события ПО МЕТКЕ ev.jam, а не по слою, поэтому
         «слои 0 и 2 без 1» — нормальное состояние, а не сбой;
     (3) onUndo НЕ ПЕРЕНУМЕРОВЫВАЕТ — и не должен: номер слоя зашит в КЛЮЧИ ВЛАДЕЛЬЦЕВ ГОЛОСОВ
         ('loop:N' / 'bassloop:N' / 'leadloop:N:v'), перенумерация оторвала бы звучащие голоса от
         их владельцев.
   Отсюда разделение: НОМЕР СЛОЯ — адрес ЗВУКА (ключи владельцев, события), id ДОРОЖКИ — адрес
   НАСТРОЙКИ, связывает их одна таблица laneId.
   ⛔ Не сливать их и ⛔ не писать id в событие: формат события слайс S1 НЕ трогает вовсе. */
let laneSeq=0;
const laneId=new Map();      // номер слоя → СТАБИЛЬНЫЙ id дорожки
const laneMute=new Set();    // id заглушённых дорожек
const laneSolo=new Set();    // id дорожек в соло
/* ⛳ ЗАКОН ЭТОГО БЛОКА, И НА НЁМ ДЕРЖИТСЯ ВСЯ КОРРЕКТНОСТЬ ДОРОЖЕК:
   **laneNew — ЕДИНСТВЕННЫЙ ПИСАТЕЛЬ laneId, и он ВСЕГДА выдаёт СВЕЖИЙ id, ЗАТИРАЯ прежнюю запись
   этого номера.** Значит правильность обеспечивает РОЖДЕНИЕ слоя, а не уборка за умершим.
   ⚠️ ПОЧЕМУ НЕ НАОБОРОТ (держать правильность на уборке) — так было, и это была мина: номера
   ПЕРЕИСПОЛЬЗУЮТСЯ (овердаб берёт maxLayer()+1), поэтому ОДНА пропущенная уборка означала бы, что
   свежезаписанный слой унаследовал id покойника вместе с его заглушением. Наружу это выглядит как
   «моя новая дорожка молчит, и непонятно почему» — тихо, правдоподобно и ищется долго.
   Теперь такого состояния не существует: что бы ни осталось в laneMute/laneSolo, НИ ОДИН номер на
   эти id больше не отображается, поэтому они НИКОГДА НИ С ЧЕМ НЕ СОВПАДУТ.
   ⛔ Не заводить второго писателя laneId. Появится новое место, где рождается слой, — оно обязано
   звать laneNew; список мест — в отчёте слайса и в комментариях у самих мест. */
function laneNew(layer){
  const old=laneId.get(layer);
  if(old!=null){ laneMute.delete(old); laneSolo.delete(old); }   // ГИГИЕНА, А НЕ КОРРЕКТНОСТЬ: без этой строки старый id просто мёртвым грузом лежал бы в множестве и ни на что не влиял — но множества росли бы всю сессию
  laneId.set(layer,++laneSeq);
  return laneSeq;
}
/* ЧТЕНИЕ id — ЧИСТОЕ: вернёт либо ДЕЙСТВУЮЩИЙ id номера (тот, что выдало последнее рождение), либо
   undefined. ⛔ ЗАВОДИТЬ id ЗДЕСЬ НЕЛЬЗЯ, и это не стиль: «страховка», заводящая id по требованию,
   была бы ВТОРЫМ писателем, а значит вторым источником правды о том, какое поколение номера сейчас
   живёт. Отсутствие записи читается как «обычная слышимая дорожка» — что и верно: id, которого
   никогда не выдавали, не может лежать ни в laneMute, ни в laneSolo. */
const laneOf=layer=>laneId.get(layer);
/* Уборка за слоями, у которых больше НЕТ СОБЫТИЙ (⤺ отмена слоя, снятие подложки).
   ⚠️ ЭТО ГИГИЕНА, А НЕ КОРРЕКТНОСТЬ (см. закон выше): пропусти мы её где-нибудь — таблица и
   множества просто подрастут мусором, но ни одна дорожка не перепутается, потому что номер получит
   свежий id при следующем рождении. Держим ради того, чтобы состояние не копилось за долгую сессию.
   Пишущийся слой ЩАДИМ — он законно пуст, пока в него не сыграли (его строку уже показывает полоса). */
function lanePrune(){
  const live=new Set(); for(const e of events) live.add(e.layer);
  for(const [ly,id] of laneId) if(!live.has(ly) && !(recording&&ly===loop.layer)){
    laneId.delete(ly); laneMute.delete(id); laneSolo.delete(id); }
}
/* ⚠️ laneSeq НАМЕРЕННО НЕ ОБНУЛЯЕТСЯ: счётчик монотонен на всю сессию. Обнуление вернуло бы в оборот
   уже выданные номера id — а это ровно тот вид совпадения, от которого id и заводился. Стоит он
   ничего (целое число), а класс ошибок закрывает целиком. */
function laneReset(){ laneId.clear(); laneMute.clear(); laneSolo.clear(); }
/* ⛳ ПРЕДИКАТ СЛЫШИМОСТИ — ОДИН НА ОБА ПУТИ ПЕРЕИГРОВКИ (scheduleLayers и fireNear).
   СОЛО ПЕРЕБИВАЕТ ЗАГЛУШЕНИЕ: как только соло включено хоть где-то, слышны РОВНО соло-дорожки, а
   остальные молчат независимо от своих галочек mute (и возвращаются как были, когда соло снимут). */
/* Зовётся из планировщика (40 раз в секунду на каждое событие) и из draw — поэтому важно, что laneOf
   ЧИСТЫЙ: ни одной записи в таблицу на горячем пути. Нет id → дорожка обычная, слышимая. */
const laneAudible=layer=>{ const id=laneOf(layer);
  return laneSolo.size ? (id!=null&&laneSolo.has(id)) : !(id!=null&&laneMute.has(id)); };
/* ⛳ ГЕЙТ ЦЕЛИКОМ ВЫКЛЮЧЕН, ПОКА НИЧЕГО НЕ ЗАГЛУШЕНО И НИЧЕГО НЕ В СОЛО — и это НЕ микро-оптимизация,
   а УСЛОВИЕ ПРИЁМКИ слайса: пока человек не тронул переключатели, пер-событийная проверка не
   выполняется ВООБЩЕ (в цикле остаётся один уже вычисленный булев), и переигровка идёт байт-в-байт
   как раньше. Считается ОДИН РАЗ НА ВЫЗОВ планировщика, а не на событие. */
const laneGated=()=> laneMute.size>0 || laneSolo.size>0;
/* Дрон — не нота, а УРОВЕНЬ (выделенные узлы, softAllOff его не трогает), поэтому «заглушить слой
   с дроном» нельзя сделать пропуском события: droneOn уже отработал. Спрашиваем отдельно, слышен ли
   дрон хоть на одной дорожке, и ведём общий уровень. */
const droneAudible=()=>events.some(e=>e.fn==='drone'&&laneAudible(e.layer));
/* Переключатели. Наружу дорожка адресуется НОМЕРОМ СЛОЯ — тем же, чем подписана её строка на полосе
   лупера; id остаётся внутренним делом (ui не может подержать протухший id).
   ⚠️ `?? laneNew(layer)` — НЕ «мягкое заведение id», а ЕДИНСТВЕННЫЙ БЕЗОПАСНЫЙ способ его получить,
   когда записи нет. Он безопасен ровно потому, что ОТСУТСТВИЕ записи не может нести устаревший id:
   вернуть что-то протухшее laneOf физически неспособен (он либо отдаёт действующий id, либо ничего).
   Сюда мы попадаем, только если слой родился мимо всех известных мест рождения, — то есть это ещё и
   САМОПОЧИНКА: дорожка получит id и переключатель сработает, вместо того чтобы молча ничего не делать. */
function toggleLaneMute(layer){ const id=laneOf(layer) ?? laneNew(layer);
  if(laneMute.has(id)) laneMute.delete(id); else laneMute.add(id);
  laneHush(); }
function toggleLaneSolo(layer){ const id=laneOf(layer) ?? laneNew(layer);
  if(laneSolo.has(id)) laneSolo.delete(id); else laneSolo.add(id);
  laneHush(); }
/* ЧИТАТЕЛИ ДЛЯ ПОКАЗА — через тот же чистый laneOf (их зовёт draw на каждый кадр; правило #5 с
   обратной стороны: рисование не смеет менять состояние). */
const laneMuted =layer=>{ const id=laneOf(layer); return id!=null&&laneMute.has(id); };
const laneSoloed=layer=>{ const id=laneOf(layer); return id!=null&&laneSolo.has(id); };
const laneSoloOn=()=> laneSolo.size>0;
/* ⚠️ ЗАГЛУШАТЬ НАДО НЕМЕДЛЕННО, А НЕ «СО СЛЕДУЮЩЕГО СОБЫТИЯ»: удержанный аккорд слоя звучал бы до
   заворота (chOff у него ещё впереди). Ключи владельцев дают ТОЧНЫЙ адрес слоя, поэтому гасим ровно
   ставшие неслышимыми слои — ТЕМ ЖЕ обходом, что и граница повтора (releaseLoopLayersAt со слоем),
   второго обхода не заводим.
   Зовём после КАЖДОГО переключения и проходим ВСЕ слои, а не только тронутый: включение соло делает
   неслышимыми чужие дорожки, а снятие одного из двух соло — ту, что осталась без него.
   Уже молчащие слои проходят вхолостую (chordOff/bassOff/leadOff выходят сразу, если владельца нет).
   ⚠️ УДАРНЫЕ ОТМЕНИТЬ НЕЛЬЗЯ: drumHit — одноразовые осцилляторы, поэтому удары, уже запланированные
   в окно SCHED_AHEAD (~300мс), прозвучат ПОСЛЕ заглушения. Та же принятая и ограниченная цена, что у
   стопа петли и у отмены слоя; чинить её здесь нечем. */
function laneHush(){
  if(!AC) return;
  const seen=new Set();
  for(const e of events){ if(seen.has(e.layer)) continue; seen.add(e.layer);
    if(!laneAudible(e.layer)) releaseLoopLayersAt(undefined,e.layer); }
  if(droneActive()){ if(loop.on&&droneAudible()) droneOn(); else droneOff(); }   // уровень дрона — по слышимости ЕГО дорожки (уровень, а не нота: пропуском события его не заглушить)
}

/* Позиция для визуализации: фаза отсчёта / игры, ПЕСЕННАЯ доля, длина песни в долях.
   ⛳ ДВЕ ПОЗИЦИИ, И У КАЖДОГО ПОТРЕБИТЕЛЯ СВОЯ (слайс S3.5b — именно здесь их и перепутали):
     МОНОТОННАЯ m = (now−t0)·bpm/60 — это ЧАСЫ. Ею считают ТОЛЬКО арифметику времени: опору t0 (смена
       темпа, перепривязка области), окно опережения планировщика (loop.sched, горизонт), счёт проходов
       области (rgnReps), отсчёт перед записью (m<0), индекс щелчка метронома (clickBeat).
     ПЕСЕННАЯ p = songAt(m) — это МЕСТО В МАТЕРИАЛЕ. Ею пользуется ВСЁ, что указывает на события или на
       длину песни: запись (push/curBeat), переигровка лида (fireNear, loop.pos), точка возобновления,
       конец песни — и ВСЁ, ЧТО ВИДИТ ЧЕЛОВЕК: бегунок полосы и её ширина.
   ⚠️ БАГ, КОТОРЫЙ ЭТО ЧИНИТ: здесь отдавалась МОНОТОННАЯ доля. Без области они совпадают (songAt —
   тождество), поэтому S3.3 был прав; S3.4 развёл их — звук пошёл по песенной и зациклился, а полоса
   осталась на часах: бегунок уезжал за конец, а ширина (max(песня, pos, подложка)) росла вслед за ним
   и дорисовывала новые такты без конца. Правило простое: ПОКАЗЫВАЕМ МАТЕРИАЛ — значит ПЕСЕННАЯ. */
function loopPos(){
  if(!loop.on||!AC)return null;
  const e=(AC.currentTime-loop.t0)*loop.bpm/60;
  /* Отсчёт кончается на ДОЛЕ ЗАПУСКА loop.lead, а не на нуле (S3.5b, тот же довод, что в tick/push): запись
     со скобы с такта 3 отсчитывает доли 4..8 — они ≥0, и по старому `e<0` полоса показывала бы бегущий
     бегунок во втором такте вместо «ОТСЧЁТ». При старте с 0 (lead=0) — прежнее `e<0` дословно. Разгон
     без отсчёта (60мс после ▶) показывает бегунок на точке запуска, а не мигает «ОТСЧЁТ 1». */
  if(e<loop.lead && loop.cnt) return {phase:'count', countLeft:Math.ceil(loop.lead-e), pos:0, total:songLen};
  return {phase:'play', pos:songAt(Math.max(e,loop.lead)), total:songLen};   // songAt: при выключенной области тождество → байт-в-байт прежнее
}

/* ENG — единая точка исполнения (живьём через W* и на переигровке). deg→частота
   выводится ЗДЕСЬ. Ладовый КОНТЕКСТ: живьём (ctx нет) — текущий лад/септаккорд;
   на переигровке ctx=событие с ЗАМОРОЖЕННЫМ ладом (ev.sc) и септаккордом (ev.sev),
   §3.4. baseF() всегда живой → тоника глобальна, лад заморожен. leadFreq/bassFreq
   сами страхуют ступень вне лада (модуло+октава), так что частота не улетает в NaN.
   Владелец голосов ПО СЛОЮ (ctx=событие переигровки): аккорд — 'loop:'+layer / живой
   'latch'; бас — 'bassloop:'+layer / живой 'bass'. Так слой не крадёт голос у живого. */
const chOwnerKey  =ctx=> ctx?'loop:'+ctx.layer:'latch';
const bassOwnerKey=ctx=> ctx?'bassloop:'+ctx.layer:'bass';
/* Ключ владельца СОЛО-голоса на ПЕРЕИГРОВКЕ: слой + номер одновременной ноты (a.v). Живой ключ
   ('lead:L'/'lead:R') строит gestures и передаёт явным аргументом — в событие он НЕ попадает (это
   состояние руки, а не намерение). a.v||0 — вот та самая совместимость: событие без v = нота №0. */
const ldKey=(ctx,a)=> ctx ? 'leadloop:'+ctx.layer+':'+(a.v||0) : 'lead:?';
/* ⛳ ЕДИНАЯ ФОРМА ВЫЗОВА: КАЖДАЯ запись ENG — это (a, ctx, opt), где opt — ОДИН И ТОТ ЖЕ ИМЕНОВАННЫЙ
   набор `{when, live, own}`. Слайс S2 завёл эту форму, и это НЕ косметика, а снятие ловушки.
   ⚠️ ЧТО БЫЛО: у записей была РАЗНАЯ позиционная форма — `leadOn:(a,ctx,live,own)` против
   `chOn:(a,ctx,when)` и `bassOn:(a,ctx,when,live)`, — а диспетчер планировщика зовёт их ОДИНАКОВО:
   `ENG[ev.fn](ev.a, ev, when)`. Пока лид шёл мимо планировщика (fireNear), это сходило с рук. Но стоило
   бы завести лид в планировщик — и ВРЕМЯ В СЕКУНДАХ легло бы в слот ЖИВЫХ ГЕРЦ терменвокса: нота
   зазвучала бы на абсурдной высоте или не зазвучала вовсе. Тихо, правдоподобно, ищется долго.
   ⚠️ ПОЧЕМУ НЕ ХВАТИЛО БЫ «поставить when последним у всех». У лида кроме when есть ещё live и own,
   поэтому третий позиционный слот У РАЗНЫХ записей всё равно значил бы разное — в каком порядке ни
   расставляй. Ловушка позиционная ПО ПРИРОДЕ, и лечится она только снятием позиционности: у
   дополнительных аргументов больше НЕТ номеров, есть ИМЕНА. Время может попасть в `live` теперь лишь
   у того, кто СОБСТВЕННОРУЧНО напишет слово `live`, — то есть ошибка стала невыразимой, а не
   несовершённой.
   ⚠️ live (живые Гц терменвокса) остаётся ОТДЕЛЬНЫМ полем и ЖИВЫМ-ТОЛЬКО (правило #11): переигровка
   его не передаёт никогда, частота там выводится из ступени по замороженному ладу.
   ⛔ Добавляешь запись в ENG — держи ту же форму. Второй формы здесь быть не должно. */
const ENG={
  /* ⚠️ setLeadInstr(a.inst) ОТСЮДА УБРАН, и это ПОЧИНКА, а не потеря: переигранный слой уводил ЖИВОЙ
     инструмент (и кнопку в панели) — слой на Ситаре молча перекрашивал руку, играющую Органом. Теперь
     тембр печётся В ГОЛОСЕ на атаке (leadOn получает inst), как это давно делают аккорды и бас. */
  leadOn:(a,ctx,{when,live,own}={})=>{ const o=own||ldKey(ctx,a);
              /* live — ЖИВОЙ override частоты (терменвокс): непрерывные Гц вместо ступенной leadFreq.
                 Только на ЖИВОМ пути (WleadOn); переигровка зовёт ENG без live → частота из leadFreq по
                 замороженному ладу (полимодальность цела). */
              if(ctx)leadCancel(o,when);           // атака переигранной ноты: снять рампы прошлого бенда (не перетечёт) — ТОЛЬКО в своём голосе и В ТО ЖЕ ВРЕМЯ, что и атака
              const base=leadFreq(a.deg,a.oct,ctx?ctx.sc:CUR());
              applyFx(a.fx);   // КАРТА ЭФФЕКТОВ ЭТОГО СОБЫТИЯ (3.7.2). Нет карты (события аранжировки) → applyFx возьмёт ТЕКУЩУЮ цепь роли, а не нейтраль
              leadOn(o,(live!=null?live:base),a.vol,a.inst===undefined?leadIdx:a.inst,a.deg,a.oct,when);   // deg/oct — не для звука (частота уже посчитана), а для ПОДСВЕТКИ: leadHold знает, что звучит
              if(a.bend&&a.bend.length)scheduleBend(o,a.bend,base,60/loop.bpm,when); },   // переигровка: кривая бенда поверх ступени замороженного лада, в СВОЙ голос, с якорем в момент атаки
  leadSet:(a,ctx,{when,own}={})=>{ const o=own||ldKey(ctx,a);
              applyFx(a.fx);
              leadSet(o,(a.hold?null:leadFreq(a.deg,a.oct,ctx?ctx.sc:CUR())),a.vol,a.deg,a.oct,when); },   // live здесь не читался никогда: ведение терменвокса идёт через hold:true (частоту не сбиваем), а не через override
  leadOff:(a,ctx,{when,own}={})=>leadOff(own||ldKey(ctx,a),when),
  /* when — ЯВНОЕ время (опережение лупера, §планировщик). Живой путь (W*) зовёт без when → undefined
     → аудио-функции берут AC.currentTime (сейчас), байт-в-байт. Переигровка слоёв передаёт точное время. */
  chOn:(a,ctx,{when}={})=>chordOn(chOwnerKey(ctx),chordFreqs(a.deg,a.oct,ctx?ctx.sc:CUR(),ctx?ctx.sev:seventh,a.ty),a.vol,a.inst,a.bri,when),   // a.bri — пер-событийная яркость (0=нейтраль); when остаётся ПОСЛЕДНИМ (планировщик)
  chSet:(a,ctx,{when}={})=>chordGlide(chOwnerKey(ctx),chordFreqs(a.deg,a.oct,ctx?ctx.sc:CUR(),ctx?ctx.sev:seventh,a.ty),a.vol,a.bri,when),
  chOff:(a,ctx,{when}={})=>chordOff(chOwnerKey(ctx),when),
  bassOn:(a,ctx,{when,live}={})=>bassOn(bassOwnerKey(ctx),(live!=null?live:bassFreq(a.deg,a.oct,ctx?ctx.sc:CUR())),a.vol,a.inst,when),   // live — живой override Гц (терменвокс-бас), как у leadOn; переигровка без него → bassFreq (полимодальность цела)
  bassSet:(a,ctx,{when}={})=>bassSet(bassOwnerKey(ctx),bassFreq(a.deg,a.oct,ctx?ctx.sc:CUR()),a.vol,when),
  bassOff:(a,ctx,{when}={})=>bassOff(bassOwnerKey(ctx),when),
  drum:(a,ctx,{when}={})=>drumHit(a.row,a.vol,a.kit,when),
  drone:(a,ctx,{when}={})=>droneOn(a.lvl,when),        // дрон: выделенные узлы, гасится по жизненному циклу (не в softAllOff)
};
const inPB=()=>loop.on;                               // для строки статуса (draw)

/* Сетка квантизации в долях: аккорды — доля, бас — восьмая, соло — не квантуется.
   УДАРНЫЕ — 1/loop.sub доли: при sub=4 шестнадцатая (как было), при sub=3 ТРИОЛЬ. Дробление —
   ЯВНАЯ настройка (панель лупера), а НЕ вывод из последнего загруженного паттерна: неявная смена
   поведения квантизации (снял джем — сетка молча переехала) хуже лишнего контрола. */
const gridFor=fn=> fn[0]==='c'?1 : fn.slice(0,4)==='bass'?0.5 : fn==='drum'?1/(loop.sub||4) : 0;
/* Запись события на ТЕКУЩУЮ АБСОЛЮТНУЮ долю песни; при квантизации время снапится к сетке.
   ⛳ ЗДЕСЬ БЫЛ СГИБ В ПЕТЛЮ — `t = e % lb` (S3.3 его снял). Ровно эта строка и делала запись
   петлёй: она уничтожала абсолютное время В МОМЕНТ ЗАПИСИ, ещё до того как событие возникало.
   ⛔ И ВМЕСТЕ С НИМ УМЕРЛА ЕГО СПУТНИЦА — «складка заворота». Она существовала затем, что при
   триольной сетке (g=1/3) удар у самого конца круга округлялся к lb−1e-16, а `%` такое значение НЕ
   сворачивал, и событие садилось на волосок ДО конца петли вместо доли 0 — на слух пропадал сильный
   удар. Без модуло округлять некуда: t=Math.round(t/g)*g и есть окончательное время.
   ⚠️ НЕ ВОССТАНАВЛИВАТЬ ни то, ни другое: обе строки осмысленны ТОЛЬКО при сворачивании в петлю, и
   вернуть их — значит вернуть петлю. Зацикливание придёт ОБЛАСТЬЮ на таймлайне, а не модулем здесь. */
/* at — ЯВНАЯ песенная доля (S3.5a-fix), и зовёт так РОВНО ОДНО место: закрытие соло-ноты на шве прохода
   (recFoldRoll), где «сейчас» уже свернулось в начало области, а выключение принадлежит КОНЦУ прошлого
   прохода. С at не квантуем (соло и так не квантуется) и не сворачиваем. Без at — байт-в-байт как было. */
function push(fn,a,at){
  if(!AC)return;
  /* ⛳ ЗАПИСЬ ИДЁТ В ПЕСЕННОЙ ДОЛЕ, то есть СВЁРНУТОЙ в область (S3.4). Отсюда и ответ на вопрос «что
     делает ● при включённом повторе»: НАКОПЛЕНИЕ В ОБЛАСТЬ — каждый следующий проход дописывает
     поверх, как и ждут от лупера и как приложение вело себя до S3.3. Ветки для этого не понадобилось
     ни одной: songAt — та же свёртка, что делал прежний `e % lb`, только переанкеренная. */
  const m=(AC.currentTime-loop.t0)*loop.bpm/60;
  /* ⚠️ ОТСЧЁТ КОНЧАЕТСЯ НА ДОЛЕ ЗАПУСКА (loop.lead), А НЕ НА НУЛЕ (S3.5b). Прежнее `e<0` было верно
     только при старте с доли 0; с доли 8 отсчёт шёл по долям 4..8 — они ≥0, и сыгранное во время
     отсчёта ложилось в запись ДО точки записи. При старте с 0 lead=0 — то же самое, что было. */
  if(at==null && m<loop.lead) return;
  const e= at!=null ? at : songAt(m);
  if(e<0)return;                                      // ещё идёт отсчёт
  let t=e;
  const g=(loop.quant&&at==null)?gridFor(fn):0;
  if(g>0){
    t=Math.round(t/g)*g;
    /* ⚠️ ОКРУГЛЕНИЕ МОГЛО ВЫНЕСТИ СОБЫТИЕ ЗА КОНЕЦ ОБЛАСТИ — сыграно внутри, а село бы снаружи, где
       повтор его уже не услышит. Сворачиваем на НАЧАЛО области: музыкально это то же место следующего
       прохода. Гейт `e<to` — чтобы трогать ровно то, что и правда сыграно внутри.
       ⛔ ЭТО НЕ ВОССТАНОВЛЕННАЯ «складка заворота» из S3.3: та была безусловной и жила при модуло,
       эта работает ТОЛЬКО при включённой области и только на её границе. */
    const R=loop.rgn;
    if(cycling() && e<R.to && t>=R.to-1e-9) t=R.from;
  }
  /* ⛔ КОПИЯ КАРТЫ ЭФФЕКТОВ — R1, САМЫЙ ОПАСНЫЙ БАГ ЭТОГО ПЛАСТА, ЗАКРЫТ ЗДЕСЬ И ТОЛЬКО ЗДЕСЬ.
     До 3.7.2 ВСЯ полезная нагрузка была примитивами, кроме двух намеренных ссылок: ty (никогда не
     мутируется) и bend (дописывается осознанно). Карта a.fx — первый МУТИРУЕМЫЙ объект в нагрузке, а
     push кладёт `a` ПО ССЫЛКЕ, и вызывающие копируют МЕЛКО ({...p}) — значит без этой строки один и
     тот же объект оказался бы и в записанном событии, и в живом состоянии сравнения. Следующее
     движение руки тихо переписало бы УЖЕ ЗАПИСАННОЕ прошлое: слой начал бы звучать не так, как его
     сыграли. Снаружи это читается как «петля сама меняется» — и искать причину пришлось бы долго.
     ЗАПИСАННАЯ КАРТА С ЭТОГО МОМЕНТА НЕИЗМЕНЯЕМА: её больше никто не трогает, только читает. */
  const ev={t,layer:loop.layer,fn,a,sc:CUR(),sev:seventh};   // §3.4: замораживаем ладовый контекст события
  if(a && a.fx) ev.a={...a, fx:{...a.fx}};
  events.push(ev);
  if(t>songLen){ songLen=t; braceFollowGrow(); }      // длина песни растёт по одному событию (полный пересчёт — только в schedInvalidate); «следующая» скоба — вместе с ней, O(1)
}
/* АБСОЛЮТНАЯ доля СЕЙЧАС (тот же счёт, что и push) — для dt точек бенда.
   ⛳ Модуль снят вместе с петлёй. Побочно это ПОЧИНКА: у ноты, тянувшейся через бывший заворот, dt
   уходил в минус и зажимался нулём (см. pushBend) — кривая бенда там врала. Теперь dt монотонен. */
const curBeat=()=>songAt((AC.currentTime-loop.t0)*loop.bpm/60);   // ПЕСЕННАЯ доля — тот же счёт, что у push (иначе dt бенда разошёлся бы с временем самой ноты)
/* Точка бенда: центы ЖИВОЙ высоты (live) относительно ступени АТАКИ (r.deg/oct по
   замороженному-в-будущем ладу CUR()). Само-прореживание порогом BEND_EPS_CENTS.
   ⛳ Кламп dt≥0 ОСТАВЛЕН, но повод у него сменился: прежде dt уходил в минус у ноты, тянувшейся ЧЕРЕЗ
   ЗАВОРОТ (curBeat сворачивался по модулю и падал ниже опоры r.t0). Заворота нет, время монотонно —
   теперь это просто страховка от отрицательного dt при перемотке/смене темпа.
   Опора и порог — В ЗАПИСИ ВЛАДЕЛЬЦА (r), поэтому две гнущие руки не путают друг другу отсчёт. */
function pushBend(r,live){
  if(!r||!r.bend||live==null)return;
  const c=1200*Math.log2(live/leadFreq(r.deg,r.oct,CUR()));
  if(r.lastC!=null&&Math.abs(c-r.lastC)<=BEND_EPS_CENTS)return;
  r.bend.push({dt:Math.max(0,curBeat()-r.t0),c});
  r.lastC=c;
}
/* СВОБОДНЫЙ НОМЕР одновременной ноты v внутри пишущегося слоя: 0,1,2… Нужен только чтобы переигровка
   спарила leadOn с его leadOff (в слое может быть открыто несколько соло-нот). Первая всегда получает 0
   — поэтому обычная одноголосная запись даёт события с v:0, а старые (без v) читаются как v=0. */
/* ⛳ S3.5a: СЧЁТ НАЧИНАЕТСЯ С vBase, А НЕ С НУЛЯ. freeSlot видит только ОТКРЫТЫЕ сейчас ноты (vSlots) и
   ничего не знает о том, что уже ЛЕЖИТ в слое. Пока каждое взятое рождает НОВЫЙ слой, лежать там нечему
   и vBase=0 — события байт-в-байт прежние. Но стоит писать В СУЩЕСТВУЮЩУЮ дорожку — и новая нота взяла
   бы v:0 у лежащей ноты с тем же v: владелец 'leadloop:N:0' один на двоих, на переигровке поздняя
   крадёт голос ранней, а leadOff ранней гасит позднюю. Две перекрытые по времени ноты глушат друг друга.
   ⚠️ ВНУТРИ взятого номера по-прежнему ПЕРЕИСПОЛЬЗУЮТСЯ (свободный от открытых) — это держит их малыми;
   монотонный счётчик «номер на ноту» тоже был бы верен (leadAlloc ищет голос по ключу лишь пока нота
   зажата), но плодил бы тысячи ключей без нужды. */
function freeSlot(){ const used=new Set([...vSlots.values()]); let v=vBase; while(used.has(v))v++; return v; }
/* Первый номер v ВЫШЕ всех соло-нот, уже лежащих в слое layer (0 — соло-нот нет). Событие без v — это
   нота №0 (совместимость ldKey), поэтому считаем его как 0, и слой со старой записью даст 1.
   ⛳ ОБХОД O(n) — ОДИН РАЗ НА ВЗЯТОЕ, на нажатии ●, а НЕ на ноту и НЕ в push: слайс S3.2 затем и был,
   чтобы на горячем пути не ходить по всей песне. На том же нажатии и так идёт maxLayer() — такой же
   полный обход, то есть цена нажатия ● по порядку не меняется. Кэша по слою НЕ заводим сознательно:
   его пришлось бы держать в строю через onUndo/clearJam/compactEvents — ещё одна точка рассинхрона.
   Отсортированность массива не нужна (максимум), поэтому хвост записи ему не помеха. */
function layerSlotTop(layer){
  let top=0;
  for(const e of events) if(e.layer===layer && e.fn.slice(0,4)==='lead'){ const v=(e.a&&e.a.v)||0; if(v+1>top) top=v+1; }
  return top;
}
/* live!=null ⟺ соло-рука назначена на ТЕРМЕНВОКС (функция руки 'therm' — gestures шлёт S.hz только
   оттуда). Тогда высоту несёт БЕНД: deg/oct ЗАМОРОЖЕНЫ на атаке (не сравниваем и не обновляем — у c
   стабильная опора), а leadSet пишем лишь на смену громкости/реверба/тембра с меткой hold (переигровка
   не сбивает бенд частотой).
   live==null (рука на любой ДРУГОЙ функции — ноты/удержание/эффекты) — логика БАЙТ-В-БАЙТ как раньше,
   только состояние взято по владельцу own. */
/* ⛳ ОБОБЩЁННОЕ ДЕЛЬТА-СЖАТИЕ ПО КАРТЕ ЭФФЕКТОВ (Пласт 3.7.2) — вместо явного списка полей.
   Прежде сравнивались ЧЕТЫРЕ ИМЕНОВАННЫХ поля (deg/oct/inst/vol/rev), а vib/drv/trm/dly, хотя и лежали
   в нагрузке, В СРАВНЕНИЕ НЕ ВХОДИЛИ ВОВСЕ — поэтому «покрутил ручку при зажатой ноте» не писалось
   НИЧЕГО, и эффекты в слой фактически не записывались. Теперь набор параметров ПРОИЗВОЛЕН, значит и
   сравнение — по МНОЖЕСТВУ: другой состав ключей ИЛИ любой ключ ушёл дальше мёртвой зоны.
   ⚠️ Порог REC_FX_EPS — в НОРМИРОВАННЫХ единицах, один на все параметры (довод — в config). */
function fxChanged(a,b){
  const A=a||{}, B=b||{}, ka=Object.keys(A), kb=Object.keys(B);
  if(ka.length!==kb.length) return true;
  for(const k of ka){ if(!(k in B) || Math.abs(A[k]-B[k])>REC_FX_EPS) return true; }
  return false;
}
const fxCopy=m=> m?{...m}:m;   // в состояние сравнения кладём КОПИЮ: иначе r.fx стал бы псевдонимом живого снимка и «изменилось?» всегда было бы «нет»
function recLeadEv(own,p,live){
  if(!recording)return;
  recFoldRoll();                                   // S3.5a-fix: СНАЧАЛА шов (если время свернулось) — иначе ниже нашлась бы запись ноты ПРОШЛОГО прохода или выдался бы номер от старой базы
  let r=recLead.get(own);
  if(!r){
    const v=freeSlot(); vSlots.set(own,v);
    if(v+1>vTop) vTop=v+1;                         // высшая выданная за взятое — до неё поднимется база на шве
    const a={...p,v};                              // v — номер одновременной ноты в слое (пара для leadOff)
    r={deg:p.deg,oct:p.oct,vol:p.vol,fx:fxCopy(p.fx),inst:p.inst,bend:null,t0:0,lastC:null,v};
    if(live!=null){ a.bend=[]; r.bend=a.bend; r.t0=curBeat(); }
    push('leadOn',a);
    recLead.set(own,r);
    if(live!=null)pushBend(r,live);                // стартовая точка (r уже есть — опора известна)
    return;
  }
  if(live!=null){                                  // терменвокс: пишем бенд + громкость/ЭФФЕКТЫ (hold), НЕ deg/oct
    pushBend(r,live);
    /* ⚠️ БЕНД НЕ ТРОГАЕМ (R3): точка бенда дописывается в a.bend ПОСЛЕ push, по ссылке из r.bend, и
       опора (r.deg/r.oct/r.t0/r.lastC) живёт своей жизнью. Карта эффектов добавлена РЯДОМ, ни ссылка,
       ни пороги бенда не задеты — hold:true по-прежнему говорит переигровке «частоту не сбивать». */
    if(p.inst!==r.inst||Math.abs(p.vol-r.vol)>REC_VOL_EPS||fxChanged(p.fx,r.fx)){
      push('leadSet',{...p,hold:true,v:r.v});
      r.vol=p.vol; r.fx=fxCopy(p.fx); r.inst=p.inst;   // deg/oct остаются на атаке
    }
    return;
  }
  if(p.deg!==r.deg||p.oct!==r.oct||p.inst!==r.inst||
     Math.abs(p.vol-r.vol)>REC_VOL_EPS||fxChanged(p.fx,r.fx)){ push('leadSet',{...p,v:r.v}); }
  else return;
  r.deg=p.deg; r.oct=p.oct; r.vol=p.vol; r.fx=fxCopy(p.fx); r.inst=p.inst;
}
function recLeadOff(own){ recFoldRoll();          // S3.5a-fix: шов ПЕРВЫМ — нота прошлого прохода закрывается на его КОНЦЕ, а не свёрнутым «сейчас» (иначе leadOff лёг бы раньше своего leadOn и нота повисла бы)
  const r=recLead.get(own);
  if(recording&&r) push('leadOff',{v:r.v});
  recLead.delete(own); vSlots.delete(own); }
function recLeadReset(){ recLead.clear(); vSlots.clear(); }   // паника/очистка: открытых нот больше нет (шов прохода во время записи идёт через recFoldRoll)
/* ═══ ШОВ ПРОХОДА ОБЛАСТИ ВО ВРЕМЯ ЗАПИСИ (слайс S3.5a-fix) ═══
   ⚠️ БАГ, КОТОРЫЙ ЭТО ЗАКРЫВАЕТ: при включённом ⟳ одно взятое пишет НЕСКОЛЬКО ПРОХОДОВ В ОДИН СЛОЙ (push
   сворачивает время в область). Раньше на шве состояние записи просто сбрасывалось, и счёт номеров
   начинался заново с vBase — нота второго прохода получала v ноты первого, которая звучит под ней. На
   переигровке поздняя крала голос ранней, а leadOff ранней обрывал позднюю.
   ⛳ ЛЕЧЕНИЕ: на шве (1) каждая открытая нота получает НАСТОЯЩИЙ leadOff на КОНЦЕ прохода (rgn.to) — она
   больше не сирота и её номер закрыт ровно один раз; (2) база поднимается выше ВСЕХ выданных за взятое
   (vBase=vTop), поэтому номер прошлого прохода больше не выдаётся никогда. ВНУТРИ прохода номера
   по-прежнему переиспользуются (freeSlot), как в линейной записи.
   ⚠️ ПОЧЕМУ ШОВ ОПРЕДЕЛЯЕМ ПО «ВРЕМЯ ЗАПИСИ ПОШЛО НАЗАД», А НЕ ТОЛЬКО ИЗ tick. Граничная функция
   liveWrapRelease достигается на КАЖДОМ шве, но ПОЗДНО: tick ходит раз в SCHED_TICK_MS (плюс любой
   затор потока), а кадр жестов между пересечением шва и тиком уже пишет СВЁРНУТОЕ время. Нота, взятая
   в этой щели, получила бы номер от старой базы, а потом тиковый сброс оставил бы её без выключения.
   Поэтому проверку зовут ОБА пути — tick (через liveWrapRelease) и сама запись (recLeadEv/recLeadOff), —
   а функция ИДЕМПОТЕНТНА: второй вызов на том же шве видит время уже не назад и ничего не делает.
   «Назад» — ровно определение бага: время вернулось на уже записанный материал. Отсюда и свойство:
   номера делятся только внутри МОНОТОННОГО участка времени, а там логика открытых нот верна.
   ⛔ ПРИ ВЫКЛЮЧЕННОЙ ОБЛАСТИ песенная доля монотонна (перемотка во время записи запрещена, темп держит
   долю) — условие не наступает НИКОГДА, база не растёт, события байт-в-байт прежние. */
function recFoldRoll(){
  if(!recording||!AC) return;
  const now=curBeat();
  if(now<recLastT-1e-6){
    const at = cycling() ? loop.rgn.to : recLastT;           // конец прохода; без области «назад» не бывает — страховка последней виденной долей
    for(const r of recLead.values()) push('leadOff',{v:r.v},at);
    recLead.clear(); vSlots.clear();
    vBase=Math.max(vBase,vTop);
  }
  recLastT=now;
}
