/* ================= ЗАПИСЬ И ЛУПЕР =================
   Событие — НАМЕРЕНИЕ, не кадр: время в ДОЛЯХ внутри петли (t ∈ [0,loopBeats)),
   высота — СТУПЕНЬ+ОКТАВА (deg/oct); частота выводится на исполнении через
   leadFreq/chordFreqs → петля перестраивается под текущий строй (§3.7).
   Пишем по изменению (дискретное — при смене, непрерывное — за мёртвой зоной),
   так кадровый лог (~60/с) схлопывается в горстку точек на ноту.
   Схема события: {t, layer, fn, a}. layer — слой овердаба (единица отмены).

   ЛУПЕР. Один насос по часам AudioContext крутит петлю фиксированной длины
   (loop.bars тактов). Позиция в долях = ((now−t0)·bpm/60) mod loopBeats; на
   завороте зависшие голоса гасятся, события переигрываются с начала. Живой ввод
   идёт через W* (звук сразу + запись, если вооружено), переигровка зовёт ENG
   НАПРЯМУЮ — поэтому переигранное не пишется заново без всякого гейта. Овердаб:
   петля играет и одновременно пишется новый слой; слой, что пишется прямо сейчас,
   НЕ переигрывается (его слышно живьём) — иначе двойной триггер.
   ВЛАДЕЛЬЦЫ ГОЛОСОВ ПО СЛОЮ: живой аккорд — 'latch', переигранный — 'loop:N';
   живой бас — 'bass', переигранный — 'bassloop:N'. Поэтому один и тот же инструмент
   слоится сам на себя (аккорд поверх аккорда, бас поверх баса) — разные владельцы,
   разные голоса из пула.
   ⚠️ СОЛО ТЕПЕРЬ ТОЖЕ ПОЛИФОНИЧНО И ТОЖЕ РАЗВЕДЕНО ПО ВЛАДЕЛЬЦАМ: живая рука — 'lead:L'/'lead:R'
   (ключ строит soloKey в gestures, он же расширяется пальцем), переигранный слой — 'leadloop:N:v'.
   ЗДЕСЬ РАНЬШЕ БЫЛО НАПИСАНО «соло остаётся моно (один envGain): соло-поверх-соло делит голос,
   побеждает последний — это не баг». БОЛЬШЕ НЕ ТАК, и это была ровно та надпись, что отправляла
   искать не там: живая игра и переигранный соло-слой больше НЕ дерутся, две руки звучат вместе.
   v в событии — НОМЕР ОДНОВРЕМЕННОЙ НОТЫ внутри слоя (0,1,…): без него две руки, пишущие разом,
   не различить на переигровке (leadOff не с чем спарить). Старые события без v читаются как v=0 —
   один голос на слой, то есть старая петля играет БИТ-В-БИТ как играла. */
let recording=false;                                 // «вооружено»: пишем живой ввод
const events=[];                                     // стабильная ссылка (её читает визуализация в draw)
const loop={ on:false, bars:2, metre:BEATS_PER_BAR, sub:4, bpm:84, t0:0, pos:-1e-9, sched:0, first:false, layer:0, clickBeat:0, quant:true };   // metre — долей в такте; sub — ДРОБЛЕНИЕ доли для квантизации ударных (4 = 16-е, 3 = триоли); pos — «сыгранная» доля (лид/дрон, почти-сейчас); sched — АБСОЛЮТНАЯ доля, до которой СЛОИ (аккорд/бас/удар) уже запланированы вперёд
const droneActive=()=>events.some(e=>e.fn==='drone');   // жив ли слой-дрон (для гашения при снятии/стопе)
let recCh=null, recBass=null, pumpTimer=null;
/* ⚠️ СОСТОЯНИЕ ЗАПИСИ СОЛО — ПО ВЛАДЕЛЬЦУ, а не одно на всех. Раньше это были ОДИНОЧНЫЕ recLead /
   recLeadBend / noteStartBeat / bendLastC («та самая единственная открытая нота»), и с моно-соло так и
   было. С полифонией две руки, пишущие ОДНОВРЕМЕННО, слились бы в один поток leadOn/leadSet: сравнение
   «изменилось ли» шло бы между нотами РАЗНЫХ рук, и в петлю легла бы каша. Теперь на каждого владельца
   своя запись {deg,oct,vol,rev,inst,bend,t0,lastC,v}. Глиссандо-в-луп (кривая бенда, центы поверх
   ступени) лежит ПО ССЫЛКЕ в событии leadOn и копится только у терменвокса (гейт live!=null). */
const recLead=new Map();     // ключ владельца ('lead:L'/'lead:R') → состояние открытой ноты
const vSlots=new Map();      // ключ владельца → номер одновременной ноты v в СЛОЕ (для пары leadOn/leadOff на переигровке)
let curChordDeg=-1, curChordOct=0;                   // ступень И РЕГИСТР аккорда, что играет петля сейчас (для подсветки, §Q5). Регистр нужен с многопериодной сеткой: одна ступень живёт в нескольких прямоугольниках, без него подсветка всегда падала бы в нижний
const loopBeats=()=>loop.bars*loop.metre;
/* ГРУППИРОВКА (акценты) по размеру — СТАТИЧНАЯ, по умолчанию. Массив длин групп, сумма = размер.
   Нечётные размеры чувствуются НЕ ровно: балканская 7 = 3+2+2, 9 = 2+2+2+3, 5 = 2+3; индийский
   тинтал (16) — 4 вибхага по 4. Пользовательский выбор 3+2+2 vs 2+2+3 отложен (BACKLOG §3.23) —
   один разумный вариант на размер. Дефолт нечислового/неизвестного — одна группа (акцент только сам).
   khali — индексы ГРУПП, что ОСЛАБЛЕНЫ (не акцент, а «пустая» голова, структурная черта тала). */
const METRE_GROUPS={ 2:[2],3:[3],4:[4],5:[2,3],6:[3,3],7:[3,2,2],8:[4,4],9:[2,2,2,3],10:[2,3,2,3],12:[3,3,3,3],16:[4,4,4,4] };
const METRE_KHALI ={ 16:[2] };   // тинтал: 3-й вибхаг (индекс 2 = доля 8) — khali (открытый баян, без баса)
/* Уровень акцента доли b∈[0,metre): 2 сам (начало такта), 1 голова группы, -1 khali-голова, 0 обычная. */
function beatLevel(metre,b){
  const g=METRE_GROUPS[metre]||[metre], kh=METRE_KHALI[metre]||[];
  let acc=0;
  for(let i=0;i<g.length;i++){ if(acc===b) return b===0?2:(kh.includes(i)?-1:1); acc+=g[i]; }
  return 0;   // не голова группы
}
const loopChordDeg=()=>loop.on?curChordDeg:-1;       // draw: подсветить аккорд петли, когда рука его не держит
const loopChordOct=()=>loop.on?curChordOct:0;        // его регистр — тем же путём (подсветка ищет прямоугольник по ПАРЕ deg+oct)
const maxLayer=()=>events.reduce((m,e)=>Math.max(m,e.layer),0);

/* ═══ ДОРОЖКИ: ЗАГЛУШЕНИЕ И СОЛО (слайс S1 «Редактора дорожек») ═══
   ⚠️ НАСТРОЙКА КЛЮЧУЕТСЯ НА СГЕНЕРИРОВАННОМ id ДОРОЖКИ, А НЕ НА НОМЕРЕ СЛОЯ. Номер для этого НЕ
   ГОДИТСЯ, и это не предосторожность на будущее, а три уже существующих факта:
     (1) номера ПЕРЕИСПОЛЬЗУЮТСЯ — овердаб берёт maxLayer()+1, поэтому после ⤺ отмены следующая
         запись получает ТОТ ЖЕ номер; ключуйся мы на номере, новая дорожка молча родилась бы
         заглушённой (и человек искал бы пропавший звук);
     (2) в номерах бывают ДЫРЫ — clearJam вырезает события ПО МЕТКЕ ev.jam, а не по слою, поэтому
         «слои 0 и 2 без 1» — нормальное состояние, а не сбой;
     (3) onUndo НЕ ПЕРЕНУМЕРОВЫВАЕТ — и не должен: номер слоя зашит в КЛЮЧИ ВЛАДЕЛЬЦЕВ ГОЛОСОВ
         ('loop:N' / 'bassloop:N' / 'leadloop:N:v'), перенумерация оторвала бы звучащие голоса от
         их владельцев.
   Отсюда разделение: НОМЕР СЛОЯ — адрес ЗВУКА (ключи владельцев, события), id ДОРОЖКИ — адрес
   НАСТРОЙКИ, связывает их одна таблица laneId.
   ⛔ Не сливать их и ⛔ не писать id в событие: формат события слайс S1 НЕ трогает вовсе. */
let laneSeq=0;
const laneId=new Map();      // номер слоя → СТАБИЛЬНЫЙ id дорожки
const laneMute=new Set();    // id заглушённых дорожек
const laneSolo=new Set();    // id дорожек в соло
/* ⛳ ЗАКОН ЭТОГО БЛОКА, И НА НЁМ ДЕРЖИТСЯ ВСЯ КОРРЕКТНОСТЬ ДОРОЖЕК:
   **laneNew — ЕДИНСТВЕННЫЙ ПИСАТЕЛЬ laneId, и он ВСЕГДА выдаёт СВЕЖИЙ id, ЗАТИРАЯ прежнюю запись
   этого номера.** Значит правильность обеспечивает РОЖДЕНИЕ слоя, а не уборка за умершим.
   ⚠️ ПОЧЕМУ НЕ НАОБОРОТ (держать правильность на уборке) — так было, и это была мина: номера
   ПЕРЕИСПОЛЬЗУЮТСЯ (овердаб берёт maxLayer()+1), поэтому ОДНА пропущенная уборка означала бы, что
   свежезаписанный слой унаследовал id покойника вместе с его заглушением. Наружу это выглядит как
   «моя новая дорожка молчит, и непонятно почему» — тихо, правдоподобно и ищется долго.
   Теперь такого состояния не существует: что бы ни осталось в laneMute/laneSolo, НИ ОДИН номер на
   эти id больше не отображается, поэтому они НИКОГДА НИ С ЧЕМ НЕ СОВПАДУТ.
   ⛔ Не заводить второго писателя laneId. Появится новое место, где рождается слой, — оно обязано
   звать laneNew; список мест — в отчёте слайса и в комментариях у самих мест. */
function laneNew(layer){
  const old=laneId.get(layer);
  if(old!=null){ laneMute.delete(old); laneSolo.delete(old); }   // ГИГИЕНА, А НЕ КОРРЕКТНОСТЬ: без этой строки старый id просто мёртвым грузом лежал бы в множестве и ни на что не влиял — но множества росли бы всю сессию
  laneId.set(layer,++laneSeq);
  return laneSeq;
}
/* ЧТЕНИЕ id — ЧИСТОЕ: вернёт либо ДЕЙСТВУЮЩИЙ id номера (тот, что выдало последнее рождение), либо
   undefined. ⛔ ЗАВОДИТЬ id ЗДЕСЬ НЕЛЬЗЯ, и это не стиль: «страховка», заводящая id по требованию,
   была бы ВТОРЫМ писателем, а значит вторым источником правды о том, какое поколение номера сейчас
   живёт. Отсутствие записи читается как «обычная слышимая дорожка» — что и верно: id, которого
   никогда не выдавали, не может лежать ни в laneMute, ни в laneSolo. */
const laneOf=layer=>laneId.get(layer);
/* Уборка за слоями, у которых больше НЕТ СОБЫТИЙ (⤺ отмена слоя, снятие подложки).
   ⚠️ ЭТО ГИГИЕНА, А НЕ КОРРЕКТНОСТЬ (см. закон выше): пропусти мы её где-нибудь — таблица и
   множества просто подрастут мусором, но ни одна дорожка не перепутается, потому что номер получит
   свежий id при следующем рождении. Держим ради того, чтобы состояние не копилось за долгую сессию.
   Пишущийся слой ЩАДИМ — он законно пуст, пока в него не сыграли (его строку уже показывает полоса). */
function lanePrune(){
  const live=new Set(); for(const e of events) live.add(e.layer);
  for(const [ly,id] of laneId) if(!live.has(ly) && !(recording&&ly===loop.layer)){
    laneId.delete(ly); laneMute.delete(id); laneSolo.delete(id); }
}
/* ⚠️ laneSeq НАМЕРЕННО НЕ ОБНУЛЯЕТСЯ: счётчик монотонен на всю сессию. Обнуление вернуло бы в оборот
   уже выданные номера id — а это ровно тот вид совпадения, от которого id и заводился. Стоит он
   ничего (целое число), а класс ошибок закрывает целиком. */
function laneReset(){ laneId.clear(); laneMute.clear(); laneSolo.clear(); }
/* ⛳ ПРЕДИКАТ СЛЫШИМОСТИ — ОДИН НА ОБА ПУТИ ПЕРЕИГРОВКИ (scheduleLayers и fireNear).
   СОЛО ПЕРЕБИВАЕТ ЗАГЛУШЕНИЕ: как только соло включено хоть где-то, слышны РОВНО соло-дорожки, а
   остальные молчат независимо от своих галочек mute (и возвращаются как были, когда соло снимут). */
/* Зовётся из планировщика (40 раз в секунду на каждое событие) и из draw — поэтому важно, что laneOf
   ЧИСТЫЙ: ни одной записи в таблицу на горячем пути. Нет id → дорожка обычная, слышимая. */
const laneAudible=layer=>{ const id=laneOf(layer);
  return laneSolo.size ? (id!=null&&laneSolo.has(id)) : !(id!=null&&laneMute.has(id)); };
/* ⛳ ГЕЙТ ЦЕЛИКОМ ВЫКЛЮЧЕН, ПОКА НИЧЕГО НЕ ЗАГЛУШЕНО И НИЧЕГО НЕ В СОЛО — и это НЕ микро-оптимизация,
   а УСЛОВИЕ ПРИЁМКИ слайса: пока человек не тронул переключатели, пер-событийная проверка не
   выполняется ВООБЩЕ (в цикле остаётся один уже вычисленный булев), и переигровка идёт байт-в-байт
   как раньше. Считается ОДИН РАЗ НА ВЫЗОВ планировщика, а не на событие. */
const laneGated=()=> laneMute.size>0 || laneSolo.size>0;
/* Дрон — не нота, а УРОВЕНЬ (выделенные узлы, softAllOff его не трогает), поэтому «заглушить слой
   с дроном» нельзя сделать пропуском события: droneOn уже отработал. Спрашиваем отдельно, слышен ли
   дрон хоть на одной дорожке, и ведём общий уровень. */
const droneAudible=()=>events.some(e=>e.fn==='drone'&&laneAudible(e.layer));
/* Переключатели. Наружу дорожка адресуется НОМЕРОМ СЛОЯ — тем же, чем подписана её строка на полосе
   лупера; id остаётся внутренним делом (ui не может подержать протухший id).
   ⚠️ `?? laneNew(layer)` — НЕ «мягкое заведение id», а ЕДИНСТВЕННЫЙ БЕЗОПАСНЫЙ способ его получить,
   когда записи нет. Он безопасен ровно потому, что ОТСУТСТВИЕ записи не может нести устаревший id:
   вернуть что-то протухшее laneOf физически неспособен (он либо отдаёт действующий id, либо ничего).
   Сюда мы попадаем, только если слой родился мимо всех известных мест рождения, — то есть это ещё и
   САМОПОЧИНКА: дорожка получит id и переключатель сработает, вместо того чтобы молча ничего не делать. */
function toggleLaneMute(layer){ const id=laneOf(layer) ?? laneNew(layer);
  if(laneMute.has(id)) laneMute.delete(id); else laneMute.add(id);
  laneHush(); }
function toggleLaneSolo(layer){ const id=laneOf(layer) ?? laneNew(layer);
  if(laneSolo.has(id)) laneSolo.delete(id); else laneSolo.add(id);
  laneHush(); }
/* ЧИТАТЕЛИ ДЛЯ ПОКАЗА — через тот же чистый laneOf (их зовёт draw на каждый кадр; правило #5 с
   обратной стороны: рисование не смеет менять состояние). */
const laneMuted =layer=>{ const id=laneOf(layer); return id!=null&&laneMute.has(id); };
const laneSoloed=layer=>{ const id=laneOf(layer); return id!=null&&laneSolo.has(id); };
const laneSoloOn=()=> laneSolo.size>0;
/* ⚠️ ЗАГЛУШАТЬ НАДО НЕМЕДЛЕННО, А НЕ «СО СЛЕДУЮЩЕГО СОБЫТИЯ»: удержанный аккорд слоя звучал бы до
   заворота (chOff у него ещё впереди). Ключи владельцев дают ТОЧНЫЙ адрес слоя, поэтому гасим ровно
   ставшие неслышимыми слои — ТЕМ ЖЕ обходом, что и граница повтора (releaseLoopLayersAt со слоем),
   второго обхода не заводим.
   Зовём после КАЖДОГО переключения и проходим ВСЕ слои, а не только тронутый: включение соло делает
   неслышимыми чужие дорожки, а снятие одного из двух соло — ту, что осталась без него.
   Уже молчащие слои проходят вхолостую (chordOff/bassOff/leadOff выходят сразу, если владельца нет).
   ⚠️ УДАРНЫЕ ОТМЕНИТЬ НЕЛЬЗЯ: drumHit — одноразовые осцилляторы, поэтому удары, уже запланированные
   в окно SCHED_AHEAD (~300мс), прозвучат ПОСЛЕ заглушения. Та же принятая и ограниченная цена, что у
   стопа петли и у отмены слоя; чинить её здесь нечем. */
function laneHush(){
  if(!AC) return;
  const seen=new Set();
  for(const e of events){ if(seen.has(e.layer)) continue; seen.add(e.layer);
    if(!laneAudible(e.layer)) releaseLoopLayersAt(undefined,e.layer); }
  if(droneActive()){ if(loop.on&&droneAudible()) droneOn(); else droneOff(); }   // уровень дрона — по слышимости ЕГО дорожки (уровень, а не нота: пропуском события его не заглушить)
}

/* Позиция для визуализации: фаза отсчёта / игры, доля внутри петли, всего долей. */
function loopPos(){
  if(!loop.on||!AC)return null;
  const e=(AC.currentTime-loop.t0)*loop.bpm/60, total=loopBeats();
  return e<0 ? {phase:'count', countLeft:Math.ceil(-e), pos:0, total, bars:loop.bars}
             : {phase:'play',  pos:e%total, total, bars:loop.bars};
}

/* ENG — единая точка исполнения (живьём через W* и на переигровке). deg→частота
   выводится ЗДЕСЬ. Ладовый КОНТЕКСТ: живьём (ctx нет) — текущий лад/септаккорд;
   на переигровке ctx=событие с ЗАМОРОЖЕННЫМ ладом (ev.sc) и септаккордом (ev.sev),
   §3.4. baseF() всегда живой → тоника глобальна, лад заморожен. leadFreq/bassFreq
   сами страхуют ступень вне лада (модуло+октава), так что частота не улетает в NaN.
   Владелец голосов ПО СЛОЮ (ctx=событие переигровки): аккорд — 'loop:'+layer / живой
   'latch'; бас — 'bassloop:'+layer / живой 'bass'. Так слой не крадёт голос у живого. */
const chOwnerKey  =ctx=> ctx?'loop:'+ctx.layer:'latch';
const bassOwnerKey=ctx=> ctx?'bassloop:'+ctx.layer:'bass';
/* Ключ владельца СОЛО-голоса на ПЕРЕИГРОВКЕ: слой + номер одновременной ноты (a.v). Живой ключ
   ('lead:L'/'lead:R') строит gestures и передаёт явным аргументом — в событие он НЕ попадает (это
   состояние руки, а не намерение). a.v||0 — вот та самая совместимость: событие без v = нота №0. */
const ldKey=(ctx,a)=> ctx ? 'leadloop:'+ctx.layer+':'+(a.v||0) : 'lead:?';
/* ⛳ ЕДИНАЯ ФОРМА ВЫЗОВА: КАЖДАЯ запись ENG — это (a, ctx, opt), где opt — ОДИН И ТОТ ЖЕ ИМЕНОВАННЫЙ
   набор `{when, live, own}`. Слайс S2 завёл эту форму, и это НЕ косметика, а снятие ловушки.
   ⚠️ ЧТО БЫЛО: у записей была РАЗНАЯ позиционная форма — `leadOn:(a,ctx,live,own)` против
   `chOn:(a,ctx,when)` и `bassOn:(a,ctx,when,live)`, — а диспетчер планировщика зовёт их ОДИНАКОВО:
   `ENG[ev.fn](ev.a, ev, when)`. Пока лид шёл мимо планировщика (fireNear), это сходило с рук. Но стоило
   бы завести лид в планировщик — и ВРЕМЯ В СЕКУНДАХ легло бы в слот ЖИВЫХ ГЕРЦ терменвокса: нота
   зазвучала бы на абсурдной высоте или не зазвучала вовсе. Тихо, правдоподобно, ищется долго.
   ⚠️ ПОЧЕМУ НЕ ХВАТИЛО БЫ «поставить when последним у всех». У лида кроме when есть ещё live и own,
   поэтому третий позиционный слот У РАЗНЫХ записей всё равно значил бы разное — в каком порядке ни
   расставляй. Ловушка позиционная ПО ПРИРОДЕ, и лечится она только снятием позиционности: у
   дополнительных аргументов больше НЕТ номеров, есть ИМЕНА. Время может попасть в `live` теперь лишь
   у того, кто СОБСТВЕННОРУЧНО напишет слово `live`, — то есть ошибка стала невыразимой, а не
   несовершённой.
   ⚠️ live (живые Гц терменвокса) остаётся ОТДЕЛЬНЫМ полем и ЖИВЫМ-ТОЛЬКО (правило #11): переигровка
   его не передаёт никогда, частота там выводится из ступени по замороженному ладу.
   ⛔ Добавляешь запись в ENG — держи ту же форму. Второй формы здесь быть не должно. */
const ENG={
  /* ⚠️ setLeadInstr(a.inst) ОТСЮДА УБРАН, и это ПОЧИНКА, а не потеря: переигранный слой уводил ЖИВОЙ
     инструмент (и кнопку в панели) — слой на Ситаре молча перекрашивал руку, играющую Органом. Теперь
     тембр печётся В ГОЛОСЕ на атаке (leadOn получает inst), как это давно делают аккорды и бас. */
  leadOn:(a,ctx,{when,live,own}={})=>{ const o=own||ldKey(ctx,a);
              /* live — ЖИВОЙ override частоты (терменвокс): непрерывные Гц вместо ступенной leadFreq.
                 Только на ЖИВОМ пути (WleadOn); переигровка зовёт ENG без live → частота из leadFreq по
                 замороженному ладу (полимодальность цела). */
              if(ctx)leadCancel(o,when);           // атака переигранной ноты: снять рампы прошлого бенда (не перетечёт) — ТОЛЬКО в своём голосе и В ТО ЖЕ ВРЕМЯ, что и атака
              const base=leadFreq(a.deg,a.oct,ctx?ctx.sc:CUR());
              applyFx(a.fx);   // КАРТА ЭФФЕКТОВ ЭТОГО СОБЫТИЯ (3.7.2). Нет карты (события аранжировки) → applyFx возьмёт ТЕКУЩУЮ цепь роли, а не нейтраль
              leadOn(o,(live!=null?live:base),a.vol,a.inst===undefined?leadIdx:a.inst,a.deg,a.oct,when);   // deg/oct — не для звука (частота уже посчитана), а для ПОДСВЕТКИ: leadHold знает, что звучит
              if(a.bend&&a.bend.length)scheduleBend(o,a.bend,base,60/loop.bpm,when); },   // переигровка: кривая бенда поверх ступени замороженного лада, в СВОЙ голос, с якорем в момент атаки
  leadSet:(a,ctx,{when,own}={})=>{ const o=own||ldKey(ctx,a);
              applyFx(a.fx);
              leadSet(o,(a.hold?null:leadFreq(a.deg,a.oct,ctx?ctx.sc:CUR())),a.vol,a.deg,a.oct,when); },   // live здесь не читался никогда: ведение терменвокса идёт через hold:true (частоту не сбиваем), а не через override
  leadOff:(a,ctx,{when,own}={})=>leadOff(own||ldKey(ctx,a),when),
  /* when — ЯВНОЕ время (опережение лупера, §планировщик). Живой путь (W*) зовёт без when → undefined
     → аудио-функции берут AC.currentTime (сейчас), байт-в-байт. Переигровка слоёв передаёт точное время. */
  chOn:(a,ctx,{when}={})=>chordOn(chOwnerKey(ctx),chordFreqs(a.deg,a.oct,ctx?ctx.sc:CUR(),ctx?ctx.sev:seventh,a.ty),a.vol,a.inst,a.bri,when),   // a.bri — пер-событийная яркость (0=нейтраль); when остаётся ПОСЛЕДНИМ (планировщик)
  chSet:(a,ctx,{when}={})=>chordGlide(chOwnerKey(ctx),chordFreqs(a.deg,a.oct,ctx?ctx.sc:CUR(),ctx?ctx.sev:seventh,a.ty),a.vol,a.bri,when),
  chOff:(a,ctx,{when}={})=>chordOff(chOwnerKey(ctx),when),
  bassOn:(a,ctx,{when,live}={})=>bassOn(bassOwnerKey(ctx),(live!=null?live:bassFreq(a.deg,a.oct,ctx?ctx.sc:CUR())),a.vol,a.inst,when),   // live — живой override Гц (терменвокс-бас), как у leadOn; переигровка без него → bassFreq (полимодальность цела)
  bassSet:(a,ctx,{when}={})=>bassSet(bassOwnerKey(ctx),bassFreq(a.deg,a.oct,ctx?ctx.sc:CUR()),a.vol,when),
  bassOff:(a,ctx,{when}={})=>bassOff(bassOwnerKey(ctx),when),
  drum:(a,ctx,{when}={})=>drumHit(a.row,a.vol,a.kit,when),
  drone:(a,ctx,{when}={})=>droneOn(a.lvl,when),        // дрон: выделенные узлы, гасится по жизненному циклу (не в softAllOff)
};
const inPB=()=>loop.on;                               // для строки статуса (draw)

/* Сетка квантизации в долях: аккорды — доля, бас — восьмая, соло — не квантуется.
   УДАРНЫЕ — 1/loop.sub доли: при sub=4 шестнадцатая (как было), при sub=3 ТРИОЛЬ. Дробление —
   ЯВНАЯ настройка (панель лупера), а НЕ вывод из последнего загруженного паттерна: неявная смена
   поведения квантизации (снял джем — сетка молча переехала) хуже лишнего контрола. */
const gridFor=fn=> fn[0]==='c'?1 : fn.slice(0,4)==='bass'?0.5 : fn==='drum'?1/(loop.sub||4) : 0;
/* Запись события на текущую позицию в петле; время при квантизации снапится к сетке. */
function push(fn,a){
  if(!AC)return;
  const e=(AC.currentTime-loop.t0)*loop.bpm/60;
  if(e<0)return;                                      // ещё идёт отсчёт
  const lb=loopBeats();
  let t=e%lb;
  const g=loop.quant?gridFor(fn):0;
  if(g>0){
    t=(Math.round(t/g)*g)%lb;
    /* СКЛАДКА ЗАВОРОТА. При g=0.25 всё точно в двоичном, при g=1/3 — нет: удар у самого конца круга
       округляется к lb−1e-16, и % его НЕ сворачивает — событие село бы на волосок ДО конца петли
       вместо доли 0 (слышно как пропавший сильный удар). Дожимаем руками. */
    if(lb-t<1e-6) t=0;
  }
  /* ⛔ КОПИЯ КАРТЫ ЭФФЕКТОВ — R1, САМЫЙ ОПАСНЫЙ БАГ ЭТОГО ПЛАСТА, ЗАКРЫТ ЗДЕСЬ И ТОЛЬКО ЗДЕСЬ.
     До 3.7.2 ВСЯ полезная нагрузка была примитивами, кроме двух намеренных ссылок: ty (никогда не
     мутируется) и bend (дописывается осознанно). Карта a.fx — первый МУТИРУЕМЫЙ объект в нагрузке, а
     push кладёт `a` ПО ССЫЛКЕ, и вызывающие копируют МЕЛКО ({...p}) — значит без этой строки один и
     тот же объект оказался бы и в записанном событии, и в живом состоянии сравнения. Следующее
     движение руки тихо переписало бы УЖЕ ЗАПИСАННОЕ прошлое: слой начал бы звучать не так, как его
     сыграли. Снаружи это читается как «петля сама меняется» — и искать причину пришлось бы долго.
     ЗАПИСАННАЯ КАРТА С ЭТОГО МОМЕНТА НЕИЗМЕНЯЕМА: её больше никто не трогает, только читает. */
  const ev={t,layer:loop.layer,fn,a,sc:CUR(),sev:seventh};   // §3.4: замораживаем ладовый контекст события
  if(a && a.fx) ev.a={...a, fx:{...a.fx}};
  events.push(ev);
}
/* Доля внутри петли СЕЙЧАС (тот же счёт, что и push) — для dt точек бенда. */
const curBeat=()=>((AC.currentTime-loop.t0)*loop.bpm/60)%loopBeats();
/* Точка бенда: центы ЖИВОЙ высоты (live) относительно ступени АТАКИ (r.deg/oct по
   замороженному-в-будущем ладу CUR()). Само-прореживание порогом BEND_EPS_CENTS. dt клампим ≥0
   (нота через заворот петли — редкость; первый круг всё равно кончается на завороте).
   Опора и порог — В ЗАПИСИ ВЛАДЕЛЬЦА (r), поэтому две гнущие руки не путают друг другу отсчёт. */
function pushBend(r,live){
  if(!r||!r.bend||live==null)return;
  const c=1200*Math.log2(live/leadFreq(r.deg,r.oct,CUR()));
  if(r.lastC!=null&&Math.abs(c-r.lastC)<=BEND_EPS_CENTS)return;
  r.bend.push({dt:Math.max(0,curBeat()-r.t0),c});
  r.lastC=c;
}
/* СВОБОДНЫЙ НОМЕР одновременной ноты v внутри пишущегося слоя: 0,1,2… Нужен только чтобы переигровка
   спарила leadOn с его leadOff (в слое может быть открыто несколько соло-нот). Первая всегда получает 0
   — поэтому обычная одноголосная запись даёт события с v:0, а старые (без v) читаются как v=0. */
function freeSlot(){ const used=new Set([...vSlots.values()]); let v=0; while(used.has(v))v++; return v; }
/* live!=null ⟺ соло-рука назначена на ТЕРМЕНВОКС (функция руки 'therm' — gestures шлёт S.hz только
   оттуда). Тогда высоту несёт БЕНД: deg/oct ЗАМОРОЖЕНЫ на атаке (не сравниваем и не обновляем — у c
   стабильная опора), а leadSet пишем лишь на смену громкости/реверба/тембра с меткой hold (переигровка
   не сбивает бенд частотой).
   live==null (рука на любой ДРУГОЙ функции — ноты/удержание/эффекты) — логика БАЙТ-В-БАЙТ как раньше,
   только состояние взято по владельцу own. */
/* ⛳ ОБОБЩЁННОЕ ДЕЛЬТА-СЖАТИЕ ПО КАРТЕ ЭФФЕКТОВ (Пласт 3.7.2) — вместо явного списка полей.
   Прежде сравнивались ЧЕТЫРЕ ИМЕНОВАННЫХ поля (deg/oct/inst/vol/rev), а vib/drv/trm/dly, хотя и лежали
   в нагрузке, В СРАВНЕНИЕ НЕ ВХОДИЛИ ВОВСЕ — поэтому «покрутил ручку при зажатой ноте» не писалось
   НИЧЕГО, и эффекты в слой фактически не записывались. Теперь набор параметров ПРОИЗВОЛЕН, значит и
   сравнение — по МНОЖЕСТВУ: другой состав ключей ИЛИ любой ключ ушёл дальше мёртвой зоны.
   ⚠️ Порог REC_FX_EPS — в НОРМИРОВАННЫХ единицах, один на все параметры (довод — в config). */
function fxChanged(a,b){
  const A=a||{}, B=b||{}, ka=Object.keys(A), kb=Object.keys(B);
  if(ka.length!==kb.length) return true;
  for(const k of ka){ if(!(k in B) || Math.abs(A[k]-B[k])>REC_FX_EPS) return true; }
  return false;
}
const fxCopy=m=> m?{...m}:m;   // в состояние сравнения кладём КОПИЮ: иначе r.fx стал бы псевдонимом живого снимка и «изменилось?» всегда было бы «нет»
function recLeadEv(own,p,live){
  if(!recording)return;
  let r=recLead.get(own);
  if(!r){
    const v=freeSlot(); vSlots.set(own,v);
    const a={...p,v};                              // v — номер одновременной ноты в слое (пара для leadOff)
    r={deg:p.deg,oct:p.oct,vol:p.vol,fx:fxCopy(p.fx),inst:p.inst,bend:null,t0:0,lastC:null,v};
    if(live!=null){ a.bend=[]; r.bend=a.bend; r.t0=curBeat(); }
    push('leadOn',a);
    recLead.set(own,r);
    if(live!=null)pushBend(r,live);                // стартовая точка (r уже есть — опора известна)
    return;
  }
  if(live!=null){                                  // терменвокс: пишем бенд + громкость/ЭФФЕКТЫ (hold), НЕ deg/oct
    pushBend(r,live);
    /* ⚠️ БЕНД НЕ ТРОГАЕМ (R3): точка бенда дописывается в a.bend ПОСЛЕ push, по ссылке из r.bend, и
       опора (r.deg/r.oct/r.t0/r.lastC) живёт своей жизнью. Карта эффектов добавлена РЯДОМ, ни ссылка,
       ни пороги бенда не задеты — hold:true по-прежнему говорит переигровке «частоту не сбивать». */
    if(p.inst!==r.inst||Math.abs(p.vol-r.vol)>REC_VOL_EPS||fxChanged(p.fx,r.fx)){
      push('leadSet',{...p,hold:true,v:r.v});
      r.vol=p.vol; r.fx=fxCopy(p.fx); r.inst=p.inst;   // deg/oct остаются на атаке
    }
    return;
  }
  if(p.deg!==r.deg||p.oct!==r.oct||p.inst!==r.inst||
     Math.abs(p.vol-r.vol)>REC_VOL_EPS||fxChanged(p.fx,r.fx)){ push('leadSet',{...p,v:r.v}); }
  else return;
  r.deg=p.deg; r.oct=p.oct; r.vol=p.vol; r.fx=fxCopy(p.fx); r.inst=p.inst;
}
function recLeadOff(own){ const r=recLead.get(own);
  if(recording&&r) push('leadOff',{v:r.v});
  recLead.delete(own); vSlots.delete(own); }
function recLeadReset(){ recLead.clear(); vSlots.clear(); }   // паника/очистка/заворот: открытых нот больше нет
/* ty входит в сравнение: у типизированных аккордов громкость ФИКСИРОВАНА, а сектор
   меняется без смены ступени/октавы — без этой проверки смена типа не попала бы в
   запись вовсе, и петля играла бы не тот аккорд. Сравнение по ссылке корректно:
   ty — это всегда один и тот же массив из таблицы CHORD_FAMS. */
/* a.bri (яркость) входит в запись КАК a.rev у соло: ложится в полезную нагрузку a (рядом с ty/inst),
   слой запоминает свою яркость и переигрывается с ней. Смена ТОЛЬКО яркости (рука двинулась в глубину,
   ступень/тип/громкость те же) должна попасть в запись → добавляем |Δbri|>REC_REV_EPS в тест chSet
   (та же мёртвая зона, что у реверба соло). События аккордов КВАНТУЮТСЯ к доле (gridFor='chOn'/'chSet'→1),
   поэтому при вкл. квантизации кривая яркости привязывается к долям (грубее соло, но согласно с тем, что
   аккорды и так поbeat-квантованы); при выкл. — полное разрешение жеста. */
function recChOn(a){ if(!recording)return; push('chOn',{...a}); recCh={deg:a.deg,oct:a.oct,vol:a.vol,ty:a.ty,bri:a.bri}; }
function recChSet(a){
  if(!recording)return;
  if(!recCh){ push('chOn',{...a}); }
  else if(a.deg!==recCh.deg||a.oct!==recCh.oct||a.ty!==recCh.ty||Math.abs(a.vol-recCh.vol)>REC_VOL_EPS||Math.abs((a.bri||0)-(recCh.bri||0))>REC_REV_EPS){ push('chSet',{...a}); }
  else return;
  recCh={deg:a.deg,oct:a.oct,vol:a.vol,ty:a.ty,bri:a.bri};
}
function recChOff(){ if(recording&&recCh){ push('chOff',{}); recCh=null; } }
function recBassEv(p){                                  // бас прореживается как соло
  if(!recording)return;
  if(!recBass){ push('bassOn',{...p}); }
  else if(p.deg!==recBass.deg||p.oct!==recBass.oct||p.inst!==recBass.inst||Math.abs(p.vol-recBass.vol)>REC_VOL_EPS){ push('bassSet',{...p}); }
  else return;
  recBass={deg:p.deg,oct:p.oct,vol:p.vol,inst:p.inst};
}
function recBassOff(){ if(recording&&recBass){ push('bassOff',{}); recBass=null; } }
function recDrum(a){ if(recording)push('drum',{...a}); }   // удар — одиночное событие
/* ⛳ ЗАКРЫТЬ В ЗАПИСИ ВСЁ, ЧТО ОСТАЛОСЬ ОТКРЫТЫМ (слайс S3.1). Зовётся при ОСТАНОВКЕ ОВЕРДАБА, когда
   человек жмёт «●», не отпустив пальцы: каждая звучащая нота обязана получить в слой своё «выключение»,
   иначе слой записан незавершённым.
   ⚠️ ДВЕ ДЫРЫ, КОТОРЫЕ ЭТО ЗАКРЫВАЕТ, И ОБЕ БЫЛИ НАСТОЯЩИМИ:
     (1) СОЛО. На остановке стоял голый `recLeadOff()` — БЕЗ АРГУМЕНТА. А состояние записи соло с
         полифонии ПО ВЛАДЕЛЬЦУ (Map recLead), поэтому `recLead.get(undefined)` не находил НИЧЕГО:
         ни одного leadOff не писалось, а запись владельца и его номер v ТЕКЛИ в recLead/vSlots до
         ближайшего recLeadReset. Обход по ВСЕМ владельцам — единственно верная форма: рук две, а
         пальцев на руке до четырёх, открытых нот может быть восемь.
     (2) БАС. Его не закрывали ВООБЩЕ: recBassOff существовал, но достижим был только из WbassOff
         (живое размыкание пальцев). Удержанный на остановке бас оставался в слое без bassOff.
   ⚠️ ПОЧЕМУ ЭТО НЕ БЫЛО СЛЫШНО: на завороте петли releaseLoopLayersAt гасит зависшие голоса слоёв, а
   liveWrapRelease — живые. Сеть безопасности прятала обе дыры. ЛИНЕЙНЫЙ ТРАНСПОРТ заворот убирает, и
   тогда такая нота звенела бы вечно — потому чиним СЕЙЧАС, пока поведение можно проверить в изоляции.
   ⛔ ЗВАТЬ ТОЛЬКО ДО setRecording(false): все три rec*Off пишут событие лишь при `recording`. Переставь
   вызовы местами — и починка тихо перестанет работать, выглядя при этом целой.
   ⚠️ КЛЮЧИ КОПИРУЕМ: recLeadOff удаляет владельца из Map прямо в цикле. */
function recAllOff(){
  for(const own of [...recLead.keys()]) recLeadOff(own);   // соло — ПО КАЖДОМУ владельцу ('lead:L'/'lead:R' и их пальцевые ключи)
  recChOff();                                              // аккорд, в т.ч. ЗАЩЁЛКНУТЫЙ: он звучит и с разомкнутыми пальцами, recCh при этом не сброшен
  recBassOff();                                            // бас — моно, одна открытая нота максимум
}

/* Обёртки W*: живой звук СРАЗУ + запись (если вооружено). Переигровка (насос)
   зовёт ENG напрямую, мимо W* → сама себя не пишет; живой гейт больше не нужен. */
/* own — КЛЮЧ ВЛАДЕЛЬЦА живого голоса ('lead:L'/'lead:R', строит gestures). В событие он НЕ пишется:
   в петле нота принадлежит СЛОЮ, а не руке — там ключ соберёт ldKey из ctx.layer и a.v. */
const WleadOn =(own,p,live)=>{ ENG.leadOn(p,null,{live,own}); recLeadEv(own,p,live); };   // live: в звук (стадия a) И в запись бенда (стадия b); ENG.leadOn получает p БЕЗ bend — живая нота не трогается. ⚠️ when НЕ передаём: живой путь звучит «сейчас», как всегда
const WleadOff=own=>{ ENG.leadOff(null,null,{own}); recLeadOff(own); };
/* ty — интервалы типизированного аккорда. Живёт в ПОЛЕЗНОЙ НАГРУЗКЕ a (как a.inst —
   тембр), а не рядом с sc/sev: тип — свойство самого аккорда, а не ладового контекста.
   Так он замораживается в событии сам собой и переигрывается как сыгран. */
const WchOn =(_o,deg,oct,vol,ins,ty,bri)=>{ const a={deg,oct,vol,inst:ins,ty,bri}; ENG.chOn(a); recChOn(a); };   // bri — живая яркость руки: в звук (ENG) И в запись (rec), как a.rev у соло
const WchSet=(_o,deg,oct,vol,ty,bri)    =>{ const a={deg,oct,vol,ty,bri};          ENG.chSet(a); recChSet(a); };
const WchOff=_o                 =>{ ENG.chOff(); recChOff(); };
const WbassOn =(p,live)=>{ ENG.bassOn(p,null,{live}); recBassEv(p); };   // live в звук, НЕ в запись (recBassEv пишет ступень) — инвариант «живые Гц не записываются», как у соло. ⚠️ Прежде здесь стояло (p,null,undefined,live) — дырка под when позиционно; с именованным набором её не существует
const WbassOff=()=>{ ENG.bassOff(); recBassOff(); };
const WdrumHit=(row,vol)=>{ const a={row,vol,kit:drumKitIdx}; ENG.drum(a); recDrum(a); };

function softAllOff(){ if(!AC)return;
  leadAllOff();                                     // все владельцы соло: 'lead:L/R' + 'leadloop:N:v' (раньше был один noteOff — соло было моно)
  Object.keys(chordHold).forEach(k=>chordOff(k));   // все владельцы аккордов: 'latch' + 'loop:N'
  Object.keys(bassHold).forEach(k=>bassOff(k));     // все владельцы баса: 'bass' + 'bassloop:N'
  setLatchDeg(-1); setLatchTy(null);              // тип гасим вместе со ступенью: иначе после паники/очистки
  recLeadReset(); recCh=null; recBass=null; }     // следующий щипок той же ступени прочёлся бы как «тот же аккорд»; открытые соло-ноты (и их бенды) сбрасываем
function setRecording(v){ recording=v; hooks.rec && hooks.rec(v); }

/* --- Транспорт петли --- */
function clearPump(){ if(pumpTimer){ clearInterval(pumpTimer); pumpTimer=null; } }
/* СЛОИ (аккорд/бас/удар) идут ВПЕРЁД по явному времени; ЛИД/дрон — «почти сейчас».
   ⚠️ ПРИЧИНА У ЛИДА БОЛЬШЕ НЕ ТА, что здесь стояла. Было: «моно-соло делит один голос с живой игрой,
   пред-планировать далеко вперёд опасно». Соло больше НЕ моно — слой и рука сидят в РАЗНЫХ голосах
   пула, драться им нечем.
   ⚠️ И ПРИЧИНА СНОВА НЕ ТА, что здесь стояла. Было: «у соло-функций нет аргумента when, а кривые бенда
   расписываются от AC.currentTime». С слайса S2 это НЕВЕРНО: when есть у leadOn/leadSet/leadOff и у
   scheduleBend (якорь кривой), дрон тоже его принимает. Осталась ОДНА причина, и она поведенческая:
   перевод лида в окно опережения — слышимое изменение (нота начинает ставиться на ~300мс вперёд, а
   гашение слоёв на границе повтора обязано поехать вместе с ней), поэтому он делается ЦЕЛИКОМ и
   проверяется на слух в транспортном слайсе, а не протаскивается попутно. Возможность готова,
   применение отложено СОЗНАТЕЛЬНО. fn[0]==='c' → аккорд;
   slice(0,4)==='bass' → бас; 'drum' → удар. Лид (leadOn/leadSet/leadOff) и дрон — НЕ вперёд. */
const isLayer=fn=> fn[0]==='c' || fn.slice(0,4)==='bass' || fn==='drum';

/* ═══ КУРСОРЫ ПЕРЕИГРОВКИ (слайс S3.2) — стоимость по ОКНУ, а не по всей песне ═══
   Оба цикла переигровки (scheduleLayers и fireNear) обходили ВЕСЬ массив событий, а tick зовёт их
   ОБА каждые SCHED_TICK_MS=25мс. На петле в 8 тактов это десятки событий и сорок обходов в секунду —
   бесплатно. На песне в несколько минут это десятки ТЫСЯЧ событий, то есть миллионы чтений полей в
   секунду на том же потоке, где крутятся MediaPipe и синтез. Курсор превращает «весь массив» в
   «события внутри окна».
   ⚠️ ОТСОРТИРОВАН ЛИ МАССИВ — ОТВЕТ: НЕ ЦЕЛИКОМ, И ЭТО ВАЖНО. Сортировка стоит в трёх местах
   (закрытие первого круга, остановка овердаба, загрузка аранжировки), а push ДОПИСЫВАЕТ в конец во
   время записи — причём t считается как `e % lb`, то есть на завороте ПАДАЕТ обратно к нулю. Значит
   дописанный хвост не отсортирован ни внутри себя, ни относительно тела.
   ⛳ НО ЭТОТ ХВОСТ — РОВНО ПИШУЩИЙСЯ СЛОЙ: push всегда ставит `layer: loop.layer`, а оба цикла и так
   его пропускают (`recording && ev.layer===loop.layer`). Поэтому курсоры работают по
   ОТСОРТИРОВАННОМУ ПРЕФИКСУ длиной cursN, а хвост вне его — и не нужен им, и не мешает.
   ⛳ ГЛАВНОЕ СВОЙСТВО БЕЗОПАСНОСТИ: курсор только СУЖАЕТ участок, который смотрим; ЧТО именно сыграть,
   по-прежнему решает явная проверка интервала внутри цикла. Поэтому курсор, вставший СЛИШКОМ РАНО,
   безвреден — лишние события отсеет проверка. Не убирайте эти проверки «раз есть курсор».
   ⚠️ ЗАВОРОТ — НЕ ОСОБЫЙ СЛУЧАЙ, а просто «позиция поехала не туда, где стоит курсор»: lo падает к
   нулю, курсор перепривязывается двоичным поиском. В коде курсора слова «заворот» нет вовсе — и когда
   заворот исчезнет вместе с петлёй, менять здесь будет нечего. */
let cursN=0;                        // длина ОТСОРТИРОВАННОГО префикса events (хвост записи — за ним)
const curSched={i:0,at:null};       // курсор scheduleLayers: i — индекс, at — доля, которой он соответствует
const curNear ={i:0,at:null};       // курсор fireNear (своя временнáя база, см. довод у fireNear)
/* Первый индекс в [0,cursN) с events[i].t >= t. Классический lower_bound. */
function cursLowerBound(t){
  let lo=0, hi=cursN;
  while(lo<hi){ const m=(lo+hi)>>1; if(events[m].t<t) lo=m+1; else hi=m; }
  return lo;
}
/* Поставить курсор на позицию x. Продолжаем с места, если он ровно там; иначе — двоичный поиск.
   Сравнение с допуском 1e-9: соседние сегменты дают ПОБИТОВО равные значения (hi предыдущего —
   то же выражение, что lo следующего), но допуск страхует от дрейфа после смены темпа. */
function cursSeek(c,x){
  /* СТРАХОВКА, О(1), на входе в оба цикла: если бы какой-то путь удалил события, забыв про
     schedInvalidate, cursN оказался бы БОЛЬШЕ массива — и цикл прочитал бы events[i].t у undefined,
     уронив насос звука целиком. Доказано, что таких путей нет (каждое удаление сбрасывает курсоры),
     но цена проверки — одно сравнение на вызов, а цена ошибки — тишина во всём приложении.
     ⛔ Это НЕ замена schedInvalidate: забытый сброс даст лишний обход, а не молчаливо верный результат. */
  if(cursN>events.length) cursN=events.length;
  if(c.at===null || Math.abs(c.at-x)>1e-9){ c.i=cursLowerBound(x); c.at=x; }
  return c.i;
}
/* ⛔ ЕДИНСТВЕННАЯ ТОЧКА СБРОСА КУРСОРОВ — сюда обязан приходить КАЖДЫЙ путь, который делает их
   неверными: правка состава событий (запись, аранжировка, отмена слоя, снятие подложки, очистка),
   пересортировка, и скачок временнóй базы (старт/возобновление транспорта, смена темпа, пауза,
   паника). Позже сюда же придут правка события и перемотка.
   ⛔ НИКАКИХ `curSched.i=0` ПО МЕСТАМ. Разбросанные сбросы — ровно тот способ, которым такая
   оптимизация тихо ломается: один забытый путь даёт пропущенные или удвоенные ноты, причём не сразу.
   Здесь же заново берётся и cursN — длина отсортированного префикса: эта функция вызывается ТОЛЬКО
   когда массив приведён в порядок (сразу после sort/уплотнения/очистки) либо когда запись ещё ничего
   не дописала, поэтому `events.length` в этот момент и есть граница сортированного. */
function schedInvalidate(){ cursN=events.length; curSched.at=null; curNear.at=null; }
/* ⛳ УПЛОТНЕНИЕ НА МЕСТЕ вместо splice-в-цикле. Прежде и onUndo, и clearJam удаляли событие за
   событием: каждый splice сдвигает ВЕСЬ хвост, поэтому снятие 10 000 событий из 30 000 — это сотни
   миллионов перемещений, то есть многосекундная заморозка потока, на котором висят и распознавание, и
   синтез. Проход с индексом записи делает ту же работу за ОДИН проход.
   ⛔ ИДЕНТИЧНОСТЬ ССЫЛКИ `events` СВЯЩЕННА: массив объявлен стабильной ссылкой и импортируется
   НАПРЯМУЮ в draw.js (полоса лупера читает его каждый кадр). Поэтому усечение через `.length`, а
   НИКОГДА не `events = …` и не новый массив — иначе draw остался бы с прежним, уже мёртвым.
   Порядок сохраняется, значит отсортированный префикс остаётся отсортированным. */
function compactEvents(drop){
  let w=0;
  for(let r=0;r<events.length;r++){ const e=events[r]; if(!drop(e)) events[w++]=e; }
  const removed=events.length-w;
  events.length=w;                                     // ⛔ усечение, а не подмена массива
  return removed;
}

/* 1) СЛОИ ВПЕРЁД: на каждый опрос планируем события в окне [loop.sched, горизонт) по их ТОЧНОМУ времени
   loop.t0 + абс.доля*spb, с проекцией через завороты (rep — номер повтора петли). Интервал ПОЛУОТКРЫТ
   [lo,hi): включает начало → доля 0 (сильный удар) не теряется на старте и после каждого заворота.
   На границе повтора гасим слои петли по ЯВНОМУ времени (releaseLoopLayersAt) — аналог softAllOff, но
   не «сейчас». Событие пишущегося слоя пропускаем. loop.sched — абсолютная доля, монотонно растёт. */
function scheduleLayers(){
  const spb=60/loop.bpm, lb=loopBeats();
  const horizon=(AC.currentTime+SCHED_AHEAD-loop.t0)/spb;   // абс. доля на горизонте опережения
  const gated=laneGated();                                  // ОДИН раз на вызов: пока никто не заглушён, в цикле остаётся готовый булев
  let guard=0;
  while(loop.sched<horizon-1e-9 && guard++<64){
    const rep=Math.floor(loop.sched/lb+1e-9), repEnd=(rep+1)*lb;
    const segEnd=Math.min(horizon,repEnd);
    const lo=loop.sched-rep*lb, hi=segEnd-rep*lb;           // [lo,hi) в пределах петли
    /* КУРСОР: встаём на первое событие с t>=lo (продолжая с места, если оно там же) и идём, пока t<hi.
       Курсор двигаем по ВСЕМ событиям окна, а не только по сыгранным: он — позиция ВО ВРЕМЕНИ, а не
       «сколько нот прозвучало». Явная проверка ev.t>=lo оставлена НАРОЧНО (см. шапку курсоров). */
    let i=cursSeek(curSched,lo);
    for(; i<cursN && events[i].t<hi; i++){
      const ev=events[i];
      if(!isLayer(ev.fn)) continue;
      if(recording&&ev.layer===loop.layer) continue;
      if(gated&&!laneAudible(ev.layer)) continue;           // дорожка заглушена (или молчит из-за чужого соло) — просто НЕ ПЛАНИРУЕМ её события; сами события НЕ трогаем
      if(ev.t>=lo){
        const when=loop.t0+(rep*lb+ev.t)*spb;               // ТОЧНОЕ время события
        ENG[ev.fn](ev.a,ev,{when});                         // ev несёт замороженный лад (§3.4). {when} ИМЕНОВАННО (S2): позиционный третий аргумент раньше значил у разных записей разное — см. шапку ENG
        if(ev.fn==='chOn'||ev.fn==='chSet'){ curChordDeg=ev.a.deg; curChordOct=ev.a.oct; }   // подсветка ведёт на опережение (~до окна) — косметика; регистр лежит в том же событии
        else if(ev.fn==='chOff')curChordDeg=-1;
      }
    }
    curSched.i=i; curSched.at=hi;                           // дошли до hi — следующий сегмент продолжит отсюда без поиска
    if(segEnd>=repEnd-1e-9) releaseLoopLayersAt(loop.t0+repEnd*spb);   // достигли границы повтора — гасим слои по явному времени
    loop.sched=segEnd;
  }
}
/* Гашение СЛОЁВ петли на границе повтора, по явному времени (owner 'loop:'/'bassloop:'; живое — latch/bass —
   гасит liveWrapRelease почти-сейчас). Читает hold СЕЙЧАС: там уже голоса уходящего повтора (chOn их создал).
   ⛳ layer — НЕОБЯЗАТЕЛЬНЫЙ фильтр (слайс S1): задан — гасим РОВНО этот слой (заглушение дорожки),
   не задан — ВСЕ слои петли, байт-в-байт прежнее поведение границы повтора. Обход ключей владельцев
   остаётся ОДИН: второй такой же цикл в другом месте рано или поздно разошёлся бы с этим.
   ⚠️ Сравниваем ХВОСТ ключа целиком ('loop:3' → '3') или хвост с двоеточием ('leadloop:3:0' → '3:'),
   а не просто начало: иначе слой 1 забрал бы и слой 12. */
function releaseLoopLayersAt(when,layer){
  const own = layer==null ? null : String(layer);
  const hit = (k,pre)=>{ if(k.slice(0,pre.length)!==pre) return false;
    if(own==null) return true;
    const rest=k.slice(pre.length);
    return rest===own || rest.slice(0,own.length+1)===own+':'; };
  for(const k of Object.keys(chordHold)) if(hit(k,'loop:')) chordOff(k,when);
  for(const k of Object.keys(bassHold))  if(hit(k,'bassloop:')) bassOff(k,when);
  /* СОЛО-СЛОИ тоже гасим на границе — иначе нота, записанная зажатой ЧЕРЕЗ заворот (leadOn есть,
     leadOff в слое нет), звучала бы вечно. Раньше её снимал голый noteOff() на завороте, потому что
     голос был один на всех.
     ⛳ `when` СОЛО ТЕПЕРЬ ПРИНИМАЕТ (слайс S2 дал leadOff явное время) — но ЗДЕСЬ МЫ ЕГО НАМЕРЕННО НЕ
     ПЕРЕДАЁМ. Лид по-прежнему идёт «почти сейчас» (он не в isLayer), поэтому гасить его к БУДУЩЕЙ
     границе повтора значило бы рассинхрон: ноты ставятся по стенным часам, а снимались бы по
     запланированным. Возможность есть, применить её — работа транспортного слайса, где перевод лида в
     планировщик делается ЦЕЛИКОМ и проверяется на слух. Пока — дословно прежнее поведение. */
  for(const k of Object.keys(leadHold))  if(hit(k,'leadloop:')) leadOff(k);
}
/* 2) ЛИД/дрон — почти-сейчас (как раньше): события в (a,b] БЕЗ when → AC.currentTime. Слои тут пропускаем.
   ⚠️ УСЛОВИЯ РАЗВЁРНУТЫ В continue-ветки (было одно длинное &&) РАДИ ЧИТАЕМОСТИ ПОСЛЕ ДОБАВЛЕНИЯ
   ГЕЙТА ДОРОЖЕК — набор условий и их смысл не изменились. */
/* ⛳ У fireNear СВОЙ КУРСОР, а не общий со scheduleLayers — и это вынужденно, а не по вкусу. Три
   различия, каждого хватило бы: (1) ВРЕМЕННÁЯ БАЗА другая — здесь позиция ИГРЫ (loop.pos), там
   горизонт ОПЕРЕЖЕНИЯ, и они расходятся на SCHED_AHEAD; (2) интервал полуоткрыт С ДРУГОЙ СТОРОНЫ
   ((a,b] против [lo,hi)); (3) на завороте fireNear зовут ДВАЖДЫ за тик, с прыжком назад к нулю.
   Общий курсор пришлось бы гонять между двумя позициями каждый тик — то есть он перестал бы быть
   монотонным и превратился бы в два двоичных поиска вместо нуля.
   В СТРОЮ они держатся тем, что оба перепривязываются через ОДНУ функцию (schedInvalidate) и делят
   ОДНУ границу отсортированного префикса cursN.
   ⚠️ lower_bound даёт первое t>=a, а нам нужно строгое t>a — разницу снимает ОСТАВЛЕННАЯ явная
   проверка ev.t<=a: курсор может встать на одно событие раньше, и это безвредно по построению. */
function fireNear(a,b){
  const gated=laneGated();                                   // как в scheduleLayers: считаем один раз на вызов
  let i=cursSeek(curNear,a);
  for(; i<cursN && events[i].t<=b; i++){
    const ev=events[i];
    if(isLayer(ev.fn)||ev.t<=a) continue;
    if(recording&&ev.layer===loop.layer) continue;
    if(gated&&!laneAudible(ev.layer)) continue;              // заглушённая / молчащая из-за чужого соло дорожка
    ENG[ev.fn](ev.a,ev);
  }
  curNear.i=i; curNear.at=b;                                 // следующий вызов придёт с a===b и продолжит без поиска
}
/* Гашение ЖИВОГО на завороте — слои петли гасятся вперёд (releaseLoopLayersAt), а ЖИВОЙ аккорд НЕ трогаем.
   Живой аккорд ('latch') принадлежит РУКЕ, а не петле: удержанный или защёлкнутый, он обязан пережить
   сколько угодно заворотов, пока игрок не отпустит пальцы (удержание) или не сменит аккорд (защёлка).
   Раньше здесь стоял chordOff('latch') + сброс latchDeg/latchTy/recCh — он и обрезал аккорд на границе;
   убрано. Лид/бас гасим по-прежнему: они переатакуются со следующего кадра ещё зажатой рукой (для
   аккорда так нельзя — живой путь WchSet→chordGlide не пересобирает удалённые голоса).
   ⚠️ ЛИД ГАСИМ ТЕПЕРЬ ИЗБИРАТЕЛЬНО — только владельцев 'lead:*' (живые руки). Прежний голый noteOff()
   означал «моно, гасим единственный голос»; в пуле он снёс бы и переигранные соло-слои, у которых своя
   граница (её держит releaseLoopLayersAt, там же где аккордовые и басовые слои). Бас остаётся МОНО и
   гасится по своему ключу — НЕ сводить эти две ветки в одну, пока бас не получит такой же пул. */
function liveWrapRelease(){ if(!AC)return;
  for(const k of Object.keys(leadHold)) if(k.slice(0,5)==='lead:') leadOff(k);
  bassOff('bass');
  recLeadReset(); recBass=null; }
function schedClicks(){                                // щелчки метронома с опережением по AC-часам
  const spb=60/loop.bpm, ahead=AC.currentTime+SCHED_AHEAD;
  while(loop.t0+loop.clickBeat*spb<ahead){
    const bt=loop.t0+loop.clickBeat*spb, inCount=loop.clickBeat<0;
    /* Просроченный щелчок (bt в прошлом — зависание ДЛИННЕЕ окна) НАМЕРЕННО пропускаем, а не играем
       поздно: поздний щелчок слышен как «флам»/спотыкание (хуже, чем разовый пропуск, который ухо
       достраивает). С окном 0.30с пропуски редки; слои же наоборот — просроченные играем (звучат
       поздно, но не рвут состояние аккорда/баса; деградация к прежнему поведению на огромных столах). */
    if(bt>=AC.currentTime-0.001&&(inCount||recording))
      metroClick(bt, beatLevel(loop.metre, (((loop.clickBeat%loop.metre)+loop.metre)%loop.metre)));   // акцент по ГРУППЕ, не только по началу такта
    loop.clickBeat++;
  }
}
function tick(){
  if(!loop.on||!AC)return;
  schedClicks();
  scheduleLayers();                                   // СЛОИ — вперёд по явному времени (сэмпл-точно)
  const e=(AC.currentTime-loop.t0)*loop.bpm/60;
  if(e<0)return;                                      // отсчёт: только щелчки/планирование
  const lb=loopBeats(); let pos=e%lb;
  if(pos<loop.pos){                                   // заворот петли (для лид/дрон)
    fireNear(loop.pos,lb);
    liveWrapRelease();                                // гасим ЖИВОЕ к границе (слои — по явному времени)
    if(loop.first){ loop.first=false; setRecording(false); events.sort((x,y)=>x.t-y.t); schedInvalidate(); loop.sched=e;   // первая запись только что стала слоем — планировать её с ТЕКУЩЕЙ позиции (во время записи слоёв не планировалось → без дублей). schedInvalidate ПОСЛЕ sort: порядок изменился, и в cursN надо взять новую границу
      hooks.tutor && hooks.tutor('loop',{ev:'loopClosed'}); }   // ЗАЦЕПКА ОБУЧЕНИЯ: первый круг замкнулся и пошёл петлёй («вернулся») — урок «Лупер»
    fireNear(-1e-9,pos);
  }else fireNear(loop.pos,pos);
  loop.pos=pos;
}
function startTransport(countIn){
  clearPump();
  const spb=60/loop.bpm;
  loop.on=true; loop.pos=-1e-9; loop.sched=0;              // sched=0 → планируем слои с доли 0 (первый удар петли — по явному времени, сэмпл-точно)
  schedInvalidate();                                       // ⛳ ГЛАВНАЯ точка сброса: временнáя база прыгнула (pos/sched/t0 переставлены). Покрывает первую запись, снятие паузы и старт от аранжировки
  loop.t0=AC.currentTime+(countIn?loop.metre*spb:0.06);   // отсчёт — ОДИН такт (loop.metre долей), при любом размере (предсказуемое правило)
  loop.clickBeat=countIn?-loop.metre:0;
  pumpTimer=setInterval(tick,SCHED_TICK_MS);
  hooks.loop && hooks.loop(true);
}

/* Кнопка «● запись»: пусто → запись слоя 0 с отсчётом (авто-луп по завершении круга);
   играет петля → тумблер овердаба (вкл/выкл новый слой). */
function onRec(){
  if(!AC)return;
  /* ⛳ МЕСТО РОЖДЕНИЯ СЛОЯ №1 из трёх (см. закон у laneNew): первая запись. laneReset — песни не было,
     значит и дорожек; laneNew выдаёт номеру 0 свежий id. */
  if(!loop.on){ events.length=0; schedInvalidate(); laneReset(); loop.first=true; loop.layer=0; laneNew(loop.layer); setRecording(true); startTransport(true);
    hooks.tutor && hooks.tutor('loop',{ev:'recStart'}); }   // ЗАЦЕПКА ОБУЧЕНИЯ: старт записи первого круга (отсчёт пошёл) — урок «Лупер»
  /* ОСТАНОВКА ОВЕРДАБА. recAllOff — СТРОГО ДО setRecording(false) (см. его шапку): он и закрывает в слое
     всё, что осталось звучать под пальцами. Прежде здесь стояло `recLeadOff(); recChOff();` — соло не
     закрывалось вовсе (вызов без владельца), бас не закрывался вообще. */
  else if(recording){ recAllOff(); setRecording(false); events.sort((x,y)=>x.t-y.t); schedInvalidate();   // sort переставил события, а дописанный хвост стал частью отсортированного тела → новая граница cursN
    hooks.tutor && hooks.tutor('loop',{ev:'overdubStop'}); }   // ЗАЦЕПКА ОБУЧЕНИЯ: овердаб остановлен (слой готов) — урок «Лупер»
  /* ⛳ МЕСТО РОЖДЕНИЯ СЛОЯ №2: овердаб. Номер (maxLayer()+1) МОГ УЖЕ ЖИТЬ — его освободила ⤺ отмена,
     — поэтому laneNew обязателен: он затирает запись прежнего жильца номера, и новая дорожка не
     наследует его заглушение. Это тот самый случай, ради которого id вообще заведён. */
  else{ loop.layer=maxLayer()+1; laneNew(loop.layer); setRecording(true); schedInvalidate();   // массив ещё не менялся, но с этого мига push начнёт дописывать ХВОСТ — фиксируем границу cursN здесь, а не «когда-нибудь»
    hooks.tutor && hooks.tutor('loop',{ev:'overdubStart'}); }   // ЗАЦЕПКА ОБУЧЕНИЯ: начат новый слой поверх петли — урок «Лупер»
}
/* Загрузить аранжировку (гармония+бас+ритм) как ОТДЕЛЬНЫЕ слои, замороженные в текущем
   ладу/септаккорде (§3.4). Пустая петля → длина из прогрессии + запуск; непустая → только
   если длина совпадает (как setLoopBars). Слои снимаются undo сверху (сначала ритм). */
function loadArrangement(sel, jam=false){
  if(!AC)return false;
  /* drumKitIdx передаём ЯВНО: без него buildArrangement брал дефолт 0 и слои аранжировки всегда играли
     «Стандартом», какой бы кит ни был выбран — паттерны, писанные В РОЛЯХ ради кит-независимости, звучали
     одним китом. bars — для пути «только ударные» (длину берёт у петли, см. buildArrangement). */
  const arr=buildArrangement(sel, {chIdx, bassIdx, drumKitIdx, metre:loop.metre, bars:loop.bars});
  if(!arr||!arr.layers.length)return false;
  if(!events.length){ loop.bars=arr.bars; loop.first=false; }
  else if(arr.bars!==loop.bars)return false;           // не тот размер — тихо, как setLoopBars
  const base=events.length?maxLayer()+1:0;
  /* ⛳ МЕСТО РОЖДЕНИЯ СЛОЯ №3 (и последнее): каждый слой аранжировки/подложки. Номер тем более мог
     быть занят — снятая подложка освобождает свои номера, а следующая берёт их же. */
  arr.layers.forEach((evs,li)=>{ const layer=base+li; laneNew(layer);
    for(const e of evs){ const ev={t:e.t, layer, fn:e.fn, a:e.a, sc:CUR(), sev:seventh};
      if(jam)ev.jam=true;                              // МЕТКА СЛОЯ ДЖЕМА: живёт В САМОМ событии → снять ровно джем, не тронув записи игрока (см. clearJam)
      events.push(ev); } });
  events.sort((x,y)=>x.t-y.t);
  schedInvalidate();                                   // добавили слои и пересортировали → курсоры недействительны (startTransport ниже сбросит ещё раз, если петля стояла — это дёшево и безвредно)
  if(!loop.on)startTransport(false);
  if(droneAudible())droneOn();                         // включаем дрон сразу (насос переподтвердит на завороте); ⚠️ именно AUDIBLE, а не ACTIVE: заглушённая дорожка дрона не должна зазвучать от добавления соседних слоёв
  if(jam) hooks.tutor && hooks.tutor('loop',{ev:'jam'});   // ЗАЦЕПКА ОБУЧЕНИЯ: джем реально встал (слои добавлены) — урок «Лупер»; только для джема, не для ручной аранжировки
  return true;                                         // добавили (джем-контроллер по этому знает, что вариант встал)
}
/* Джем — та же аранжировка-shortcut, но её слои ПОМЕЧЕНЫ (e.jam). loadJam кладёт помеченные,
   clearJam снимает РОВНО их. Записи игрока (push никогда не ставит jam) неуязвимы по построению. */
const loadJam=sel=>loadArrangement(sel, true);
function clearJam(){
  if(!events.length)return;
  const removed=compactEvents(e=>e.jam);               // ОДИН проход вместо splice-в-цикле (см. compactEvents)
  if(!removed)return;
  schedInvalidate();                                   // состав событий изменился → курсоры недействительны
  lanePrune();                                         // у слоёв подложки больше нет событий → снимаем их настройки, чтобы не всплыли на следующем джеме с теми же номерами
  softAllOff(); if(!droneActive())droneOff();          // бухгалтерия как в onUndo: гасим зависшее, ушёл слой-дрон → гасим дрон
  if(!events.length)clearRec(); else hooks.loop&&hooks.loop(loop.on);   // пусто → полный сброс; остались записи игрока → петля играет дальше
}
function onLoop(){                                     // играть/пауза петли
  if(!AC)return;
  if(loop.on){ loop.on=false; clearPump(); softAllOff(); droneOff(); setRecording(false); schedInvalidate();   // пауза: возобновление придёт через startTransport с новой базой, курсор до тех пор недействителен
    hooks.rec&&hooks.rec(false); hooks.loop&&hooks.loop(false); }
  else if(events.length){ startTransport(false); if(droneAudible())droneOn(); }   // ⚠️ AUDIBLE: снятие паузы не должно воскрешать заглушённую дорожку дрона
}
function onUndo(){                                      // снять последний слой (на месте — ссылка events стабильна)
  if(!events.length)return;
  const top=maxLayer();
  compactEvents(e=>e.layer===top);                      // ОДИН проход вместо splice-в-цикле (см. compactEvents)
  schedInvalidate();                                    // состав событий изменился → курсоры недействительны
  lanePrune();                                          // снятая дорожка не должна оставить своё заглушение следующей записи на том же номере
  softAllOff(); if(!droneActive())droneOff();           // сняли слой-дрон → гасим (softAllOff дрон не трогает)
  if(!events.length)clearRec(); else hooks.loop && hooks.loop(loop.on);
  hooks.tutor && hooks.tutor('loop',{ev:'undo'});       // ЗАЦЕПКА ОБУЧЕНИЯ: снят верхний слой — урок «Лупер» (дошли только при непустой петле — ранний выход выше)
}
function setLoopBars(n){                                // длина меняется только на пустой петле
  if(events.length||loop.on)return;
  loop.bars=Math.max(1,Math.min(8,n));
}
const METRES=[2,3,4,5,6,7,8,9,10,12,16];               // допустимые размеры (долей в такте) — см. UI
function setLoopMetre(n){                               // размер меняется ТОЛЬКО на пустой петле (как bars: смена переосмыслила бы времена всех событий)
  if(events.length||loop.on)return;
  loop.metre = METRES.includes(+n) ? +n : loop.metre;
}
function setLoopQuant(v){ loop.quant=!!v; }             // общий тумблер квантизации
const SUBS=[4,3];                                       // дробление доли для квантизации ударных: 4 = 16-е, 3 = триоли
function setLoopSub(n){                                 // МОЖНО менять когда угодно: это настройка ЗАПИСИ, а не геометрия петли (в отличие от bars/metre)
  loop.sub = SUBS.includes(+n) ? +n : loop.sub;
}
/* ⚠️ Смена темпа — СКАЧОК ВРЕМЕННÓЙ БАЗЫ: доли считаются как (now−t0)·bpm/60, поэтому при новом bpm
   и НЕТРОНУТОМ t0 позиция в долях меняется разрывно. Курсор хранит долю, значит обязан отвязаться.
   (Сам разрыв позиции — предсуществующее поведение, этот слайс его НЕ чинит: см. отчёт.) */
function setLoopBpm(v){ loop.bpm=Math.max(40,Math.min(240,+v||loop.bpm)); schedInvalidate(); }   // темп петли — только пользователь
function clearRec(){
  clearPump(); events.length=0; schedInvalidate(); laneReset(); loop.on=false; setRecording(false); softAllOff(); droneOff();   // ✕ — песни больше нет, значит нет и дорожек: настройки уходят вместе с ними
  hooks.loop && hooks.loop(false);
}
/* ⚠️ panic НАМЕРЕННО НЕ ТРОГАЕТ настройки дорожек: события переживают панику, значит переживают и
   дорожки. «■» — это «замолчи сейчас», а не «забудь, что я намикшировал». */
function panic(){
  clearPump(); loop.on=false; schedInvalidate();   // события целы, но транспорт остановлен — возобновят его с новой базой
  softAllOff(); droneOff();
  setRecording(false); hooks.loop && hooks.loop(false);
}

