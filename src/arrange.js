/* --- Дробление и пригодность паттерна: ЕДИНЫЙ источник для генерации и для UI --- */
export const subOf=r=>r.sub||4;                                  // ячеек на долю; отсутствие sub = прежние 16-е
/* ЗАЩИТА ОТ ОПЕЧАТКИ В ДАННЫХ: сетка обязана быть ровно beats*sub. Без неё лишняя/недостающая ячейка
   молча растянула бы шаг (15 ячеек на 4 доли → 0.2667) и такт поехал бы, а найти это почти невозможно. */
export const gridOk=r=>r.grid.length===(r.beats||4)*subOf(r);
export const rhythmFits=(r,metre)=>!!r&&(r.beats||4)===metre&&gridOk(r);   // паттерн годен для размера
export const rhythmsForMetre=metre=>RHYTHMS.map((r,i)=>i).filter(i=>rhythmFits(RHYTHMS[i],metre));   // индексы годных (UI: фильтр списка и цикл «только ударные»)
/* Бас — только «честные» режимы: корень (фундамент аккорда) и педаль (дрон-тоника). */
export const BASS_MODES=[
  {id:'none',  name:{en:'None', ru:'Нет'}},
  {id:'roots', name:{en:'Root notes', ru:'Основные тоны'}},
  {id:'pedal', name:{en:'Pedal (tonic)', ru:'Педаль (тоника)'}},
];

const CHORD_VOL=0.55, BASS_VOL=0.6;

/* Чистая генерация: sel={prog, rhythm, bass}, ctx={chIdx, bassIdx, drumKitIdx, metre, bars}.
   metre — долей в такте (переменный размер, из loop.metre); дефолт 4 = прежнее поведение.
   → {bars, layers:[evList,…]} в порядке ГАРМОНИЯ, БАС, РИТМ (undo снимает сверху → сначала ритм).

   ТОЛЬКО УДАРНЫЕ (sel.prog<0): ни гармонии, ни баса — один ритмический слой. Длину брать неоткуда
   (её диктовала прогрессия), поэтому берём ДЛИНУ ПЕТЛИ (ctx.bars) → arr.bars всегда равен loop.bars,
   и проверка длины в loadArrangement для этого пути отказать не может (в отличие от джема). */
export function buildArrangement(sel, ctx){
  const { chIdx=0, bassIdx=0, drumKitIdx=0, metre=4, bars:ctxBars=2 } = ctx || {};
  const drumsOnly = sel.prog<0;                              // ветка ДО гейта !h: у ударных гармонии нет по определению
  const h = drumsOnly ? null : HARMONIES[sel.prog];
  if(!drumsOnly && !h) return null;
  const degs = drumsOnly ? [] : (h.drone ? [0,0] : h.degs);   // дрон: неявная тоника на 2 такта (для длины/баса)
  const bars = drumsOnly ? Math.max(1,ctxBars) : degs.length, layers=[];

  if(!drumsOnly){
    // Гармония: дрон — один событие-маркер (выделенные узлы dO1/dO2/dG); иначе аккорд на такт
    if(h.drone) layers.push([{ t:0, fn:'drone', a:{lvl:0.18} }]);
    else layers.push(degs.map((deg,bar)=>({ t:bar*metre, fn:'chOn',
      a:{deg, oct:0, vol:CHORD_VOL, inst:chIdx} })));

    // Бас (корни берём из degs — у дрона это тоника)
    const bass=BASS_MODES.find(b=>b.id===sel.bass);
    if(bass&&bass.id==='roots')
      layers.push(degs.map((deg,bar)=>({ t:bar*metre, fn:'bassOn',
        a:{deg, oct:0, vol:BASS_VOL, inst:bassIdx} })));
    else if(bass&&bass.id==='pedal')
      layers.push([{ t:0, fn:'bassOn', a:{deg:0, oct:0, vol:BASS_VOL, inst:bassIdx} }]);   // тоника на весь круг
  }

  // Ритм: только ГОДНЫЙ паттерн — своего размера и с сошедшейся сеткой (rhythmFits), иначе пропускаем.
  const rhythm=RHYTHMS[sel.rhythm];
  if(rhythmFits(rhythm, metre)){
    const stepBeat=1/subOf(rhythm);                          // доля одной ячейки: 1/4 у 16-х, 1/3 у триолей
    const drums=[];
    for(let bar=0;bar<bars;bar++) rhythm.grid.forEach((cell,st)=>{ if(!cell)return;
      for(const row in cell) drums.push({ t:bar*metre+st*stepBeat, fn:'drum',
        a:{row:+row, vol:cell[row], kit:drumKitIdx} }); });
    if(drums.length) layers.push(drums);
  }
  return { bars, layers };
}
