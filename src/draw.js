/* activeDegs — МНОЖЕСТВО звучащих ступеней (Set), а не одна: соло полифонично, и двумя руками можно
   держать два ряда сразу. У аккордов/баса в множестве максимум одна — рисунок тот же, что и был. */
function drawGrid(zx0,zx1,accent,labelOf,activeDegs,gridH=canvas.height,labelX=zx0+7){
  const s=CUR(), ivx=IVX(), rows=ivx.length, seg=gridH/rows;
  if(activeDegs&&activeDegs.size){
    ctx.fillStyle=hexA(accent,.26);
    for(const d of activeDegs) if(d>=0&&d<rows) ctx.fillRect(zx0,(rows-1-d)*seg,zx1-zx0,seg);
  }
  const every=seg>=15?1:seg>=9?2:4;
  ctx.font='12px system-ui'; ctx.textBaseline='middle'; ctx.textAlign='left';
  for(let i=0;i<rows;i++){
    const y=i*seg, deg=rows-1-i, ton=ivx[deg]%s.edo===0;
    ctx.strokeStyle=ton?'rgba(87,217,163,.30)':'rgba(255,255,255,.08)';
    ctx.beginPath(); ctx.moveTo(zx0,y); ctx.lineTo(zx1,y); ctx.stroke();
    if(ton||deg%every===0){
      ctx.fillStyle=ton?'#57d9a3':'rgba(255,255,255,.55)';
      ctx.fillText(labelOf(deg),labelX,y+seg/2);
    }
  }
}
/* ЕДИНАЯ ПОДПИСЬ НОТЫ — одна на ОБЕ раскладки (прямоугольники и узкие ряды).
   ⚠️ ПОДПИСЬ ЗАВИСИТ ОТ ЛАДА, А НЕ ОТ РАСКЛАДКИ. Раньше функций было ДВЕ (rectNoteLbl — всегда
   порядковый; gridNoteLbl — свары/имена нот/порядковый), и это сходило с рук ровно потому, что
   прямоугольники стояли на четырёх ладах, каждому из которых порядковый и был нужен. Как только
   мажор можно положить в прямоугольники, две функции начали бы врать друг про друга: одна и та же
   нота читалась бы «C» в рядах и «2» в прямоугольниках. Слито в одну.
   Ветки (порядок важен):
   (1) свары (индийские) — саргам;
   (2) fixedKey — сетка приколочена к C, имена нот СНОВА правдивы (rowLabel даёт NOTE_NAMES по КЛЮЧУ);
   (3) ПОРЯДКОВЫЙ Т,2,3,4… — трём родам ладов: НЕОКТАВНЫМ (period≠2: номер шага врал бы off-by-one),
       CENTS-ладам (их ноты не на 12-TET высотах: пифагоров D#=611.73¢ — имена C/C#/D врали бы) и
       ладам, у которых edo НЕ 12/24 (19/31-TET): у них rowLabel печатает НОМЕР ШАГА (Т,1,2…), а он
       на единицу расходится с легендой пальцев I–IV — «5-я нота» звалась бы «4». Тонику ловим
       СТРУКТУРНО (IVX[deg]%edo===0, как зелёная линия в drawGrid), а не через centsOf===0: у
       неоктавного периода центы сверху не округляются в ровный ноль;
   (4) иначе — реальные имена нот (12-TET, макамы 24-TET).
   БАЙТ-В-БАЙТ у всех четырёх сегодняшних rect-ладов: 19/31-TET (edo∉{12,24} → порядковый),
   Партч (cents → порядковый), гамма (period≠2 → порядковый) — ровно то, что давал rectNoteLbl;
   структурная проверка тоники совпадает с прежней centsOf===0 и на нижней, и на верхней тонике.
   Ветка (3) по edo∉{12,24} СЕГОДНЯ недостижима у нерект-ладов (единственные такие лады — 19/31-TET,
   а они rect), поэтому нерект-подписи тоже байт-в-байт; достижимой она станет, когда человек
   переключит 19/31-TET в узкие ряды — и там она как раз и нужна. */
/* s — ЗАМОРОЖЕННЫЙ лад события (S5.4), с умолчанием из живого: подпись остаётся ОДНОЙ функцией на все
   раскладки (правило #26), просто теперь умеет назвать ступень в ЧУЖОМ ладу — том, в котором её сыграли.
   Все внутренние вызовы получают ТОТ ЖЕ s: иначе «раги» читались бы по хроматике и наоборот. */
const noteLbl = (deg,s=CUR()) =>
  s.swaraNames ? swaraLbl(deg,s)
    : s.fixedKey ? rowLabel(deg,s)
    : (periodOf(s)!==2 || s.cents || (s.edo!==12 && s.edo!==24))
    ? (IVX(s)[deg]%s.edo===0 ? 'Т' : String(deg+1))
    : rowLabel(deg,s);
/* Сетка ПРЯМОУГОЛЬНИКОВ (соло/бас/аккорды). Прямоугольник выбирается по Y, нота/корень внутри —
   ПАЛЬЦЕМ, а НЕ горизонталью: X — громкость. Поэтому ноты показываем КОМПАКТНОЙ ЛЕГЕНДОЙ по пальцам
   (I/II/… → нота), а не колонками. Активный палец подсвечен, активный прямоугольник подтонирован.
   Полосу даёт rectBandY (тот же делитель высоты, что у degHyst в gestures), число полос и ВСЮ
   арифметику — rectLayout: ввод и картинка не разъедутся.
   ⚠️ ТРИ ВЕЩИ ЗДЕСЬ ПЕРЕМЕННЫЕ, а не константы:
   (1) НОТ В ПРЯМОУГОЛЬНИКЕ RL.k (4/3/2) — никаких зашитых четвёрок; лишние пальцы рисуем ТУСКЛЫМ
       прочерком: молчание без объяснения читается как поломка (при k=2 половина руки холостая);
   (2) ОКТАВНАЯ ПОЛОСА ЕСТЬ НЕ ВСЕГДА — смещение «полоса→прямоугольник» берём из RL.regBands
       (при показе всех регистров она равна 0 и полоса === прямоугольник);
   (3) ПЕРИОДОВ НА ЭКРАНЕ МОЖЕТ БЫТЬ НЕСКОЛЬКО — тогда у каждой полосы свой регистр, и его НАДО
       показать (маркер справа): четыре одинаковых блока без пометки не дают понять, куда целишься.
   activeSlots — МНОЖЕСТВО (Set) звучащих СЛОТОВ (не ступеней!), см. правило про подсветку в drawRole.
   ⚠️ Именно множество: соло полифонично (нота на руку сейчас, до четырёх на руку с многопальцевым
   вводом), и подсветить надо КАЖДУЮ звучащую. Отсюда же второе требование: в одном прямоугольнике
   может гореть НЕСКОЛЬКО строк легенды — по строке на звучащий палец.
   x0..x1 — X-ПРОТЯЖЁННОСТЬ: соло/бас на всю ширину роли; ТИПИЗИРОВАННЫЕ аккорды — правее палитры
   [palSplitX,rx1], нетипизированные (палитры нет) — тоже на всю ширину роли. lblOf(deg) — подпись
   ноты/корня, её выбирает вызывающий (соло/бас: нота+центы; аккорды: корень+центы или имя аккорда). */
function drawRectGrid(x0,x1,playH,accent,activeSlots,lblOf,role){
  const RL=rectLayout(), nB=RL.bands, w=x1-x0, base=rectBase(rectOctReg(role));
  const aSet=activeSlots||new Set();
  const rectOn=new Set(); for(const g of aSet) rectOn.add(Math.floor(g/RL.k));   // прямоугольники, где звучит хоть одна нота
  const lx=x0+7;                                 // легенда от СВОЕГО левого края (у аккордов x0=split — правее палитры). ⚠️ Слайс б.2 убрал отсюда резерв под столбики (rx0+bandR+8): столбики ушли к ПРАВОЙ кромке, отодвигаться слева не от чего. Параметр rx0 существовал ТОЛЬКО ради этого слагаемого и снят вместе с ним
  ctx.textBaseline='middle';
  for(let b=0;b<nB;b++){
    const [yTop,yBot]=rectBandY(b,playH,nB), h=yBot-yTop;
    if(RL.hasReg&&b===0){
      drawRectOctBand(x0,w,lx,yTop,h,role);      // общий с терменвоксом рендер октавной полосы (роль → чей регистр подсветить)
    }else{
      const r=b-RL.regBands, on=rectOn.has(r);   // нотный прямоугольник = полоса − октавная (если она есть); «активен» = звучит ЛЮБАЯ его нота
      ctx.fillStyle= on ? hexA(accent,.16) : (r%2?'rgba(255,255,255,.05)':'rgba(255,255,255,.03)');
      ctx.fillRect(x0,yTop,w,h);
      ctx.strokeStyle= on ? accent : 'rgba(255,255,255,.12)';
      ctx.lineWidth= on ? 2 : 1; ctx.strokeRect(x0+0.5,yTop+0.5,w-1,h-1);
      /* Легенда пальцев (I=указ. … ), стопкой — это КЛЮЧ, а не зоны выбора. Строк RL.k; холостые пальцы
         дорисовываем тусклым прочерком, чтобы «мизинец молчит» читалось как УСТРОЙСТВО, а не как сбой.
         Высоту делим на ВСЕ ЧЕТЫРЕ пальца — стопка не скачет при смене лада.
         ⚠️ ПОРЯДОК СТРОК ПЕРЕВЁРНУТ: НИЖНЯЯ нота прямоугольника — ВНИЗУ, верхняя — вверху. Раньше
         список шёл сверху вниз, то есть ВНУТРИ блока высота росла вниз, а сама сетка снаружи растёт
         ВВЕРХ — «выше звучит, ниже написано». Это ТОЛЬКО ПОРЯДОК ОТРИСОВКИ: палец n по-прежнему берёт
         слот r*k+n (указательный — первая нота прямоугольника, мизинец — последняя), подсветка ищет тот
         же слот, звук не тронут. Меняется y строки, и ничего больше. */
      const NF=FINGER_TIPS.length, eh=Math.min(20,(h-8)/NF), sy=yTop+(h-eh*NF)/2;
      for(let n=0;n<NF;n++){
        const ey=sy+(NF-1-n)*eh+eh/2, live=n<RL.k, act=aSet.has(r*RL.k+n);   // (NF-1-n) — тот самый переворот; подсвечиваем СТРОКУ ЗВУЧАЩЕГО пальца, а не «строку активного прямоугольника»: в одном прямоугольнике их может гореть несколько
        ctx.textAlign='left';
        if(!live){ ctx.font='11px system-ui'; ctx.fillStyle='rgba(255,255,255,.22)'; ctx.fillText(`${OCT_ROMAN[n]}  —`, lx, ey); continue; }
        const deg=rectNoteAt(Math.min(r*RL.k+n,RL.notes-1),base).deg;
        ctx.font= act?'700 13px system-ui':'12px system-ui';
        ctx.fillStyle= act?accent:'rgba(255,255,255,.6)';
        ctx.fillText(`${OCT_ROMAN[n]}  ${lblOf(deg)}`, lx, ey);
      }
      /* МАРКЕР РЕГИСТРА у правого края полосы — только когда периодов на экране несколько.
         Без него четыре одинаковых блока не отличить, и человек не знает, в какой октаве целится.
         Регистр берём ТОЙ ЖЕ формулой, что и звук (rectNoteAt), поэтому маркер не может соврать. */
      if(RL.octaves>1){
        const o=rectNoteAt(r*RL.k,base).oct;
        ctx.font='700 11px system-ui'; ctx.textAlign='right';
        ctx.fillStyle= on ? hexA(accent,.95) : 'rgba(255,255,255,.34)';
        ctx.fillText(OCT_ROMAN[o]||String(o+1), x1-6, yTop+Math.min(10,h/2));   // ВВЕРХУ полосы, а не по центру: центр справа занимает разбор Гц звучащего аккорда
      }
    }
  }
  ctx.textBaseline='alphabetic'; ctx.textAlign='left';
}
/* ОКТАВНАЯ ПОЛОСА (нижний прямоугольник) — распорядитель регистра, control-синий. Строки
   палец→регистр; активный регистр РОЛИ (rectOctReg: соло→octReg, бас→bassOctReg, аккорды→chordOctReg)
   подсвечен. Рендер октавной полосы для rect-сетки (drawRectGrid); терменвокс теперь аддитивный
   оверлей и полосу НЕ перерисовывает (её даёт сетка).
   ⚠️ ПОЛОСА ЕСТЬ ТОЛЬКО ТАМ, ГДЕ ПОКАЗАН НЕ ВЕСЬ ДИАПАЗОН (rectLayout().hasReg), и она двигает ОКНО
   из octaves периодов, а не одну октаву. Значит выбираемых баз не всегда четыре: их rectBaseMax()+1
   (при одном периоде — прежние четыре, байт-в-байт), и лишние пальцы холостые — тем же тусклым
   прочерком, что и в нотном прямоугольнике. Подпись окна из двух периодов — «окт II–III». */
function drawRectOctBand(x0,w,lx,yTop,h,role){
  ctx.fillStyle=hexA('#4cc2ff',.10); ctx.fillRect(x0,yTop,w,h);
  ctx.strokeStyle=hexA('#4cc2ff',.55); ctx.lineWidth=1.5; ctx.strokeRect(x0+0.5,yTop+0.5,w-1,h-1);
  const oc=rectLayout().octaves, nSel=rectBaseMax()+1, rows=FINGER_TIPS.length+1;   // строк всегда 5 (шапка+4 пальца) — стопка не скачет от лада к ладу
  const eh=Math.min(18,(h-6)/rows), sy=yTop+(h-eh*rows)/2, reg=rectBase(rectOctReg(role));
  ctx.textBaseline='middle'; ctx.textAlign='left'; ctx.font='700 12px system-ui'; ctx.fillStyle=hexA('#4cc2ff',.9);
  ctx.fillText(periodOf()===2?t('reg.octaveFull'):regWord().toUpperCase(), lx, sy+eh/2);   // слово-регистр по периоду (октава→ОКТАВА; период≠2 → ТРИТАВА/РЕГ.)
  for(let n=0;n<FINGER_TIPS.length;n++){
    const ey=sy+(n+1)*eh+eh/2;
    if(n>=nSel){ ctx.font='11px system-ui'; ctx.fillStyle='rgba(255,255,255,.22)'; ctx.fillText(`${OCT_ROMAN[n]}  —`, lx, ey); continue; }   // база вне допустимой — палец холостой
    const act=n===reg, span = oc>1 ? `${OCT_ROMAN[n]}–${OCT_ROMAN[n+oc-1]}` : OCT_ROMAN[n];
    ctx.font= act?'700 13px system-ui':'12px system-ui';
    ctx.fillStyle= act?'#4cc2ff':'rgba(255,255,255,.6)';
    ctx.fillText(`${OCT_ROMAN[n]}  ${regWord()} ${span}`, lx, ey);
  }
}
/* ТЕРМЕНВОКС — АДДИТИВНЫЙ ОВЕРЛЕЙ поверх ОБЫЧНОЙ сетки (rect-прямоугольники/узкие ряды остаются как
   есть; терменвокс их НЕ заменяет — лишь добавляет линии). Рисуем ТОЛЬКО тонкие линии — по одной на
   реальную ноту (у rect-ладов 4 на прямоугольник), в ЦЕНТРЕ своего деления: ориентир для непрерывной
   высоты. Поле/октавную полосу/грубые границы уже нарисовала сетка — здесь НЕ повторяем (иначе двойная
   заливка/затемнение). Геометрия — thereminSpan, ТОТ ЖЕ раздел, что у звука (gestures), поэтому линия и
   слышимый центр совпадают. Ближайшие ноты (activeSlots) ярче. Показываем ТОЛЬКО когда какая-то рука
   роли назначена на терменвокс (drawRole). */
/* activeSlots — МНОЖЕСТВО (Set) звучащих слотов: терменвоксом тоже можно вести двумя руками, и ярче
   должна быть КАЖДАЯ ведомая линия, а не одна. У баса (моно) в множестве максимум одна. */
function drawThereminLines(x0,x1,playH,accent,activeSlots,role='ld'){
  const {M,spanBot,divH}=thereminSpan(playH), last=M-1, s=CUR();   // M = ноты НА СЕТКЕ (см. thereminSpan)
  const lx=x0+7;                                 // как у сетки: от своего левого края, без резерва (слайс б.2 — столбики теперь справа)
  const every=divH>=15?1:divH>=9?2:4;             // подписи прореживаем, если линии частые (Партч=44 нот)
  /* i — СЛОТ, а не ступень: у многопериодной сетки одна ступень встречается в каждом периоде,
     поэтому подпись и «зелёная тоника» берутся через rectNoteAt — ту же формулу, что даёт звук. */
  const base=rectGrid()?rectBase(rectOctReg(role)):0;
  const degOf = i => rectGrid() ? rectNoteAt(i,base).deg : i;
  ctx.textBaseline='middle';
  for(let i=0;i<=last;i++){
    const yc=spanBot-(i+0.5)*divH, on=!!(activeSlots&&activeSlots.has(i)), d=degOf(i);
    const ton=IVX()[d]%s.edo===0;                  // тоника/октава — зелёным (как drawGrid)
    ctx.strokeStyle= on?accent : ton?'rgba(87,217,163,.5)':'rgba(255,255,255,.22)';   // чуть ярче: линии поверх готовой сетки
    ctx.lineWidth= on?2:0.8;
    ctx.beginPath(); ctx.moveTo(x0,yc); ctx.lineTo(x1,yc); ctx.stroke();
    if(on||i%every===0){
      ctx.fillStyle= on?accent : ton?'#57d9a3':'rgba(255,255,255,.6)';
      ctx.font= on?'700 12px system-ui':'11px system-ui'; ctx.textAlign='left';
      ctx.fillText(`${noteLbl(d)} · ${centsOf(d)}c`, lx, yc);   // та же подпись, что у сетки и у ярлыка — одна функция на все раскладки
    }
  }
  ctx.textBaseline='alphabetic'; ctx.textAlign='left';
}
function drawTag(x,y,lines,color){
  ctx.font='600 15px system-ui';
  let w=0; for(const L of lines)w=Math.max(w,ctx.measureText(L).width);
  const lh=19, h=lines.length*lh+12, bw=w+18;
  let bx=x+16, by=y-h-10;
  if(bx+bw>canvas.width-6)bx=x-bw-16;
  if(by<50)by=y+16;
  ctx.fillStyle='rgba(10,10,20,.82)';
  ctx.strokeStyle=color; ctx.lineWidth=1.5;
  ctx.beginPath(); ctx.roundRect(bx,by,bw,h,9); ctx.fill(); ctx.stroke();
  ctx.textAlign='left'; ctx.textBaseline='middle';
  lines.forEach((L,i)=>{
    ctx.font=i===0?'700 15px system-ui':'12px system-ui';
    ctx.fillStyle=i===0?color:'rgba(255,255,255,.8)';
    ctx.fillText(L,bx+9,by+10+lh*i+lh/2-3);
  });
}
/* ================= ЖИВЫЕ ГЦ ЗВУЧАЩЕГО АККОРДА (только роль АККОРДЫ) =================
   Соло/бас показывают Гц и центы в ярлыке; у аккордов не было НИЧЕГО про верхние голоса —
   а именно они и есть смысл строя (какая терция, какая септима). Показываем РЕАЛЬНЫЕ Гц каждой
   ноты + в скобках интервал НАД КОРНЕМ в центах.
   ЕДИНЫЙ ИСТОЧНИК: берём частоты прямо из звучащих голосов chordHold['latch'] — это в точности
   вывод того самого вызова chordFreqs(), что породил звук (chordOn: o1.frequency.setValueAtTime(fr);
   гуманизация сидит на detune, не на frequency, поэтому .value === чистый fr). Ничего не пересчитываем
   параллельным путём → цифры не могут разойтись со слышимым; замороженный per-event sc уже учтён на
   стороне движка (latch живёт под текущим ладом — смена лада/тоники гасит его через softAllOff).
   ПОЧЕМУ интервал НАД КОРНЕМ, а не центы-от-тоники: верхние голоса центами-от-тоники читаются плохо,
   а «сколько над корнем» — ровно то число, что проверяют на слух (386 = чистая терция, 408 —
   пифагорова, 400 — 12-TET, 969 — натуральная септима 7/4). Корню скобка не нужна (0). */
function latchChordFreqs(){                        // частоты звучащего защёлкнутого аккорда, корень первым; null — тишины/нет голосов
  const vs=chordHold['latch']; if(!vs||!vs.length)return null;
  return vs.map(v=>v.o1.frequency.value);
}
/* ЖИВЫЕ НОТЫ ОДНОЙ РУКИ — из leadHold, реестра ЗВУЧАЩИХ голосов. ТА ЖЕ дисциплина, что у аккордового
   разбора (latchChordFreqs): показываем то, что ЗВУЧИТ, а не то, что намеревалась рука — HANDS хранит
   намерение и разошлось бы со звуком там, где голос украли. Ключи этой руки: 'lead:L' (потолок 1 и
   терменвокс — нота у руки одна) либо 'lead:L:<палец>' (многопальцевый). Гц считаем leadFreq(deg,oct) —
   ТОЙ ЖЕ функцией, что дала частоту звуку (recorder.ENG.leadOn), поэтому число не может разойтись.
   Сортируем по высоте: список читается снизу вверх, как сама сетка. */
function handLeadNotes(key){
  const pre='lead:'+handSide(key), out=[];
  for(const k in leadHold){
    if(k!==pre && k.slice(0,pre.length+1)!==pre+':')continue;
    const v=leadHold[k]; if(v.deg>=0) out.push({deg:v.deg,oct:v.oct,f:leadFreq(v.deg,v.oct)});
  }
  return out.sort((a,b)=>a.f-b.f);
}
/* Строки ярлыка для НЕСКОЛЬКИХ нот. Лестница деградации — ТА ЖЕ, что у аккордового разбора (fitReadout):
   «нота Гц (центы)» на всех → центы только у первых трёх → одни Гц → и лишь в самом конце «…». Число
   НИКОГДА не режется посередине: packSegs переносит сегментами. */
function fitLeadNotes(notes,maxW,maxLines){
  const nm=n=>noteLbl(n.deg), hz=n=>String(Math.round(n.f)), ct=n=>`${nm(n)} ${hz(n)} (${centsOf(n.deg)}c)`;
  const full=notes.map(ct), first3=notes.map((n,i)=>i<3?ct(n):`${nm(n)} ${hz(n)}`), hzOnly=notes.map(n=>`${nm(n)} ${hz(n)}`);
  for(const segs of [full,first3,hzOnly]){ const L=packSegs(segs,maxW,maxLines,false); if(L)return L; }
  return packSegs(hzOnly,maxW,maxLines,true);
}
/* Разложить сегменты по строкам (≤maxLines) под ширину maxW. trunc=false → null, если не влезло
   (пробуем более компактный вариант/шрифт); trunc=true → добиваем «…» на границе СЕГМЕНТА, число
   не режем никогда. */
function packSegs(segs,maxW,maxLines,trunc){
  const lines=[]; let cur='';
  for(const s of segs){
    const cand=cur?cur+' · '+s:s;
    if(ctx.measureText(cand).width<=maxW){ cur=cand; continue; }
    if(cur){ lines.push(cur); cur=''; }
    if(lines.length>=maxLines){ if(!trunc)return null; lines[maxLines-1]+=' …'; return lines; }
    if(ctx.measureText(s).width<=maxW){ cur=s; }
    else { if(!trunc)return null; lines.push('…'); if(lines.length>=maxLines)return lines.slice(0,maxLines); }
  }
  if(cur)lines.push(cur);
  return lines.length<=maxLines?lines:(trunc?lines.slice(0,maxLines):null);
}
/* Подобрать раскладку: сперва все ноты с центами, не влезло — центы только у первых трёх (Гц у всех),
   не влезло — только Гц. Шрифт 11→10. Гарантированный фолбэк — Гц с «…», без обрезки числа.
   Единицу «Гц» дописываем ОДИН раз к ПОСЛЕДНЕМУ сегменту (не после каждого числа — строка длиннее не
   нужна): встаёт в конец последней строки «… 220 (700¢) Гц», как читает и соло-ярлык («Гц» словом, а
   не «Hz»). Приписана ДО упаковки, поэтому её ширина учтена — за край не вылезет. */
function fitReadout(freqs,maxW){
  const f0=freqs[0], hz=f=>String(Math.round(f)),
        ct=f=>`${Math.round(f)} (${Math.round(1200*Math.log2(f/f0))}¢)`;
  const unit=a=>{ const b=a.slice(); b[b.length-1]+=' '+t('unit.hz'); return b; };   // «Гц» на последний сегмент → конец последней строки
  const withC =unit(freqs.map((f,i)=>i===0?hz(f):ct(f)));
  const first3=unit(freqs.map((f,i)=>i===0?hz(f):(i<3?ct(f):hz(f))));
  const hzOnly=unit(freqs.map(hz));
  for(const px of [11,10]){ ctx.font=`600 ${px}px system-ui`;
    for(const segs of [withC,first3,hzOnly]){ const L=packSegs(segs,maxW,2,false); if(L)return{lines:L,px}; } }
  ctx.font='600 10px system-ui';
  return {lines:packSegs(hzOnly,maxW,2,true),px:10};
}
/* Нарисовать разбор внутри полосы [x0..x1]×[yTop..yBot], прижав вправо (слева — корневая подпись/легенда
   пальцев). Тёмная подложка — чтобы Гц читались поверх подсвеченного прямоугольника. */
function drawChordReadout(x0,x1,yTop,yBot,freqs,accent){
  const maxW=Math.max(40,x1-x0-10), band=yBot-yTop;
  const fit=fitReadout(freqs,maxW); ctx.font=`600 ${fit.px}px system-ui`;
  const lh=fit.px+4, blockH=fit.lines.length*lh, by=yTop+Math.max(0,(band-blockH)/2);
  let bw=0; for(const L of fit.lines)bw=Math.max(bw,ctx.measureText(L).width);
  ctx.fillStyle='rgba(10,10,20,.74)';
  ctx.beginPath(); ctx.roundRect(x1-8-bw-6,by-3,bw+12,blockH+6,5); ctx.fill();
  ctx.textAlign='right'; ctx.textBaseline='middle'; ctx.fillStyle=accent;
  fit.lines.forEach((L,i)=>ctx.fillText(L,x1-10,by+lh*i+lh/2));
  ctx.textAlign='left'; ctx.textBaseline='alphabetic';
}
/* ================= ВИЗУАЛИЗАЦИЯ ЛУПЕРА =================
   Полоса-транспорт сверху-по-центру: сетка тактов/долей, бегунок позиции,
   по строке на слой с метками событий (соло — оранжевые, аккорды — сиреневые).
   Видна только когда есть петля или идёт запись; иначе не мешает синтезатору. */

/* ⛳ ПРЕОБРАЗОВАНИЕ «ДОЛЯ ↔ ПИКСЕЛЬ» — ЕДИНЫЙ ИСТОЧНИК ДЛЯ РИСОВАНИЯ И ПОПАДАНИЯ (правило #9).
   Заводится СЕЙЧАС, хотя масштаб пока ровно один (вся петля в ширину полосы) и управлять им нечем:
   всё, что придёт в полосу дальше (прокрутка, зум, пиано-ролл, перетаскивание событий), обязано
   попадать туда же, куда рисует. Две независимые копии геометрии — ровно та ошибка, от которой
   правило #9 и написано; дешевле завести одну ТЕПЕРЬ, пока потребитель один.
   ⚠️ ВЫРАЖЕНИЕ ОСТАВЛЕНО ДОСЛОВНО ПРЕЖНИМ — x0 + bw*(доля/span). Алгебраически это то же, что
   «доля/шаг», но НЕ то же в плавающей точке, а картинка обязана остаться прежней.
   loopView — снимок геометрии ПОСЛЕДНЕГО нарисованного кадра полосы; null, когда полосы нет. */
let loopView=null;
const laneBeatX=(V,b)=> V.x0 + V.bw*((b-V.beat0)/V.span);
/* ⛳ ОБРАТНОЕ ПРЕОБРАЗОВАНИЕ «ПИКСЕЛЬ → ДОЛЯ» (слайс S3.5b) — ЗДЕСЬ ЖЕ, из ТОГО ЖЕ снимка V и той же
   формулы, вывернутой алгебраически: x = x0 + bw·(b−beat0)/span  ⇔  b = beat0 + span·(x−x0)/bw.
   Поэтому laneBeatX(V, laneBeatAt(V,x)) === x (до плавающей точки) на всей линейке — палец берёт ту долю,
   над которой нарисован.
   ⛔ НЕ ВЫВОДИТЬ ОБРАТНОЕ ИЗ ОТДЕЛЬНО ПОСЧИТАННОЙ ГЕОМЕТРИИ (своё x0, своя ширина, «сколько тактов влезло»):
   это ровно та вторая копия, от которой правило #9. Появится зум/прокрутка — поменяются beat0/span в V,
   и обе функции поедут вместе. Кламп по линейке: тап чуть левее/правее неё — это край, а не «доля −3». */
const laneBeatAt=(V,x)=> V.beat0 + V.span*(Math.max(0,Math.min(V.bw,x-V.x0))/V.bw);
/* ⛳ ВЫСОТНАЯ ПАРА К ВРЕМЕННÓЙ (пиано-ролл, S5.0) — ЗДЕСЬ ЖЕ и выведена ТАК ЖЕ, из того же снимка V.
   У полосы лупера высоты не было (строка = дорожка, её считал сам drawLooper), у ролла она несущая:
   ряд — это ЗВУК (ударный ряд, дальше будет ступень), и палец обязан брать тот ряд, который видит.
   Ряд 0 — ВНИЗУ: так же пронумерованы ряды ударных (DRUM_NAMES, индекс 0 = низ) и так же считает
   игровое поле (degRaw). Поэтому z=rows-1-r, а не r.
   rollRowY даёт ВЕРХ ряда, rollRowAt — обратная: rollRowAt(V, rollRowY(V,r)+ε) === r на всей сетке. */
/* ⛳ S5.5: ряд отсчитывается от НИЖНЕГО ВИДИМОГО (V.row0) — это вертикальная прокрутка. У ударных рядов
   шесть, они влезают всегда и row0===0, поэтому выражение вырождается в прежнее БАЙТ-В-БАЙТ. У ладов же
   рядов бывает под две сотни (43 ступени × 4 регистра), и без прокрутки до верхних не добраться.
   ⛔ Прокрутка живёт В СНИМКЕ, а не отдельной переменной у рисования: попадание обязано считать её тем же
   числом, что и рисование (правило #9). */
const rollRowY =(V,r)=> V.gy0 + (V.rows-1-(r-(V.row0||0)))*V.rowH;
const rollRowAt=(V,y)=> (V.row0||0) + V.rows-1-Math.floor((y-V.gy0)/V.rowH);
/* Ширина гнезда переключателя и зазор. Нарисованная кнопка мельче гнезда — палец толще буквы. */
const LANE_TOG_W=21, LANE_TOG_GAP=2;
/* ✕ удаления (S3.5d) — третьим гнездом, но ОТСТУПЛЕН на LANE_DEL_GAP: соседство с S шириной в 2px делало бы
   промах «хотел соло — взвёл удаление» частым. Промах всё равно не разрушает (нужен второй тап), но
   отступ снимает большую часть ложных взводов. Зазор — мёртвая зона, тап в него не делает ничего. */
const LANE_DEL_GAP=6, LANE_DEL_COL='#e5484d';
const LANE_MUTE_COL='#e5a23c', LANE_SOLO_COL='#57d9a3';   // заглушено — янтарь (внимание), соло — тот же зелёный, что у «играет»
const LANE_OFF_A=0.34;                                    // прозрачность НЕСЛЫШНОЙ строки
/* Кнопка дорожки: буква в рамке, залитая — когда включена. Буква, а не значок: на 380px значок в
   21px нечитаем, а места под подпись нет. Буквы локализованы (M/S ↔ М/С) — см. словари. */
function laneTog(x,ry,rowH,lbl,on,col){
  const w=LANE_TOG_W, h=rowH-3, y=ry+1.5;
  ctx.beginPath(); ctx.roundRect(x,y,w,h,3);
  ctx.fillStyle   = on ? col : 'rgba(255,255,255,.07)'; ctx.fill();
  ctx.strokeStyle = on ? col : 'rgba(255,255,255,.20)'; ctx.lineWidth=1; ctx.stroke();
  ctx.fillStyle   = on ? '#0b0b14' : 'rgba(255,255,255,.60)';
  ctx.font='600 10px system-ui'; ctx.textAlign='center'; ctx.textBaseline='middle';
  ctx.fillText(lbl, x+w/2, y+h/2+0.5);
}
function drawLooper(){
  if(!loop.on && !events.length){ syncLoopTransport(false,0); loopView=null; return; }   // нет петли — полоса прячется (и попадать не во что)
  const W=canvas.width, info=loopPos();
  /* ⛳ ЛИНЕЙНЫЙ ТАЙМЛАЙН (S3.3). Раньше полоса показывала ОДИН круг петли: total = такты×размер, и
     всё — сетка, метки, бегунок — делилось на эту фиксированную длину.
     Теперь показываем ВСЮ ПЕСНЮ ЦЕЛИКОМ: выбранное отображение — «вписать всё» (fit), без прокрутки и
     зума. Это честный минимум для слайса: масштаб ОДИН, управлять им нечем, и он не врёт — видно
     ровно столько, сколько записано.
     ⚠️ Окно РАСТЁТ по мере записи, поэтому при длинной песне метки густеют. Прокрутка и зум придут с
     таймлайном редактора; преобразование доля↔пиксель для них уже есть (S1, loopView/laneBeatX) и
     менять его не придётся — поменяется только span и beat0.
     span берём как максимум из трёх: длина песни, ТЕКУЩАЯ позиция (иначе во время записи бегунок
     упёрся бы в правый край и встал) и длина ПОДЛОЖКИ (пустая песня — не нулевой отрезок, на нём
     видно сетку тактов и куда ляжет 🎵). */
  const posNow=info?info.pos:0;
  /* ⚠️ posNow — ПЕСЕННАЯ доля (loopPos, S3.5b): при повторе она не растёт за конец скобы, поэтому и
     ширина больше не ползёт вслед за часами. loop.rgn.to — четвёртый член (S3.5b): «следующая» скоба
     округлена вверх до такта и может быть чуть длиннее материала — без него её правый край рисовался бы
     за линейкой. */
  const total=Math.max(songBeats(), posNow, loop.bars*loop.metre, loop.rgn.to);
  const sw=Math.min(560,W-40), x0=(W-sw)/2;     // sw — ПОЛОСА ЦЕЛИКОМ (прежний bw): по ней считается коробка, и она не изменилась
  /* ⛳ МЕСТО ПОД ПЕРЕКЛЮЧАТЕЛИ ОТРЕЗАЕМ ОТ ЛИНЕЙКИ ВРЕМЕНИ, А НЕ ОТ КОРОБКИ, и слева его взять нельзя:
     на телефоне 380px коробка уже упирается в кромки (x0=20), а подпись слоя («L1») висит ЛЕВЕЕ неё.
     Поэтому кнопки идут СПРАВА внутри коробки, а линейка ровно на столько же короче.
     ⚠️ ЦЕНА ВИДИМАЯ И НАЗВАННАЯ: сетка долей, метки событий и бегунок стали уже. Но ВСЕ ТРИ одинаково —
     они считаются из ОДНОГО loopView, поэтому разъехаться не могут (правило #9). */
  const togBand=LANE_TOG_W*3+LANE_TOG_GAP*2+LANE_DEL_GAP+6;    // три гнезда (M, S, ✕) + зазоры + отступ ✕ + отступ от линейки. На 380px линейка 290→261px
  const bw=Math.max(60,sw-togBand), x1=x0+bw;   // линейка времени; пол 60px — страховка на совсем узком экране
  const ids=[...new Set(events.map(e=>e.layer))].sort((a,b)=>a-b);
  const rows=ids.slice();
  if(recording && !rows.includes(loop.layer)) rows.push(loop.layer);   // пустой слой, что пишется прямо сейчас
  /* rowH 13 → 16: строка стала не только читаемее, но и НАЖИМАЕМЕЕ — в ней теперь живут две кнопки.
     Выше не берём: каждая дорожка — это высота на экране, а их бывает много (см. отчёт слайса). */
  /* braceH — полоса СКОБЫ ПОВТОРА (S3.5b) между заголовком и строками. ОТДЕЛЬНАЯ полоса, а не тап по
     строкам: строки уже заняты mute/solo (и скоро — выбором дорожки для записи), и «тап по времени» с
     «тапом по дорожке» обязаны быть разными целями. */
  const nRow=Math.max(1,rows.length), rowH=16, headH=22, braceH=16, pad=7, y0=64;   // ниже заголовков зон (y≈52)
  const gy0=y0+headH+braceH, boxH=headH+braceH+nRow*rowH+pad*2, gy1=y0+boxH-pad;
  syncLoopTransport(true, y0+boxH+4);         // считаем из ТОГО ЖЕ boxH, что рисуем → разъехаться не могут
  /* Снимок геометрии для попадания — ОДИН объект, тот же, по которому ниже рисуем. tx0 — левый край
     первого гнезда переключателей. */
  loopView={ x0, bw, beat0:0, span:total, gy0, rowH, rows, tx0:x1+6, by0:y0+headH, hy0:y0 };   // by0 — верх полосы скобы (рисование); hy0 — верх её ЗОНЫ ПОПАДАНИЯ: вместе с заголовком, в котором тапать больше не во что, — ~38px под большой палец вместо 16

  ctx.fillStyle='rgba(10,10,20,.74)'; ctx.strokeStyle='rgba(255,255,255,.14)'; ctx.lineWidth=1;
  ctx.beginPath(); ctx.roundRect(x0-10,y0,sw+20,boxH,11); ctx.fill(); ctx.stroke();

  /* ⛳ ОБЛАСТЬ ПОВТОРА (S3.4) — рисуем ПОД сеткой и строками, чтобы она читалась как подсветка участка,
     а не как ещё один слой поверх. Показываем ТОЛЬКО включённой: помеченный, но выключенный участок
     обещал бы повтор, которого нет. Границы — из того же преобразования, что сетка и метки. */
  const RG=loop.rgn, cyc=cycling();   // cyc — тот же предикат, по которому ЗВУК решает, есть ли повтор (S3.5b; прежде здесь стояла своя копия условия)
  if(cyc){
    const rx0=laneBeatX(loopView,RG.from), rx1=laneBeatX(loopView,RG.to);
    ctx.fillStyle='rgba(87,217,163,.10)';                       // тот же зелёный, что у «играет» — это его участок
    ctx.fillRect(rx0,gy0,Math.max(1,rx1-rx0),gy1-gy0);
    ctx.strokeStyle='rgba(87,217,163,.55)'; ctx.lineWidth=1.5;  // скобки по краям: видно, ГДЕ шов
    ctx.beginPath(); ctx.moveTo(rx0,gy0); ctx.lineTo(rx0,gy1); ctx.moveTo(rx1,gy0); ctx.lineTo(rx1,gy1); ctx.stroke();
  }

  // заголовок — режим
  /* ⛳ ЗАГОЛОВОК ПЕРЕСОБРАН ПОД ЛИНЕЙНУЮ МОДЕЛЬ (S3.3): вместо «круг N тактов» — ДОРОЖКИ и ДЛИНА
     ПЕСНИ в тактах (выводимая из материала). Ветки loop.first больше нет — запись всегда «дорожка N». */
  const songBars=Math.max(1,Math.ceil(songBeats()/loop.metre));
  const armLy=armedLayer();                  // S3.5c: вооружённая дорожка (слой) или null — один раз на кадр, её читают и заголовок, и строки
  const delLy=laneDelPendingLayer();         // S3.5d: дорожка со взведённым удалением или null
  let head, hc;
  if(info&&info.phase==='count'){ head=t('looper.count',{n:info.countLeft}); hc='#57d9a3'; }
  else if(recording){ head=t('looper.overdub',{n:loop.layer+1}); hc='#e5484d'; }
  else if(loop.on){ head=t('looper.playing',{bars:songBars, layers:ids.length}); hc='#57d9a3'; }
  else { head=t('looper.paused',{bars:songBars, layers:ids.length}); hc='rgba(255,255,255,.7)'; }
  /* СОЛО ОБЪЯВЛЯЕМ В ЗАГОЛОВКЕ: иначе «молчит половина дорожек» читается как поломка, а не как режим.
     Приписка к готовой строке, а не отдельный ключ на каждую фразу — состояний заголовка четыре. */
  /* S3.5c: КУДА ПОЙДЁТ ● — словом в заголовке, рядом с красной рамкой строки. «(не слышно)» — если дорожка
     заглушена или молчит из-за чужого соло: запись в неё разрешена (панч-ин), но человек обязан знать, что
     после ● свою запись он не услышит, пока не снимет заглушение. Во время записи заголовок и так
     называет дорожку («● ЗАПИСЬ · дорожка N»). */
  if(!recording && armLy!=null){
    const heard = laneSoloOn() ? laneSoloed(armLy) : !laneMuted(armLy);
    head += ' · ' + t(heard ? 'looper.armed' : 'looper.armedSilent', {n:armLy+1});
  }
  if(cyc) head += ' · ' + t('looper.regionOn');   // повтор объявляем словом: одна подсветка на полосе легко теряется на пёстрой камере
  if(laneSoloOn()) head += ' · ' + t('looper.soloOn');
  /* S3.5d: ВЗВЕДЁННОЕ УДАЛЕНИЕ ЗАМЕНЯЕТ заголовок целиком, красным: это единственное, что сейчас важно, и
     приписка к и без того длинной строке на 380px ушла бы за кромку. */
  if(delLy!=null){ head=t('looper.delConfirm',{n:delLy+1}); hc='#ff6b6f'; }
  ctx.textAlign='left'; ctx.textBaseline='middle'; ctx.font='600 12px system-ui';
  ctx.fillStyle=hc; ctx.fillText(head,x0-2,y0+headH/2+1);

  /* ДРОБЛЕНИЕ ДОЛИ — тонкие короткие штрихи, и ТОЛЬКО когда сетка не шестнадцатая (loop.sub!==4):
     играющий должен ВИДЕТЬ ту сетку, к которой его квантуют (иначе триольная квантизация — сюрприз).
     При sub=4 (умолчание) не рисуем ничего → вид 4/4 байт-в-байт. Рисуем ДО долевых линий: те поверх. */
  /* ⛳ ПЛОТНОСТЬ СЕТКИ ТЕПЕРЬ ПЕРЕМЕННАЯ (S3.3). В петле долей было 8–32, и рисовать их все было
     даром. У песни на пять минут их СОТНИ: сплошная заливка вместо сетки и бессмысленная работа
     каждый кадр. Поэтому мелкое рисуем, только пока оно РАЗЛИЧИМО: доли — от 6px между ними,
     дробление доли — от 4px. Такты рисуем всегда (это скелет), но если и они гуще 3px — прореживаем
     кратно, чтобы линии не слились в кашу. */
  const pxPerBeat=bw/Math.max(1e-9,total);
  const barStep=Math.max(1,Math.ceil(3/(pxPerBeat*loop.metre)));   // рисовать каждый barStep-й такт
  if(loop.sub!==4 && pxPerBeat/loop.sub>=4){
    ctx.strokeStyle='rgba(255,255,255,.07)'; ctx.lineWidth=0.8;
    const sy0=gy0+(gy1-gy0)*0.35;                  // короче долевых — читается как «мельче», не спорит с ними
    for(let b=0;b<total;b++) for(let k=1;k<loop.sub;k++){
      const gx=laneBeatX(loopView,b+k/loop.sub);
      ctx.beginPath(); ctx.moveTo(gx,sy0); ctx.lineTo(gx,gy1); ctx.stroke();
    }
  }
  // сетка долей и тактов
  const showBeats=pxPerBeat>=6;
  for(let b=0;b<=total;b++){
    const bib=b%loop.metre;
    if(bib===0){ if((b/loop.metre)%barStep) continue; }        // прореживание тактов на длинной песне
    else if(!showBeats) continue;                             // доли не различимы — не рисуем вовсе
    const gx=laneBeatX(loopView,b), lvl=beatLevel(loop.metre,bib);   // видно 3+2+2, а не N одинаковых чёрточек; X — через ЕДИНОЕ преобразование, как метки и бегунок
    let sc,lw;
    if(bib===0){ sc='rgba(255,255,255,.34)'; lw=1.4; }        // начало такта
    else if(lvl===1){ sc='rgba(255,255,255,.24)'; lw=1.1; }   // голова группы
    else if(lvl===-1){ sc='rgba(140,180,255,.20)'; lw=1.0; }  // khali — холодный тусклый штрих («пустая» голова)
    else { sc='rgba(255,255,255,.11)'; lw=0.8; }              // обычная доля
    ctx.strokeStyle=sc; ctx.lineWidth=lw;
    ctx.beginPath(); ctx.moveTo(gx,gy0); ctx.lineTo(gx,gy1); ctx.stroke();
  }
  /* ⛳ ПОЛОСА СКОБЫ ПОВТОРА (S3.5b). Читается честно и без легенды:
       заливка — какие ТАКТЫ под скобой; зелёная — повтор ВКЛЮЧЁН (тот же зелёный, что «играет»),
       серая — скоба есть, но не повторяется (она всё равно задаёт начало записи);
       края — скобки ⌈…⌉; СПЛОШНЫЕ — скобу поставил человек, ПУНКТИР + «авто» — скоба следует за материалом;
       надпись — номера тактов «3–5» (с единицы, включительно).
     Риски линий тактов в полосе — цели тапа: тап едет на ближайшую линию. Прореживание то же (barStep),
     что у сетки, — риска не обещает линию, которой на сетке нет.
     ⛔ Все X — через laneBeatX того же loopView (правило #9); попадание — через laneBeatAt того же V. */
  {
    const M=loop.metre, byA=loopView.by0+2, byB=gy0-3, bh=byB-byA, tab=5;
    ctx.fillStyle='rgba(255,255,255,.05)'; ctx.fillRect(x0,byA,bw,bh);
    ctx.strokeStyle='rgba(255,255,255,.22)'; ctx.lineWidth=1;
    for(let b=0;b*M<=total+1e-9;b+=barStep){ const gx=laneBeatX(loopView,b*M);
      ctx.beginPath(); ctx.moveTo(gx,byB-4); ctx.lineTo(gx,byB); ctx.stroke(); }
    const bx0=laneBeatX(loopView,RG.from), bx1=laneBeatX(loopView,RG.to);
    ctx.fillStyle= cyc ? 'rgba(87,217,163,.40)' : 'rgba(255,255,255,.16)';
    ctx.fillRect(bx0,byA,Math.max(1,bx1-bx0),bh);
    ctx.strokeStyle= cyc ? '#57d9a3' : 'rgba(255,255,255,.8)'; ctx.lineWidth= RG.user ? 2 : 1.2;
    if(!RG.user) ctx.setLineDash([2,2]);
    ctx.beginPath();
    ctx.moveTo(bx0+tab,byA); ctx.lineTo(bx0,byA); ctx.lineTo(bx0,byB); ctx.lineTo(bx0+tab,byB);
    ctx.moveTo(bx1-tab,byA); ctx.lineTo(bx1,byA); ctx.lineTo(bx1,byB); ctx.lineTo(bx1-tab,byB);
    ctx.stroke(); ctx.setLineDash([]);
    const a=Math.round(RG.from/M), z=Math.round(RG.to/M), nums= z-a<=1 ? String(z) : `${a+1}–${z}`;
    ctx.font='600 9px system-ui'; ctx.textAlign='center'; ctx.textBaseline='middle';
    const room=bx1-bx0-2*tab-4;
    let lbl= RG.user ? nums : nums+' · '+t('looper.braceAuto');
    if(ctx.measureText(lbl).width>room) lbl=nums;               // узко — только номера; «авто» всё равно читается по пунктиру
    if(ctx.measureText(lbl).width<=room){ ctx.fillStyle='rgba(255,255,255,.92)'; ctx.fillText(lbl,(bx0+bx1)/2,(byA+byB)/2+0.5); }
    ctx.textAlign='left';
  }
  // строки слоёв + переключатели дорожки
  const soloOn=laneSoloOn();
  const rowOf=new Map();                                 // номер слоя → индекс строки (для ОДНОГО прохода по событиям, см. ниже)
  rows.forEach((lid,ri)=>{
    rowOf.set(lid,ri);
    const ry=gy0+ri*rowH, mid=ry+rowH/2, live=recording&&lid===loop.layer;
    const muted=laneMuted(lid), soloed=laneSoloed(lid);
    /* ПРИГЛУШАЕМ ПО СЛЫШИМОСТИ, А НЕ ПО ГАЛОЧКЕ MUTE: при включённом соло молчат ВСЕ, кроме соло-дорожек,
       и это ровно то, что человек должен видеть. Показывай мы только mute — «включил соло на одной»
       выглядело бы как «ничего не изменилось», хотя замолчало почти всё. Тот же предикат, что и в звуке. */
    const off = soloOn ? !soloed : muted;
    ctx.globalAlpha = off ? LANE_OFF_A : 1;              // одна альфа на ВСЮ строку: фон и подпись гаснут вместе
    ctx.fillStyle=live?'rgba(229,72,77,.16)':'rgba(255,255,255,.04)';
    ctx.fillRect(x0,ry+1,bw,rowH-2);
    ctx.fillStyle='rgba(255,255,255,.5)'; ctx.font='10px system-ui'; ctx.textAlign='right';
    ctx.fillText('L'+(lid+1),x0-4,mid);
    ctx.globalAlpha=1;                                   // кнопки рисуем В ПОЛНУЮ СИЛУ: это орган управления, он обязан читаться и на погашенной строке
    /* ⛳ ВООРУЖЁННАЯ ДОРОЖКА (S3.5c) — красная рамка во всю строку, красная точка записи в её начале и красная
       подпись, В ПОЛНУЮ СИЛУ даже на заглушённой строке: «куда я сейчас запишу» читается с одного взгляда
       на 380px, где слева от линейки места под значок нет (подпись L1 и так упирается в кромку).
       Во время записи рамку не рисуем: пишущуюся строку уже выделяет красная заливка (live). */
    if(!recording && lid===armLy){
      ctx.strokeStyle='#e5484d'; ctx.lineWidth=2; ctx.strokeRect(x0+1,ry+1.5,bw-2,rowH-3);
      ctx.fillStyle='#e5484d'; ctx.beginPath(); ctx.arc(x0+8,mid,3.5,0,7); ctx.fill();
      ctx.fillStyle='#ff6b6f'; ctx.font='600 10px system-ui'; ctx.textAlign='right'; ctx.fillText('L'+(lid+1),x0-4,mid);
    }
    /* ⛳ ИНДИКАТОР ЗАМОРОЗКИ (F5) — ТОЛЬКО ЗНАЧОК, без кнопки: на строке уже три органа управления и
       подпись в шестнадцати пикселях, четвёртый под палец не попал бы. Сама кнопка живёт в баре
       РЕДАКТОРА. ⛳ Геометрия — ИЗ ТОГО ЖЕ СНИМКА loopView (правило #9): значок садится на левый край
       дорожки, где для него есть место, и едет вместе со строкой.
       ТРИ СОСТОЯНИЯ, РАЗЛИЧИМЫЕ С ОДНОГО ВЗГЛЯДА НА 380px: голубая ❄ — свежая (играет буфер);
       оранжевая ❄ с точкой — УСТАРЕЛА (правили после заморозки, играет СВОИ СОБЫТИЯ); ничего — не
       заморожена. Цвет несёт смысл сам, подпись рядом не нужна — её место занято. */
    const fzs=freezeState(lid);
    if(fzs!=='none'){
      const fresh=fzs==='fresh';
      ctx.fillStyle = fresh?'#4cc2ff':'#f5a524';
      ctx.font='600 11px system-ui'; ctx.textAlign='left'; ctx.textBaseline='middle';
      ctx.fillText('❄', x0+3, mid);
      if(!fresh){ ctx.beginPath(); ctx.arc(x0+14,ry+5,2,0,7); ctx.fill(); }   // точка «устарело»: отличает и в оттенках серого
      ctx.textBaseline='alphabetic';
    }
    laneTog(loopView.tx0,                          ry,rowH,t('looper.laneMute'),muted, LANE_MUTE_COL);
    laneTog(loopView.tx0+LANE_TOG_W+LANE_TOG_GAP,  ry,rowH,t('looper.laneSolo'),soloed,LANE_SOLO_COL);
    /* S3.5d: ✕ — залит красным, пока удаление взведено; строка при этом краснеет поверх (видно, КАКАЯ дорожка уйдёт). */
    if(lid===delLy){ ctx.fillStyle='rgba(229,72,77,.24)'; ctx.fillRect(x0,ry+1,bw,rowH-2); }
    laneTog(loopView.tx0+2*(LANE_TOG_W+LANE_TOG_GAP)+LANE_DEL_GAP, ry,rowH,t('looper.laneDel'),lid===delLy,LANE_DEL_COL);
  });
  /* ⛳ МЕТКИ СОБЫТИЙ — ОДНИМ ПРОХОДОМ ПО ВСЕМ СОБЫТИЯМ, а не проходом НА КАЖДУЮ СТРОКУ (S3.3).
     Было O(дорожек × событий) НА КАДР: на петле с тремя строками и парой сотен событий незаметно, на
     песне в несколько минут с двумя десятками дорожек — десятки миллионов чтений в секунду, и полоса
     съедала бы кадр, ради которого весь S3.2 и делался. Стало O(событий): строку находим по карте.
     Альфу дорожки применяем поштучно — строки рисуются раньше, общий globalAlpha уже снят. */
  const laneAlpha=new Map();
  for(const lid of rows) laneAlpha.set(lid, (soloOn ? !laneSoloed(lid) : laneMuted(lid)) ? LANE_OFF_A : 1);
  for(const e of events){
    if(e.fn==='leadOff'||e.fn==='chOff') continue;
    const ri=rowOf.get(e.layer); if(ri===undefined) continue;
    const ex=laneBeatX(loopView,e.t), ry=gy0+ri*rowH;    // ⛳ через ЕДИНОЕ преобразование — то же, по которому идёт попадание
    ctx.globalAlpha=laneAlpha.get(e.layer);
    ctx.fillStyle=e.fn[0]==='c'?'#b18cff':'#ff9e2c';
    ctx.beginPath(); ctx.roundRect(ex-1.5,ry+3,3.5,rowH-6,1.5); ctx.fill();
  }
  ctx.globalAlpha=1;
  // бегунок позиции
  if(info&&info.phase==='play'){
    /* ⛳ Тоже через ЕДИНОЕ преобразование. Прежде здесь стояло деление на info.total, а сетка делила на
       свой total — величины совпадали, но источников было ДВА; теперь источник один (loopView.span). */
    const px=laneBeatX(loopView,info.pos), ph0=loopView.by0+2;   // S3.5b: бегунок идёт и сквозь полосу скобы — видно, где он относительно неё
    if(cyc){ ctx.strokeStyle='rgba(10,10,20,.85)'; ctx.lineWidth=4;   // тёмная подложка ТОЛЬКО при повторе: на зелёной заливке скобы зелёный бегунок иначе тонет
      ctx.beginPath(); ctx.moveTo(px,ph0); ctx.lineTo(px,gy1+2); ctx.stroke(); }
    ctx.strokeStyle=recording?'#e5484d':'#57d9a3'; ctx.lineWidth=2;
    ctx.beginPath(); ctx.moveTo(px,ph0); ctx.lineTo(px,gy1+2); ctx.stroke();
    ctx.fillStyle=ctx.strokeStyle; ctx.beginPath(); ctx.arc(px,ph0,3,0,7); ctx.fill();
  }
  ctx.textAlign='left'; ctx.textBaseline='alphabetic';
}
/* Видео-фон рисуем ДО детекции (тот же синхронный тик = тот же кадр видео),
   накладки — ПОСЛЕ. Так пиксели видео и точки руки берутся из ОДНОГО кадра:
   экран показывает то, ЧТО ПРОЗВУЧИТ, а не гонит свежее видео впереди отстающих
   точек. Это фикс когерентности, НЕ латентности — видео становится позже, чтобы
   совпасть с точками (звук по-прежнему из того же старого кадра). */
function drawVideoBackground(){
  const W=canvas.width, H=canvas.height;
  /* COVER-кадрирование: на холст попадает суб-прямоугольник кадра с соотношением ХОЛСТА, поэтому
     картинка НЕ растягивается (прежняя прямая растяжка кадра 4:3 в широкое окно давала горизонтальный
     растяг). Прямоугольник считает config.coverView из интрин. пикселей видео (videoWidth/Height) и
     формы холста; ТУ ЖЕ область кладём в state.viewRect (setViewRect) — ремап точек (sx/sy) кадрирует
     ЕЮ ЖЕ, так что картинка и рука режутся ОДНИМ прямоугольником и не разъедутся (правило #12). Пишем
     rect ДО детекции (правило #8: этот кадр видео → detect → processHands читает свежий viewRect).
     Пока видео не готово (нет размеров) — держим прежний rect (дефолт полей), рисуем лишь затемнение.
     Зеркалим только фронтальную (mirrored — тот же источник, что flipX/sx; rect симметричен по X). */
  const vw=video.videoWidth, vh=video.videoHeight;
  if(vw&&vh){
    const r=coverView(vw,vh,W,H); setViewRect(r);
    const sx0=r.ax0*vw, sy0=r.ay0*vh, sw=(r.ax1-r.ax0)*vw, sh=(r.ay1-r.ay0)*vh;
    if(mirrored()){ ctx.save(); ctx.scale(-1,1); ctx.drawImage(video,sx0,sy0,sw,sh,-W,0,W,H); ctx.restore(); }
    else ctx.drawImage(video,sx0,sy0,sw,sh,0,0,W,H);
  }
  ctx.fillStyle='rgba(7,7,13,.5)'; ctx.fillRect(0,0,W,H);
}
/* ================= РЕДАКТОР ДОРОЖКИ: ПИАНО-РОЛЛ (слайс S5.0) =================
   ЧТО ЭТО. Полноэкранная сетка ВРЕМЯ × РЯД для ОДНОЙ дорожки. В этом слайсе — только УДАРНЫЕ и только
   ЧТЕНИЕ: показать, прокрутить, приблизить, выбрать. Ни одно событие здесь не меняется.
   ⛳ СНИМОК ГЕОМЕТРИИ — СВОЙ (rollView), А НЕ ПЕРЕКРОЕННЫЙ loopView, и это решение, а не лень:
   полоса лупера рисует ДОРОЖКИ против времени, ролл — РЯДЫ ОДНОЙ дорожки против времени. Это разные
   оси Y при одной оси X. Одновременно они не видны НИКОГДА (ролл занимает весь экран и рисуется
   вместо игрового поля), поэтому у каждой поверхности по-прежнему РОВНО ОДИН снимок — правило #9 цело.
   ⛳ ОБЕ ОСИ И ПОПАДАНИЕ ЧИТАЮТ ОДИН ОБЪЕКТ: время — laneBeatX/laneBeatAt (те самые, без изменений),
   ряд — rollRowY/rollRowAt рядом с ними. rollHit берёт ТОТ ЖЕ rollView, что нарисован последним кадром.
   ⛳ ЦЕНА КАДРА. Полоса лупера обходит ВСЕ события каждый кадр — ролл так не может (пять минут музыки
   это десятки тысяч). Здесь: songNotes() отдаёт готовый кэш (перестраивается только в schedInvalidate),
   удары дорожки отбираются ОДИН раз на смену вида/дорожки (rollCache — memo по ИДЕНТИЧНОСТИ объекта
   вида, не по длине массива), а рисуются только попавшие в окно — двоичный поиск + проход по видимым.
   Кадр = O(log n + видимые удары + 6 рядов + линии сетки). */
const ROLL_BAR_H=46, ROLL_TP_H=44;      // высоты HTML-панели редактора и транспортной полосы под ней
const ROLL_RULER_H=16;                  // полоса ЛИНЕЙКИ (S5.2): тап по ней = перемотка; своя цель, как полоса скобы у лупера
