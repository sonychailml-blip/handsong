/* Геометрия столбиков эффектов. Правый край считаем ИЗ КОНСТАНТ, чтобы подписи
   ступеней сдвигались автоматически при подкрутке ширины/зазора — иначе разъедется. */
/* ГЕОМЕТРИЯ СТОЛБИКОВ — ОТ ПРАВОЙ КРОМКИ РОЛИ (слайс б.2; прежде FX_X0=6 и стопка от ЛЕВОЙ).
   Слева нельзя: там палитра типов аккордов — ровно поэтому индикатор ЯРК с самого начала стоял справа.
   Раз сторона одна на все роли, левый резерв под столбики стал не нужен НИКОМУ (см. ниже, где сняты
   fxBandR/fxN/soloBarsN/bandR).
   FX_EDGE — КРАЙНЕЕ ГНЕЗДО, и оно ЗАНЯТО НЕ НАМИ: там живёт одиночный индикатор роли «ВЫР»
   (drawExprBar, соло), по формуле rx1-FX_BAR_W-10. Цепочка эффектов начинается СЛЕДУЮЩИМ гнездом,
   поэтому у соло с рукой-выразительностью И рукой-эффектами ничего не наезжает друг на друга: ВЫР у
   кромки, эффекты левее с обычным зазором.
   ⚠️ ВТОРЫМ ЖИЛЬЦОМ ЭТОГО ГНЕЗДА БЫЛ «ЯРК» У АККОРДОВ — его больше нет: яркость стала обычным
   столбиком цепи (BRI) и встала в общий ряд. Гнездо у аккордов теперь просто пустует.
   ⚠️ СМЕЩЕНИЕ НА ГНЕЗДО — БЕЗУСЛОВНОЕ, а не «когда индикатор есть». Иначе включение руки-
   выразительности СДВИГАЛО БЫ всю цепочку под пальцем. Пустое гнездо у кромки — честная цена за то,
   что столбик не уезжает из-под руки.
   ⚠️ ЗАОДНО ЭТО УБИРАЕТ НАЛОЖЕНИЕ НА РЕГИСТРОВУЮ МЕТКУ полосы (drawRectGrid рисует её при octaves>1
   у самой кромки, x1-6): цепочка начинается не ближе x1-35, метка занимает ~x1-22..x1-6. */
const FX_EDGE=FX_BAR_W+10;                        // отступ крайнего ГНЕЗДА от правой кромки роли — тот же, что у ВЫР/ЯРК
const FX_STEP=FX_BAR_W+FX_BAR_GAP;                // шаг гнезда
const fxBarsY=H=>({ y0:H-40-FX_BAR_MAX, y1:H-40 });   // вертикаль столбика: выше строки статуса. ОДИН источник — им пользуются и отрисовка, и обход препятствий ниже
/* ЕДИНЫЙ ИСТОЧНИК «какие столбики эффектов есть сейчас» — и для ОТРИСОВКИ, и для ШИРИНЫ ОТСТУПА под
   легенду. Раньше и состав, и счёт брались прямо из FX_META (константа на четыре); теперь состав
   задаёт ЦЕПЬ СОЛО (state.fxChains по ключу CHAIN_SOLO, Пласт 3.3/O-0; прежде fxLayout — слот всё так же палец), а
   цепь живая. Разойдись счёт с рисованием — легенда наехала бы на столбики; поэтому обе стороны
   зовут ОДНУ функцию (тот же закон, что у сетки: попадание и отрисовка от одной геометрии).
   Слот с МОДУЛЕМ (реверб) в покое даёт ОДИН столбик (первый параметр), а пока его палец ЗАЖАТ —
   РАЗВОРАЧИВАЕТСЯ по столбику на параметр (TAIL/TONE): три ручки видно тогда, когда их крутят.
   Пустой слот («нет эффекта») не даёт столбика вовсе. */
/* ДВА РАЗНЫХ ВОПРОСА К РЕЕСТРУ — и после раздвоения реестра (Пласт 3.5.1) их нельзя задавать одному
   и тому же объекту, потому что ответы нужны из разных мест:
     fxSpecOf — СКОЛЬКО у эффекта параметров. Это СТАТИКА, и берётся из ФАБРИКИ: счёт нужен для
       ОТСТУПА под легенду, который обязан быть устойчив. Спроси мы экземпляр — отступ зависел бы от
       того, построен ли он уже, и легенда прыгала бы при первом обращении к эффекту.
     fxInstOf — ЖИВЫЕ ВЕЛИЧИНЫ (getNorm) и короткие подписи столбиков. Их знает только ЭКЗЕМПЛЯР:
       у фабрики значений нет и быть не может, она описывает вид, а не звучащий узел.
   ⚠️ fxInstOf БЕРЁТ ВЛАДЕЛЬЦА (слайс б.1 — роль, с O-0 — КЛЮЧ), и это НЕ косметика: экземпляры живут
   ПО ВЛАДЕЛЬЦАМ (FX_INST[key][fxId], Пласт 3.5.1), поэтому литерал 'ld' в нём означал бы «рисуя чужую цепь,
   показывай ЖИВЫЕ ВЕЛИЧИНЫ СОЛО». Столбики выглядели бы правдоподобно и врали бы — тем тише, чем
   ближе цепи по составу. fxSpecOf владельца не берёт по-прежнему: фабрика одна на всех, она описывает
   ВИД эффекта, а не звучащий узел.
   ⚠️ Экземпляр соло строится в initAudio ЯВНО, поэтому к первому кадру он уже есть; у прочих ролей
   fxInstance создаёт по требованию, а до AudioContext честно отдаёт пусто (ветка !mod ниже). */
/* ⚠️ fxInChain УДАЛЁН вместе с отдельным столбиком ЯРК: «эффект есть в цепи?» больше некому задавать
   в обход общего пути — на этот вопрос отвечает САМ обход цепи в fxBarItems, тем, что рисует запись
   или не находит её. Предикат существовал ровно для одного исключения, а исключения не стало. */
const fxSpecOf=eff=> FX_FACTORY[eff.fxId];
const fxInstOf=(key,eff)=> fxInstance(key,eff.fxId);   // O-0: экземпляр берём у ВЛАДЕЛЬЦА ЦЕПИ (ключ), а не у роли — довод тот же, что был про литерал 'ld' выше
/* ⚠️ СКОЛЬКО СТОЛБИКОВ РОЛЬ МОЖЕТ ЗАНЯТЬ — ПО ФАБРИКЕ И ПО МАКСИМУМУ, а не по нарисованному сейчас.
   Это ВОСКРЕШЁННЫЙ счётчик (в б.2 он умер вместе с левым резервом), и воскрешён СОЗНАТЕЛЬНО, но для
   ДРУГОГО дела — поэтому ⛔ ЭТО НЕ ВОЗВРАТ ПРАВИЛА R-1, и путать их нельзя:
     R-1 был ЛЕВЫМ резервом под ЛЕГЕНДУ СТУПЕНЕЙ, и чужая роль брала там СОЛО-число. Его нет.
     Здесь — ПРАВАЯ рамка САМИХ столбиков, по ЦЕПИ СВОЕЙ РОЛИ, и нужна она ровно одному соседу:
     разбору Гц аккорда, который прижат к той же правой кромке (см. drawRole).
   ПО МАКСИМУМУ (фабрика), а не по факту, — по той же причине, что и у покойного резерва: аккордеон
   разворачивает эффект под зажатым пальцем (1 столбик → 3), и рамка, посчитанная по факту, дёргала бы
   разбор Гц в такт щипку. Максимум неподвижен. */
/* ⛳ СТОЛБИК ПОСТОЯННОЙ ЗАПИСИ (громкость) — ТОЛЬКО КОГДА ОНА НА ПАЛЬЦЕ руки-эффектов (VOL-2). На горизонтали играющей руки её
   «столбик» — сама рука (положение и есть величина, у каждой руки своя), у «Фиксировано» — число в меню; столбик там был бы
   лишним гнездом на каждой роли. На пальце же без столбика не видно, куда ты его поставил, — там он нужен, как у любого
   эффекта. ⛔ ОДИН предикат на рисунок (fxBarItems) и на габарит (fxBarsMaxN): разойдутся — разбор Гц аккорда встанет
   не там, где кончаются столбики (правило #9). */
const fxBarHidden=eff=>{ if(!fxPerm(eff.fxId)) return false;
  const pa=eff.params&&eff.params[0]; return !(pa && pa.mode==='drive' && pa.hand==='fx'); };
const fxBarsMaxN=key=> fxChainOf(key).reduce((n,sl)=>{
  if(fxBarHidden(sl)) return n;                     // громкость без пальца столбика не рисует (fxBarItems) — значит и места в рамке не занимает
  if(fxIsScalar(sl.fxId)) return n+1;              // старый скалярный — по ЕДИНОМУ признаку (в.1), не по FX_META: делей-модуль там остался ради цвета, а столбиков у него три
  const mod=fxSpecOf(sl); return n+(mod?mod.params.length:0);   // ФАБРИКА, не экземпляр: рамка не должна зависеть от того, построен ли эффект
},0);
/* Габарит полосы столбиков роли — или null, когда её нет (нет руки-эффектов / пустая цепь).
   xL — левая кромка САМОГО ЛЕВОГО возможного столбика; вертикаль включает подпись над столбиком. */
const fxBarsBox=(key,rx1,H)=>{
  const n = fxBarsMaxN(key);                      // ПО ЦЕПИ, не по руке: столбики есть у всякой непустой цепи (см. drawFxBars), значит и рамка вокруг них
  if(!n) return null;
  const {y0,y1}=fxBarsY(H);
  return { xL: rx1-FX_EDGE-FX_STEP*n, y0: y0-16, y1 };   // -16 — строка подписи (11px по базовой линии y0-5)
};
/* ПАЛЕЦ, зажатый сейчас у руки-эффектов ЭТОЙ РОЛИ (Пласт 3.4.2; прежде — «активный слот», но слот
   перестал существовать: палец переехал в адрес параметра).
   ⚠️ ФИЛЬТР ПО РОЛИ ОБЯЗАТЕЛЕН (слайс б.1). Прежде перебор шёл по ВСЕМ рукам и отдавал первую
   попавшуюся в зоне 'fx' — верно ровно пока fx-рука бывала одна, у соло. В сплите fx-руки могут быть
   У ДВУХ РОЛЕЙ СРАЗУ, и без фильтра щипок в одной половине РАЗВОРАЧИВАЛ БЫ столбики ЧУЖОЙ: разворот
   («показываем все параметры эффекта, пока его палец зажат») пошёл бы от чужого пальца.
   S.role заморожена на захвате в ОБЕИХ ветках (см. gestures, слайс б.1) — до неё это чтение было бы
   невозможно в single-role, где S.role пустовала. Щипок fx-руки ОДНОЙ роли по-прежнему один, поэтому
   активный палец на роль не больше одного. */
const fxActiveFinger=role=>{ for(const k in HANDS){ const S=HANDS[k]; if(S.pinch&&S.zone==='fx'&&S.adj&&S.role===role) return S.adj.finger; } return null; };
/* «Этот параметр ведёт ВОТ ЭТОТ палец fx-руки» — один предикат на подсветку и на разворот. */
const fxParamOnFinger=(pa,f)=> !!(pa && f!=null && pa.mode==='drive' && pa.hand==='fx' && pa.finger===f);
/* «Этот параметр ведёт ДРУГАЯ (играющая) рука» — Пласт 3.2. Признак берём из РАСКЛАДКИ (адрес
   управления живёт там), а НЕ из дескриптора модуля: модуль знает про свои секунды и герцы, но не про
   то, чья рука его крутит. */
const fxParamIsPlay=la=> !!(la && la.mode==='drive' && la.hand==='play');
/* ⚠️ ДВА АРГУМЕНТА, И ЭТО НЕ ИЗБЫТОЧНОСТЬ (O-0). role — про РУКУ: какой палец зажат у fx-руки ЭТОЙ
   РОЛИ (fxActiveFinger сравнивает замороженную S.role), то есть вопрос экранно-ролевой. key — про
   ЦЕПЬ: чьи записи перечислять и чьи экземпляры читать. Сегодня одно выводится из другого, завтра
   (цепь у тембра) — нет, и слить их в один аргумент значило бы спрятать этот разрыв. */
const fxBarItems=(role,key)=>{
  const act=fxActiveFinger(role), out=[];
  fxChainOf(key).forEach(eff=>{   // ЦЕПЬ ЭТОЙ РОЛИ (слайс б.1; прежде литерал 'ld' — «столбики бывают только у соло»). С б.2 зовут для ЛЮБОЙ роли (drawFxBars — у правой кромки каждой роли/половины)
    if(fxBarHidden(eff)) return;                   // VOL-2: громкость — столбик только на пальце (тот же предикат — в fxBarsMaxN выше: рисунок и габарит считают одно)
    const m=FX_META.find(q=>q.k===eff.fxId);   // МЕТАДАННЫЕ ПОКАЗА (цвет, подпись) — у трёх скаляров и у делея-модуля (в.1): его столбики остались синими
    if(fxIsScalar(eff.fxId)){ out.push({v:fxAimGet(key,eff.fxId,FX_AMT,fx[eff.fxId]), c:m.color, l:m.label, fing:eff.params[0], play:fxParamIsPlay(eff.params[0]), drv:fxIsDriven(key,eff.fxId,FX_AMT)}); return; }   // старый скалярный — как было (у него ровно один параметр). Признак — по store (в.1), не по FX_META. O-3.1: величина — ПРИЦЕЛ руки, drv — правит ли этим адресом запись
    const mod=fxInstOf(key,eff); if(!mod) return;                                  // нет экземпляра (неизвестная запись / ещё нет AudioContext) — молча без столбика, как было при пустом реестре
    /* Идём по ИНДЕКСАМ, а не по значениям: индекс — единственное, чем дескриптор модуля (mod.params)
       связан со своим параметром в цепи (eff.params), где и лежит адрес управления.
       РАЗВОРОТ (Пласт 3.4.2): разворачивается эффект, У КОТОРОГО ХОТЬ ОДИН параметр сидит на зажатом
       пальце. Прежде условие звучало «слот === активный слот» — то же самое, пока эффект целиком
       принадлежал одному пальцу; теперь параметры одного эффекта могут быть на разных пальцах, и
       разворот обязан следовать за ПАРАМЕТРОМ. На дефолтной цепи это ровно прежнее поведение. */
    const idx=(mod.params.length>1 && eff.params.some(pa=>fxParamOnFinger(pa,act))) ? mod.params.map((_,i)=>i) : [0];
    for(const i of idx){ const p=mod.params[i];
      out.push({v:fxAimGet(key,eff.fxId,p.key,p.cur), c:m?m.color:REV_COLOR, l:p.short, fing:eff.params[i],
                play:fxParamIsPlay(eff.params[i]), drv:fxIsDriven(key,eff.fxId,p.key)}); }   // O-3.1: v — ПРИЦЕЛ руки (что поставил палец), drv — ведёт ли этот адрес запись. Признак ПО ПАРАМЕТРУ: у одного эффекта подмес может быть записан, а длина — нет   // REV_COLOR — исторический тон реверба; отдельного столбика REV больше нет (Пласт 3.1), реверб показывают ЕГО СОБСТВЕННЫЕ параметры: TAIL/TONE/MIX
  });
  return out;
};
/* ⛳ ЛЕВЫЙ РЕЗЕРВ ПОД СТОЛБИКИ СНЯТ ЦЕЛИКОМ (слайс б.2). Здесь жили fxBandR/fxBarsMaxN/fxN/soloBarsN/
   bandR — арифметика «отодвинь легенду ступеней вправо, чтобы не наехала на столбики эффектов».
   ⚠️ ОДНО ИМЯ ИЗ ЭТОГО СПИСКА ВЕРНУЛОСЬ — fxBarsMaxN (см. выше, у fxBarsBox), и это НЕ откат: там оно
   считает ПО СВОЕЙ РОЛИ и служит ПРАВОЙ рамке самих столбиков, чтобы разбор Гц аккорда уступил им
   дорогу (слайс б.3). Левого резерва и межролевого чтения в нём нет — доводы расписаны на месте.
   ⚠️ И ЗДЕСЬ ЖЕ ЖИЛО ПРАВИЛО R-1, которое три слайса подряд помечалось ⛔ «не трогать»: чужая роль
   (аккорды/бас/ударные) СОЗНАТЕЛЬНО брала СОЛО-число столбиков, чтобы её легенда стояла там, где
   стояла. ПРАВИЛО НЕ НАРУШЕНО — ОНО ПЕРЕСТАЛО СУЩЕСТВОВАТЬ, и это разные вещи. Причина: столбики
   ушли к ПРАВОЙ кромке у ВСЕХ ролей (см. FX_EDGE выше), слева не осталось ничего, от чего надо
   отодвигаться, — а значит и межролевому чтению нечего переносить. Резерв под то, чего нет, — это
   пустая полоса, а у прочих ролей он был вдвойне странен: они отступали под ЧУЖИЕ столбики, которых
   у них не рисовалось никогда.
   ⛔ НЕ ВОЗВРАЩАТЬ РЕЗЕРВ. Если когда-нибудь столбики (или что-то другое) вернутся к левой кромке,
   отступ считать ЗАНОВО и ПО СВОЕЙ РОЛИ — прежнее межролевое чтение было следствием того, что
   столбики бывали только у соло, а с б.1/б.2 рука-эффекты бывает у любой роли, и «соло-число»
   стало бы просто неверным числом. Легенды теперь начинаются от x0+7 (сетка) и rx0+7 (подписи
   роли) — от собственного края, без слагаемых. */

