/* ⛳ ОПЫТ 2: ПРОПУСТИТЬ ЗАГРУЗКУ ВОРКЛЕТА, НЕ ТРОГАЯ ДВИЖОК.
   initAudio зовёт `AC.audioWorklet.addModule(...)` у ТОГО контекста, который ему передали, — а контекст
   создаём мы. Значит достаточно подменить `audioWorklet` СОБСТВЕННЫМ свойством ЭТОГО экземпляра:
   прототипный геттер перекрывается, движок правится нулём строк.
   ⚠️ ЗАГЛУШКА РАЗРЕШАЕТ, А НЕ ОТКЛОНЯЕТ, и это осознанный выбор с ценой: при отказе initAudio пишет
   console.warn и ставит ksReady=false (запасные щипки). Разрешение молчит и оставляет ksReady=true —
   то есть ЛЖЁТ про загрузку. ⛔ Поэтому так можно ТОЛЬКО с материалом БЕЗ KS-инструментов: возьми он
   KS-банк, buildKSBank создал бы AudioWorkletNode('ks-string') в контексте, где процессор не
   зарегистрирован, и рендер упал бы. Опыт 2 пускает общий материал (аккорд/соло/бас/шум) — KS в нём нет.
   ⚠️ Если defineProperty не пройдёт (свойство не настраиваемое), возвращаем false и честно говорим,
   что пропуск в этом браузере снаружи невозможен; движковый путь тогда — необязательный аргумент у
   initAudio, но здесь мы его НЕ заводим. */
function stubWorklet(ctx){
  try{
    Object.defineProperty(ctx,'audioWorklet',{ configurable:true, value:{ addModule:()=>Promise.resolve() } });
    return true;
  }catch(e){ return false; }
}

/* ⛳ ВРЕМЯ ПО ЧАСТЯМ. Замеряем, а не прикидываем: от этого числа зависит, сколько будет длиться
   заморозка, и план прямо требует ИЗМЕРИТЬ его, а не оценить.
   ⚠️ ЧЕСТНАЯ ПОДПИСЬ: addModule (сетевая выборка ворклета + подъём его глобальной области) лежит
   ВНУТРИ initAudio, отделить его отсюда нельзя, не трогая движок, — поэтому столбец так и назван.
   Сколько именно он стоит, отвечает опыт 2. */
const TIME={n:0, importMs:0, initMs:0, renderMs:0, audioSec:0};
const timeReset=()=>{ TIME.n=0; TIME.importMs=0; TIME.initMs=0; TIME.renderMs=0; TIME.audioSec=0; };

/* ОДИН ОФЛАЙН-РЕНДЕР: своя копия модуля, своё семя, свой контекст, свой материал.
   opts.noWorklet — опыт 2 (пропустить addModule); opts.prep(eng,ctx) — опыт 1 (правка ПОСЛЕ постройки
   графа и ДО материала: подмес обязан стать нулём раньше, чем зазвучит первая нота). */
async function renderOnce(seed, material, seconds, opts){
  const o=opts||{};
  const rate=LIVE_AC.sampleRate;
  const frames=Math.max(1,Math.round(rate*seconds));
  const OfflineCtor=window.OfflineAudioContext||window.webkitOfflineAudioContext;
  const t0=now();
  const eng=await engine();
  const t1=now();
  /* ⛳ ПОСЕВ — СТРОГО ДО initAudio, И ЭТОТ ПОРЯДОК НЕСУЩИЙ. Буфер шума набивается ВНУТРИ initAudio
     (последние строки), поэтому семя, поставленное раньше, покрывает его даром. Поставь мы семя после,
     шум разошёлся бы между рендерами, а его читает почти вся ритм-секция, и факт 5 развалился бы. */
  eng.setRnd(mulberry32(seed));
  /* ⛳ F2 — ОФЛАЙН-РАСКЛАДЧИК, ПО ЗАПРОСУ. Пока включаем его ТОЛЬКО там, где он и проверяется: прежние
     факты (посев, опыты 1–2) меряются на живом раскладчике, чтобы их величины остались сравнимы с уже
     записанными. ⚠️ F3, который пойдёт по настоящим событиям, включит его на ВСЕХ рендерах — иначе
     тысячи нот схлопнутся в один голос (довод целиком — у setOffline в audio.js). */
  /* ⚠️ СТАВИМ ВСЕГДА, А НЕ ТОЛЬКО ПРИ true: копия движка одна на сессию, и флаг в ней ЖИВЁТ между
     рендерами. Забудь мы сбросить — следующий рендер молча унаследовал бы чужой раскладчик. */
  eng.setOffline(!!o.offline);
  /* ⛳ ЧАСТОТА ДИСКРЕТИЗАЦИИ ПРИКОЛОЧЕНА К ЖИВОЙ (F0) — иначе ks-worklet, считающий длину линии из
     sampleRate, перестроился бы на центы, а буфер при воспроизведении пересэмплировался. */
  const ctx=new OfflineCtor(2, frames, rate);
  const wkSkipped = o.noWorklet ? stubWorklet(ctx) : false;
  await eng.initAudio(()=>ctx);
  const t2=now();
  if(o.prep) o.prep(eng,ctx);
  material(eng);
  const buf=await ctx.startRendering();
  const t3=now();
  const t={importMs:t1-t0, initMs:t2-t1, renderMs:t3-t2};
  TIME.n++; TIME.importMs+=t.importMs; TIME.initMs+=t.initMs; TIME.renderMs+=t.renderMs; TIME.audioSec+=seconds;
  return {eng, ctx, buf, frames, rate, t, seconds, wkSkipped, ksReady:!!eng.ksReady};
}

/* ПОБИТОВОЕ СРАВНЕНИЕ ДВУХ БУФЕРОВ. ⛔ ИМЕННО ТОЧНОЕ РАВЕНСТВО, И ПОРОГА ЗДЕСЬ НЕ БУДЕТ НИКОГДА:
   обещание слайса — «те же сэмплы», а допуск превратил бы его в непроверяемое.
   Отдаём три числа, и все три печатаются: сколько сэмплов разошлось, МАКСИМАЛЬНОЕ отличие (по нему
   опознаётся виновник — оно равно амплитуде разошедшегося источника) и ВРЕМЯ ПЕРВОГО расхождения.
   ⚠️ Разная форма буфера — не «бесконечное отличие», а другой род ответа: величины тут нет вовсе,
   поэтому числа остаются null, а поле shapeOk говорит, что именно не сошлось. */
function diffOf(a,b){
  if(a.length!==b.length||a.numberOfChannels!==b.numberOfChannels)
    return {same:false, shapeOk:false, maxAbs:null, diffSamples:null, firstSec:null};
  let max=0, n=0, first=-1;
  for(let c=0;c<a.numberOfChannels;c++){
    const x=a.getChannelData(c), y=b.getChannelData(c);
    for(let i=0;i<x.length;i++){
      const d=x[i]-y[i]; if(d===0) continue;
      const ad=d<0?-d:d; n++; if(ad>max)max=ad;
      if(first<0||i<first) first=i;
    }
  }
  return {same:n===0, shapeOk:true, maxAbs:max, diffSamples:n,
          firstSec: first<0?null:+(first/a.sampleRate).toFixed(4)};
}
function peakOf(b){ let p=0;
  for(let c=0;c<b.numberOfChannels;c++){ const d=b.getChannelData(c);
    for(let i=0;i<d.length;i++){ const a=d[i]<0?-d[i]:d[i]; if(a>p)p=a; } }
  return p; }
/* Однострочное описание расхождения — одна формулировка на все места отчёта. */
const diffStr=d=> d.same ? 'совпали'
  : !d.shapeOk ? 'РАЗНАЯ ФОРМА БУФЕРА (длина или число каналов) — сравнивать величины не с чем'
  : 'РАЗОШЛИСЬ: '+d.diffSamples+' сэмплов, макс '+d.maxAbs.toExponential(2)+', первое на '+d.firstSec+' с';
/* ⛔ «СОВПАЛИ» ПРИ НУЛЕВОМ ПИКЕ НИЧЕГО НЕ ЗНАЧИТ — это «две тишины сошлись». Пик проверяем у КАЖДОГО
   источника, а не только у общего материала: иначе немой источник молча выдавал бы себя за пройденный. */
const audStr=p=> p>0 ? 'пик '+(+p.toFixed(5)) : '⛔ НЕМОЙ (пик 0) — вывод недействителен';
/* СРЕДНЕКВАДРАТИЧНОЕ — для F2. ⛳ Именно ОНО, а не пик: N некогерентных нот складываются ПО МОЩНОСТИ,
   поэтому rms(N нот)/rms(одной) ≈ √N. Схлопнись все N в один голос — отношение упало бы к 1, потому
   что звучала бы ровно одна нота той же громкости. Пик такого различия не показал бы. */
function rmsOf(b){ let s=0,n=0;
  for(let c=0;c<b.numberOfChannels;c++){ const d=b.getChannelData(c);
    for(let i=0;i<d.length;i++){ s+=d[i]*d[i]; n++; } }
  return n?Math.sqrt(s/n):0; }

/* МЕМО. Зонд делает 19 полных постановок движка. Это раз на загрузку страницы, не больше; он
   диагностический и запускается руками.
   ⚠️ Отказ «живой движок не поднят» стоит ДО мемо: попади он в кэш, человек нажал бы «▶ Играть»,
   позвал зонд снова и получил бы ТОТ ЖЕ отказ навсегда. */
let PROBE=null;
