/* ГЕНЕРАТОР mulberry32 — маленький, быстрый, с длинным периодом; ровно тот род, что нужен для
   ВОСПРОИЗВОДИМОСТИ, а не для криптографии. Отдаёт [0,1), как Math.random, поэтому в местах подмены
   не меняется ни одна формула. Новый замкнутый `a` на каждый вызов mulberry32 — поэтому два рендера с
   одним семенем начинают последовательность С ОДНОГО МЕСТА, а не продолжают её. */
function mulberry32(a){
  return function(){
    a|=0; a=a+0x6D2B79F5|0;
    let t=Math.imul(a^a>>>15,1|a);
    t=t+Math.imul(t^t>>>7,61|t)^t;
    return ((t^t>>>14)>>>0)/4294967296;
  };
}

