/* ═══ S5: ГОЛОС, ВЫДАННЫЙ ПОСЛЕ ИЗОГНУТОЙ НОТЫ, НАЧИНАЕТ БЕЗ ЕЁ КРИВОЙ — ПРОВЕРКА НА ЗВУКЕ (P.checkSoloEdit) ═══
   ⛳ ПОЧЕМУ РЕНДЕР, А НЕ СЧЁТ: расписанные события AudioParam из JS не прочесть; единственное честное доказательство — ВЫСОТА того, что
   прозвучало. Материал на копии движка с офлайн-раскладчиком (как у заморозки): нота A (440 Гц, Флейта — почти чистый тон) получает
   кривую с точкой +700 ¢ на 0.55 с, но ОТПУСКАЕТСЯ на 0.30 с — хвост кривой остаётся расписанным в голосе; нота B (330 Гц) берёт ТОТ ЖЕ
   голос на 0.35 с (офлайн голос свободен с отпускания, сродство банка — тот же голос; факт reused). Высота B после 0.55 с обязана
   остаться 330 Гц: прежде (до S5) чужая точка перестраивала её на 659 Гц (440·2^(700/1200)). КОНТРОЛЬ — тот же материал, где у B СВОЯ кривая +700 ¢ на
   0.70 с: мера обязана её увидеть (494 Гц, окно с 0.85 с — точка устоялась: 7.5τ, τ 20 мс), иначе «не изогнулась» могло бы значить «мера слепа». Высота — автокорреляцией окна
   (первый пик не ниже 90 % лучшего — период, а не его кратное), допуск 1.5 % (гуманизация — ±4 ¢; 330 и 494 разнятся на 700 ¢). */
const RU_SEC=1.2, RU_SPB=0.25, RU_INS=4, RU_F1=440, RU_F2=330, RU_C=700;
/* ⛳ ПОЧИНКА МЕРЫ (после S5): прежняя мера искала период по ВСЕМУ диапазону (80…1500 Гц) и брала первый пик не ниже 90 % лучшего — и на
   контроле прочла 164.7 Гц вместо 494.4 (ровно треть: субгармоника). Ответ «какая высота звучит» здесь не нужен — нужен ответ «какая из
   ИЗВЕСТНЫХ высот звучит»: у каждого рендера два кандидата (ожидаемая и та, что дала бы ошибка). Поэтому мера оценивает КАЖДОГО кандидата
   на ЕГО периоде: нормированная автокорреляция окна при дробной задержке rate/f (линейная интерполяция), с поиском максимума в ±1 полутоне
   (гуманизация ±4 ¢, расстройка флейты 4 ¢). Решение — сравнением кандидатов (ниже: RU_FLOOR, RU_MARGIN); если звучат оба — ВЫСШИЙ (сигнал с периодом P
   коррелирует и на 2P, 3P… — низший кандидат «звучит» и у высшего сигнала, обратное неверно: на половине периода сигнал противофазен).
   Субгармоника кандидатом не бывает вовсе. Числа корреляций обоих кандидатов печатаются в отчёте. */
/* ⛳ ВТОРАЯ ПОЧИНКА (после MX1): контроль прочёлся 494.4 Гц с корреляцией 0.8786 против −0.6488 у 330 — вердикт верный, но порог 0.9
   его отверг. ПРИЧИНА — НЕ «высота движется в окне» (окно начиналось через 5τ после точки изгиба: остаток 0.7 % скачка, ~4 ¢, и он тает
   дальше; поиск в ±1 полутоне такое покрывает), а ЧУЖОЙ ЗВУК В ОКНЕ: (1) рендер шёл через СОЛО-ЦЕПЬ ПО УМОЛЧАНИЮ — реверб и делей
   (state.fxChains) открыты, и хвосты 330 Гц (B до изгиба) и 440 Гц (A) лежали под окном; 330 и 494.4 — это 2:3, общий период 1/164.8 с —
   ровно та «субгармоника», что прочла прежняя мера; (2) leadOn без applyFx берёт величины ЧУЖОЙ ноты (pendFx — модульное состояние копии
   движка, общей на сессию: после заморозок и рендеров посева в нём может стоять вибрато или драйв чьей-то соло-ноты).
   ПОЭТОМУ: подмес каждого шинного эффекта соло-цепи — ноль (zeroMix, тот же приём, что в опыте 1: модуль при mix=0 — тождество
   сэмпл в сэмпл), и перед каждой атакой applyFx({}) — сухой голос без вибрато, драйва и тремоло. Окна сдвинуты туда, где высота
   устоялась: 7.5τ после последней точки (остаток 0.06 %).
   ⛳ РЕШЕНИЕ — СРАВНЕНИЕМ КАНДИДАТОВ, а не абсолютным порогом. Кандидатов в каждом рендере два (ожидаемая высота и та, что дала бы
   ошибка). (а) Оба ≥ RU_FLOOR — побеждает ВЫСШИЙ: сигнал с периодом P коррелирует и на 2P (пара 330/659 — октава), а на дробной доле
   периода — нет; так субгармоника выбраться не может. (б) Иначе победитель — тот, кто ≥ RU_FLOOR И выше другого не меньше чем на
   RU_MARGIN. (в) Иначе — ни один (мера не решила; это расхождение, а не «прошло»).
   ЧИСЛА — из напечатанных корреляций: даже ЗАГРЯЗНЁННЫЙ контроль (хвосты двух нот под окном) дал 0.88 против −0.65, зазор 1.53. Пол 0.6
   оставляет 0.28 запаса под худшим увиденным верным ответом; на чистом сигнале неверный кандидат стоит на НЕ-кратной доле периода —
   для пары 2:3 это ≈ −0.3…−0.7 по основному тону, для октавы сверху (659 на сигнале 330 — полпериода) ≈ −1, — то есть пол ему
   недостижим. Зазор 0.5 — треть увиденного: ниже него два кандидата считаются неразличимыми. */
const RU_FLOOR=0.6, RU_MARGIN=0.5, RU_SEMI=Math.pow(2,1/12);
function corAt(x,a,N,lag){ const i0=Math.floor(lag), fr=lag-i0; let s=0,e0=0,e1=0;
  for(let i=a;i<a+N;i++){ const u=x[i], v=x[i+i0]*(1-fr)+x[i+i0+1]*fr; s+=u*v; e0+=u*u; e1+=v*v; }
  return (e0>0&&e1>0) ? s/Math.sqrt(e0*e1) : 0; }
/* ⛳ МЕРА — ПО СУММЕ ОБОИХ КАНАЛОВ (починка после MX2). Прежде высота читалась по ЛЕВОМУ каналу: голос, по любой причине ушедший вправо
   (панорама MX2 ставит R=√2, L=0 РОВНО на крайнем праве), дал бы в окне тишину — и «корреляцию 0» у обоих кандидатов вместо высоты.
   Моно-сумма 0.5·(L+R) слышит голос в любом месте панорамы. */
function monoOf(buf){ const L=buf.getChannelData(0), R=buf.numberOfChannels>1?buf.getChannelData(1):L, x=new Float32Array(L.length);
  for(let i=0;i<x.length;i++) x[i]=0.5*(L[i]+R[i]); return x; }
function candScore(x,rate,t0,t1,f){   // лучшая корреляция в ±1 полутоне вокруг f → { cor, f } (f — где лучшая)
  const a=Math.floor(t0*rate), lagHi=rate/(f/RU_SEMI), N=Math.floor(t1*rate)-a-Math.ceil(lagHi)-2;
  if(N<256) return { cor:0, f:NaN };
  let best={ cor:-2, f:NaN };
  for(let lag=rate/(f*RU_SEMI); lag<=lagHi; lag+=0.05){ const c=corAt(x,a,N,lag); if(c>best.cor) best={ cor:c, f:rate/lag }; }
  return best; }
function whichSounds(x,rate,t0,t1,cands){   // ровно два кандидата → { pick: частота или null, rule, margin, scores:[{f,cor,at}] }
  const scores=cands.map(f=>{ const r=candScore(x,rate,t0,t1,f); return { f, cor:+r.cor.toFixed(4), at:+(r.f||0).toFixed(1) }; });
  const [hi,lo]=[...scores].sort((p,q)=>q.f-p.f), margin=+Math.abs(hi.cor-lo.cor).toFixed(4);
  if(hi.cor>=RU_FLOOR && lo.cor>=RU_FLOOR) return { pick:hi.f, rule:'both clear the floor → the higher', margin, scores };
  const w= hi.cor>=lo.cor ? hi : lo, o= w===hi ? lo : hi;
  if(w.cor>=RU_FLOOR && w.cor-o.cor>=RU_MARGIN) return { pick:w.f, rule:'floor and margin', margin, scores };
  return { pick:null, rule:'undecided', margin, scores }; }
/* ⛳ ЭНЕРГИЯ ОКНА — ДО ВЕРДИКТА О ВЫСОТЕ. Тишина (или NaN в буфере) не высота: «0 и 0 → не решено» читалось как вердикт о звуке.
   Порог RU_RMS_MIN = 1e-3 (−60 dBFS) по моно-сумме окна ноты B: нота громкостью 0.8 (амплитуда 0.64 у Флейты, ×0.8 мастер) лежит около
   −25…−30 dBFS — на 30 дБ выше порога; ниже −60 dBFS в окне нет ноты — значит рендер не тот, мера читать нечего. Печатаем и по каналам
   (L/R) и пик всего буфера: по ним видно, тишина целиком или один канал. */
const RU_RMS_MIN=1e-3;
function winStat(buf,t0,t1){ const rate=buf.sampleRate, a=Math.floor(t0*rate), b=Math.min(buf.length,Math.floor(t1*rate));
  const L=buf.getChannelData(0), R=buf.numberOfChannels>1?buf.getChannelData(1):L;
  let sl=0, sr=0, sm=0, nan=0, pk=0;
  for(let i=0;i<buf.length;i++){ const u=L[i], v=R[i]; if(u!==u||v!==v){ nan++; continue; } const m=Math.max(Math.abs(u),Math.abs(v)); if(m>pk) pk=m; }
  for(let i=a;i<b;i++){ const u=L[i], v=R[i]; if(u!==u||v!==v) continue; sl+=u*u; sr+=v*v; const m=0.5*(u+v); sm+=m*m; }
  const n=Math.max(1,b-a), db=x=> x>0 ? (20*Math.log10(x)).toFixed(1) : '−∞';
  const rms=Math.sqrt(sm/n);
  return { ok: !nan && rms>=RU_RMS_MIN, rms, txt:`window ${t0}–${t1} s: mono ${db(rms)} dBFS (L ${db(Math.sqrt(sl/n))}, R ${db(Math.sqrt(sr/n))}), buffer peak ${db(pk)} dBFS${nan?`, ${nan} NaN samples`:''}` }; }
/* ТРИ РЕНДЕРА одного материала (A с кривой после своего отпускания, B на ТОМ ЖЕ голосе):
     M — настоящий случай: B обязан звучать СВОЮ высоту 330 Гц, а не 659 (чужую кривую A); окно 0.70–1.05 с (точка A — на 0.55);
     C — контроль «мера видит изгиб»: у B своя кривая +700 ¢ (точка на 0.70 с) → обязан прочесться 494 Гц, а не 330; окно 0.85–1.09 с
         (отпускание B — на 1.10);
     S — контроль «мера видит наследство»: B получает ту же точку, что дала бы чужая кривая A (659 Гц на 0.55 с), → обязан прочесться
         659 Гц; окно 0.70–1.05 с.
   ⛳ ПОРЯДОК СУЖДЕНИЯ (починка после MX2): (1) голос переиспользован; (2) в окне КАЖДОГО рендера есть звук (RU_RMS_MIN) — иначе «мера не
   состоялась: тихое окно» с цифрами каналов; (3) ОБА контроля прочлись верно — иначе «контроль провален»; (4) только тогда — вердикт по
   настоящему случаю. Без (2) тишина читалась «не решено», без (3) «не изогнулась» могло бы значить «мера слепа». */
async function reuseCheck(){
  if(!LIVE_AC) return { ok:false, why:'audio is not started (press ▶ Play)' };
  const F659=RU_F1*Math.pow(2,RU_C/1200), F494=RU_F2*Math.pow(2,RU_C/1200);
  const pass=async kind=>{ let reused=false;
    const R=await renderOnce(SEED_A, eng=>{
      eng.applyFx({});   // сухой голос: без вибрато/драйва/тремоло чужой ноты (с renderReset pendFx и так нейтрален — вызов остаётся контрактом: leadOn без applyFx берёт чужие величины)
      eng.leadOn('s5:A',RU_F1,0.8,RU_INS,undefined,undefined,undefined,undefined,0.05);   // позиционно: deg, oct, glide, tie — пусто; время ПОСЛЕДНИМ (правило #15)
      eng.scheduleBend('s5:A',[{dt:0,c:0},{dt:2,c:RU_C}],RU_F1,RU_SPB,0.05);              // точка +700 ¢ на 0.05+2·0.25 = 0.55 с — ПОСЛЕ отпускания A
      const vA=eng.leadHold['s5:A'];
      eng.leadOff('s5:A',undefined,0.3);
      eng.applyFx({});
      eng.leadOn('s5:B',RU_F2,0.8,RU_INS,undefined,undefined,undefined,undefined,0.35);
      reused= !!vA && eng.leadHold['s5:B']===vA;
      if(kind==='C') eng.scheduleBend('s5:B',[{dt:0,c:0},{dt:1.4,c:RU_C}],RU_F2,RU_SPB,0.35);   // своя кривая B: 494 Гц с 0.35+1.4·0.25 = 0.70 с
      if(kind==='S') eng.scheduleBend('s5:B',[{dt:0,c:0},{dt:0.8,c:1200*Math.log2(F659/RU_F2)}],RU_F2,RU_SPB,0.35);   // как если бы кривая A перешла к B: 659 Гц с 0.55 с
      eng.leadOff('s5:B',undefined,1.1);
    }, RU_SEC, { offline:true, prep:eng=>{ zeroMix(eng,CHAIN_SOLO); } });   // шинные эффекты соло-цепи — тождество: в окне только сам голос
    return { reused, buf:R.buf }; };
  const M=await pass('M'), C=await pass('C'), S=await pass('S');
  const W={ M:[0.70,1.05], C:[0.85,1.09], S:[0.70,1.05] };
  const st={ M:winStat(M.buf,...W.M), C:winStat(C.buf,...W.C), S:winStat(S.buf,...W.S) };
  const energy=`real case ${st.M.txt}; control ${st.C.txt}; inheritance control ${st.S.txt}`;
  const base={ reused:M.reused, want:RU_F2, wantControl:+F494.toFixed(2), energy };
  if(!M.reused) return { ...base, ok:false, why:'the second note did not take the first note’s voice — the material proves nothing', detail:energy };
  const silent=['M','C','S'].filter(k=>!st[k].ok);
  if(silent.length) return { ...base, ok:false, why:`measurement failed: silent window (${silent.map(k=>({M:'real case',C:'bend control',S:'inheritance control'})[k]).join(', ')}) — ${energy}`, detail:energy };
  const xm=monoOf(M.buf), xc=monoOf(C.buf), xs=monoOf(S.buf), rate=M.buf.sampleRate;
  const m=whichSounds(xm,rate,...W.M,[RU_F2,F659]), c=whichSounds(xc,rate,...W.C,[F494,RU_F2]), sm=whichSounds(xs,rate,...W.S,[RU_F2,F659]);
  const fmt=w=>w.scores.map(z=>`${z.f.toFixed(1)} Hz cor ${z.cor}`).join(', ')+` → ${w.pick==null?'none':w.pick.toFixed(1)+' Hz'} (${w.rule}, margin ${w.margin})`;
  const detail=`floor ${RU_FLOOR}, margin ${RU_MARGIN} · real case: ${fmt(m)}; control (own bend): ${fmt(c)}; simulated inheritance: ${fmt(sm)} · ${energy}`;
  const ctl= c.pick!==F494 ? `the bend control does not read as ${F494.toFixed(1)} Hz (${fmt(c)})`
           : sm.pick!==F659 ? `the inheritance control does not read as ${F659.toFixed(1)} Hz (${fmt(sm)})` : null;
  if(ctl) return { ...base, ok:false, real:m, control:c, simulated:sm, f:m.pick, fControl:c.pick, detail, why:`control failed: ${ctl} — the measurement cannot judge the real case` };
  const ok= m.pick===RU_F2;
  return { ...base, ok, real:m, control:c, simulated:sm, f:m.pick, fControl:c.pick, detail,
           why: ok ? null : `the reused voice does not sound its own ${RU_F2} Hz (${fmt(m)}) — it inherited the previous note's curve` };
}

/* ⛳ СНИМОК КОПИИ ДВИЖКА ДЛЯ СТРАЖА P.all — переключатели, которые рендер ей ставит (уровень и панорама по ключу, раскладчик, семя, отладка,
   ключ удара, величины соло-ноты). После каждого рендера копия в СБРОСЕ (renderReset в finally), значит снимок между строками P.all — один
   и тот же; иной — строка оставила копию в чужом состоянии. Только чтение. */
/* ⛳ AF1 (уборка LR1): переключатель R.liveReverb('old'|'new') СНЯТ вместе с прежней живой проводкой — проводка одна (с одним входом в каждую
   петлю), спрашивать «какая сейчас» незачем. Принято на слух пользователем: прежняя «чуть просторнее», новая «чуть чище». */
/* ═══ ⛳ LR1: ЖИВОЙ И ЗАМОРОЖЕННЫЙ РЕВЕРБ СОГЛАСНЫ — тело пробы P.checkRevAgree ═══
   МАТЕРИАЛ: временная дорожка аккордов в конце песни (recorder.seedTake — та же воронка, что P.seed): один аккорд органом (CHORD_INSTR[2]:
   атака 12 мс, отпускание 90 мс — после отпускания звучит почти один реверб), ≈1.5 с; на миг взятия у ЖИВОГО реверба цепи аккордов подмес
   поднят до упора (захват снимает величины живой цепи — это и есть «запись»), длина и окраска — те, что стоят.
   ЖИВОЙ ПУТЬ: R.live этой дорожки (живой движок, захваченная цепь), выход МАСТЕРА снят audio.probeCapture — в колонки не идёт.
   ПУТЬ ЗАМОРОЗКИ: renderTrack той же дорожки с семенем её заморозки (то, что стало бы буфером), тоже мастер (offlineTapMaster).
   МЕРА (моно, начало — по порогу 5 % пика, отпускание = начало + длина аккорда):
     ЭНЕРГИЯ ХВОСТА — 10·lg(E хвоста / E звучания), хвост — [отпускание + 0.3 с, + 1.0 с], звучание — [начало + 0.35 с, отпускание − 0.05 с];
     отношение к звучанию снимает уровень мастера, гейн копии и гуманизацию громкости;
     СПЕКТРАЛЬНЫЙ БАЛАНС ХВОСТА — 10·lg(E первой разности / E) в том же окне (наклон +6 дБ/окт: чем ярче хвост, тем больше).
   ДОПУСК: живой против замороженного — |Δ| ≤ RA_TOL_E по энергии и ≤ RA_TOL_B по балансу (дБ). Прежняя живая проводка давала ±10 %
   энергии хвоста от загрузки к загрузке (≈ ±0.4 дБ), гуманизация — доли дБ; 1 дБ — запас над ними и далеко под слышимой сменой комнаты.
   КОНТРОЛИ (мера обязана уметь провалиться): та же дорожка, взятая с ДРУГОЙ длиной хвоста (RA_CTRL_DECAY с), — её энергия хвоста ОБЯЗАНА
   выйти за допуск; с другой окраской (RA_CTRL_TONE Гц) — баланс ОБЯЗАН выйти за допуск. Временные дорожки снимаются (✕ дважды), величины
   живой цепи аккордов возвращаются. Время: живой съём ≈ 3.5 с реального времени + три полных рендера (≈ 1–2 с каждый). */
const RA_TOL_E=1.0, RA_TOL_B=1.0, RA_CTRL_DECAY=0.4, RA_CTRL_TONE=400;
function raMeasure(L,R,rate,dur){
  const n=Math.min(L.length,R.length), x=new Float32Array(n); let pk=0;
  for(let i=0;i<n;i++){ const v=0.5*(L[i]+R[i]); x[i]=v; const a=v<0?-v:v; if(a>pk) pk=a; }
  if(!(pk>0)) return { why:'silent' };
  let on=-1; for(let i=0;i<n;i++) if(Math.abs(x[i])>0.05*pk){ on=i; break; }
  const o=on/rate, rel=o+dur;
  if((rel+1.0)*rate>n) return { why:`the signal is too short (${(n/rate).toFixed(2)} s for a tail up to ${(rel+1).toFixed(2)} s)` };
  const ix=t=>Math.max(1,Math.min(n,Math.floor(t*rate)));
  const E=(a,b)=>{ let s=0; for(let i=ix(a);i<ix(b);i++) s+=x[i]*x[i]; return s/Math.max(1,ix(b)-ix(a)); };
  const Dd=(a,b)=>{ let s=0; for(let i=ix(a);i<ix(b);i++){ const d=x[i]-x[i-1]; s+=d*d; } return s/Math.max(1,ix(b)-ix(a)); };
  const S=E(o+0.35, rel-0.05), T=E(rel+0.3, rel+1.0), D=Dd(rel+0.3, rel+1.0);
  if(!(S>0)||!(T>0)) return { why:'no sustain or no tail energy' };
  return { onset:+o.toFixed(3), energy:10*Math.log10(T/S), bright:10*Math.log10(D/T) };
}
async function revAgree(){
  if(!LIVE_AC) return { ok:false, why:'audio is not started (press ▶ Play)' };
  if(REC.loop.on||REC.recording) return { ok:false, why:'the transport is playing or recording — stop it first' };
  if(REC.editIsOpen()) return { ok:false, why:'the track editor is open — close it first' };
  const key=chainKeyOf('ch');
  if(!fxChainOf(key).some(e=>e.fxId==='reverb')) return { ok:false, why:'the chord chain holds no reverb (it does by default) — add one to run this probe' };
  const inst=LIVE.fxInstance(key,'reverb'); if(!inst) return { ok:false, why:'no live reverb instance for chords' };
  stop();
  const keepAll=[]; for(const e of fxChainOf(key)){ const I=LIVE.fxInstance(key,e.fxId); if(I&&I.params) for(const p of I.params) keepAll.push([p,p.cur]); }   // все величины цепи аккордов — вернуть ровно как были
  const P=k=>inst.params.find(p=>p.key===k), dec0=P('decay').cur, tone0=P('tone').cur;
  const spb=60/REC.loop.bpm, beats=Math.max(1,Math.round(1.5/spb)), dur=beats*spb, made=[];
  const tStart=performance.now();
  const take=(decN,toneN)=>{
    P('mix').setNorm(1); P('decay').setNorm(decN); P('tone').setNorm(toneN);
    const T=Math.ceil(REC.songBeats())+8;
    const steps=ty=>[{fn:'chOn',a:{deg:0,oct:1,vol:0.7,inst:2,ty},t:T,id:1},{fn:'chOff',a:{},t:T+beats,id:1}];
    let r=REC.seedTake(steps(null)); if(!r||!r.layers.length) return null;
    let ly=r.layers[0], on=REC.events.find(e=>e.layer===ly&&e.fn==='chOn');
    if(!on || !REC.evHz(on.a,on,'ch').length){   // лад без аккордов по правилу — однонотный аккорд (его цена — сам корень)
      REC.laneDelTap(ly); REC.laneDelTap(ly);
      r=REC.seedTake(steps(chordUnit(CUR()))); if(!r||!r.layers.length) return null; ly=r.layers[0]; }
    made.push(ly); return ly; };
  const norm=(p,v)=>{ const x= p.curve==='log' ? Math.log(v/p.min)/Math.log(p.max/p.min) : (v-p.min)/(p.max-p.min); return Math.max(0,Math.min(1,x)); };
  const out={ ok:false, tolE:RA_TOL_E, tolB:RA_TOL_B };
  try{
    // ---- живой против заморозки ----
    const A=take(dec0,tone0); if(A==null){ out.why='the temporary chord track could not be recorded'; return out; }
    const capP=LIVE.probeCapture(0.3+dur+1.8);
    if(!live(A)){ out.why='R.live refused'; return out; }
    const cap=await capP; stop();
    const chOf=b=>[b.getChannelData(0), b.numberOfChannels>1?b.getChannelData(1):b.getChannelData(0)];
    const mL=raMeasure(cap.L,cap.R,cap.rate,dur);
    const rA=await renderTrack(A,{ quiet:true, seed:seedOfLane(REC.freezeTicket(A).id) });
    const mR=raMeasure(...chOf(rA.buf), rA.buf.sampleRate, dur);
    if(mL.why||mR.why){ out.why='measure: live — '+(mL.why||'ok')+'; frozen — '+(mR.why||'ok'); return out; }
    // ---- контроли: другая длина хвоста, другая окраска ----
    const B=take(norm(P('decay'),RA_CTRL_DECAY),tone0), C=take(dec0,norm(P('tone'),RA_CTRL_TONE));
    if(B==null||C==null){ out.why='a control track could not be recorded'; return out; }
    const mOf=async ly=>{ const r=await renderTrack(ly,{ quiet:true, seed:seedOfLane(REC.freezeTicket(ly).id) }); return raMeasure(...chOf(r.buf), r.buf.sampleRate, dur); };
    const mB=await mOf(B), mC=await mOf(C);
    if(mB.why||mC.why){ out.why='control measure: '+(mB.why||mC.why); return out; }
    const r2=v=>Math.round(v*100)/100;
    Object.assign(out,{ live:{ energy:r2(mL.energy), bright:r2(mL.bright) }, frozen:{ energy:r2(mR.energy), bright:r2(mR.bright) },
      dEnergy:r2(mR.energy-mL.energy), dBright:r2(mR.bright-mL.bright),
      ctrlDecay:{ sec:RA_CTRL_DECAY, dEnergy:r2(mB.energy-mL.energy) }, ctrlTone:{ hz:RA_CTRL_TONE, dBright:r2(mC.bright-mL.bright) } });
    out.agree= Math.abs(out.dEnergy)<=RA_TOL_E && Math.abs(out.dBright)<=RA_TOL_B;
    out.controlsFail= Math.abs(out.ctrlDecay.dEnergy)>RA_TOL_E && Math.abs(out.ctrlTone.dBright)>RA_TOL_B;
    out.ok=true;
  } catch(err){ out.why='failed: '+(err&&err.message); }
  finally{
    stop();
    for(const ly of made.slice().reverse()){ REC.laneDelTap(ly); REC.laneDelTap(ly); }
    for(const [p,v] of keepAll) p.setNorm(v);
    out.seconds=+((performance.now()-tStart)/1000).toFixed(1);
  }
  return out;
}
