/* =====================================================================
   КОНТЕКСТ РЕНДЕРА — слайс F0 дуги «ЗАМОРОЗКА»
   ---------------------------------------------------------------------
   ⛳ ЧТО ЭТОТ ФАЙЛ ДОКАЗЫВАЕТ, И БОЛЬШЕ НИЧЕГО: движок можно построить
   против ДРУГОГО аудио-контекста. Ни одной ноты здесь не играется, ни
   одна дорожка не читается, ни один байт не рендерится в музыку.

   ⛔ ЭТОТ МОДУЛЬ НЕ ИМПОРТИРУЕТ НИКТО. Он достаётся руками из консоли:

       (await import(new URL('src/render.js', location.href).href)).probe()

   Оттого приёмка слайса тривиально верна: приложение не изменилось,
   потому что этого кода в нём нет.

   ═══ ЗАЧЕМ ВООБЩЕ ВТОРАЯ КОПИЯ ДВИЖКА ═══
   audio.js держит контекст в МОДУЛЬНОЙ переменной AC, а рядом с ней —
   мастер, лимитер, четыре шины, три пула, дрон, буфер шума, LFO и восемь
   таблиц эффектов (FX_INST, FX_CHAIN_HEAD/OUT/LINKS, FX_PLAY_PATH,
   FX_AIM, FX_DIP_T, pendFx). 171 обращение к AC, из них 138 — createXxx.
   Отрендерить офлайн значит построить ВСЁ ЭТО против другого контекста.
   Три пути было:
     (а) подменить модульный AC на время рендера — ⛔ смертельно: AC
         экспортирован ЖИВОЙ СВЯЗКОЙ и его читают main/ui/demo/recorder
         (только recorder — в двенадцати местах), а leadHold/chordHold
         читает draw. Всё приложение ушло бы в офлайн вместе с ним;
     (б) фабрика makeEngine(ctx) — верная КОНЕЧНАЯ форма, но это весь
         файл разом: 138 вызовов в двадцати функциях плюс восемь таблиц
         в поля экземпляра. Проверить такое в браузере нечем;
     (в) ВТОРАЯ КОПИЯ МОДУЛЯ через другой спецификатор импорта — браузер
         считает './audio.js?render' другим модулем и заводит ему СВОЙ
         набор всех переменных выше. Ноль правок в audio.js, кроме одного
         защищённого умолчанием аргумента у initAudio.
   Взяли (в). К (б) переходим только если (в) когда-нибудь станет тесна.

   ═══ ⚠️ ТРИ ЦЕНЫ ВТОРОЙ КОПИИ — ЧИТАТЬ ПЕРЕД ТЕМ, КАК ПИСАТЬ РЕНДЕР ═══
   Копии РАЗНЫЕ только у тех модулей, чей спецификатор отличается. Всё,
   что audio.js импортирует БЕЗ строки запроса (state.js, scales.js,
   hooks.js, config.js), у обеих копий ОДНО И ТО ЖЕ. Читать оттуда —
   ровно то, что нужно (лад, тоника, состав цепей). Писать — беда:

   1. ⛔ РЕНДЕР НЕ СМЕЕТ ХОДИТЬ ЧЕРЕЗ fxPlaySet И fxRestoreAim.
      fxPlaySet пишет `fx[fxId]=v` для СТАРЫХ СКАЛЯРОВ (драйв/вибрато/
      тремоло-нота), а fxRestoreAim — `fx[eff.fxId]=a`. Этот store живёт
      в ОБЩЕМ state.js, значит офлайн-копия, ведя захваченную ленту,
      перетёрла бы ЖИВЫЕ ручки человека посреди рендера. Величины
      скаляров рендер обязан доносить до голоса пер-нотно, через pendFx
      (то есть тем же путём, каким их несёт a.fx живой ноты), а не через
      общий store. Туда же и FX_AIM: прицел принадлежит РУКЕ (правило #29),
      и офлайн-копии в нём делать нечего.
   2. ⛔ РЕНДЕР НЕ СМЕЕТ ЗВАТЬ setLeadInstr. hooks.js тоже общий, и
      setLeadInstr дёргает hooks.leadInstr — то есть ПЕРЕКРАСИЛ БЫ кнопку
      тембра в живой панели. Звать его и не надо: ENG.leadOn намеренно
      этого не делает, тембр печётся в голосе по a.inst.
   3. ⚠️ ДВИЖОК ЧИТАЕТ ЖИВОЕ СОСТОЯНИЕ ПРЯМО ПРИ ПОСТРОЙКЕ. initAudio
      ставит частоты дрона из tonicFreq(), то есть из ЖИВОЙ тоники и
      живого эталона A4. Значит ЗАМОРОЗКА ТОНИКИ/aRef обязана случиться
      ДО initAudio офлайн-копии, а не после — иначе дрон уже построен не
      на той высоте. (Зонд ниже этим и пользуется как проверкой связности,
      см. комментарий у droneOn.)

   ═══ ПРАВИЛА, КОТОРЫХ ЭТОТ ФАЙЛ КАСАЕТСЯ ═══
   • #1 — оговорка про офлайн-контекст записана у самого initAudio и в
     CLAUDE.md. Здесь просто не повторяем.
   • #3 (осцилляторы не разбираются) — у офлайн-копии СВОИ осцилляторы, и
     живут они ровно столько, сколько её контекст. Это ВТОРОЙ ЭКЗЕМПЛЯР
     ПРАВИЛА, а не исключение из него: внутри своего контекста всё то же —
     завели один раз, глушим гейтом, не разбираем.
   • #5 — этот модуль НЕ ТРОГАЕТ DOM. Отчёт уходит в console и возвратом.

   ═══ ⚠️ ЕЩЁ ОДНА ЗАПИСКА ВПЕРЁД (не для этого слайса) ═══
   ⛔ ОФЛАЙН НЕЛЬЗЯ ПРАВИТЬ ЦЕПЬ ЧЕРЕЗ fxChainResplice/fxRespliceSmooth.
   «Мягкая» пересборка гасит хвост рампой и доделывает работу в setTimeout —
   то есть по СТЕННЫМ часам, тогда как офлайн-контекст идёт по своим и к
   моменту срабатывания может быть уже отрендерен. Рампа при этом ляжет на
   currentTime=0, то есть в самое начало буфера. Офлайн правка состава —
   только прямой fxResplice. Сегодня путь не задевается: зонд спрашивает
   уже построенный экземпляр, а внутри initAudio смягчённая ветка сама
   вырождается в прямую (концы ещё не зарегистрированы).
   ===================================================================== */

/* ⚠️ ЭТОТ import — ЖИВАЯ копия движка (без строки запроса), и берём мы из неё РОВНО ОДНО: частоту
   дискретизации живого контекста. Не перепутать с офлайн-копией ниже: у них одинаковые имена и
   совершенно разные переменные. */
import { AC as LIVE_AC, ksReady as liveKsReady } from './audio.js';
import { CHAIN_SOLO } from './state.js';

const ENG_SPEC='./audio.js?render';   // ⛳ СПЕЦИФИКАТОР ОБЯЗАН БЫТЬ ПОСТОЯННЫМ. Строка запроса — это и есть «другой модуль» для браузера; сделай её уникальной на каждый рендер (?render=1, ?render=2…), и каждая заморозка утекала бы ЦЕЛЫМ разобранным движком, который уже никогда не выгрузится
const PROBE_SEC=1.0;                  // длительность пробного рендера, с

/* МЕМО. Держим ОДНО обещание на всю сессию: разбор модуля дорог, а повторный initAudio на той же копии
   сегодня небезопасен (довод — в шапке initAudio). Поэтому зонд одноразов ПО СУЩЕСТВУ, а не ради
   скорости: startRendering у OfflineAudioContext тоже одноразов, второй вызов на том же контексте
   бросает InvalidStateError. Второй probe() отдаёт тот же отчёт мгновенно. */
let PROBE=null;

/* ⛳ ЗОНД. Отвечает на ТРИ вопроса и ни на один больше:
     1) загрузился ли KS-ворклет в ОФЛАЙН-контекст (и не разошёлся ли ответ с живым);
     2) построился ли экземпляр эффекта и цел ли он концами — причём принадлежащими ИМЕННО этому контексту;
     3) разрешился ли рендер буфером ожидаемой формы.
   Возвращает объект отчёта и печатает его же. Ошибку не глотает: любая падает в поле error и в консоль. */
function probe(){
  /* ⛔ ЖИВОЙ ДВИЖОК ОБЯЗАН БЫТЬ ПОДНЯТ. Не из вредности: частота дискретизации офлайн-контекста берётся
     у него, а спросить её больше негде — её назначает браузер при создании ЖИВОГО контекста.
     ⚠️ ЭТОТ ОТКАЗ — ДО МЕМО, И ЭТО НЕ МЕЛОЧЬ: попади он в мемо, человек нажал бы «▶ Играть», позвал зонд
     снова и получил бы ТОТ ЖЕ отказ навсегда, до перезагрузки страницы. Кэшируем только настоящий заход. */
  if(!LIVE_AC){
    const R={ ok:false, worklet:{live:null,offline:null}, fx:{}, buffer:{}, error:'живой AudioContext ещё не создан',
              notes:['⛔ Сперва нажмите «▶ Играть» (движок поднимается там), потом зовите probe() снова.'] };
    print(R); return Promise.resolve(R);
  }
  if(!PROBE) PROBE=run();
  return PROBE;
}

async function run(){
  const R={ ok:false, worklet:{live:null, offline:null}, fx:{}, buffer:{}, notes:[], error:null };
  try{
    /* ⛳ ЧАСТОТА ДИСКРЕТИЗАЦИИ ПРИКОЛОЧЕНА К ЖИВОЙ, И ЭТО НЕ АККУРАТНОСТЬ, А ПОЧИНКА ЗАРАНЕЕ.
       Две причины, обе тихие:
         • ks-worklet.js считает ДЛИНУ ЛИНИИ ЗАДЕРЖКИ из sampleRate (N=ceil(sampleRate/20)+8, и
           L=round(sampleRate/f) на каждый щипок). Другая частота — другое округление длины, то есть
           другая высота струны: КС-тембры поехали бы по строю на центы, без единой ошибки;
         • буфер, отрендеренный на чужой частоте, при воспроизведении в живом контексте будет
           ПЕРЕСЭМПЛИРОВАН — то есть сдвинут по высоте и длительности целиком.
       Умолчания у OfflineAudioContext нет: частота — обязательный аргумент конструктора. Одна строка. */
    const rate=LIVE_AC.sampleRate;
    const frames=Math.max(1,Math.round(rate*PROBE_SEC));

    const OfflineCtor=window.OfflineAudioContext||window.webkitOfflineAudioContext;
    if(!OfflineCtor) throw new Error('OfflineAudioContext в этом браузере отсутствует');

    /* ВТОРАЯ КОПИЯ ДВИЖКА. Динамический импорт со строкой запроса: тот же файл, другой модуль. */
    const t0=(performance&&performance.now)?performance.now():0;
    const eng=await import(ENG_SPEC);
    const ctx=new OfflineCtor(2, frames, rate);

    /* ⚠️ ЗДЕСЬ ЖЕ ПРОХОДИТ ГРАНИЦА ЦЕНЫ №3 ИЗ ШАПКИ: initAudio строит дрон из ЖИВОЙ tonicFreq().
       Слайсу F3 придётся заморозить тонику и aRef ИМЕННО ПЕРЕД этой строкой. Сегодня это неважно —
       зонд ничего музыкального не проверяет, — но место названо. */
    await eng.initAudio(()=>ctx);
    const tInit=((performance&&performance.now)?performance.now():0)-t0;

    /* ═══ ФАКТ 1: ВОРКЛЕТ ═══
       ⚠️ ДА, ОФЛАЙН-ЗАГРУЗКА МОЖЕТ ПРОВАЛИТЬСЯ ПРИ УСПЕШНОЙ ЖИВОЙ, и именно поэтому её спрашивают
       отдельно, а не выводят из живой. addModule принадлежит КОНТЕКСТУ: каждый компилирует модуль в
       СВОЙ AudioWorkletGlobalScope, и провал у одного ничего не говорит о другом. Плюс это ВТОРАЯ
       сетевая выборка того же файла (обычно из кэша, но кэш умеет ревалидировать и умеет не ответить),
       и поддержка audioWorklet у OfflineAudioContext исторически отставала от AudioContext.
       ⛔ ЦЕНА ПРОГЛАТЫВАНИЯ: audio.js на провале НЕ ПАДАЕТ — он ставит buildKSFallback в слоты 16..22,
       и семь тембров (Струна/Ситар/Уд/Кото/Сантур/Гитара/Пиццикато) молча становятся субтрактивными
       щипками. Буфер выйдет нужной длины, нужной высоты и НЕ ТОГО ТЕМБРА. Такое отгружают не заметив —
       поэтому ответ печатается всегда, а расхождение с живым помечается отдельной строкой. */
    R.worklet.live=!!liveKsReady;
    R.worklet.offline=!!eng.ksReady;
    if(R.worklet.live && !R.worklet.offline)
      R.notes.push('⛔ ВОРКЛЕТ: живьём загрузился, ОФЛАЙН — нет. KS-тембры (индексы 16..22) отрендерятся ЗАПАСНЫМ ЩИПКОМ, тихо и не тем тембром.');
    if(!R.worklet.live)
      R.notes.push('⚠️ ВОРКЛЕТ не загрузился и в ЖИВОМ контексте — расхождение проверить нечем, сравнение бессмысленно.');

    /* ═══ ФАКТ 2: ЭКЗЕМПЛЯР ЭФФЕКТА ═══
       Реверб цепи соло строит сам initAudio (он в цепи по умолчанию), так что здесь мы его только
       СПРАШИВАЕМ. Проверяем три вещи, и третья — главная: узлы обязаны принадлежать ЭТОМУ контексту.
       Если бы вторая копия по недосмотру оказалась той же самой, что живая, первые две проверки прошли
       бы как ни в чём не бывало, а `.context===ctx` — нет. Это и есть доказательство слайса. */
    const inst=eng.fxInstance(CHAIN_SOLO,'reverb');
    R.fx.built=!!inst;
    R.fx.wiredIn=!!(inst&&inst.in);
    R.fx.wiredOut=!!(inst&&inst.out);
    R.fx.ownContext=!!(inst&&inst.in&&inst.out&&inst.in.context===ctx&&inst.out.context===ctx);
    R.fx.params=inst&&inst.params?inst.params.map(p=>p.key).join(','):'';
    R.fx.liveIsSeparate=!!(inst&&inst.in&&LIVE_AC&&inst.in.context!==LIVE_AC);
    if(!R.fx.ownContext) R.notes.push('⛔ ЭФФЕКТ: узлы экземпляра не принадлежат офлайн-контексту — копия движка НЕ отдельная.');

    /* ═══ ФАКТ 3: РЕНДЕР ═══
       ⛳ ТИШИНА БЫЛА БЫ СЛАБЫМ ДОКАЗАТЕЛЬСТВОМ: буфер нужной длины, набитый нулями, значит лишь
       «обещание разрешилось». Поэтому открываем ДРОН — единственный источник движка, который звучит
       БЕЗ единого события, без записи, без транспорта и без единой строки музыки. Он доказывает то,
       что и требуется: сигнал доходит до destination сквозь backBus → master → limiter.
       ⚠️ droneOn ЧИТАЕТ ЖИВУЮ tonicFreq() — ровно цена №3 из шапки, вот она в работе. Зонду всё равно
       (высота не проверяется), рендеру — нет. when=0: отсчёт офлайн-контекста начинается с нуля, а
       AC.currentTime под JS у него не идёт вовсе. */
    if(eng.droneOn) eng.droneOn(0.2,0);
    const t1=(performance&&performance.now)?performance.now():0;
    const buf=await ctx.startRendering();
    const tRender=((performance&&performance.now)?performance.now():0)-t1;

    let peak=0;
    for(let c=0;c<buf.numberOfChannels;c++){ const d=buf.getChannelData(c);
      for(let i=0;i<d.length;i++){ const a=d[i]<0?-d[i]:d[i]; if(a>peak)peak=a; } }

    R.buffer={ length:buf.length, expected:frames, sampleRate:buf.sampleRate, rateMatchesLive:buf.sampleRate===rate,
               channels:buf.numberOfChannels, seconds:+(buf.duration.toFixed(3)), peak:+(peak.toFixed(5)) };
    R.timing={ initMs:Math.round(tInit), renderMs:Math.round(tRender),
               xRealtime: tRender>0 ? +((PROBE_SEC*1000/tRender).toFixed(1)) : null };
    if(peak<=0) R.notes.push('⚠️ РЕНДЕР: буфер пуст (пик 0). Значит сигнал до destination НЕ дошёл — граф собран, но не звучит.');
    if(!R.buffer.rateMatchesLive) R.notes.push('⛔ ЧАСТОТА: буфер не на живой частоте — при воспроизведении его пересэмплируют.');

    R.ok = R.fx.ownContext && R.buffer.length===frames && R.buffer.rateMatchesLive && peak>0;
  }catch(e){
    R.error=(e&&e.message)?e.message:String(e);
    R.notes.push('⛔ ЗОНД УПАЛ: '+R.error);
  }
  print(R);
  return R;
}

/* ПЕЧАТЬ ОТЧЁТА. Правило #5 цело: console — не DOM. */
function print(R){
  const y=v=>v===true?'ДА':v===false?'НЕТ':String(v);
  /* eslint-disable no-console */
  console.log('%c[render F0] зонд контекста рендера','font-weight:bold');
  console.log('  1. KS-ворклет:  офлайн '+y(R.worklet.offline)+'   ·   живьём '+y(R.worklet.live));
  console.log('  2. Эффект:      построен '+y(R.fx.built)+'   ·   in/out '+y(R.fx.wiredIn&&R.fx.wiredOut)
              +'   ·   свой контекст '+y(R.fx.ownContext)+'   ·   параметры ['+(R.fx.params||'')+']');
  console.log('  3. Буфер:       '+(R.buffer.length!=null?R.buffer.length+' сэмплов ('+R.buffer.seconds+' с), '
              +R.buffer.sampleRate+' Гц, каналов '+R.buffer.channels+', пик '+R.buffer.peak:'нет'));
  if(R.timing) console.log('     время:      initAudio '+R.timing.initMs+' мс · рендер '+R.timing.renderMs
              +' мс ('+R.timing.xRealtime+'× реального времени)');
  for(const n of R.notes) console.log('  '+n);
  console.log('  ИТОГ: '+(R.ok?'✅ офлайн-граф строится и звучит':'❌ см. пометки выше'));
  /* eslint-enable no-console */
}

