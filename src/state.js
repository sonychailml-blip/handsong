export const sx=(nx,W)=>{ const x=flipX(nx); return (x-viewRect.ax0)/(viewRect.ax1-viewRect.ax0)*W; };
export const sy=(ny,H)=> (ny-viewRect.ay0)/(viewRect.ay1-viewRect.ay0)*H;
