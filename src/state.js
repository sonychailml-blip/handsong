export const fxChainOf = role => fxChains[role] || [];
/* Сеттеры — API этого пласта. Цепь пишет ТОЛЬКО ui (панель конструктора), gestures её ЧИТАЕТ:
   правило #5 (нижние слои DOM не трогают) с обратной стороны — ui не лезет в жест-состояние, а
   кладёт данные сюда. */
/* НЕЙТРАЛЬ старых скалярных эффектов = 0 у ВСЕХ ЧЕТЫРЁХ, и это не совпадение: в applyFx каждый входит
   МНОЖИТЕЛЕМ (p.vib*35, p.drv, p.trm*0.45, p.dly*0.55), а множитель 0 — тождество: вибрато без глубины,
   сухой сигнал вместо драйва, тремоло без качания, посыл в делей закрыт.
   ⚠️ Появится эффект с НЕнулевой нейтралью — это поле переедет в FX_META, к остальным метаданным
   эффекта, а не размножится нулями по коду. */
const FX_NEUTRAL=0;
/* Эффект, УБРАННЫЙ ИЗ ЦЕПИ, обязан ЗАМОЛЧАТЬ, а не висеть на последнем значении: крутить его больше
   нечем, и «звучит то, чем не управляешь» читается как поломка, а не как настройка.
   ⚠️ Условие СТАЛО ПРОЩЕ в 3.4.2 и заодно вернее: было «снят со ВСЕХ ПАЛЬЦЕВ» (эффект жил на слоте,
   слот был пальцем), стало «ОТСУТСТВУЕТ В ЦЕПИ». Эффект, чьи параметры все до одного зафиксированы
   или отданы играющей руке, на пальце не сидит, но ЗВУЧИТ — и гасить его было бы неверно. Владение
   цепью роли ровно это и утверждает: наличие в цепи, а не наличие пальца.
   ⚠️ Гасим ЧЕРЕЗ state.fx[k], а НЕ прямой записью в узел — и это несущее, а не стилистика:
     • fx[k] — то, что читает applyFx И что уезжает в событие ноты. Ноль здесь означает разом «тихо
       живьём» И «записано нулём в НОВЫХ событиях» (незакреплённый эффект не играется — так и надо).
       СТАРЫЕ события держат свои замороженные значения и играют как играли: формат записи не тронут.
     • иначе и нельзя: audio импортирует state, обратный импорт — цикл. Слой выбран не по вкусу.
   ⚠️ Звук меняется на БЛИЖАЙШЕМ applyFx (он зовётся с каждой соло-нотой). Пока нота звучит — это
   тот же кадр; если не звучит ничего, эффекты соло и так не слышны. Единственный видимый хвостик —
   уже висящее эхо делея доиграет до следующей ноты. Сочтено приемлемым: хвост и так затухает.
   ⚠️ РЕВЕРБ (модуль) СЮДА НЕ ПОПАДАЕТ, НАМЕРЕННО. Его длина/окраска — свойство КОМНАТЫ, а не пальца:
   в запись они не идут, а подмесом до Пласта 3 рулит ИГРАЮЩАЯ рука через p.rev. Снятие с пальца
   отнимает у fx-руки УПРАВЛЕНИЕ комнатой, но саму комнату не перестраивает — гасить FDN было бы
   слышно на аккордах, которые в тот же реверб посылаются и к пальцу отношения не имеют. */
/* ⚠️ СМОТРИМ ЦЕПЬ СОЛО, и это не небрежность: state.fx — store СТАРЫХ СКАЛЯРНЫХ эффектов СОЛО-шины
   (его читает applyFx, он же уезжает в событие ноты). Появись такой эффект в цепи другой роли, ему
   понадобился бы СВОЙ store, а не расширение этого предиката, — вопрос Пласта 3.5. */
function hushUnassignedFx(){
  for(const m of FX_META)
    if(!fxChainOf('ld').some(e=>e&&e.fxId===m.k)) fx[m.k]=FX_NEUTRAL;
}
/* ⚠️ ПОВТОРНОЕ ДОБАВЛЕНИЕ НАЧИНАЕТСЯ С НУЛЯ — само собой, без отдельной ветки: удаление уже обнулило
   fx[k], а вернуть прежний дефолт некому. Захват щипка берёт базу из fx[k], значит палец поднимает
   эффект ИЗ ТИШИНЫ. «В цепи, но не тронут» = молчит, пока не двинешь, — этого и хотели. */
/* ⚠️ ЭМИТИМ ПОЛНУЮ ФОРМУ (mode+hand+finger), а не голые {axis,inv}. Параметр без mode/hand жест-цикл
   ПРОПУСТИЛ бы по фильтру, а без finger не нашёлся бы НИ ПОД ОДНИМ пальцем — и эффект молча перестал
   бы отзываться. Пусть ошибка будет ГРОМКОЙ (её видно сразу), а не замаскированной оборонительным
   чтением вида (pa.mode||'drive'). */
/* ⚠️ РОЛЬ — ПЕРВЫМ АРГУМЕНТОМ (обещание, данное в 3.3, исполнено в 3.4.2): как у setHandFn(role,…) и
   setRectOctReg(role,…). И только ЯВНЫМ аргументом: выводить роль из глобального phoneInstr запрещено
   правилом CLAUDE.md (в сплите он не указывает на роль щипнувшей руки).
   ⚠️ АДРЕСУЕМ ПАРОЙ (effIdx,pIdx) — место в цепи и номер параметра. Прежний slot (=палец) как адрес
   ИСЧЕЗ вместе с setFxSlotId: палец теперь ВНУТРИ параметра, а не снаружи него.
   ⚠️ ПРАВИМ ОБЪЕКТ ПАРАМЕТРА НА МЕСТЕ, а не заменяем его. Это несущее: gestures держит ССЫЛКУ на этот
   объект в S.adj на всё время щипка (см. captureFx), чтобы смена оси/инверсии из меню действовала
   ЖИВЬЁМ. Заменишь объект — щипок останется на старом, и правка «не подействует до отпускания».
   Операция, которая ЗАМЕНИТ запись эффекта целиком (3.4.3, «сменить/убрать эффект»), обязана будет
   сбросить S.adj — иначе ссылка повиснет. */
const fxParamAt=(role,effIdx,pIdx)=>{
  const e=fxChainOf(role)[effIdx];
  return (e&&e.params&&e.params[pIdx]) || null;
};
/* АДРЕС УПРАВЛЕНИЯ целиком: рука + (палец, если fx) + ось + инверсия. Запись адреса ПОДРАЗУМЕВАЕТ
   режим 'drive' — у зафиксированного параметра адреса нет по определению.
   ⚠️ finger пишем ТОЛЬКО когда он передан: у 'play' пальца нет, и затирать прежний нельзя — человек,
   вернувшись с глубины на палец, должен получить СВОЙ палец, а не нулевой (тот же закон, что у
   axis/inv при уходе в 'fixed'). */
export const setFxParamAddr=(role,effIdx,pIdx,addr)=>{
  const p=fxParamAt(role,effIdx,pIdx); if(!p||!addr)return;
  p.mode='drive';
  if(addr.hand!=null) p.hand=addr.hand;
  if(addr.finger!=null) p.finger=addr.finger|0;
  if(addr.axis!=null) p.axis=addr.axis;
  p.inv=!!addr.inv;
};
/* РЕЖИМ параметра: 'drive' (ведёт рука) ↔ 'fixed' (стоит на значении из меню). axis/inv при переходе
   в 'fixed' НЕ стираем — вернувшись в 'drive', человек получит свою ось обратно.
   ⚠️ v01 здесь лишь СТРАХУЕТСЯ нулём. Засеять его ЖИВЫМ текущим значением обязан ui: только он может
   спросить fxParamsOf(fxId)[pIdx].get() — state до audio не дотянется (audio импортирует state, обратный
   импорт — цикл). Без такого засева переключение в 'fixed' прыгнуло бы в минимум вместо «стоит там же». */
export const setFxParamMode=(role,effIdx,pIdx,mode)=>{
  const p=fxParamAt(role,effIdx,pIdx); if(!p)return;
  p.mode = mode==='fixed' ? 'fixed' : 'drive';
  if(p.mode==='fixed' && p.v01==null) p.v01=0;
};
/* ЗНАЧЕНИЕ фиксированного параметра — в НОРМИРОВАННЫХ 0..1, тех же, что даёт жест и принимает setNorm.
   Ручка «0..100» в меню — это ровно v01*100 для показа: min/max/curve живут ИСКЛЮЧИТЕЛЬНО внутри
   setNorm/fxDenorm (audio.js), поэтому второго представления диапазона не возникает, а лог-шкала
   реверба соблюдается сама собой. Применение значения в звук — дело ui (тот же fxParamsOf().set). */
export const setFxParamFixed=(role,effIdx,pIdx,v01)=>{
  const p=fxParamAt(role,effIdx,pIdx); if(!p)return;
  const v=+v01; p.v01 = Math.max(0, Math.min(1, isNaN(v)?0:v));
};
/* ПОРЯДОК ОСЕЙ ПО УМОЛЧАНИЮ у многопараметрического эффекта (константа вернулась в 3.4.3 вместе с
   операцией «добавить»; в 3.4.2 она ушла с setFxSlotId, а довод остался прозой в шапке): первый
   параметр — на ВЕРТИКАЛЬ (как было всегда и как ждёт рука), дальше горизонталь, глубина ПОСЛЕДНЕЙ —
   она шумнее плоских (считается из размера кисти, и поворот кисти её сдвигает, не двигая руку). */
const FX_AXIS_DEF=['y','x','z'];
/* СВОБОДНЫЙ ПАЛЕЦ — тот, которого не ведёт НИ ОДИН параметр цепи. Нужен ровно при добавлении эффекта.
   ⚠️ ПОЧЕМУ НЕ «ставим новый эффект на указательный»: указательный уже ведёт реверб, и новый эффект
   молча поехал бы ВМЕСТЕ с ним. Делить адрес — законно и даже задумано, но как ОСОЗНАННЫЙ выбор
   человека, а не как молчаливый дефолт: «добавил тремоло — поехала комната» читается как поломка. */
const fxFreeFinger=role=>{
  const used=new Set();
  for(const e of fxChainOf(role)) for(const p of e.params)
    if(p.mode==='drive' && p.hand==='fx' && p.finger!=null) used.add(p.finger);
  for(let f=0;f<4;f++) if(!used.has(f)) return f;   // 4 = FINGER_TIPS.length; config импортировать сюда ради одной длины не стоит — см. FINGER_KEYS в ui
  return -1;
};
/* ДОБАВИТЬ ЭФФЕКТ В ЦЕПЬ (Пласт 3.4.3). Возвращает индекс новой записи или -1, если добавить нечего.
   ⚠️ ИНВАРИАНТ «НЕ БОЛЕЕ ОДНОЙ ЗАПИСИ НА fxId» ПРОВЕРЯЕТСЯ ЗДЕСЬ — это единственное место, где цепь
   растёт, значит инвариант держится по построению (тем же приёмом, что hushUnassignedFx внутри
   сеттера). Довод — в шапке: две записи одного эффекта делили бы ОДИН store и дрались за него.
   ⚠️ АДРЕСА НОВЫХ ПАРАМЕТРОВ. Есть свободный палец — все параметры идут на НЕГО, по осям
   FX_AXIS_DEF (вертикаль, горизонталь, глубина): ровно то, что делал прежний выбор эффекта на строке
   пальца. Свободного НЕТ (четыре пальца заняты, а эффектов пять — та самая теснота, из-за которой
   тремоло и не назначено по умолчанию) — параметры встают ФИКСИРОВАННЫМИ. Это честно: эффект в цепи,
   звучит предсказуемо и молчит, пока ему не дадут адрес, — вместо тайной езды вдвоём на чужом пальце.
   ⚠️ v01 фиксированных здесь лишь СТРАХУЕТСЯ нулём; засеять их ЖИВЫМ значением обязан ui (state до
   audio не дотянется — обратный импорт был бы циклом), тем же приёмом, что при переходе в 'fixed'. */
export const fxChainAdd=(role,fxId,nParams=1)=>{
  const ch=fxChainOf(role);
  if(!fxId || ch.some(e=>e&&e.fxId===fxId)) return -1;
  const n=Math.max(1,nParams|0), f=fxFreeFinger(role);
  ch.push({ fxId, params:Array.from({length:n},(_,i)=> f>=0
    ? { mode:'drive', hand:'fx', finger:f, axis:FX_AXIS_DEF[i%FX_AXIS_DEF.length], inv:false }
    : { mode:'fixed', hand:'fx', finger:0, axis:FX_AXIS_DEF[i%FX_AXIS_DEF.length], inv:false, v01:0 }) });
  return ch.length-1;   // ui разворачивает добавленное: у него, возможно, нет адреса, и это надо увидеть сразу
};
/* УБРАТЬ ЭФФЕКТ ИЗ ЦЕПИ. hushUnassignedFx ОБЯЗАТЕЛЕН и не «на всякий случай»: правило слайса 2.5 —
   эффект, которым больше нечем управлять, ДОЛЖЕН ЗАМОЛЧАТЬ, иначе «звучит то, чем не управляешь»
   читается как поломка. Убранный делей обязан стихнуть тут же (хвост уже висящего эха доиграет — это
   принято ещё в 2.5). Реверб (модуль) под гашение не попадает намеренно, см. довод там же.
   ⚠️ Гасим ПОСЛЕ splice: предикат читает «отсутствует в цепи», а до splice эффект ещё в ней. */
export const fxChainRemove=(role,effIdx)=>{
  const ch=fxChainOf(role);
  if(!(effIdx>=0 && effIdx<ch.length)) return;
  ch.splice(effIdx,1);
  hushUnassignedFx();
};
