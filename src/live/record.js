const takeSrc=new Map();     // слой взятого → ключ его источника (noteSource). Нет записи — дорожка ● ещё ничья
/* ⛳ СЛЕДУЮЩИЙ СВОБОДНЫЙ НОМЕР СЛОЯ — ОДИН НА ВСЕ МЕСТА РОЖДЕНИЯ ПОСРЕДИ ПЕСНИ (T2). `maxLayer()+1` видит
   только слои, в которых уже ЕСТЬ события, а дорожка взятого до первой ноты пуста: две дорожки, рождённые
   в одном взятом, и подложка, положенная посреди записи, получили бы тот же номер — и laneNew переписал бы
   id уже пишущейся дорожки (правило #27 держится рождением, но номер-то один). Поэтому поверх него — все
   слои ТЕКУЩЕГО взятого. ⚠️ Подложка до T2 уже так ломалась: джем, положенный посреди записи до первой её
   ноты, ложился в слой пишущейся дорожки. */
function nextFreeLayer(){
  let n = events.length ? maxLayer()+1 : 0;
  if(recording) for(const ly of takeSt.keys()) if(ly+1>n) n=ly+1;
  return n;
}
/* ⛳ МЕСТО РОЖДЕНИЯ ДОРОЖКИ ПОСРЕДИ ДУБЛЯ (T2) — ЧЕТВЁРТОЕ после onRec, loadArrangement и самопочинки
   `?? laneNew`. ⛔ Правило #27: id выдаёт ТОЛЬКО laneNew, и зовётся он здесь РОВНО на рождении — из push,
   когда «вкл» роли без дорожки уже ТОЧНО ЛОЖИТСЯ (после отказа отсчёта), и больше нигде. Отказанное «вкл»
   дорожку не рождает. */
function takeMint(src){
  const ly=nextFreeLayer();
  laneNew(ly); takeJoin(ly); takeSrc.set(ly,src);
  hooks.rec && hooks.rec(true);   // подсказка ● перечислит новую дорожку (hooks.rec лишь перерисовывает кнопку — правило #5)
  return ly;
}
/* Куда ляжет новая нота роли: дорожка этой роли во взятом → иначе ещё ничья дорожка ● → иначе null («родится
   новая»). ЧИСТОЕ чтение — для соло, которому номер v нужен ДО push (у новой дорожки он 0: там пусто). */
function takePeek(src){
  for(const [ly,k] of takeSrc) if(k===src) return ly;
  for(const ly of takeSt.keys()) if(!takeSrc.has(ly)) return ly;
  return null;
}
/* То же, но ДЕЙСТВИЕМ: занять ничью дорожку или родить новую. Зовёт ТОЛЬКО push — после того, как событие
   прошло отказ отсчёта. */
function takeRoute(src){
  for(const [ly,k] of takeSrc) if(k===src) return ly;
  for(const ly of takeSt.keys()) if(!takeSrc.has(ly)){ takeSrc.set(ly,src); return ly; }   // ⛳ claim ПИШЕТСЯ ПОД КЛЮЧОМ ИСТОЧНИКА: второй источник эту дорожку уже не займёт
  return takeMint(src);
}
