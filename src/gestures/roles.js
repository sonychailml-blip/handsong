/* GES1: the hand ROLES and OWNER KEYS — stateless helpers of the gesture machine (gestures/hands.js): depth, voice-mode zones, live owner
   keys, sound + record by role, the finger-action registry, which role a hand plays now, the note volume resolver. No hand table here. */
import { REV_NEAR, REV_RANGE } from '../config.js';
import { fxChainOf, FX_VOL, handActOf, phoneInstr, handFnOf, playsNotes, splitOn, phoneHalves, sx, handSide, isLeadMode } from '../state.js';
import { typedChords } from '../scales.js';
import { WleadOn, WleadOff, WbassOn, WbassOff } from '../recorder.js';
import { fxInstance, fxHandRange } from '../audio.js';
import { clamp01, clamp, dist, emaS } from './features.js';

/* ═══ ГЛУБИНА РУКИ — ОДИН ШАГ СГЛАЖИВАНИЯ НА РУКУ ЗА КАДР (VOL-4) ═══
   Размер кисти dist(0,9), сглаженный emaS(S,'hs',…,0.15), — это ГЛУБИНА руки. Читателей у неё четыре: fx-рука (своя ось z),
   аккордовая ветка (яркость и прочее на play:z), блок глубины играющей руки (соло/бас/ударные) и — с VOL-4 — громкость на
   глубине (noteVolOf). ⛔ emaS продвигает фильтр при КАЖДОМ вызове: второй вызов за кадр сделал бы сглаживание вдвое быстрее,
   и глубина вела бы себя иначе, чем до слайса, только потому, что громкость стоит на ней.
   ⛳ ГАРАНТИЯ ПО ПОСТРОЕНИЮ: вызов emaS(S,'hs',…) в файле ОДИН — здесь. Результат кадра лежит в S.hsF; его сбрасывает РОВНО
   ОДНО место — начало обработки руки в processHands (рядом с S.seen=now), а рука обрабатывается раз за кадр. Значит, кто бы
   ни спросил первым, шаг фильтра делается один раз, а остальные читают ту же величину. ⚠️ Кто спрашивает — не важно, и
   порядок читателей больше ничего не решает. С нетронутыми умолчаниями последовательность прежняя дословно: у руки, которую
   сегодня читает один из трёх прежних читателей, по-прежнему ровно один шаг в том же кадре с тем же входом; громкость на
   горизонтали глубину не спрашивает вовсе. */
function depthOf(S,lm){ if(S.hsF==null) S.hsF=emaS(S,'hs',dist(lm[0],lm[9]),0.15); return S.hsF; }
/* Глубина как АДРЕС (0 — рука близко к камере, 1 — далеко): тот же закон, что у реверба до 3.1 и у яркости аккордов, — один на
   всех читателей играющей руки, поэтому два параметра на глубине едут вместе. */
const depthN=(S,lm)=>clamp01((REV_NEAR-depthOf(S,lm))/REV_RANGE);

const melodicZone=z=> z==='ld'||z==='bs';
const polyZone=z=> melodicZone(z) && !isLeadMode(z);
const leadZone=z=> melodicZone(z) && isLeadMode(z);
/* Ключ владельца ПОЛИФОНИЧЕСКОЙ ноты руки. ПАЛЕЦ — только при многопальцевом щипке: при потолке 1 и у терменвокса ключ
   руки БЕЗ пальца, поэтому смена пальца на лету ведёт ТУ ЖЕ ноту глиссандо, а не переатакует её. Формат совпадает по
   духу с 'loop:N'/'latch' у аккордов. Соло — 'lead:L[:f]' (как было всегда), бас — 'bass:L[:f]' (ключи полифонического
   баса, V2/V3; префикс 'bass:' понимают recorder.isLiveBassOwner, подсветка и ярлык в draw). */
const soloKey=(key,finger=null)=> 'lead:'+handSide(key)+(finger==null?'':':'+finger);
const liveKey=(role,key,finger=null)=> role==='bs' ? 'bass:'+handSide(key)+(finger==null?'':':'+finger) : soloKey(key,finger);
/* Ключ ЕДИНСТВЕННОГО голоса роли в ВЕДУЩЕМ режиме. Бас — 'bass', ровно прежний живой ключ баса. Соло — 'lead:M': начинается
   с 'lead:', поэтому его ловят ВСЕ проверки живого соло по префиксу (сброс живых голосов на шве liveWrapRelease,
   softAllOff — «не дорожка», подсветка соло из leadHold), а руке он не принадлежит (буквы L/R нет) — многонотный
   ярлык руки его не берёт, и ведущее соло показывает однонотный, как бас. */
const monoKey=role=> role==='bs' ? 'bass' : 'lead:M';
/* Звук + запись по роли — ОДНИМ местом (прежде две развилки руками: WleadOn у соло, WbassOn у баса). */
const wOn =(role,own,p,live)=> role==='bs' ? WbassOn(p,live,own) : WleadOn(own,p,live);
const wOff=(role,own)=> role==='bs' ? WbassOff(own) : WleadOff(own);

/* handRole (левая='fx' палитра / правая='ноты') УДАЛЁН: привязки роли к handedness не осталось нигде.
   Соло/бас/аккорды берут функцию руки из handFn (handFnOf), палитра типов выбирается ПО ПОЛОЖЕНИЮ —
   одинаково в single-role и в сплите. Ударные палитры не имеют (обе руки бьют по рядам). */
/* ═══ ДИСКРЕТНЫЕ ДЕЙСТВИЯ ПАЛЬЦЕВ — ДЕСКРИПТОРЫ (слайс «д») ═══
   Всё, что движок обязан знать о действии, лежит ЗДЕСЬ, а не в ветках кода: движок не должен опознавать
   действие ПО ИМЕНИ, иначе каждое новое потянет за собой правку гейтов.
     avail()   — осмысленно ли действие ПРЯМО СЕЙЧАС. Это и есть механизм МЯГКОЙ ДЕГРАДАЦИИ: на ладу без
                 палитры (`typedChords` ложен) подписка НЕ СТИРАЕТСЯ, а просто не срабатывает, и палец
                 падает в обычное ведение параметров — не повисает мёртвым. Та же дисциплина, по которой
                 у параметра эффекта палец/ось переживают смену режима: снимать выбор человека молча нельзя.
     region    — где должен оказаться щипок ('palette' — внутри палитры; null — где угодно).
     exclusive — СЪЕДАЕТ ли действие палец. У палитры НЕТ (false): внутри палитры палец выбирает тип,
                 ВНЕ её — по-прежнему ведёт свои параметры эффекта, и разводит их ПОЛОЖЕНИЕ, безо всякого
                 дополнительного правила. У команд лупера было бы true — щипок срабатывает где угодно.
   ⚠️ ПОРЯДОК СТАРШИНСТВА, одной строкой: сперва решает ФУНКЦИЯ РУКИ, потом ПОДПИСКА ПАЛЬЦА. Рука не на
   эффектах ведёт себя ровно как раньше (положение + большой-указательный); рука НА эффектах делает
   только то, что её пальцам назначено. Прежде эти два гейта разводил ПОРЯДОК В ТЕРНАРЕ — палитра стояла
   выше эффектов и молча забирала указательный. */
const ACTIONS={
  chFam:{ id:'chFam', labelKey:'act.chFam', avail:()=>typedChords(), region:'palette', exclusive:false },
};
/* «Действие ВЗВЕДЕНО на этом пальце» — обобщённо, без упоминания конкретного действия. */
const actArmed=(role,hand,finger,actId)=>{
  const a=ACTIONS[actId];
  return !!a && a.avail() && handActOf(role,hand,finger)===actId;
};
/* ⛳ ЕДИНСТВЕННЫЙ ИСТОЧНИК «ЭТА РУКА ВЫБИРАЕТ ТИП АККОРДА ЭТИМ ПАЛЬЦЕМ». Зовётся ДВАЖДЫ — из тернара
   зоны (захват) и из пофреймовой перепроверки внутри зоны 'chFam'. ⛔ НЕ РАЗМНОЖАТЬ: разойдись эти два
   ответа, и ведение оборвалось бы ПОСРЕДИ жеста (палитру можно тянуть до соседней ячейки, не разжимая
   пальцев). Та же дисциплина, что у captureFx и пофреймового цикла в слайсе б.1.
   ⚠️ РУКА НЕ НА ЭФФЕКТАХ → палец 0, дословно как было: это документированная ОДНОРУЧНАЯ МОДЕЛЬ аккордов
   (одна и та же рука берёт тип слева и корень справа — по очереди, аккорд звучит и после размыкания).
   Подписки для неё не существует: назначаемы пальцы ТОЛЬКО у руки-эффектов — тем же законом, по
   которому handFn решает, чем рука ЯВЛЯЕТСЯ. */
const paletteFinger=(key,role,finger)=>
  handFnOf(key,role)==='fx' ? actArmed(role,'fx',finger,'chFam') : finger===0;
/* Роль-половина ЭТОЙ руки СЕЙЧАС: single — глобальный phoneInstr; сплит — замороженная S.role (щипок)
   или живая половина под указательным (lm[8]). Правило #18: в сплите функция руки берётся ПО РОЛИ
   ПОЛОВИНЫ.
   Потребителей два: рука-ВЫРАЗИТЕЛЬНОСТЬ и noteHandRole (ниже; прежде soloNoteHand).
   ⚠️ ПЕРЕИМЕНОВАНА ИЗ soloHalfRole (слайс б.1): «solo» в имени стало ложью. Функция и раньше
   отвечала про ЛЮБУЮ роль-половину — соло было лишь у её тогдашних потребителей; теперь роль руки
   спрашивают и для эффектов, где она может быть любой. Тело не тронуто. */
function handHalfRole(key,S,W){
  if(!splitOn) return phoneInstr;
  if(S.pinch) return S.role;
  const lm=S.lm; if(!lm) return null;
  // px через sx (поля кадра); для ВЫБОРА половины клампим в [0,W): рука в полях сатурируется к ближней кромке, а не проваливается в чужую половину
  const px=clamp(sx(lm[8].x,W),0,W-1), hs=phoneHalves(W), h=hs.find(q=>px>=q.rx0&&px<q.rx1)||hs[hs.length-1];
  return h.role;
}
/* «ИГРАЮЩАЯ (нотная) рука СОЛО» — та, чья ГЛУБИНА ведёт назначенный ей параметр (Пласт 3.2).
   ⚠️ Предикат ВОСКРЕШЁН: в Пласте 3.1 он был удалён вместе с прицелом реверба (его единственным
   потребителем был ПОКАЗ). Теперь у него снова один потребитель, но уже НАСТОЯЩИЙ — УПРАВЛЕНИЕ.
   Условия те же: (1) роль-половина этой руки — соло; (2) рука реально играет ноты (не эффекты, не
   лупер, не выразительность — единый закон state.playsNotes). Двух нотных рук — пишут обе, побеждает
   последняя за кадр: ровно тем же правилом жил реверб до 3.1. */
/* ⛳ soloNoteHand ОБОБЩЁН в noteHandRole (яркость для всех ролей): ИГРАЮЩАЯ рука ЛЮБОЙ РОЛИ, кроме аккордов, — её
   роль-половина либо null. У соло ответ дословно прежний (роль 'ld' + playsNotes), бас и ударные добавились. Аккорды
   исключены — их глубину ведёт аккордовая ветка (под щипком, как всегда). Второго шага фильтра за кадр с VOL-4 не бывает в
   любом случае — мемо depthOf. */
function noteHandRole(key,S,W){
  const r=handHalfRole(key,S,W);
  return (r==='ld'||r==='bs'||r==='dr') && playsNotes(handFnOf(key,r)) ? r : null;
}
/* ═══ ГРОМКОСТЬ НОТЫ — ЧЕРЕЗ ПАРАМЕТР «ГРОМКОСТЬ» (слайс VOL-1 плана «громкость как параметр») ═══
   Один резолвер НА РУКУ вместо прежней развилки «0.2+0.8·xn либо fxVolFix» (VOL-1). Отдаёт ЧИСЛО громкости ноты (0…1);
   в звук его переводит одна кривая config.volAmp (v², VOL-2b) — уже в движке, не здесь.
   ⛳ НА ГОРИЗОНТАЛИ — ПО ВЕЛИЧИНЕ ЭТОЙ РУКИ: xn — позиция ИМЕННО этой руки в её замороженном диапазоне; результат уходит
   в S.vol руки и дальше в её ноты. ⛔ В общий параметр роли (экземпляр модуля, p.cur) такая громкость НЕ пишется: он один
   на роль, и две руки одной роли, которые держат СВОИ громкости, начали бы драться за одно число. Поэтому захват
   громкости на горизонтали держит только снимок взятого (умолчание модуля) и ни одной точки ленты; читать это некому —
   переигровка пропускает пер-нотное (fxLaneMerge), снимок ноты — поле со своим местом (fxSnapshot), голос берёт a.vol.
   ⛳ ВЕТКИ (VOL-2), по порядку:
     1. Громкость ЗАФИКСИРОВАНА в своей записи → её v01 (шкала сырая: v01 === a.vol, «Фиксировано 50» = a.vol 0.5).
        Это и есть бывший fxVolFix: отдельного числа по ролям больше нет (state.js, у fxVolReset).
     2. Громкость НА ПАЛЬЦЕ руки-эффектов → ОБЩАЯ величина роли: её ведёт fx-рука через тот же fxParamsOf, что и любой
        параметр (captureFx → p.set: пишутся p.cur и прицел), а каждая нотная рука этой роли читает p.cur. ⚠️ Значит на
        пальце громкость ОДНА на все руки роли — в отличие от горизонтали, где она у каждой руки своя. Ход руки
        (handRange; с VOL-2b полный [0,1]) действует и здесь: палец, как и горизонталь, — рука; «Фиксировано» — нет.
        Удерживаемая нота подхватывает её каждым кадром щипка (свелл пальцем); ⚠️ защёлкнутый аккорд с разомкнутыми
        пальцами ведений не получает — до него смена громкости пальцем не доходит (названный предел).
     3. На ГЛУБИНЕ ИГРАЮЩЕЙ РУКИ (VOL-4) → глубина ЭТОЙ руки (zOf — ленивый вопрос к мемо depthOf: шаг фильтра один на руку
        за кадр, кто бы ни спросил первым), тем же ходом [lo,hi] и той же инверсией. Как и горизонталь — СВОЯ у каждой руки,
        в общий параметр роли не пишется (оба цикла глубины громкость пропускают).
     4. Иначе — ХОД РУКИ ПО ГОРИЗОНТАЛИ: lo+(hi−lo)·v, [lo,hi] = ход громкости из объявления (с VOL-2b — [0,1]).
   ⛳ ПРАВИЛО ОБЩЕЙ ОСИ (VOL-2) — здесь его нет, и это правильно: другой параметр на горизонтали ведётся своим циклом ниже
   по кадру, а громкость остаётся на своём адресе. Прежняя ветка «X отдан эффекту → fxVolFix» (исключительность) удалена.
   ⛳ ПОБИТНОСТЬ. В VOL-1/VOL-2 ход был [0.2,1], и резолвер доказанно давал побитно прежние 0.2+0.8·xn (1−0.2 === 0.8 в double:
   разность 0x66666666666666·2⁻⁵⁵ стоит посередине сетки [0.5,1) и округляется к чётному — к 0x1999999999999A·2⁻⁵³ = 0.8).
   ⛔ С VOL-2b ПОБИТНОСТЬ С ПРЕЖНИМ ЗВУКОМ НЕ ДЕЙСТВУЕТ И НЕ ТРЕБУЕТСЯ: слайс меняет звук намеренно (левый край — тишина,
   кривая v²). Что осталось точным: ход [0,1] даёт 0+1·v = v без округления, а на ПРАВОМ краю (xn = 1) число 1 уходит в
   кривую как 1·1 = 1 — полная громкость каждой роли побитно прежняя (довод по ролям — у config.volAmp). */
function noteVolOf(zk,xn,zOf){
  const eff=fxChainOf(zk).find(e=>e&&e.fxId===FX_VOL), pa=eff&&eff.params[0];
  if(pa && pa.mode==='fixed' && pa.v01!=null) return pa.v01;          // 1. громкость зафиксирована в своей записи (бывший fxVolFix)
  const [lo,hi]=fxHandRange(FX_VOL,'amt');
  if(pa && pa.mode==='drive' && pa.hand==='fx'){                       // 2. на пальце руки-эффектов — общая величина роли
    const inst=fxInstance(zk,FX_VOL), c=inst ? inst.params[0].cur : null;
    if(c!=null) return lo+(hi-lo)*c;
  }
  const z = pa && pa.mode==='drive' && pa.hand==='play' && pa.axis==='z' && zOf;   // 3. VOL-4: на глубине — спрашиваем её ТОЛЬКО здесь (на горизонтали мемо глубины не трогаем)
  const a = z ? zOf() : xn;
  const v = pa&&pa.inv ? 1-a : a;
  return lo+(hi-lo)*v;                                                 // 3/4. ход руки по глубине или горизонтали: с VOL-2b [0,1] — ровно v (левый край / рука у камеры = тишина)
}

export { depthOf, depthN, melodicZone, polyZone, leadZone, liveKey, monoKey, wOn, wOff, ACTIONS, paletteFinger, handHalfRole, noteHandRole, noteVolOf };
